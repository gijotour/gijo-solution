// tools/opssim-evidence.mjs — 야간 하네스 기록의 **근거 칸**을 적을지 말지 한 곳에서 정한다.
//
// ■ 왜 갈랐나
//   판정을 ops-sim.mjs 안에 두면 시험이 못 부른다 — 그 파일은 **불러들이는 순간 하네스를
//   통째로 돌린다**(형제 파일 opssim-rules.mjs·opssim-report.mjs를 가른 것과 같은 이유).
//   스위치를 켰는데도 조각이 적히면 그것이 곧 사고인데, 부를 수 없으면 시험이 못 문다.
//
// ■ 무엇을 지키나 (2026-09-08 사장님 결정)
//   `.tmp-reports/ops-sim.json`에는 2026-09-08부터 **가드가 본 근거 조각 본문**이 평문으로
//   담긴다. 하네스 계정이 claude-deploy(admin)라 **등급 C(기밀) 사내 문답 조각**까지 그대로
//   들어간다. 이 기록은 되먹임 값어치가 커서(citeguard 재생 41건이 여기서 산다) **지우지
//   않기로** 했고, 대신 ① 원격(gb10) 사본으로 나가는 길을 막고 ② **끄는 스위치**를 둔다.
//   → 개발 기계(win)는 기록이 기본. 파일럿·출하·시연 기계는 이 스위치로 끈다.
//     (출하 전 되돌리기 목록: GIJO_AS_AI팀_증류학습_계획서.md 「출하 전 되돌리기」 절)
//
// ■ 끈 자리를 **보이게** 남긴다
//   칸이 통째로 사라지면 「옛 서버라 못 받았다」와 구별이 안 된다 — 그러면 다음 사람이
//   설계를 고장으로 읽는다. 그래서 끄더라도 **가드횟수는 남기고** `근거기록끔: true`를 적는다.
//   「일부러 안 적었다」가 기록 자체에 보여야 한다.

import fs from "node:fs";
import path from "node:path";

/**
 * 이번 회차에 근거 칸을 적을 것인가.
 *   · `--no-evidence` 플래그        → 안 적는다
 *   · `GIJO_OPSSIM_EVIDENCE=0`      → 안 적는다 (예약 실행처럼 인자를 못 주는 자리용)
 *   · 그 밖에는 적는다(개발 기계 기본 — 되먹임이 값어치다)
 * ⚠ 값을 받는 인자가 아니다(`--no-evidence 5` 같은 꼴을 만들지 않는다) — 있으면 끈 것이다.
 */
export function 근거기록할까(argv = process.argv, env = process.env) {
  if (argv.includes("--no-evidence")) return false;
  if (String(env.GIJO_OPSSIM_EVIDENCE ?? "").trim() === "0") return false;
  return true;
}

/**
 * 스위치를 켜도 **안 빠지는 것**을 한 문장으로 적어 둔다.
 *
 * ★ 왜 있나 (2026-09-08 검토관 적발): 되돌리기 표가 `--no-evidence`와 `.tmp-reports 비우기`를
 *   **대등한 두 갈래**로 적고 있었다. 그런데 이 스위치는 **근거 조각 본문만** 뺀다 — 질문(q)과
 *   답 본문(out)은 그대로 적힌다. 실측(같은 날 · 기록 177행): out에 사내 IP가 **29행**,
 *   사내 낱말이 **92행**. 출하 기계에서 싼 쪽(스위치)을 고르면 「되돌렸다」가 **반쪽**이 된다.
 *   → 끄는 사람이 **그 자리에서** 듣게 한다(하네스 시작 배너). 끝나고 기록을 열어 보고서야
 *     아는 것은 늦다. 문구가 갈리지 않게 여기 한 곳에 두고, 계획서 §「출하 전 되돌리기」의
 *     ③행이 같은 사실을 적었는지는 opssimevidence.test.ts가 문다.
 */
export const 끈회차에도남는것 =
  "⚠ 스위치는 **근거 조각 본문만** 뺍니다 — 질문(q)과 답 본문(out)은 그대로 적힙니다" +
  "(답이 사내 문서를 인용하면 그 대목도 함께 남습니다). 아무것도 안 남기려면" +
  " .tmp-reports 를 비우거나 이 하네스를 아예 안 돌립니다.";

/**
 * 응답의 `근거원천`을 기록에 실을 꼴로 만든다.
 *
 * @param 근거원천  서버 qa 응답의 j.근거원천 (옛 서버면 undefined)
 * @param 기록할까  근거기록할까()의 결과
 * @returns 결과 객체에 펼쳐 넣을 칸들
 *
 * ⚠ 조각 `null`은 **판정 보류**(RAG 미실행·검색 실패)라 `[]`(0건)과 뜻이 다르다 — 뭉개지 않는다.
 *   citeguard.test가 `Array.isArray(근거조각)`으로 그 둘을 가른다.
 * ⚠ 자르지 않는다 — 겹침 판정 창이 20자라 조각 꼬리를 자르면 라이브엔 없던 빨강이 난다.
 */
export function 근거칸(근거원천, 기록할까) {
  // 옛 서버는 이 칸을 안 준다 → 칸을 통째로 안 만든다(종전 갈래 그대로).
  if (!근거원천) return {};
  if (기록할까) {
    return {
      근거조각: 근거원천.조각,
      추가원천: 근거원천.추가원천,
      가드횟수: 근거원천.보고횟수,
    };
  }
  // 껐다 — 본문(조각·추가원천)은 안 적고, **끈 사실과 가드횟수만** 남긴다.
  return { 가드횟수: 근거원천.보고횟수, 근거기록끔: true };
}

/**
 * 실전 답 기록을 재료로 쓰는 시험들이 **왜 건너뛰는지**를 한 문장으로 만든다.
 *
 * 왜 여기 있나: 같은 사유를 시험마다 따로 적으면 어긋난다. 특히 「재료 없음」의 뜻이
 *   사본마다 달라서(gb10은 **일부러 안 옮긴다**) 그 사실을 빠뜨린 파일부터 오해가 난다.
 *
 * ★ 원인은 **아는 만큼만** 말한다 (2026-09-08 검토관 적발 뒤 고침)
 *   옛 판은 거른 뒤 건수 하나만 보고 「하네스가 도는 중이거나 --limit 실행이다」라고 원인을
 *   단정했다. 그런데 이 함수가 받는 건수는 `out`이 빈 행을 걸러 낸 **뒤**의 수라, 완주 회차라도
 *   응답이 많이 실패한 날에는 적게 나온다 — 그날 로그에 **틀린 진단**이 찍힌다.
 *   citeguard.test가 2026-09-06에 없앤 「손으로 적은 숫자」와 같은 계보(모르는 것을 아는 척).
 *   → 완주 여부는 **하네스가 적는** `ops-sim.meta.json`에서 읽는다. 잣대는 아는 쪽이 적는다.
 *
 * ⚠ 메타가 없거나 깨졌으면 「못 가린다」로 떨어진다 — 원인을 지어내지 않는다.
 * ⚠ citeguard.test.ts는 자기 재료상태()를 그대로 둔다(그 파일은 메타↔기록 **행수** 어긋남까지
 *   겸해 판정이 더 촘촘하다). 문구가 갈리지 않게, 고칠 일이 생기면 두 곳을 같이 본다.
 *
 * @param 기록경로  `.tmp-reports/ops-sim.json` 같은 기록 파일 경로(메타는 형제 `.meta.json`)
 * @param 건수      읽어 낸(빈 답을 거른) 답의 수
 * @param 최소      이 시험이 「증명했다」고 말하려면 필요한 최소 건수
 * @returns 건너뛸 사유(빈 문자열이면 잴 수 있다)
 */
export function 건너뛸사유(기록경로, 건수, 최소 = 50) {
  // 옛 판은 첫 인자가 boolean(있나)이었다. 조용히 받으면 메타를 못 읽는 판정이 되살아난다.
  if (typeof 기록경로 !== "string") {
    throw new TypeError(
      "건너뛸사유(기록경로, 건수, 최소) — 첫 인자는 기록 파일 **경로**다(옛 판은 boolean이었다). " +
      "메타를 못 읽으면 원인을 지어내는 옛 판정으로 되돌아간다."
    );
  }
  if (!fs.existsSync(기록경로)) {
    return "재료 없음 — 하네스를 아직 안 돌렸거나, gb10 사본은 일부러 재료를 안 옮긴다" +
      "(등급 C 조각이 원격으로 나가지 않게 · tools/gb10-test.sh). 다시 재려면 win의 WSL로.";
  }

  // 하네스가 적는 회차 메타 — 총문항·기록·완주. 없거나 깨졌으면 null(=모른다).
  const 메타파일 = path.join(
    path.dirname(기록경로),
    path.basename(기록경로, ".json") + ".meta.json",
  );
  let 메타 = null;
  try {
    if (fs.existsSync(메타파일)) 메타 = JSON.parse(fs.readFileSync(메타파일, "utf8"));
  } catch {
    메타 = null;   // 쓰는 중이거나 깨졌다 — 아래 「모른다」 갈래로 떨어진다
  }

  if (메타 && typeof 메타 === "object") {
    if (메타.완주 !== true) {
      // 여기서만 원인을 단정한다 — 하네스가 그렇게 적었으니 안다.
      return `부분 기록 — 이번 회차가 ${메타.기록 ?? "?"}/${메타.총문항 ?? "?"}문항만 돌았다` +
        "(--limit 실행이다). 반쪽 기록으로는 「0건」을 증명할 수 없다.";
    }
    if (건수 < 최소) {
      // 완주인데 쓸 수 있는 답이 적다 — **왜인지는 모른다**. 지어내지 않는다.
      return `완주 회차인데 쓸 수 있는 답이 ${건수}건뿐이다(최소 ${최소}건) — 답이 비었거나 ` +
        "실패한 회차다. 반쪽 기록으로는 「0건」을 증명할 수 없다(까닭은 기록을 봐야 안다).";
    }
    return "";
  }

  if (건수 < 최소) {
    return `부분 기록 ${건수}건(최소 ${최소}건) · 메타 없음(또는 못 읽음) — 완주 여부를 못 가린다. ` +
      "반쪽 기록으로는 「0건」을 증명할 수 없다.";
  }
  return "";
}
