const 뿌리 = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const 엔진 = (f) => fs.readFileSync(path.join(뿌리, "server/src/engine", f), "utf8");

// ── 안내 문구 뽑기 ────────────────────────────────────────────────────────────
// 제품이 답변 안에서 따옴표로 적어 주는 명령들. `"○○ 자산 취약점 알려줘"` 꼴.
// ★ 2026-08-04 넓힘: **화면의 칩·버튼이 대화창에 넣어 주는 말**도 같은 약속이다.
//   오히려 더 강한 약속이다 — 담당자가 친 게 아니라 **제품이 글자를 직접 넣어 준다.**
//   누르면 그대로 보내지는데 답이 회차마다 다르면 그건 버튼이 고장 난 것이다.
function 화면줄들() {
  const dir = path.join(뿌리, "client/src/renderer/pages");
  try {
    return fs.readdirSync(dir)
      .filter((f) => /\.(html|js)$/.test(f))
      .flatMap((f) => fs.readFileSync(path.join(dir, f), "utf8").split("\n"));
  } catch { return []; }
}

function 안내명령들() {
  // agenttools는 2026-08-06에 3파일로 나뉨 — 배럴만 읽으면 안내 문구를 몽땅 놓친다
  // nextguide(다음 걸음 칩)·scenarios(시나리오 단계)도 「안내한 말」이다(2026-08-21 편입 —
  // 설계관 대조에서 nextguide 41칩 중 26개가 검사 밖에서 근사 변형으로 쌓여 있었다).
  const 줄들 = ["agenttools.ts", "agenttools/handlers.ts", "agenttools/registry.ts", "agentloop.ts", "dispatcher.ts", "screenguide.ts", "workflow.ts", "nextguide.ts", "scenarios.ts", "docdigest.ts"]
    .flatMap((f) => { try { return 엔진(f).split("\n"); } catch { return []; } })
    .concat(화면줄들());
  // 2026-08-31: 「지켜봐 줘」(띄어쓰기 포함) 추가 — 📂 지켜보는 폴더 안내가 이 말을 약속한다.
  // 2026-09-07: 「넣어줘」 추가 — 📄 조각 없는 문서 안내가 「<문서이름> 다시 넣어줘」를 약속하는데
  //   동사 목록에 없어 **원리상 한 번도 안 세어졌다**(관문이 82개를 재고 초록이라 말한 그 옆에서).
  //   수확 못 하는 약속은 이 도구가 눈을 감은 자리다 — 새 안내 동사가 생기면 여기에 함께 적을 것.
  // 2026-09-13: 「돌려줘」 추가 — 검증 화면 안내가 「FW-01 하드닝 점검 돌려줘」를 약속하는데(등록 장비
  //   수동 점검 도구 scan_hardening_target) 동사 목록에 없어 수확 밖이었다(D 사슬 검토관 하급 이관).
  const 끝맺음 = /(해줘|알려줘|보여줘|만들어줘|읽어줘|배정해줘|정리해줘|확인해줘|추천해줘|복구해줘|찾아줘|넣어줘|돌려줘|지켜봐\s*줘)$/;
  const 본것 = new Set();
  const 결과 = [];
  let 설명안 = false;
  let can안 = false;
  for (const 줄 of 줄들) {
    // ⚠ **도구 설명(description) 안의 예시는 세지 않는다**(2026-08-04 스스로 정정).
    //   그건 담당자에게 주는 약속이 아니라 **LLM 라우터에게 주는 예시**다 — 모델이
    //   고르라고 적어 둔 것을 "모델 판단이라 문제"라고 세면 숫자가 부풀려진다.
    //   처음 돌렸을 때 29개가 나왔는데, 그중 상당수가 이것이었다.
    // 🔎 can: [...] 구간을 따로 안다(2026-08-31). 여기가 제품이 담당자에게 **「이렇게 치세요」**
    //   라고 내놓는 자리다. 그런데 수확 조건이 「해줘·알려줘류로 끝나는 문장」뿐이라
    //   **물음꼴 안내는 한 번도 재어진 적이 없었다** — guidance-check가 「읽기 안내 전부
    //   결정적」이라는 초록을 내면서 그 물음들을 아예 안 세고 있었다.
    //   ⚠ 물음표 하나로 넓히면 **과포착**이다(실측: 66 → 287개, FAQ 물음까지 딸려 온다).
    //   그래서 **can: 안에서만** 물음꼴을 받는다 — 제품이 약속한 자리만 잰다.
    if (/^\s*can:\s*\[/.test(줄)) can안 = true;
    else if (can안 && /^\s*\]/.test(줄)) can안 = false;
    if (/^\s*description:/.test(줄)) 설명안 = true;
    else if (/^\s*(name|label|domain|write|params|run|effect|undo|directAnswer|autoFill|\}|\{)/.test(줄)) 설명안 = false;
    if (설명안) continue;
    // 주석 안의 예시도 세지 않는다 — 담당자가 보는 글이 아니다.
    if (/^\s*(\/\/|\*|\/\*)/.test(줄)) continue;

    // ⚠ 따옴표 세 종류를 **따로** 훑는다(2026-08-04 내가 낸 버그를 고친 것).
    //   한 규칙으로 `["'\`]…["'\`]`를 쓰면 `'… "이 건 담당자 ○○로 배정해줘"'` 같은 줄에서
    //   **바깥 작은따옴표가 안쪽 큰따옴표를 통째로 삼킨다** — 서버 문구가 26개에서 5개로
    //   줄었는데 총계가 우연히 26으로 같아 하마터면 못 볼 뻔했다.
    // ⚠ **코드 이음매는 버리지 말고 완성형으로 되살린다**(2026-09-13 수리).
    //   화면은 대상 이름을 따옴표 **밖에서** 이어 붙인다 — `pd.name + " 점검 일정 알려줘"`.
    //   정규식은 JS 문법을 모르니 그대로 두면 「점검 일정 알려줘」라는 **토막**을 재는데,
    //   그건 사람이 치는 말이 아니다(제품이 보내는 말은 「<제품이름> 점검 일정 알려줘」다).
    //   그렇다고 버리면(9-12의 첫 수리) 그 칩은 **어느 관문도 안 재는 사각**이 된다 —
    //   게다가 버림이 한쪽(작은따옴표)만이라 모집단이 JS 따옴표 문법에 따라 갈렸다.
    //   그래서 변수 자리를 「○○」로 채워 **제품이 실제로 보내는 문장**으로 되살린 뒤 잰다
    //   (○○는 아래에서 우리 데이터의 실제 이름으로 바뀐다). 실측: 83개 → 91개, 그중 6개는
    //   여태 **어느 관문도 안 재던 칩**이었다(session-explorer·map-view).
    //   ⚠ **글자를 만드는 식은 이름이 아니다** — `String.fromCharCode(34)`는 따옴표 한 자를
    //     만든다(screenguide.ts의 lawlookup can[]이 안내를 그렇게 적는다). 이것까지 ○○로
    //     채우면 「개인정보 보호법 찾아줘」 같은 **멀쩡한 안내 4개가 통째로 사라진다**(실측).
    const 이름식 = (식) => !/fromCharCode/.test(식);
    let 본문 = 줄;
    for (let i = 0; i < 5; i++) {          // "…" + 이름 + "…"  (같은 따옴표끼리만 잇는다)
      const 앞 = 본문;
      본문 = 본문.replace(/(["'`])\s*\+\s*([^"'`+\n]{1,60})\+\s*\1/g, (전, _q, 식) => (이름식(식) ? "○○" : 전));
      if (본문 === 앞) break;
    }
    // 이름 + "…" — 앞자리 식이 **이름꼴**(변수·속성·esc(이름)·(a.name || a.id))일 때만 채운다
    본문 = 본문.replace(
      /((?:[A-Za-z_$가-힣][\w$.가-힣]*)?\([^()]*\)|[A-Za-z_$가-힣][\w$.가-힣]*)\s*\+\s*(["'`])/g,
      (전, 식, q) => (이름식(식) ? `${식} ${q}○○` : 전),
    );
    const 후보 = [
      ...본문.matchAll(/"([^"\n]{4,44})"/g),
      ...본문.matchAll(/'([^'\n]{4,44})'/g),
      ...본문.matchAll(/`([^`\n]{4,44})`/g),
    ];
    for (const m of 후보) {
      let s = m[1].trim();
      if (!끝맺음.test(s) && !(can안 && /\?$/.test(s))) continue;
      if (s.includes("${") || s.includes("<")) continue;  // 코드 조각·자리표시자는 그대로 못 친다
      // ⚠ **되살리지 못한 이음매를 받는 그물**. 위에서 이음매는 ○○로 채우지만, 식 안에 `+`나
      //   따옴표가 들어 있으면 못 채운다 — 그때는 이음매 글자가 리터럴에 그대로 남는다.
      //   실측(2026-09-13): 이 줄을 꺼도 91개로 같다 — **오늘은 하나도 안 걸린다.**
      //   그래도 남긴다: 안 걸리는 그물은 0을 버리지만, 없는 그물은 **코드 조각을 안내로
      //   세어** 관문을 헛돌게 한다(9-12에 map-view의 그 조각이 실제로 세어졌다).
      if (s.includes("' + ") || s.includes("+ esc(")) continue;
      if (/^[a-z_]+$/i.test(s)) continue;           // 도구 이름
      // ⚠ 조각으로 시작하는 것은 안내가 아니다 — 화면이 앞에 대상 이름을 붙여 완성한다
      //   (「의 가장 급한 취약점…」처럼 조사로 시작하는 줄). 그대로 재면 거짓 실패가 난다.
      if (/^[의를을이가에]/.test(s)) continue;
      // 안내 문장 안의 **예시**는 명령 자체가 아니다(「… 예: 방화벽 정책 점검해줘」).
      if (/(예:|예를 들어|주세요\s*—)/.test(s)) continue;
      // ⚠ 두 낱말 이하의 토막(「배정해줘」·「설명해줘」)은 안내가 아니라 **말투 예시**다.
      //   그대로 쳐도 대상이 없어 안 되는 게 맞다 — 결함으로 세면 안 된다.
      if (s.split(/\s+/).length < 2) continue;
      // 「○○」는 담당자가 실제 이름을 넣는 자리다 — 우리 데이터에 있는 이름으로 바꿔 잰다.
      const 원문 = s;
      s = s.replace(/○○/g, "GIJO AS 서버");
      if (본것.has(s)) continue;
      본것.add(s);
      결과.push({ 원문, 질문: s });
    }
  }
  return 결과;
}

// 소스에서 못 읽어 **검사에서 빠진** 규칙들. 비어 있어야 정상이다.
// ⚠ 이걸 안 세면 규칙 하나가 통째로 검사에서 사라져도 도구는 초록불을 낸다.
