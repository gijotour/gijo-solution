/**
 * **쓰기를 시키는 안내는 따로 센다.**
 *
 * ★ 2026-08-04 실측 중 깨달은 구분: 쓰기(배정·기한·조치)는 **결재판이 사람에게
 *   확인받고** 실행한다. 모델이 대상을 잘못 골라도 담당자가 승인 창에서 본다 —
 *   그래서 모델 판단이어도 위험하지 않다.
 *   오히려 쓰기를 정규식으로 못 박으면 **엉뚱한 대상에 결재판이 뜬다**(더 나쁘다).
 *   읽기는 답이 그대로 나가므로 흔들리면 안 된다 — 여기만 결정적이어야 한다.
 */
// ⚠ 2026-09-07: 「다시 넣어줘」(재인입)를 여기 넣는다. reingest_document는 write:true라 결재판이
//   받쳐 주는데, 이 목록에 없으면 「읽기인데 모델 판단」으로 **잘못 세어진다**(위험도가 반대로 읽힌다).
const 쓰기말 = /(배정|맡겨|기한|조치해|처리해|등록해|삭제|수집해|생성해|만들어|다시 넣|재인입)/;

// ⚠ **함수로 판단하는 결정적 경로** — 이 도구는 정규식만 읽으므로(위 주석) 함수·전용
//   블록이 받는 문구는 원리상 「모델 판단」으로 오판한다. 그 경우에만, **근거(파일:줄과
//   확인 날짜)를 반드시 적고** 여기 명단에 올린다. 근거 없는 항목은 넣지 말 것 —
//   이 명단이 커지면 검사가 눈을 감는 것과 같아진다(항목마다 이유 강제, 소스감시 관례).
const 함수경로확인 = [
  { re: /^검증 현황 보여줘$/, 근거: "datacard.ts:38-44 화면이름 카드 결정 트리거(2026-08-21 검토관 확인)" },
  { re: /^어댑터 현황 알려줘$/, 근거: "agentloop.ts 어댑터 전용 블록(/어댑터/ 낱말 결정 처리, 1460년대 줄 — 2026-08-21 검토관 확인)" },
];

const 결정적 = [];
const 모델판단 = [];
const 쓰기안내 = [];
for (const x of 안내) {
  const r = 규칙.find((g) => g.re.test(x.질문));
  const s = 특수.find((g) => g.re.test(x.질문));
  const f = 함수경로확인.find((g) => g.re.test(x.질문));
  if (r) 결정적.push({ ...x, 도착: r.tool });
  else if (s) 결정적.push({ ...x, 도착: s.이름 });
  else if (f) 결정적.push({ ...x, 도착: "함수경로(" + f.근거.slice(0, 30) + "…)" });
  else if (쓰기말.test(x.질문)) 쓰기안내.push(x);
  else 모델판단.push(x);
}

console.log("\n  제품이 「이렇게 말하세요」라고 안내한 명령 — 실제로 걸리는가\n");
console.log(`    안내 문구 ${안내.length}개 · 규칙 ${규칙.length}개 · 특수경로 ${특수.length}개`);
// 못 읽은 게 있으면 **먼저** 말한다 — 아래 숫자들이 그만큼 덜 센 결과이기 때문이다.
if (못읽은규칙.length) {
  console.log(`\n    ✗ 소스에서 못 읽어 검사에서 빠진 규칙 ${못읽은규칙.length}개 — 아래 집계는 그만큼 덜 셌다:`);
  못읽은규칙.forEach((x) => console.log(`        · ${x}`));
  console.log(`      (제품 코드 모양이 바뀌어 추출 정규식이 못 따라간 것이다. 도구를 맞춰야 한다.)`);
}
console.log(`    ✓ 결정적으로 걸림 ${결정적.length}개`);
console.log(`    ○ 쓰기 안내 ${쓰기안내.length}개 — 모델 판단이지만 **결재판이 사람에게 확인받는다**`);
console.log(`    ⚠ 읽기인데 모델 판단 ${모델판단.length}개  ← 답이 그대로 나가는데 회차마다 달라질 수 있다\n`);

if (쓰기안내.length) {
  console.log("  쓰기 안내(결재판이 받쳐 준다 — 못 박지 않는다):");
  쓰기안내.forEach((x) => console.log("    · " + x.원문));
  console.log("");
}
if (모델판단.length) {
  console.log("  ⚠ 읽기인데 모델 판단으로 가는 안내:");
  모델판단.forEach((x) => console.log("    · " + x.원문));
  console.log("\n  이것들이 곧 「우리가 시킨 대로 쳤는데 답이 흔들리는」 자리다.");
} else {
  console.log("  ✓ 읽기 안내는 전부 결정적이다 — 시킨 대로 치면 같은 답이 나온다.");
}

