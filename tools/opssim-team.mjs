//
// ★ 왜 ops-sim.mjs 안이 아니라 여기인가 — 그 파일은 **불러들이는 순간 하네스를 통째로 돌리는**
//   최상위 스크립트라 시험이 부를 수 없다(형제 opssim-rules.mjs·opssim-report.mjs와 같은 이유).
//   판정식과 문항표를 여기 두어야 `server/test/opssimteam.test.ts`가 **제품 함수로** 문다.
//
// ★★ 정직 계약 세 가지 — 이 마당이 거짓을 만들 수 있는 자리는 여기뿐이다
//   ① **「문으로 갔다」와 「두뇌가 돌았다」는 다른 말이다.**
//      제품의 팀원 여덟 중 **넷(scan·curator·bom 일부·normaltic 일부)은 대화 요청에서 두뇌가
//      안 돈다** — 그 팀원의 LLM은 **문서 반입·스캔 등록 때**(memory.categorizeDocument ·
//      scandrafts.draftScanInterpretation · bomdrafts.draftBomInterpretation) 돌고, 대화창에서는
//      그때 남긴 글을 **규칙이 보여줄 뿐**이다(도구가 directAnswer). 이것을 「팀원이 답했다」로
//      세면 정의 A가 **거짓 초록**이 된다. 그래서 행마다 `두뇌돎`을 적고, false면 두뇌·지연 판정을
//      **아예 안 한다**(기록에는 「문만」으로 남는다 — 덮지 않는다).
//   ② **배정표를 코드에 박지 않는다.** 위치·모델은 회차마다 `/api/agents`에서 읽는다
//      (`배정표스냅샷`). `assignedLocation`이 null이면 **「전역 따름」**이라 그 팀원의 위치는
//      알 수 없다 — 그때는 위치·지연 판정을 건너뛰고 「미배정」으로 **세어서 드러낸다.**
