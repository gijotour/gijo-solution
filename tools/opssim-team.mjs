/**
 * `/api/agents` 응답을 이 마당이 쓰는 꼴로 줄인다 — **회차마다 읽어** meta.json에 그대로 남긴다.
 *
 * ⚠ `assignedLocation`이 null이면 **「전역 따름」**이다 — 그 팀원이 어디서 도는지 이 표만으로는
 *   알 수 없다. `위치: null`로 두고 판정을 건너뛴다(모르는 것을 아는 척하지 않는다).
 * @param {Array} 목록 /api/agents가 준 배열(못 읽었으면 빈 배열·null 그대로 넘겨도 된다)
 */
export function 배정표스냅샷(목록) {
  const 표 = {};
  for (const a of Array.isArray(목록) ? 목록 : []) {
    if (!a || typeof a.id !== "string") continue;
    표[a.id] = {
      이름: String(a.name ?? a.id),
      약자: String(a.abbr ?? ""),
      위치: a.assignedLocation ?? null,   // null = 전역 따름(미배정)
      모델: a.assignedModelId ?? null,    // null = 전역 모델 따름
    };
  }
  return 표;
}

/** 이 팀원에게 걸리는 지연 상한(ms). 위치를 모르면 null — 그때는 재지 않는다. */
export function 상한MS(위치) {
  return 위치 && Object.prototype.hasOwnProperty.call(지연상한MS, 위치) ? 지연상한MS[위치] : null;
}

/**
 * 이 답이 **실패**인가 — 「오류」·「빈 답」·아니면 null.
 *
 * ★ 잣대 한 곳: 하네스의 불편 판정(`오류`·`빈 답`)과 ⑲ 판정이 **같은 함수**를 본다.
 *   두 벌로 두면 한쪽만 고쳐지는 날 「실패인데 도착을 쟀다」거나 그 반대가 난다.
 * ⚠ `out` 칸이 아예 없는 그릇은 **실패로 보지 않는다** — 짝 시험의 가짜 답(`{ 팀원, ms }`)은
 *   답 본문을 안 싣고 판정식만 재는 그릇이라, 그것을 빈 답으로 세면 시험이 통째로 딴것을 잰다.
 *   실제 하네스의 `물어보기()`는 **언제나** `out`(문자열)을 실어 준다.
 */
export function 실패이유(r) {
  if (!r || typeof r !== "object") return null;
  if (r.err) return "오류";
  if ("out" in r && !String(r.out ?? "").trim()) return "빈 답";
  return null;
}

/** 답에서 실제로 어디에 닿았는지 — 신호 종류별로 **한 곳에서** 뽑는다(두 벌이면 어긋난다). */
function 실제신호(신호, r) {
  if (신호.종류 === "팀원") return { 값: r.팀원 ?? null, 맞나: r.팀원 === 신호.값 };
  if (신호.종류 === "단계") {
    const 것들 = (r.단계 ?? []).map((s) => s?.action).filter(Boolean);
    return { 값: 것들.join("+") || null, 맞나: 것들.includes(신호.값) };
  }
  const 것들 = r.도구 ?? [];
  return { 값: 것들.join("+") || null, 맞나: 것들.includes(신호.값) };
}

/** 이 행에서 **두뇌 표식으로 위치를 견줄 수 있나** — 세 조건이 모두 맞아야 한다(계약 ①④와 표식주인). */
export function 표식잴수있나(행) {
  return !!행.두뇌돎 && 행.표식주인 !== false && 행.표식남나 !== false;
}

/** 기록 한 줄 — 판정이 끝난 뒤와 실패로 건너뛴 뒤가 **같은 꼴**이어야 표가 안 어긋난다. */
function 기록만들기(행, { 실패 = null, 배정 = null, 기대위치 = null, 닿음 = null, 표식 = null, 상한 = null, ms = null, 지연잼 = false }) {
  return {
    팀원: 행.팀원,
    q: 행.q,
    결정적: 행.결정적,
    두뇌돎: !!행.두뇌돎,
    두뇌조건: 행.두뇌조건 ?? null,           // null = 언제나 돎
    표식주인: 행.표식주인 !== false,
    표식남나: 행.표식남나 !== false,          // false = 결정 호출이라 표식이 원리상 없다
    실패,                                    // null이 아니면 도착·두뇌를 안 잰 줄이다
    도착기대: `${행.신호.종류} ${행.신호.값}`,
    도착실제: 닿음?.값 ?? null,
    도착맞음: !!닿음?.맞나,
    기대위치,                                 // null = 전역 따름(미배정)
    실제위치: 표식?.location ?? null,          // null = 표식 없음 또는 두뇌 안 돎
    표식있음: !!표식,
    폴백: !!표식?.fallback,
    모델: 표식?.model ?? 배정?.모델 ?? null,
    ms,
    상한,
    지연잼,                                   // 이 줄에 지연 판정을 **실제로 걸었나**
  };
}

/**
 * ⑲ 판정 — 한 문항의 불편과 표에 실을 기록을 낸다.
 *
 * @param {object} 행     팀원문항의 한 줄
 * @param {object} r      물어보기()가 돌려준 답({ 팀원, 도구, 단계, 두뇌, ms, wouldHandoff, out, err … })
 * @param {object} 배정표 배정표스냅샷()의 결과(못 읽었으면 {})
 * @param {boolean} 이미느림 기존 30초 규칙이 이 답을 이미 「너무 오래 걸림」으로 셌는가
 * @returns {{불편: Array, 기록: object}}
 */
export function 팀원판정(행, r, 배정표 = {}, 이미느림 = false) {
  const 목 = [];
  const 배정 = 배정표?.[행.팀원] ?? null;
  const 기대위치 = 배정?.위치 ?? null;
  const ms = typeof r?.ms === "number" ? r.ms : null;

  // ⓪ 실패한 답(오류·빈 답) — **기록만 남기고 아무것도 재지 않는다**(정직 계약 ⑤).
  //   ⚠ 여기서 「다른 팀원에게 감」을 붙이면 같은 실패를 두 번 세게 된다(하네스가 이미 셌다).
  //   ⚠ 그래도 줄은 남는다 — 빠지면 분모가 줄어 죽은 회차가 초록으로 읽힌다.
  const 실패 = 실패이유(r);
  if (실패) return { 불편: [], 기록: 기록만들기(행, { 실패, 배정, 기대위치, ms }) };

  const 잴수있나 = 표식잴수있나(행);
  const 상한 = 잴수있나 ? 상한MS(기대위치) : null;
  const 닿음 = 실제신호(행.신호, r);

  // ① 그 팀원의 문으로 갔나 — ⑲의 본체다.
  if (!닿음.맞나) {
    목.push({
      종류: "다른 팀원에게 감",
      상세: `${행.팀원} 기대(${행.신호.종류} ${행.신호.값}) → 실제 ${닿음.값 ?? "없음"}` +
        (행.결정적 ? "" : " · 이 말은 강제 규칙이 없어 모델이 고른다"),
    });
  }

  // ② 두뇌 표식 — 없으면 **옛 서버**이거나(계약 ③) **결정 호출**이다(계약 ④). 둘 다 빨강 아님.
  const 표식 = r.두뇌 ?? null;
  if (잴수있나 && 표식) {
    const 실제위치 = 표식.location ?? null;
    if (기대위치 && 실제위치 && 실제위치 !== 기대위치) {
      목.push({ 종류: "배정과 다른 두뇌", 상세: `배정 ${기대위치} → 실제 ${실제위치}` });
    }
    if (표식.fallback) {
      목.push({ 종류: "원격이 안 닿아 이 PC로", 상세: `${행.팀원} — 배정 ${기대위치 ?? "전역 따름"}` });
    }
  }

  // ③ 지연 상한 — **배정된 위치**가 약속한 시간이다. 위치를 모르면(전역 따름) 재지 않는다.
  //   ⚠ 기존 30초 규칙이 이미 셌으면 겹쳐 세지 않는다 — 같은 사실을 두 번 세면 불편 수가 거짓이 된다.
  //   ⚠ 리포트꼴 답(wouldHandoff)도 안 잰다 — 사람 경로는 3초에 리포트로 물러난다.
  const 지연잼 = 상한 !== null && !r.wouldHandoff && !이미느림 && ms !== null;
  if (지연잼 && ms > 상한) {
    목.push({ 종류: "두뇌 느림", 상세: `${Math.round(ms / 1000)}초 — ${기대위치} 상한 ${상한 / 1000}초` });
  }

  return { 불편: 목, 기록: 기록만들기(행, { 배정, 기대위치, 닿음, 표식: 잴수있나 ? 표식 : null, 상한, ms, 지연잼 }) };
}

/**
 * 사람이 읽는 한 줄 — 표와 요약이 **같은 말**을 쓰도록 한 곳에 둔다.
 * 「실패 / 문만 / 여럿이 돎 / 돎(결정 호출) / 폴백 / 원격·로컬 / 표식 없음(옛 서버)」.
 */
export function 두뇌말(기록) {
  if (기록.실패) return `실패(${기록.실패})`;
  if (!기록.두뇌돎) return "문만(반입 때 돎)";
  const 앞 = 기록.두뇌조건 ? "조건부 " : "";
  // ⚠ 「여럿이 돎」을 「원격/로컬」로 적으면 남의 두뇌를 이 팀원 것으로 보고하게 된다.
  if (!기록.표식주인) return `${앞}여럿이 돎(표식은 첫 것)`;
  // ⚠ 표식이 **원리상 없는** 갈래(결정 호출·explain 없는 chat)를 「옛 서버」로 적으면
  //   매일 밤 거짓 진단이 나간다 — 「돌기는 했다」까지만 적는다.
  if (!기록.표식남나) return `${앞}돎(표식 안 남는 갈래)`;
  if (기록.폴백) return `${앞}폴백(${기록.실제위치 ?? "?"})`;
  if (기록.실제위치) return 앞 + (기록.실제위치 === "remote" ? "원격" : "로컬");
  return `${앞}표식 없음(옛 서버)`;
}

/**
 * 보고서(ops-sim.md)의 **팀원별 표** 한 대목 — 문항 수 · 두뇌 · 평균 지연 · 불편.
 *
 * ⚠ 이 회차에 ⑲를 안 돌렸으면(--only·--limit) **없는 표를 만들지 않는다** — 빈 표는 「0건 초록」이라
 *   가장 나쁜 거짓말이다. 일부만 돈 회차는 분모를 `N/27`로 적어 **덜 돌았음을 드러낸다.**
 *
 * @param {Array} 결과   하네스의 결과 줄들(⑲ 아닌 줄이 섞여 있어도 된다 — `팀원기록`이 있는 줄만 본다)
 * @param {object} 배정표 배정표스냅샷()의 결과
 * @returns {string[]} 마크다운 줄들
 */
export function 팀원표(결과, 배정표 = {}) {
  const 줄들 = (결과 ?? []).filter((r) => r && r.팀원기록);
  if (!줄들.length) return [];

  const 묶음 = {};
  for (const r of 줄들) {
    const k = r.팀원기록.팀원;
    묶음[k] ??= {
      전체: 0, 도착맞음: 0, ms: [], 불편: 0, 두뇌: {}, 결정적: 0, 두뇌돎: 0,
      조건부: 0, 표식잴수있음: 0, 위치확인: 0, 표식안남: 0, 여럿: 0, 문만: 0, 실패: 0, 지연잼: 0,
    };
    const b = 묶음[k];
    const g = r.팀원기록;
    b.전체++;
    if (g.실패) b.실패++;
    if (g.도착맞음) b.도착맞음++;
    if (g.결정적) b.결정적++;
    if (g.두뇌돎) b.두뇌돎++;
    if (g.두뇌돎 && g.두뇌조건) b.조건부++;
    if (!g.두뇌돎) b.문만++;
    if (g.두뇌돎 && !g.표식주인) b.여럿++;
    if (g.두뇌돎 && g.표식주인 && !g.표식남나) b.표식안남++;
    if (!g.실패 && g.두뇌돎 && g.표식주인 && g.표식남나) b.표식잴수있음++;
    if (g.표식있음 && g.실제위치) b.위치확인++;
    if (g.지연잼) b.지연잼++;
    // ⚠ 지연은 **이 팀원 것으로 잴 수 있는 답**만 평균에 넣는다 — 여럿이 도는 답의 시간을
    //   섞으면 「해설이 40초」 같은 남의 시간이 이 팀원 줄에 찍힌다. 실패 줄도 뺀다(잰 시간이 아니다).
    if (typeof g.ms === "number" && !g.실패 && (!g.두뇌돎 || g.표식주인)) b.ms.push(g.ms);
    if ((r.불편 ?? []).length) b.불편++;
    const 말 = 두뇌말(g);
    b.두뇌[말] = (b.두뇌[말] ?? 0) + 1;
  }

  const 순서 = 팀원순서.filter((id) => 묶음[id]);
  const 평균 = (xs) => (xs.length ? (xs.reduce((a, b) => a + b, 0) / xs.length / 1000).toFixed(1) + "s" : "-");
  const 미배정 = 순서.filter((id) => !(배정표?.[id]?.위치));
  const 실패수 = 줄들.filter((r) => r.팀원기록.실패).length;
  const 조건부수 = 줄들.filter((r) => r.팀원기록.두뇌돎 && r.팀원기록.두뇌조건).length;

  // ★ 「위치를 실제로 확인할 수 있는가」 — 이 마당이 정의 A를 **어디까지** 증명하는지 적는 자리다.
  //   확인 못 하는 이유는 셋뿐이고(문만·결정 호출·여럿이 돎) 전부 **설계 그대로**라 빨강이 아니다.
  //   그렇다고 조용히 넘기면 「⑲가 초록이니 팀원마다 다른 두뇌가 증명됐다」는 과장이 남는다.
  const 못재는이유 = (b) => [
    b.문만 ? `문만 ${b.문만}` : "",
    b.표식안남 ? `표식 안 남는 갈래 ${b.표식안남}` : "",
    b.여럿 ? `여럿이 돎 ${b.여럿}` : "",
  ].filter(Boolean).join(" · ");
  const 잴수있는팀원 = 순서.filter((id) => 묶음[id].표식잴수있음);
  const 못재는팀원 = 순서.filter((id) => !묶음[id].표식잴수있음);
  const 원격배정 = 순서.filter((id) => 배정표?.[id]?.위치 === "remote");
  const 원격확인가능 = 원격배정.filter((id) => 묶음[id].표식잴수있음);

  return [
    `## ${마당이름}`,
    "",
    "정의 A(팀원마다 다른 두뇌로 실제 동작)를 **숫자로** 보는 자리입니다. 두 가지는 다른 말입니다 —",
    "**「그 팀원의 문으로 갔나」**(도착)와 **「이 요청에서 그 팀원의 두뇌가 돌았나」**(두뇌).",
    "「문만(반입 때 돎)」은 결함이 아니라 **설계 그대로**입니다: 그 팀원의 두뇌는 문서 반입·스캔 등록 때 돌고,",
    "대화창에서는 그때 남긴 글을 규칙이 보여 줍니다. 두뇌·지연 판정은 **「돎」인 문항에만** 겁니다.",
    "「돎(표식 안 남는 갈래)」도 결함이 아닙니다 — 두뇌는 돌지만 서버가 그 호출에 **표식을 안 남깁니다**:",
    "표식은 **담당자가 그대로 읽는 답**에만 붙습니다(brainmark.ts의 약속 — 결정 호출·내부 호출 제외).",
    "그런 줄은 위치·폴백·지연을 재지 않고 「돌았다」까지만 적습니다.",
    "",
    "| 팀원 | 배정 위치 | 배정 두뇌 | 문항 | 도착 맞음 | 두뇌 | 평균 지연 | 상한 | 불편 |",
    "|---|---|---|---:|---:|---|---:|---:|---:|",
    ...순서.map((id) => {
      const b = 묶음[id];
      const 배정 = 배정표?.[id] ?? null;
      const 상한 = 상한MS(배정?.위치);
      const 이름 = 배정?.이름 ? `${배정.이름}${배정.약자 ? `(${배정.약자})` : ""}` : id;
      // 상한 칸은 **잰 횟수까지** 적는다 — 「30s」만 적으면 한 번도 안 잰 회차가 잰 것처럼 읽힌다.
      const 상한칸 = b.표식잴수있음 && 상한 !== null ? `${상한 / 1000}s(잰 ${b.지연잼})` : "-";
      return `| ${이름} | ${배정?.위치 ?? "전역 따름"} | ${배정?.모델 ?? "전역 따름"} | ${b.전체} | ${b.도착맞음}/${b.전체} |` +
        ` ${Object.entries(b.두뇌).map(([k, v]) => `${k} ${v}`).join(" · ")} | ${평균(b.ms)} |` +
        ` ${상한칸} | ${b.불편} |`;
    }),
    "",
    `합계: 문항 ${줄들.length}/${팀원문항.length} · 도착 맞음 ${줄들.filter((r) => r.팀원기록.도착맞음).length} ·` +
      ` 이 요청에서 두뇌가 도는 문항 ${줄들.filter((r) => r.팀원기록.두뇌돎).length}` +
      (조건부수 ? `(그중 조건부 ${조건부수} — 데이터가 없던 밤에는 안 돕니다)` : "") + " ·" +
      ` 강제 규칙이 못 박는 문항 ${줄들.filter((r) => r.팀원기록.결정적).length}` +
      (실패수 ? ` · 실패 ${실패수}` : ""),
    // ⚠ 일부만 돈 회차를 조용히 넘기지 않는다 — 줄어든 분모로 100%가 나오면 그게 거짓 초록이다.
    ...(줄들.length < 팀원문항.length
      ? ["", `⚠ 이 회차는 ⑲ ${팀원문항.length}문항 중 **${줄들.length}개만** 돌았습니다(--only·--limit 또는 중단) —` +
         " 위 숫자는 그 문항들만의 것입니다."]
      : []),
    ...(실패수
      ? ["", `⚠ **실패 ${실패수}건**(오류·빈 답)은 도착·두뇌를 재지 못했습니다 — 위 불편 표에서 이미 세었고,` +
         " 여기서는 **분모에 남겨 둡니다**(빼면 살아남은 문항만으로 100%가 되어 죽은 회차가 초록으로 읽힙니다)."]
      : []),
    // ⚠ 「표식 없음」을 조용히 넘기지 않는다 — M2가 안 실린 회차인지 사람이 바로 알아야 한다.
    //   ★ **표식이 남는 줄**(결정 호출·여럿이 돎·문만이 아닌 줄)에서만 본다 — 안 그러면 M2가 제대로
    //     실린 서버에도 매일 밤 「미반영」이라는 거짓 진단이 찍힌다(2026-09-10 검토관 적발).
    ...(줄들.some((r) => !r.팀원기록.실패 && r.팀원기록.두뇌돎 && r.팀원기록.표식주인 && r.팀원기록.표식남나 && !r.팀원기록.표식있음)
      ? ["", "⚠ **두뇌 표식이 없는 회차입니다**(서버가 답에 `brain`을 안 싣습니다 — M2 미반영).",
         "위치·폴백 판정은 건너뛰었고, 지연 상한만 배정표 기준으로 쟀습니다. 이것은 결함이 아니라 **옛 서버**입니다."]
      : []),
    // ★ 이 마당이 **어디까지 증명하는가** — 과장하지 않는다(2026-09-10 검토관 적발 ②).
    "",
    `📏 두뇌 위치를 **표식으로 확인할 수 있는 팀원 ${잴수있는팀원.length}명**(이 회차 ${순서.length}명 중) ·` +
      ` 실제로 확인된 팀원 ${순서.filter((id) => 묶음[id].위치확인).length}명` +
      (원격배정.length ? ` · 원격 배정 ${원격배정.length}명 중 확인 가능 ${원격확인가능.length}명` : ""),
    ...(못재는팀원.length
      ? [`   못 재는 팀원: ${못재는팀원.map((id) => `${id}(${못재는이유(묶음[id]) || "잴 줄 없음"})`).join(" · ")}`,
         "   → 셋 다(문만·표식 안 남는 갈래·여럿이 돎) **설계 그대로**라 빨강이 아닙니다. 다만 정의 A",
         "   (팀원마다 다른 두뇌)는 이 마당만으로 **전부 증명되지 않습니다** — chat마다 팀원 id를 싣는",
         "   표식이 생기거나, 그 팀원의 답 chat이 담당자용 답(explain)으로 나가면 그때 열립니다."]
      : []),
    ...(원격배정.length && !원격확인가능.length
      ? ["", `⚠⚠ **이 회차에서 원격 두뇌를 눈으로 확인한 문항은 0건입니다**(원격 배정 ${원격배정.length}명: ${원격배정.join(", ")}).`,
         "   표식이 남는 갈래는 총괄의 최종 답 하나뿐이고 총괄은 코드로 이 PC 고정이라, ⑲의 초록은",
         "   「그 팀원의 문으로 갔다」까지만 뜻합니다 — **「원격 두뇌가 답했다」는 아직 증명되지 않았습니다.**"]
      : []),
    ...(미배정.length
      ? ["", `⚠ **두뇌 위치가 배정되지 않은 팀원 ${미배정.length}명**(전역 따름): ${미배정.join(", ")} —` +
         " 정의 A는 「팀원마다 다른 두뇌」라, 전원 미배정이면 이 마당이 초록이어도 팀은 아직 갈라지지 않은 것입니다."]
      : []),
    "",
  ];
}
