// tools/opssim-report.mjs — 야간 회귀 보고서(ops-sim.md)의 **내용 실패 상세** 한 대목.
//
// 왜 파일을 갈랐나 (2026-09-06 · D4):
//   상세는 `.tmp-reports/ops-sim.json`에만 있었고, 사람이 읽는 `ops-sim.md`에는
//   「내용이 다름」이라는 **종류 이름**까지만 실렸다. 야간 회귀(03:00)가 끝나고 이 보고서만
//   읽는 사람은 **무엇을 기대했고 무엇이 왔는지를 볼 길이 아예 없었다** — 「경고 없는 % 단정」
//   처럼 새로 만든 잣대일수록 그렇다. 재는 규칙을 늘려 놓고 사람이 읽는 자리에 안 실으면
//   **안 만든 것과 같다**(이 저장소가 반복해 겪은 실패다).
//
// ★ 왜 ops-sim.mjs 안이 아니라 여기인가 — 그 파일은 **불러들이는 순간 하네스를 통째로 돌리는**
//   최상위 스크립트라 시험이 부를 수 없다. 같은 이유로 갈라 둔 형제가 `opssim-rules.mjs`이고,
//   그 갈래 덕분에 「경고 없는 % 단정」은 지금 시험이 문다(opssimrules.test.ts 머리글).
//   보고서 조립도 같은 처지였다 — **가짜 결과를 넣어 md를 만들어 보는 시험**이 있어야
//   상세가 빠진 채로 배포되는 일을 막는다. 사본을 두면 여기만 고쳐도 시험은 옛 잣대로 초록이다.
//
// ⚠ 여기에는 **서버도 파일도 안 건드리는 순수 조립**만 둔다(형제 파일과 같은 계약).

/** 상세를 따로 싣는 불편 종류 — 「무엇이 다른가」가 한 줄 이름으로는 안 전해지는 것들. */
export const 상세대상종류 = new Set(["내용이 다름", "기계 데이터 누출"]);

/** 기대표 한 줄을 사람 말로 편다. 없으면 「기대 미기재」 — 없는 것을 있는 척하지 않는다. */
export function 기대적기(e) {
  if (!e) return "기대 미기재(형식만 봄)";
  const 칸 = [];
  if (e.도구?.length) 칸.push(`도구 ${e.도구.join("|")}`);
  if (e.도구대신포함?.length) 칸.push(`도구 대신 인정 ${e.도구대신포함.map(String).join(" ")}`);
  if (e.포함?.length) 칸.push(`있어야 할 말 ${e.포함.map(String).join(" ")}`);
  if (e.금지?.length) 칸.push(`있으면 안 되는 말 ${e.금지.map(String).join(" ")}`);
  if (e.경고없는퍼센트금지) 칸.push("경고 없는 % 단정 금지");
  return 칸.length ? 칸.join(" · ") : "기대 미기재(형식만 봄)";
}

/** 여러 줄·표를 깨는 글자를 한 줄로 눕힌다(마크다운 본문용). */
function 한줄로(s, n) {
  return String(s ?? "").replace(/\r?\n/g, " ").replace(/\s+/g, " ").trim().slice(0, n);
}

/**
 * 내용 실패 상세 — **실패 항목마다** 문항·기대·실제 앞 120자·근거세기·근거없음을 싣는다.
 *
 * @param {Array} 결과   ops-sim의 결과 줄들({ 마당, q, out, 도구, 근거세기, 근거없음, 불편:[{종류,상세}] })
 * @param {Object} 기대표 물음 → 기대 신호({도구,포함,금지,경고없는퍼센트금지})
 * @returns {string[]} 마크다운 줄들 (실패가 없으면 「없음」 한 대목)
 */
export function 내용실패상세(결과, 기대표 = {}) {
  const 대상 = (결과 ?? []).filter((r) => (r.불편 ?? []).some((x) => 상세대상종류.has(x.종류)));
  const 머리 = [
    "## 내용 실패 상세 — 무엇을 기대했고 무엇이 왔나",
    "",
    "⚠ 위 목록의 「내용이 다름」은 **이름일 뿐**입니다. 고치려면 기대와 실제를 나란히 봐야 하고,",
    "그 짝은 예전에 `ops-sim.json`에만 있었습니다(2026-09-06 D4에서 이 대목을 여기 싣습니다).",
    "근거세기·근거없음을 함께 적는 이유: 「경고 없는 % 단정」은 **근거 장치를 하나도 안 거친 %**를",
    "가리키는 잣대라, 그 두 칸을 보지 않으면 왜 걸렸는지 알 수 없습니다.",
    "",
  ];
  if (!대상.length) return [...머리, "이번 회차에는 내용 실패가 없습니다.", ""];

  const 몸 = [];
  대상.forEach((r, i) => {
    const 사유 = (r.불편 ?? [])
      .filter((x) => 상세대상종류.has(x.종류))
      .map((x) => `${x.종류} — ${한줄로(x.상세, 300) || "(상세 없음)"}`);
    몸.push(
      `**${i + 1}. 「${한줄로(r.q, 120)}」**  · ${한줄로(r.마당, 24)}`,
      "",
      ...사유.map((s) => `- 사유: ${s}`),
      `- 기대: ${한줄로(기대적기(기대표[r.q]), 300)}`,
      // 120자 — 판정 사유를 눈으로 확인하기에 필요한 최소치다(표 칸의 70자로는 잘려 못 본다).
      `- 실제(앞 120자): ${한줄로(r.out, 120) || "(빈 답)"}`,
      `- 근거세기: ${r.근거세기 || "없음(재검색 안 돎)"} · 근거없음 표식: ${r.근거없음 || "없음"} · 부른 도구: ${(r.도구 ?? []).join(", ") || "없음"}`,
      "",
    );
  });
  return [...머리, ...몸];
}
