// tools/consistency-check.mjs — 규정 질문 상충 감지 (중-3 게이트 보강)
//
// ⚠ 왜 (2026-08-10 실측, Mac 발견): ops-sim은 각 문항 **1회**라 「통과했는데 회차마다 답이
//   정반대」를 못 본다. 「퇴사자 계정 언제까지」가 10회에 6개월/1년/2년/즉시로 갈렸는데
//   낱말 판정(개인정보|보관|삭제)이 5/5 통과했다. 담당자가 이 답으로 규정을 정하면
//   어제는 1년, 오늘은 2년이다. **핵심 수치가 회차마다 갈리면 실패**로 잡는다.
//
// ⚠ 근본은 RAG 오염(모델이 회차마다 다르게 씀)이라 ①ⓑ가 고칠 것이다. 이 검사는 그걸
//   **드러내는 잣대**다 — ①ⓑ 전후로 「상충 N건 → 몇 건」을 같은 방법으로 잰다.
//
// 사용:  QA_USER/QA_PASS 환경변수 후  node tools/consistency-check.mjs [반복수(기본 5)]
const base = "http://localhost:4000";
const N = Number(process.argv[2] ?? 5);

// 수치(기간)로 답해야 하는 규정 질문 — 회차마다 갈리면 담당자가 규정을 잘못 정한다.
// 「타대상」: 답이 덧붙이는 **남의 기간**(접속기록·근로계약 등)을 질문 대상과 섞지 않게 한다.
//   ★ 질문 대상은 타대상에 넣지 않는다 — 접속기록 질문에선 접속기록이 대상이라 2년(조건별)을 살려야 한다.
const 규정질문 = [
  { q: "퇴사자 계정 언제까지 남겨둬야 해?", 타대상: /접속\s*기록|근로\s*계약|장비\s*로그/ },
  { q: "개인정보 접속기록 몇 년 보관해야 해?", 타대상: /퇴사자|계정\s*파기|근로\s*계약|장비\s*로그/ },
  // ⚠ 「장비 로그 보관 기간」은 뺐다(2026-08-10 실측): 우리 규정 문서에 장비 로그의 법정 기간이
  //   없어 모델이 개인정보 접속기록(1년/2년)으로 답한다 — 문서에 답이 명확한 질문만 이 잣대에 둔다.
  //   (모델이 장비 로그를 개인정보 접속기록과 뭉뚱그리는 답 품질은 별개 과제로 남긴다.)
];

// 답에서 「질문 대상의 보관/삭제 기간」 값을 뽑는다. 년·개월·일 수치와 「즉시」를 모은다.
//
// ⚠ **오탐 수정 (2026-08-10, Windows).** ② 문서 보강 뒤 답이 「지체 없이 파기 · 5일 · 제21조」로
//   10회 일관인데 옛 잣대가 상충으로 찍었다 — 답 **전체**의 모든 숫자를 세어, 질문 대상(계정)이
//   아닌 것까지 섞은 탓이었다:
//     · 「6개월·1년 같은 기간은 **없다**」        ← 부정 예시(지어낸 숫자를 부정)
//     · 「다만 **접속기록은** 별도로 1년/2년」    ← 다른 대상(계정이 아니다)
//     · 「근로계약서류는 **3년**」                ← 다른 대상
//   → 문장 단위로 ① 부정문 ② **질문 대상이 아닌 다른 대상**(타대상)의 문장을 뺀다.
//
//   ★ Mac이 되돌린 실패를 피하는 자리: Mac은 「다만/별도」 문장을 통째 빼다가 **접속기록 질문의
//     조건별 2년까지** 잘라 1/3→2/3으로 악화됐다. 여기선 **질문 대상은 타대상에 없어서**
//     접속기록 질문에선 접속기록 문장(1년·2년)이 남는다. 「지체 없이」는 부정문으로 오인하지
//     않게 부정 판정을 「기간/바/규정 … 없」에 한정했다. 연도(2023년)도 값에서 제외한다.
function 기간값(text, 타대상) {
  const s = new Set();
  for (const 문장 of String(text).split(/[\n]+|(?<=[.!?])\s+/)) {
    if (!문장.trim()) continue;
    // ① 「정해진 기간 없음」류 부정 예시 제외 — 단 「지체 없이」(긍정 답)는 살린다
    if (/(기간|바|규정|근거|의무)[은이가]?\s*없|정하지\s*않|규정되?[어은지]*\s*있지\s*않|명시.{0,6}않/.test(문장)) continue;
    // ② 질문 대상이 아닌 다른 대상(접속기록·근로계약 등)의 기간 제외
    if (타대상 && 타대상.test(문장)) continue;
    for (const m of 문장.matchAll(/(\d+)\s*(년|개월|주|일)(?!\s*(이내|간|자)?\s*(전|후|째))?/g)) {
      if (m[2] === "년" && +m[1] >= 1900) continue; // 연도(2023년·2025년) 제외
      s.add(`${m[1]}${m[2]}`);
    }
    if (/즉시\s*(삭제|비활성|파기)|지체\s*없이/.test(문장)) s.add("즉시");
  }
  return [...s];
}

const l = await (await fetch(base + "/api/auth/login", { method: "POST", headers: { "Content-Type": "application/json" },
  body: JSON.stringify({ username: process.env.QA_USER, password: process.env.QA_PASS, force: true }) })).json();
// ⚠ **못 재면 통과가 아니라 실패다.** 2026-08-10에 env 이름을 틀려(QA_USER 아닌 것) 로그인이
//   실패했는데, 전 회차가 빈 답 → 기간값 0개 → 「서로 다른 답 1종」 → **「전부 일관 (통과)」**로
//   보고됐다. 아무것도 안 잰 것을 초록으로 내면 잣대가 아니라 위장이다.
if (!l.accessToken) {
  console.error("★ 로그인 실패 — QA_USER / QA_PASS 를 확인하라. 측정하지 못했으므로 통과가 아니다.");
  console.error(`   서버 응답: ${JSON.stringify(l).slice(0, 200)}`);
  process.exit(2);
}
const H = { Authorization: "Bearer " + l.accessToken, "Content-Type": "application/json" };

let 상충건수 = 0;
console.log(`규정 질문 ${규정질문.length}개 × ${N}회 상충 검사\n`);
for (const cfg of 규정질문) {
  const 회차값 = [];
  for (let i = 0; i < N; i++) {
    const j = await (await fetch(base + "/api/dispatch", { method: "POST", headers: H, body: JSON.stringify({ text: cfg.q, qa: true }), signal: AbortSignal.timeout(120000) })).json();
    회차값.push(기간값(j.output ?? "", cfg.타대상));
  }
  // ⚠ 「한 답에 여러 값」(1년/2년 조건별 구분 = 정상)과 「회차마다 값이 바뀜」(모델이 지어냄 = 상충)을
  //   가른다. 정답: 회차별 값 **집합**이 전부 같으면 일관, 하나라도 다르면 상충.
  //   (접속기록은 매번 {1년,2년}로 일관 — 조건별 구분이라 정상. 퇴사자는 회차마다 달라 상충.)
  const 정규화 = 회차값.map((v) => [...v].sort().join("|") || "—");
  const 서로다른답 = [...new Set(정규화)];
  // ⚠ 전 회차가 빈 값이면 **일관이 아니라 못 잰 것**이다. 답이 수치를 안 담았거나 호출이
  //   실패한 것이라, 「일관」으로 넘기면 잣대가 조용히 눈을 감는다.
  const 못잼 = 정규화.every((s) => s === "—");
  const 상충 = !못잼 && 서로다른답.length > 1;
  if (상충 || 못잼) 상충건수++;
  console.log(`${못잼 ? "★ 못 잼" : 상충 ? "⚠ 상충" : "✓ 일관"}  "${cfg.q}"`);
  console.log(`   회차별 기간값: ${회차값.map((v) => `{${v.join(",") || "—"}}`).join(" ")}`);
  console.log(`   서로 다른 답 ${서로다른답.length}종: ${서로다른답.map((s) => `{${s.replace(/\|/g, ",")}}`).join(" ")}`);
  if (못잼) console.log(`   ★ 어느 회차에서도 기간을 못 뽑았다 — 답이 비었거나 수치를 안 담았다. 통과가 아니다.`);
  console.log("");
}
console.log(`■ 상충 ${상충건수}/${규정질문.length}건 — ${상충건수 === 0 ? "전부 일관 (통과)" : "규정 질문이 회차마다 갈린다 (RAG 오염 ①ⓑ가 고칠 것)"}`);
process.exit(상충건수 === 0 ? 0 : 1);
