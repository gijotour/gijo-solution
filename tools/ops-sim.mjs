// 무엇이 났나: `--only`를 맨 뒤에 치거나(`node tools/ops-sim.mjs --only`) 값을 빼먹으면
//   `process.argv[i+1]`이 undefined라 고른마당이 **빈 문자열**이 된다. 그러면
//   ① 「0문항이면 마당 목록 찍고 멈춘다」 guard가 `고른마당 &&`라 안 걸리고,
//   ② 파일이름이 `ops-sim.only`가 아니라 **`ops-sim`**으로 잡혀,
//   오타 한 번에 **전 문항이 돌면서 야간 회차의 온전한 판을 덮어쓴다** — 이 파일 머리글의
//   경합 사고, 그리고 --only가 애초에 막으려던 바로 그 덮어쓰기다.
// → 값이 없거나 다음 플래그(`--`)면 **멈춘다.** 조용히 딴 일을 하지 않는다.
function 값인자(플래그, 기본값 = "") {
  const i = process.argv.indexOf(플래그);
  if (i < 0) return 기본값;
  const v = process.argv[i + 1];
  if (v === undefined || String(v).startsWith("--")) {
    console.error(`✗ ${플래그} 뒤에 값이 없습니다. 예: ${플래그} ${플래그 === "--limit" ? "5" : 플래그 === "--out" ? "ops-sim.only" : '"⑯"'}`);
    process.exit(2);
  }
  return String(v);
}
const 제한 = (() => {
  const v = 값인자("--limit");
  if (!v) return 0;
  const n = Number(v);
  if (!Number.isFinite(n) || n <= 0) { console.error(`✗ --limit 값이 숫자가 아닙니다: ${v}`); process.exit(2); }
  return n;
})();

