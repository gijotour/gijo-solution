  //   단, 감추지 않고 「리포트 전환」으로 따로 센다.
  if (r.ms > 30000 && !r.wouldHandoff) 목.push({ 종류: "너무 오래 걸림", 상세: Math.round(r.ms / 1000) + "초" });
