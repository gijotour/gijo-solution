// ── 불편 판정 ───────────────────────────────────────────────────────
const 되물음 = /무엇을 도와드릴까요/;
const 규칙누출 = /【|당신은\s.{0,20}(입니다|이다)|위\s*규칙을\s*따라/;
const 내부id = /\bid=(vuln|asset|finding|task):|[0-9a-f]{16,}/;
const 영문상태 = /"(active|pending|open|done|closed|approved|rejected)"/;
const 없음답 = /없습니다|없어요|해당(하는)?\s*(항목|건|자료)가?\s*없/;
const 부정 = /기록하지 않습니다|지원하지 않습니다|기능이 없습니다|제공하지 않습니다/;
const 갈곳 = /화면|메뉴|여기서|누르|열어|가서|＋|▸/;

function 불편찾기(q, r) {
  const o = String(r.out || "").trim();
  const 목 = [];
  if (r.err) return [{ 종류: "오류", 상세: r.err }];
  if (!o) return [{ 종류: "빈 답", 상세: "" }];
  if (되물음.test(o)) 목.push({ 종류: "못 알아들음", 상세: "되물음으로 끝남" });
  if (규칙누출.test(o)) 목.push({ 종류: "내부 규칙 노출", 상세: o.slice(0, 60) });
  if (부정.test(o)) 목.push({ 종류: "있는 기능을 없다고 함", 상세: o.slice(0, 70) });
  if (내부id.test(o)) 목.push({ 종류: "내부 식별자 노출", 상세: (o.match(내부id) || [""])[0] });
  if (영문상태.test(o)) 목.push({ 종류: "영문 상태값 노출", 상세: (o.match(영문상태) || [""])[0] });
  if (r.ms > 30000) 목.push({ 종류: "너무 오래 걸림", 상세: Math.round(r.ms / 1000) + "초" });
  if (o.length > 2000) 목.push({ 종류: "너무 긺", 상세: o.length + "자 — 읽지 않는다" });
  if (o.replace(/\s/g, "").length < 25 && !없음답.test(o)) 목.push({ 종류: "너무 짧음", 상세: o.length + "자" });
  // 숫자를 세어 주면서 갈 곳을 안 알려 주는 것 — 이 제품에서 반복된 결함
  if (/\d+\s*건/.test(o) && !갈곳.test(o) && o.length > 60) {
    목.push({ 종류: "숫자만 주고 갈 곳 없음", 상세: "화면·다음 행동 안내 없음" });
  }
  return 목;
}

async function 로그인() {
  const r = await fetch(BASE + "/api/auth/login", {
    method: "POST", headers: { "content-type": "application/json" },
    body: JSON.stringify({ username: USER, password: PASS, force: true }),
  });
  const j = await r.json();
  const t = j.accessToken || j.token;
  if (!t) throw new Error("로그인 실패: " + JSON.stringify(j).slice(0, 200));
  return t;
}

/**
 * ⚠ **응답 상태를 반드시 본다.**
 *   첫 실행(2026-08-01)에서 115상황 중 35건이 "빈 답"으로 나왔다. 제품 결함인 줄 알았는데
 *   실제로는 **접속표(access token)가 15분 만에 만료**된 것이었고, 내 하네스가 401을 그냥
 *   삼켜 `j.output`이 undefined → 빈 문자열이 됐다. 4ms 만에 돌아온 "답"을 답으로 세고 있었다.
 *   시험이 제품을 모함한 셈 — 상태 코드를 안 보면 이런 착각이 조용히 쌓인다.
 *   그래서 ① 상태를 기록하고 ② 401이면 다시 로그인해 그 문항을 재시도한다.
 */
async function 물어보기(H, text, screen, sessionId) {
  const t0 = Date.now();
  const 한번 = async () => {
    const r = await fetch(BASE + "/api/dispatch", {
      method: "POST", headers: H,
      body: JSON.stringify({ text, screen, qa: true, ...(sessionId ? { sessionId } : {}) }),
    });
    const j = await r.json().catch(() => ({}));
    return { status: r.status, j };
  };
  try {
    let { status, j } = await 한번();
    if (status === 401) {
      H.authorization = "Bearer " + (await 로그인()); // 15분 만료 — 다시 받아 이어 간다
      ({ status, j } = await 한번());
    }
    if (status !== 200) {
      return { out: "", action: "HTTP" + status, ms: Date.now() - t0, err: "HTTP " + status };
    }
    return { out: String(j.output ?? ""), action: j.route?.action ?? "?", ms: Date.now() - t0, sources: j.sources };
  } catch (e) {
    return { out: "", action: "ERROR", ms: Date.now() - t0, err: String(e).slice(0, 120) };
  }
}

