// tools/opssim-rules.mjs — **회귀 하네스의 내용 판정 규칙 가운데 「혼자서도 잴 수 있는 것」**.
//
// 왜 파일을 갈랐나 (2026-09-06 검토관 적발):
//   「경고 없는 % 단정」 규칙은 ops-sim.mjs 안에만 있었다. 그런데 ops-sim.mjs는 **불러들이는 순간
//   하네스 전체를 돌리는** 최상위 스크립트라 시험이 부를 수 없다 — 그래서 이 규칙을 무는 시험이
//   **한 개도 없었다.** 누가 판정을 고쳐도 vitest는 초록이고, 규칙이 도는 것은 실서버로 하네스를
//   돌릴 때뿐이다(하루 한 번, 03:00). 「세 번째면 소스 감시」의 계보 — 규칙만 따로 꺼내
//   **양쪽이 같은 함수를 부르게** 한다(사본 금지: 사본을 두면 여기만 고쳐도 시험은 옛 잣대로 초록이다).
//
// ⚠ 여기에는 **서버도 파일도 안 건드리는 순수 판정**만 둔다. 로그인·HTTP·파일 쓰기가 섞이면
//   시험이 다시 못 부른다(그게 애초의 병이었다).

/** 답 안에 「92%」·「16.2 퍼센트」 같은 **확정 숫자꼴**이 있는가. */
export const 퍼센트꼴 = /\d+(?:\.\d+)?\s*(?:%|퍼센트)/;

/**
 * **경고 없는 % 단정** — 도구도 안 부르고 · 근거없음 표식도 없이 · %를 확정한 답.
 *
 * 라이브 실물(2026-09-06): 「제출률은 92%입니다」 — 조각 8건에 '제출률'은 0건이었고,
 * 배너도 도구 호출도 없었다. 92는 문서에 있던 **랜섬웨어 건수**였다(숫자 관문은 「조각에 그 숫자가
 * 있나」만 보므로 원리상 통과시킨다). 지어낸 %인지는 하네스가 못 가리지만,
 * **아무 근거 장치도 안 거친 % 단정**은 가릴 수 있다.
 *
 * ⚠ 세 조건을 **모두** 봐야 한다:
 *   · 도구가 답했으면 그 %는 계산값이다(조치율 74.2%) — 벌하면 제품이 숫자를 안 내게 된다.
 *   · 근거없음 표식이 붙었으면 제품이 이미 「믿지 말라」고 말한 것이다 — 정직을 벌점으로 만들지 않는다.
 *
 * @param {string} 답        모델 답 전문
 * @param {string[]} 도구    그 턴에 실제로 부른 도구 이름들
 * @param {boolean} 근거없음 근거없음 표식(배너)이 붙었는가
 */
export function 경고없는퍼센트단정(답, 도구, 근거없음) {
  return 퍼센트꼴.test(String(답 ?? "")) && !(도구 ?? []).length && !근거없음;
}

// ── ⑯ 마당 전용 — **마케팅 조언으로 답했는가** (2026-09-06) ───────────────────
//
// 이 제품에서 클릭률·열람률·전환율은 피싱 모의훈련 지표인데, 모델이 학습한 세상에서 그 낱말의
// 주인은 웹 마케팅이다. 답이 통째로 마케팅 조언이 되어 나가는 것을 잡는다.
//
// ⚠ **대비해서 설명하는 정답을 벌주지 않는다**(2026-09-06 검토관 적발). 뜻 주입이
//   「웹 광고·마케팅의 클릭률(CTR)이 아닙니다」라고 대비해서 가르치므로, **제대로 답한 모델일수록**
//   「배너 광고·랜딩 페이지의 클릭률과는 다릅니다」처럼 그 낱말을 되풀이한다. 홑낱말로 금지하면
//   가장 정확한 답이 빨강이 된다 — 「퇴사자 계정」에서 이미 치른 값이다(정답에 든 「1년」을 금지로
//   걸었던 자리). 그래서 **대비 문장은 빼고** 남은 문장에서만 본다.
// ⚠ 이 판정을 ops-sim.mjs 안에 두면 시험이 못 부른다(그 파일은 import가 곧 실행이다).
//   실제로 옛 판은 인라인 정규식이라 **한 번도 시험된 적이 없었다** — 막은 적도 오탐도 미증명.
//   여기로 옮겨 opssimrules.test가 양쪽(정답·마케팅 답)을 다 물게 한다.
export const 마케팅조언_RE =
  /랜딩\s*페이지|\bCTA\b|배너\s*광고|광고\s*(?:문구|소재|카피|예산|단가)|타겟팅|ROAS|\bCPC\b|장바구니|이커머스|전자상거래/;

/** 대비해서 설명하는 문장인가 — 「…가 아닙니다」·「…와 다릅니다」·「혼동」 계열. */
const 대비문장_RE = /아닙니다|아니라|아니고|아닌|다릅니다|다른\s*뜻|구분|혼동|반대로/;

/** 답이 **마케팅 조언**인가(대비 설명은 빼고 본다). */
export function 마케팅조언인가(답) {
  return String(답 ?? "")
    .split(/(?<=[.!?。\n])/)               // 문장 단위로 자른다
    .filter((s) => !대비문장_RE.test(s))   // 대비해서 가르치는 문장은 판정에서 뺀다
    .some((s) => 마케팅조언_RE.test(s));
}

// ── ⑰ 마당 전용 — **사내 문답이 근거를 독점하고, 예시가 의무가 되는가** (2026-09-07) ───────
//
// 라이브 실물: 「보안 교육을 몇 번 해야 해?」 → 「…연 2회 이상 실시하고 있어야 합니다」.
// 근거 4건 중 3건이 사내 승인 문답이었고, 그 3건의 원문은 답이 아니라 **점검 질문**이었다
// (「…연 2회 이상 실시하고 있습니까?」). 숫자의 뿌리는 안내서의 **「예시: 연 2회」**다 —
// 예시 → 점검질문 → 의무 단정으로 3단 변질됐다. 지어낸 숫자가 아니라 **자리 독점**이다.
//
// ⚠ 이 셋은 **⑰ 마당에만** 건다. 다른 마당에는 「해야 합니다」가 정당하게 드는 답이 많다
//   (조치 절차·설정 안내). 전 문항에 걸면 정답을 벌준다 — ⑮⑯에서 이미 치른 값이다.

/** 사내 승인 문답 문서의 documentId 접두.
 *  ⚠ 제품 쪽 **단일 출처는 server/src/engine/docorigin.ts 의 `승인문답_접두`**다. 여기 있는 것은
 *    .mjs 도구가 TS를 못 부르기 때문에 생긴 그림자다 — memorymix.test가 **두 값이 같은지**를 문다
 *    (사본을 두고 시험을 안 두면 어긋난 줄 아무도 모른다). 고칠 일이 생기면 두 곳을 함께 고친다. */
export const 승인문답_접두_그림자 = "승인문답:";

/**
 * **사내 문답이 근거를 독점했나** — 근거(sources) 가운데 승인 문답이 **과반**인가.
 *
 * 왜 과반인가: 사내 문답이 근거에 **드는 것 자체는 정상**이다(그 물음을 사람이 승인했다).
 * 문제는 뜻이 겹치는 문답 여러 건이 자리를 채워 **다수결로 답을 뒤집는** 것이라, 한 건은
 * 통과시키고 과반을 잡는다. 자리 배분 수리(memory.문서를섞어자르기 가족 몫)의 **바깥 눈**이다 —
 * 막는 쪽과 보는 쪽을 같은 코드로 두면 같이 눈이 먼다.
 *
 * @param {string[]} sources 그 답의 근거 문서 id 목록(서버가 내려준다)
 */
export function 사내문답이근거를독점했나(sources) {
  const 목록 = Array.isArray(sources) ? sources.map((s) => String(s ?? "")) : [];
  if (목록.length === 0) return false; // 근거가 없는 답은 이 규칙이 볼 것이 아니다
  const 문답 = 목록.filter((s) => s.startsWith(승인문답_접두_그림자)).length;
  // ★★ **한 건은 언제나 통과**(2026-09-07 검토관 적발 — 위 약속과 코드가 어긋나 있었다).
  //   과반만 보면 근거가 **1건**이고 그게 승인 문답일 때 1×2 > 1 이라 true가 됐다.
  //   그런데 자리 배분 수리 뒤 topK=4의 가족 몫이 1이라 **승인 문답은 top-4에 최대 1건**이고,
  //   그 1건만 관련성 게이트를 통과하면 sources가 딱 그것 하나가 된다 — **정상 답**이다.
  //   그걸 빨강으로 만들면 하네스가 「1건 중 과반이 승인 문답」이라는 말이 안 되는 말을 한다.
  if (문답 < 2) return false;
  return 문답 * 2 > 목록.length;
}

/**
 * 규범을 **단정**하는 말투인가.
 *
 * ⚠ 2026-09-07 검토관 실측 — 옛 판은 **어미 몇 가지만** 알았다. 같은 뜻·다른 동사로 쓴
 *   「받아야 합니다」·「하여야 합니다」(법조문 어투)·「규정하고 있습니다 + 의무 사항입니다」·
 *   「과태료가 부과됩니다」가 ⓑ·ⓒ **둘 다 통과**했다. 회귀가 그 어미로 다시 나면 하네스가
 *   조용히 초록이다 — 이 파일이 스스로 「0건 초록이 가장 나쁜 거짓말」이라 적은 자리다.
 *   → 「…해/아/어/여야 합니다」를 **한 갈래로** 묶고(받아야·하여야·있어야·적어야가 한 번에 든다),
 *     규범 단정의 다른 얼굴(규정하고 있다 · 의무 사항 · 과태료)을 함께 넣는다.
 * ⚠ 「필요합니다」는 **홑으로 넣지 않는다** — 「추가 확인이 필요합니다」 같은 정직한 유보가
 *   벌점을 받는다. 「연 2회 이상**이** 필요합니다」처럼 수량·강제어에 붙은 꼴만 본다.
 * ⚠ 완전한 목록이 아니다(어미는 끝이 없다). 새 어미로 새는 것이 보이면 여기 한 곳에 더한다.
 */
/**
 * ⚠⚠ 2026-09-07 **재수리**(⑰ 배포 뒤 실측 · 오탐) — 위 갈래를 「…해/아/어/여야 합니다」로
 *   넓힌 뒤 **조언 문장이 규범 단정으로 잡혔다.** 라이브 ⑰-① 「보안 교육을 몇 번 해야 해?」의
 *   **맞는 답**이 그 자리다:
 *     「법과 기준에서 명확한 횟수를 정하고 있지 않지만 … 연 1회 이상 실시하는 것이 권고되나,
 *      … 적절한 주기를 **조정해야 합니다**.」  ← 「평가해야/조정해야」 때문에 ⓑ 빨강.
 *   이 답은 **규범을 못박지 않았다** — 오히려 「법이 횟수를 안 정한다」고 정직하게 말했다.
 *   그런 답을 벌주면 하네스가 **정직을 벌점으로 만든다**(⑯ 「퇴사자 계정」에서 이미 치른 값).
 * ★ 가르는 잣대: 「…해야 합니다」 **앞말이 무엇인가**.
 *   · 조언 동사(평가·조정·검토·점검·고려·확인·대조·활용·관리·준비·설계) → 규범 단정이 **아니다**.
 *   · 강제 동사(실시·시행·이수·수행·받) → 앞말이 무엇이든 **그대로 단정으로 센다**
 *     (사고 문장이 전부 이 계열이다: 「연 2회 이상 실시해야 합니다」·「교육을 받아야 합니다」).
 * ⚠ 정직한 대가: 「연 1회 이상 **점검해야** 합니다」처럼 조언 동사로 쓴 **진짜 규범**은 이제 안 잡힌다.
 *   그래도 이쪽을 택한 이유 — ⑰의 사고는 전부 실시·받 계열이었고, 반대쪽(정답을 빨강으로)은
 *   **하네스를 못 믿게 만들어 규칙 전체를 죽인다**. 새는 것이 보이면 강제 동사 쪽에 더한다.
 * ⚠ 잣대는 **한 곳**이다 — ⓑ·ⓒ가 같은 `규범단정인가`를 부른다(사본을 두면 한쪽만 고쳐진다).
 */
/** 앞말과 무관하게 **그 자체로** 규범을 못박는 말투. */
const 의무단정_고정_RE =
  /의무입니다|의무이며|의무화|의무\s*(?:사항|항목)(?:입니다|이다|이며)|필수입니다|반드시\s*(?:실시|시행|이수|수행|해|받)|(?:하도록|하게)\s*규정하고\s*있(?:습니다|다)|과태료가?\s*(?:부과|부여)|(?:이상|반드시)\s*(?:이|가)?\s*필요합니다/;

/** 「…해/아/어/여야 합니다」를 **앞말과 함께** 훑는다.
 *  ⚠ 앞말 자리에 강조 표식(`**`)을 허용한다 — 「위험 **평가**해야 합니다」에서 `**`가 앞말을
 *    끊어 버리면 조언인데도 단정으로 세게 된다(같은 파일이 이미 두 번 밟은 함정).
 *  ⚠ 정규식 객체를 돌려쓰지 않는다(`/g`의 lastIndex가 남아 **두 번째 호출이 딴 답을 낸다**).
 *    부를 때마다 새로 만든다 — 짝 시험이 「두 번 불러도 같은 답」을 문다. */
const 해야합니다_SRC = String.raw`((?:[가-힣]|\*|_){0,10}?)(?:해|아|어|여)야\s*(?:합니다|한다)`;
/** 조언 동사 — 「…해야 합니다」가 붙어도 규범을 **못박은 것이 아니다**. */
const 조언동사_RE = /평가|조정|검토|점검|고려|확인|대조|활용|관리|준비|설계/;
/** 강제 동사 — 조언 동사가 섞여 있어도 **그대로 단정**이다(사고 문장의 계열). */
const 강제동사_RE = /실시|시행|이수|수행|받/;

/** 규범을 **단정**했는가 — ⓑ·ⓒ가 함께 쓰는 단일 잣대. */
export function 규범단정인가(답) {
  const o = String(답 ?? "");
  if (의무단정_고정_RE.test(o)) return true;
  for (const m of o.matchAll(new RegExp(해야합니다_SRC, "g"))) {
    const 앞말 = m[1] ?? "";
    if (강제동사_RE.test(앞말)) return true;   // 실시·받 계열은 앞말이 무엇이든 단정
    if (조언동사_RE.test(앞말)) continue;      // 평가·조정 계열은 조언 — 세지 않는다
    return true;
  }
  return false;
}
/**
 * 근거 **이름**을 댔는가 — 법·령·고시·기준·조문·인증기준.
 *
 * ⚠ 2026-09-07 검토관 적발 — 「안내서」·「해설서」·「가이드라인」·「내부 관리계획」을 **홑낱말로**
 *   두었더니, 「관련 안내서를 참고하시기 바랍니다」 한 줄만 붙여도 무근거 의무 단정이 통과했다.
 *   LLM이 상투적으로 붙이는 맺음말이 판정을 통째로 끄는 꼴이다. 게다가 「내부 관리계획」은
 *   아래 연2회조건_RE에도 들어 있어 **한 낱말이 두 판정을 동시에 껐다**.
 *   → 홑낱말을 뺀다. 사고의 그 안내서를 **제대로 인용하면** 이름 안에 「안전성 확보조치」가
 *     들어 있어 여전히 통과한다(정답을 벌주지 않는다는 원칙은 그대로).
 *     펴내는 **기관 이름**(개인정보보호위원회·KISA…)도 인용으로 친다 — 그건 홑낱말이 아니다.
 * ⚠ 남는 대가를 **정직하게 적는다**: 이제 「내부 관리계획에 횟수를 명기해야 합니다」처럼
 *   **맞는 말인데 법 이름을 하나도 안 댄 답**도 걸린다. 그 자리가 바로 담당자가 근거 없이
 *   공지로 옮기는 자리라 걸리는 쪽을 택했다 — ⑰은 **법·기준 물음 마당**이고, 포함 기대가
 *   이미 「연 1회/횟수 규정」을 요구하므로 근거 이름을 함께 요구하는 것이 과하지 않다.
 */
const 근거이름_RE = /개인정보\s*보호법|정보통신망법|전자금융|신용정보법|시행령|시행규칙|고시|안전성\s*확보조치|ISMS|ISO\s*27001|제\s*\d+\s*조|개인정보보호위원회|KISA|한국인터넷진흥원|금융보안원/;

/**
 * **근거 없는 의무 단정** — 「…해야 합니다/의무입니다」로 규범을 못박으면서 법·고시·기준 이름을
 * 하나도 안 댄 답. 담당자는 이 문장을 그대로 사내 공지에 옮긴다 — 근거 없이 옮기면 그 공지가 틀린다.
 */
export function 근거없는의무단정인가(답) {
  const o = String(답 ?? "");
  return 규범단정인가(o) && !근거이름_RE.test(o);
}

/**
 * 「연 2회」에 붙어야 할 **조건**(그 숫자가 예시이거나 특정 대상에만 걸린다는 단서).
 *
 * ⚠ 2026-09-07 검토관 적발 — 「내부 관리계획」·「별도」를 조건으로 세었더니
 *   「**내부 관리계획에 따라** 개인정보보호 보안 교육을 연 2회 이상 실시해야 합니다」가
 *   ⓑ·ⓒ 둘 다 통과했다. 사고 문장을 **낱말 하나만 바꾼 재진술**인데 바깥 눈이 감은 것이다.
 *   내부 관리계획은 **회사가 스스로 적는 문서**라 「연 2회가 의무다」의 근거도, 조건도 아니다
 *   (안내서의 연 2회는 「고유식별정보 취급자」라는 **대상**에 걸린 예시다 — 대상이 조건이다).
 *   → 뺀다. 대상·예시·권고를 밝힌 답은 그대로 통과한다.
 */
const 연2회조건_RE = /예\s*시|예를\s*들어|고유식별정보|권장|권고|경우에\s*따라|기관(?:이나|에)\s*따라|사업자에\s*따라|자율/;

/**
 * **조건 없는 「연 2회」 의무 단정** — 라이브에서 실제로 샌 그 문장.
 *
 * 원문(개인정보 안전성 확보조치 기준 안내서 2024)은 **연 1회 이상**이 기본이고, 연 2회는
 * 「고유식별정보가 저장된 DB 서버에 접근 가능한 자」에 대해 내부 관리계획에 적을 수 있는
 * **예시**다. 조건을 떼고 「연 2회 이상 해야 합니다」로 나가면 없는 의무를 만든 것이다.
 *
 * ⚠ 「연 2회」 자체를 금지하지 않는다 — 조건을 밝히고 쓰면 그것이 정답이다(안내서에 실재한다).
 *   정답에 든 낱말을 홑으로 금지하면 **가장 정확한 답이 빨강**이 된다(⑯에서 치른 값).
 */
export function 조건없는연2회의무인가(답) {
  const o = String(답 ?? "");
  return /연\s*2\s*회/.test(o) && 규범단정인가(o) && !연2회조건_RE.test(o);
}

// ── ⑰ 마당 — **「의무가 아니다」를 답이 실제로 말했는가** (2026-09-07 하네스 오탐 수리) ──────
//
// 실측(야간 회귀 2026-09-07 03:04 · 「피싱 모의훈련은 의무야?」):
//   답 「피싱 모의훈련은 **법률적 의무**는 아니지만, … **추천 사항**으로 자리 잡고 있습니다.」
//   → **정답이다.** 그런데 하네스는 「있어야 할 말 없음」으로 빨강을 냈다.
//   옛 식 `/의무가?\s*아니|권장|권고|법(?:적)?\s*의무는?\s*(?:아니|없)/` 이 못 읽은 세 가지:
//     ① 조사 「는」 — 「의무가?」는 주격 조사만 알아서 **「의무는 아니」**를 못 봤다.
//     ② 「법률적」 — 「법(?:적)?」이라 「법률적 의무」를 못 봤다(첫 갈래로 잡히지도 않았다).
//     ③ 「추천 사항」 — 권장·권고의 흔한 동의어인데 목록에 없었다.
// ⚠ **강조 표식(**)은 원인이 아니었다**(2026-09-07 실측으로 걸렀다): 172답의 포함·금지 판정을
//   강조를 걷은 사본으로 다시 매겨 보니 **바뀌는 자리가 0곳**이었다. 「마크다운이 정규식을 깼다」는
//   그럴듯한 짐작이었고 재 보니 아니었다 — 짐작으로 고쳤으면 진짜 원인이 그대로 남았다.
// ⚠ 정직한 한계: 「의무는 아니라고 볼 수 없다」 같은 겹부정은 이 식이 통과시킨다. 글자 판정의
//   한계이고 옛 식도 같았다 — 새로 여는 구멍이 아니다.
// ⚠⚠ **「아닙니다」에는 「아니」가 없다**(2026-09-07, 이 수리를 쓰다가 짝 시험이 잡았다).
//   한글은 낱자가 아니라 **음절 덩이**로 저장된다 — 「아닙니다」는 아·닙·니·다라서 「아니」가
//   부분문자열이 아니다(「아니지만」은 아·니·지·만이라 든다). 그래서 「법적 의무가 아닙니다」가
//   식에 안 걸렸다. 옛 식도 같은 구멍이었고, 권장·권고가 우연히 가려 주고 있었을 뿐이다.
//   → 어미를 함께 적는다(아니·아닙·아님). **홑 「아」로 줄이지 말 것** — 「아직」·「아마」가 든다.
// ⚠⚠ **강조 표식이 낱말과 조사 사이에 낀다**(2026-09-07 재수리 실측). 그날 통과한 실물은
//   「**법률적 의무**는 아니지만」이라 「의무」와 「는」 사이에 `**`가 있다 — 부정 갈래는
//   **여전히 안 걸렸고**, 답이 초록이 된 것은 오직 「추천 사항」 덕이었다. 「조사를 더했으니
//   부정을 읽는다」는 말은 그래서 그때 참이 아니었다. → 강조 표식을 사이에 허용한다.
//   (⚠ 이것은 앞 커밋이 「마크다운은 원인이 아니었다」고 잰 것과 어긋나지 않는다: 그 실측은
//    **172답의 판정이 바뀌는가**를 잰 것이고, 여기는 **어느 갈래로 통과했나**를 잰 것이다.)
const 강조 = String.raw`(?:\*\*|__|\*|_)?`;
/** 「의무가 아니다」를 **직접** 말했는가 — 아래 두 곳이 이 하나를 함께 쓴다(단일 출처). */
export const 의무부정_RE = new RegExp(
  String.raw`의무${강조}(?:가|는|은|이|도)?\s*(?:아(?:니|닙|님)|없)` +
  String.raw`|강제${강조}(?:가|는|사항)?\s*(?:은|는|이)?\s*아(?:니|닙|님)`,
);
export const 의무아님_RE = new RegExp(
  의무부정_RE.source + String.raw`|권장|권고|추천\s*사항|자율(?:적|에\s*맡)`,
);

/**
 * **의무라고 못박았는가** — 「…는 의무입니다/의무이며/의무화되어 있습니다」.
 *
 * ★ 왜 따로 두나(2026-09-07 재수리 · 검토관 적발): 위 식에 「추천 사항」·「자율」을 더하면서
 *   **틀린 답 하나가 초록이 됐다** — 「피싱 모의훈련은 의무이며 추천 사항으로도 널리 쓰입니다」.
 *   ⑰ 「피싱 모의훈련은 의무야?」의 기대는 포함 하나가 유일한 잣대라, 뒷말에 「추천 사항」만
 *   붙으면 앞말이 무엇이든 통과한다. **동의어를 넓힐수록 이 구멍이 커진다.**
 * ⚠ 부정을 함께 말한 답은 안 잡는다 — 「피싱 모의훈련은 의무가 아니지만 정보보호 교육은
 *   의무입니다」는 **맞는 답**이고, 그것까지 빨강으로 만들면 이번에 고친 오탐을 새로 만드는 꼴이다.
 * ⚠ 여전히 못 잡는 것: 「의무는 아니라고 볼 수 없다」 같은 겹부정(글자 판정의 한계 — 옛 식도 같다).
 *
 * ⚠⚠ 2026-09-07 **재수리**(⑰ 배포 뒤 실측 — 거짓 초록) — 이 식은 「의무 **사항**」만 알고
 *   「의무 **항목**」을 몰랐다. 배포 16 뒤 실물이 정확히 그 낱말로 샜다:
 *     「피싱 모의훈련은 법과 인증 기준이 요구하는 **의무 항목입니다**.」 ← 틀린 답인데 **초록**.
 *   뒤에 「권장합니다」가 붙어 포함(의무아님_RE)은 통과했고, 못박음은 낱말 하나 차이로 빗나갔다.
 *   **동의어 한 낱말이 판정을 통째로 끈다** — 이 파일이 「추천 사항」에서 이미 겪은 일이다.
 *   → 「사항|항목」을 한 갈래로 묶고 「의무로 규정/명시」까지 넣는다.
 * ⚠ 부정 검사를 **문장 단위로도** 본다. 「…의무로 규정되어 있지 **않습니다**」는 맞는 답인데,
 *   답 전체를 보는 의무부정_RE(「의무가 아니다」)로는 안 걸러진다 — 그 문장 안의 부정을 봐야 한다.
 */
const 의무못박음_RE = new RegExp(
  String.raw`의무${강조}(?:입니다|이며|이고|이다|입니까)` +
  String.raw`|의무화${강조}(?:되어|가|를)?\s*(?:있|되|한|함)` +
  // ★ 「의무 사항」과 「의무 항목」은 같은 말이다(2026-09-07 실물이 뒤쪽으로 샜다).
  String.raw`|의무${강조}\s*${강조}(?:사항|항목)${강조}(?:입니다|이며|이고|이다)` +
  String.raw`|의무${강조}로\s*(?:규정|정하|정해|명시)`,
);
/** 같은 문장 안에서 부정을 함께 말했는가 — 「아니/아닙/아님/없/않」. */
const 못박음부정_RE = /아(?:니|닙|님)|없|않/;
export function 의무라고못박았나(답) {
  const o = String(답 ?? "");
  if (의무부정_RE.test(o)) return false; // 답 어디서든 「의무가 아니다」를 직접 말했으면 못박은 것이 아니다
  return o
    .split(/(?<=[.!?。\n])/)
    .some((s) => 의무못박음_RE.test(s) && !못박음부정_RE.test(s));
}

