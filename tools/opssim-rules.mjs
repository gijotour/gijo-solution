// tools/opssim-rules.mjs — **회귀 하네스의 내용 판정 규칙 가운데 「혼자서도 잴 수 있는 것」**.
//
// 왜 파일을 갈랐나 (2026-09-06 검토관 적발):
//   「경고 없는 % 단정」 규칙은 ops-sim.mjs 안에만 있었다. 그런데 ops-sim.mjs는 **불러들이는 순간
//   하네스 전체를 돌리는** 최상위 스크립트라 시험이 부를 수 없다 — 그래서 이 규칙을 무는 시험이
//   **한 개도 없었다.** 누가 판정을 고쳐도 vitest는 초록이고, 규칙이 도는 것은 실서버로 하네스를
//   돌릴 때뿐이다(하루 한 번, 03:00). 「세 번째면 소스 감시」의 계보 — 규칙만 따로 꺼내
//   **양쪽이 같은 함수를 부르게** 한다(사본 금지: 사본을 두면 여기만 고쳐도 시험은 옛 잣대로 초록이다).
//
// ⚠ 여기에는 **서버도 파일도 안 건드리는 순수 판정**만 둔다. 로그인·HTTP·파일 쓰기가 섞이면
//   시험이 다시 못 부른다(그게 애초의 병이었다).

/** 답 안에 「92%」·「16.2 퍼센트」 같은 **확정 숫자꼴**이 있는가. */
export const 퍼센트꼴 = /\d+(?:\.\d+)?\s*(?:%|퍼센트)/;

/**
 * **경고 없는 % 단정** — 도구도 안 부르고 · 근거없음 표식도 없이 · %를 확정한 답.
 *
 * 라이브 실물(2026-09-06): 「제출률은 92%입니다」 — 조각 8건에 '제출률'은 0건이었고,
 * 배너도 도구 호출도 없었다. 92는 문서에 있던 **랜섬웨어 건수**였다(숫자 관문은 「조각에 그 숫자가
 * 있나」만 보므로 원리상 통과시킨다). 지어낸 %인지는 하네스가 못 가리지만,
 * **아무 근거 장치도 안 거친 % 단정**은 가릴 수 있다.
 *
 * ⚠ 세 조건을 **모두** 봐야 한다:
 *   · 도구가 답했으면 그 %는 계산값이다(조치율 74.2%) — 벌하면 제품이 숫자를 안 내게 된다.
 *   · 근거없음 표식이 붙었으면 제품이 이미 「믿지 말라」고 말한 것이다 — 정직을 벌점으로 만들지 않는다.
 *
 * @param {string} 답        모델 답 전문
 * @param {string[]} 도구    그 턴에 실제로 부른 도구 이름들
 * @param {boolean} 근거없음 근거없음 표식(배너)이 붙었는가
 */
export function 경고없는퍼센트단정(답, 도구, 근거없음) {
  return 퍼센트꼴.test(String(답 ?? "")) && !(도구 ?? []).length && !근거없음;
}

// ── ⑯ 마당 전용 — **마케팅 조언으로 답했는가** (2026-09-06) ───────────────────
//
// 이 제품에서 클릭률·열람률·전환율은 피싱 모의훈련 지표인데, 모델이 학습한 세상에서 그 낱말의
// 주인은 웹 마케팅이다. 답이 통째로 마케팅 조언이 되어 나가는 것을 잡는다.
//
// ⚠ **대비해서 설명하는 정답을 벌주지 않는다**(2026-09-06 검토관 적발). 뜻 주입이
//   「웹 광고·마케팅의 클릭률(CTR)이 아닙니다」라고 대비해서 가르치므로, **제대로 답한 모델일수록**
//   「배너 광고·랜딩 페이지의 클릭률과는 다릅니다」처럼 그 낱말을 되풀이한다. 홑낱말로 금지하면
//   가장 정확한 답이 빨강이 된다 — 「퇴사자 계정」에서 이미 치른 값이다(정답에 든 「1년」을 금지로
//   걸었던 자리). 그래서 **대비 문장은 빼고** 남은 문장에서만 본다.
// ⚠ 이 판정을 ops-sim.mjs 안에 두면 시험이 못 부른다(그 파일은 import가 곧 실행이다).
//   실제로 옛 판은 인라인 정규식이라 **한 번도 시험된 적이 없었다** — 막은 적도 오탐도 미증명.
//   여기로 옮겨 opssimrules.test가 양쪽(정답·마케팅 답)을 다 물게 한다.
export const 마케팅조언_RE =
  /랜딩\s*페이지|\bCTA\b|배너\s*광고|광고\s*(?:문구|소재|카피|예산|단가)|타겟팅|ROAS|\bCPC\b|장바구니|이커머스|전자상거래/;

/** 대비해서 설명하는 문장인가 — 「…가 아닙니다」·「…와 다릅니다」·「혼동」 계열. */
const 대비문장_RE = /아닙니다|아니라|아니고|아닌|다릅니다|다른\s*뜻|구분|혼동|반대로/;

/** 답이 **마케팅 조언**인가(대비 설명은 빼고 본다). */
export function 마케팅조언인가(답) {
  return String(답 ?? "")
    .split(/(?<=[.!?。\n])/)               // 문장 단위로 자른다
    .filter((s) => !대비문장_RE.test(s))   // 대비해서 가르치는 문장은 판정에서 뺀다
    .some((s) => 마케팅조언_RE.test(s));
}

// ── ⑰ 마당 전용 — **사내 문답이 근거를 독점하고, 예시가 의무가 되는가** (2026-09-07) ───────
//
// 라이브 실물: 「보안 교육을 몇 번 해야 해?」 → 「…연 2회 이상 실시하고 있어야 합니다」.
// 근거 4건 중 3건이 사내 승인 문답이었고, 그 3건의 원문은 답이 아니라 **점검 질문**이었다
// (「…연 2회 이상 실시하고 있습니까?」). 숫자의 뿌리는 안내서의 **「예시: 연 2회」**다 —
// 예시 → 점검질문 → 의무 단정으로 3단 변질됐다. 지어낸 숫자가 아니라 **자리 독점**이다.
//
// ⚠ 이 셋은 **⑰ 마당에만** 건다. 다른 마당에는 「해야 합니다」가 정당하게 드는 답이 많다
//   (조치 절차·설정 안내). 전 문항에 걸면 정답을 벌준다 — ⑮⑯에서 이미 치른 값이다.

/** 사내 승인 문답 문서의 documentId 접두.
 *  ⚠ 제품 쪽 **단일 출처는 server/src/engine/docorigin.ts 의 `승인문답_접두`**다. 여기 있는 것은
 *    .mjs 도구가 TS를 못 부르기 때문에 생긴 그림자다 — memorymix.test가 **두 값이 같은지**를 문다
 *    (사본을 두고 시험을 안 두면 어긋난 줄 아무도 모른다). 고칠 일이 생기면 두 곳을 함께 고친다. */
export const 승인문답_접두_그림자 = "승인문답:";

/**
 * **사내 문답이 근거를 독점했나** — 근거(sources) 가운데 승인 문답이 **과반**인가.
 *
 * 왜 과반인가: 사내 문답이 근거에 **드는 것 자체는 정상**이다(그 물음을 사람이 승인했다).
 * 문제는 뜻이 겹치는 문답 여러 건이 자리를 채워 **다수결로 답을 뒤집는** 것이라, 한 건은
 * 통과시키고 과반을 잡는다. 자리 배분 수리(memory.문서를섞어자르기 가족 몫)의 **바깥 눈**이다 —
 * 막는 쪽과 보는 쪽을 같은 코드로 두면 같이 눈이 먼다.
 *
 * @param {string[]} sources 그 답의 근거 문서 id 목록(서버가 내려준다)
 */
export function 사내문답이근거를독점했나(sources) {
  const 목록 = Array.isArray(sources) ? sources.map((s) => String(s ?? "")) : [];
  if (목록.length === 0) return false; // 근거가 없는 답은 이 규칙이 볼 것이 아니다
  const 문답 = 목록.filter((s) => s.startsWith(승인문답_접두_그림자)).length;
  return 문답 * 2 > 목록.length;
}

/** 규범을 **단정**하는 말투인가. */
const 의무단정_RE = /의무입니다|의무이며|의무화|필수입니다|반드시\s*(?:실시|시행|이수|수행)|(?:실시|시행|이수|수행)하?(?:고\s*있어)?야\s*합니다|해야\s*합니다/;
/** 근거 **이름**을 댔는가 — 법·령·고시·기준·조문·인증기준. */
const 근거이름_RE = /개인정보\s*보호법|정보통신망법|전자금융|신용정보법|시행령|시행규칙|고시|안전성\s*확보조치|내부\s*관리계획|ISMS|ISO\s*27001|안내서|해설서|제\s*\d+\s*조|가이드라인/;

/**
 * **근거 없는 의무 단정** — 「…해야 합니다/의무입니다」로 규범을 못박으면서 법·고시·기준 이름을
 * 하나도 안 댄 답. 담당자는 이 문장을 그대로 사내 공지에 옮긴다 — 근거 없이 옮기면 그 공지가 틀린다.
 */
export function 근거없는의무단정인가(답) {
  const o = String(답 ?? "");
  return 의무단정_RE.test(o) && !근거이름_RE.test(o);
}

/** 「연 2회」에 붙어야 할 **조건**(그 숫자가 예시이거나 특정 대상에만 걸린다는 단서). */
const 연2회조건_RE = /예\s*시|예를\s*들어|고유식별정보|별도|내부\s*관리계획|권장|권고|경우에\s*따라|기관(?:이나|에)\s*따라|사업자에\s*따라|자율/;

/**
 * **조건 없는 「연 2회」 의무 단정** — 라이브에서 실제로 샌 그 문장.
 *
 * 원문(개인정보 안전성 확보조치 기준 안내서 2024)은 **연 1회 이상**이 기본이고, 연 2회는
 * 「고유식별정보가 저장된 DB 서버에 접근 가능한 자」에 대해 내부 관리계획에 적을 수 있는
 * **예시**다. 조건을 떼고 「연 2회 이상 해야 합니다」로 나가면 없는 의무를 만든 것이다.
 *
 * ⚠ 「연 2회」 자체를 금지하지 않는다 — 조건을 밝히고 쓰면 그것이 정답이다(안내서에 실재한다).
 *   정답에 든 낱말을 홑으로 금지하면 **가장 정확한 답이 빨강**이 된다(⑯에서 치른 값).
 */
export function 조건없는연2회의무인가(답) {
  const o = String(답 ?? "");
  return /연\s*2\s*회/.test(o) && 의무단정_RE.test(o) && !연2회조건_RE.test(o);
}
