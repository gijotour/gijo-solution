/**
 * 프로필 이름 → 정의. 이름이 비면(기본 4000) **null** — 데이터 의존을 아무것도 안 거른다.
 * 모르는 이름이면 예외를 던진다(호출부가 `--profile` 오타를 조용히 삼키지 않게).
 */
export function 프로필가져오기(이름) {
  if (!이름) return null;
  const p = 프로필들[이름];
  if (!p) throw new Error(`없는 프로필: "${이름}" (있는 프로필: ${Object.keys(프로필들).join(", ") || "(없음)"})`);
  return p;
}

/**
 * 이 문항을 이번 회차에 **건너뛰나** — 표식이 요구하는 것을 프로필/감지된 설정이 못 주면 사유 라벨을,
 * 아니면 null을 돌려준다. 사유 라벨은 **표식표의 「의존」 문자열 그대로**다(라벨이 곧 보고서 그룹 키).
 *
 * @param {string} q 물음(마당의 글자와 하나까지 같아야 표식이 걸린다)
 * @param {object|null} 프로필 프로필가져오기()의 결과 — null이면 데이터 의존은 절대 안 거른다(기본 4000)
 * @param {{법령?: boolean|null, CTI?: boolean|null, 원격두뇌?: boolean|null}} 감지된설정
 *   null = 못 읽음(모름) — 「꺼짐」으로 단정하지 않는다(멀쩡한 문항을 건너뛰지 않는다).
 */
export function 건너뜀사유(q, 프로필, 감지된설정 = {}) {
  const 표 = 표식표[q];
  if (!표) return null;
  for (const 의존 of 표.의존) {
    // 설정 의존 — 프로필과 무관하게 **항상** 본다(꺼진 기계용 안전망은 이름 없는 4000도 지킨다).
    if (의존 === "설정:법령" && 감지된설정.법령 === false) return "설정:법령";
    if (의존 === "설정:CTI" && 감지된설정.CTI === false) return "설정:CTI";
    if (의존 === "설정:원격두뇌" && 감지된설정.원격두뇌 === false) return "설정:원격두뇌";
    // 데이터 의존 — 프로필이 없으면(기본 4000) 절대 안 거른다.
    if (!프로필) continue;
    if (의존 === "데이터:업무" && !프로필.업무데이터) return "데이터:업무";
    if (의존 === "데이터:씨앗문서" && !프로필.씨앗문서) return "데이터:씨앗문서";
  }
  return null;
}

/**
 * 「제품 계약 부분집합」 — 의존 표식이 **하나도 없는** 문항만 남긴다.
 * ⚠ 지금은 표식표에 16개만 적혀 있어 205-16=189가 나온다(174가 아니다) — 그건 결함이 아니라
 *   **범위**다: ③ 내장판(경계 ①~⑧, 설계관 지시서 embed_path)은 이번 라운드 구현 대상이 아니다.
 *   나머지 회색 지대 15개(위 표식표 머리말)까지 판정하는 일은 ③ 착수 때 할 일이고, 그때 이
 *   함수는 안 바뀐다 — 표식표가 늘면 이 함수의 답이 저절로 좁아진다(단일 출처).
 *
 * @param {Array<string|{q: string}>} 문항목록 문자열 배열 또는 {q,...} 객체 배열
 */
export function 계약부분집합(문항목록) {
  return (문항목록 ?? []).filter((x) => !의존적힌문항인가(typeof x === "string" ? x : x?.q));
}

// ── 설정 자동 감지 ───────────────────────────────────────────────────────────
// ⚠ 이 회차에 실제로 걸려 있는 값을 **회차마다** 읽는다 — 배정표·전역원격(ops-sim.mjs 876-888행)과
//   같은 계약이다: 못 읽으면 null(모름)로 두고, 감지 결과는 meta에 그대로 남긴다.
// ⚠ fetchImpl을 인자로 받는다 — 시험이 실 서버(4000·4100) 없이 이 함수를 부를 수 있어야 한다
//   (직렬 자원 금지 — 시험이 운영 포트를 두드리면 안 된다).
export async function 설정감지(BASE, authHeader, fetchImpl = fetch) {
  const 결과 = { 법령: null, CTI: null };
  try {
    const r = await fetchImpl(BASE + "/api/law/config", { headers: { authorization: authHeader } });
    결과.법령 = r.ok ? !!(await r.json())?.enabled : null;
  } catch { /* 못 읽음 — 모름으로 둔다 */ }
  try {
    const r = await fetchImpl(BASE + "/api/cti/feeds", { headers: { authorization: authHeader } });
    if (r.ok) {
      const j = await r.json();
      결과.CTI = Array.isArray(j) ? j.some((f) => f && f.connected === true) : null;
    }
  } catch { /* 못 읽음 — 모름으로 둔다 */ }
  return 결과;
}

// ── 집계 — 「잰 것」과 「건너뛴 것」을 가른다(확정안 ② 통과율 분모 = 잰 것만) ───────────────────
// ⚠ ops-sim.mjs의 보고 조립이 **이 함수 하나만** 부른다 — 사본을 두면 md·meta·console이 어긋난다.
//   건너뛴 줄은 결과 배열에서 빼지 않는다(호출부 계약) — 이 함수는 **가르기만** 한다.
//
// @param {Array<{마당:string, q:string, 불편:Array, 건너뜀?:string}>} 결과
export function 집계(결과) {
  const 목록 = 결과 ?? [];
  const 건너뜀행 = 목록.filter((r) => r && r.건너뜀);
  const 잰결과 = 목록.filter((r) => !(r && r.건너뜀));
  const 불편건 = 잰결과.filter((r) => (r.불편 ?? []).length);
  const 건너뜀사유별 = {};
  for (const r of 건너뜀행) 건너뜀사유별[r.건너뜀] = (건너뜀사유별[r.건너뜀] ?? 0) + 1;
  const 마당별 = {};
  for (const r of 목록) {
    마당별[r.마당] ??= { 전체: 0, 불편: 0, 건너뜀: 0 };
    마당별[r.마당].전체++;
    if (r.건너뜀) 마당별[r.마당].건너뜀++;
    else if ((r.불편 ?? []).length) 마당별[r.마당].불편++;
  }
  return { 건너뜀행, 잰결과, 불편건, 건너뜀사유별, 마당별 };
}

