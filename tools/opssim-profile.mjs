/**
 * 이 회차의 「영발화」 보고 줄들 — 건너뛴 행은 빼고(잰 것만), 그 문항 자체를 안 물은 회차
 * (--only 등)는 조용히 지나간다(적을 것이 없다는 뜻이지 0건 발화가 아니다).
 */
export function 영발화보고(결과) {
  const 목록 = 결과 ?? [];
  const 줄 = [];
  for (const 정의 of Object.values(영발화대상)) {
    const 대상행 = 목록.filter((r) => r && !r.건너뜀 && 정의.문항.includes(r.q));
    if (!대상행.length) continue;
    const 최대값 = Math.max(0, ...대상행.map((r) => 정의.잰다(r)));
    if (최대값 < 정의.문턱) 줄.push(정의.표시(대상행.length));
  }
  return 줄;
}
