// 대화창에 들어온 말이 **LLM까지 갈 값어치가 있는가** — 가기 전에 거르는 규칙들.
//
// LLM은 한 번에 수십 초를 쓴다. 뜻 없는 입력·한 낱말 입력을 그대로 보내면
// 담당자는 아무것도 못 얻고 30초를 기다린다(실측). 보내기 전에 되묻는 편이 빠르고 정직하다.
import { describe, it, expect } from "vitest";
import { isTooVague, 한낱말되묻기 } from "../src/engine/scopeguard";

describe("★ 한 낱말만 던졌을 때 (2026-08-01 하루 실전 ⑪마당)", () => {
  // 담당자는 "취약점", "급한거", "방화벽"처럼 한 낱말만 치는 일이 흔하다.
  // 뜻 없는 입력이 아니라서 LLM으로 갔고 **34초를 헤매다 내부 규칙 이야기**를 내놨다.
  it("그 낱말에 맞는 예시로 되묻는다", () => {
    const r = 한낱말되묻기("취약점");
    expect(r).toContain("미조치 취약점 알려줘");
    expect(한낱말되묻기("급한거")).toContain("오늘 뭐부터 볼까?");
    expect(한낱말되묻기("방화벽")).toContain("월간 정기점검");
  });

  it("★ 대신 답해 주지 않는다 — 무엇을 원하는지 알 수 없다", () => {
    // "취약점"이 목록인지 설명인지 알 수 없다. 추측해 답하면 틀렸을 때 더 헤맨다.
    const r = 한낱말되묻기("취약점") ?? "";
    expect(r, "숫자를 세어 주면 추측한 것이다").not.toMatch(/\d+\s*건/);
  });

  it("문장으로 물으면 비켜선다 — 진짜 질문을 가로채면 안 된다", () => {
    expect(한낱말되묻기("미조치 취약점 알려줘")).toBeNull();
    expect(한낱말되묻기("방화벽 뭐 쓰고 있어?")).toBeNull();
    expect(한낱말되묻기("오늘 뭐부터 볼까?")).toBeNull();
  });
});
