// ★★ ⑰ 근거가 답을 이끈다 (2026-09-07 라이브 사고 뒤 신설)
//
// 실물: 「보안 교육을 몇 번 해야 해?」 → 「…연 2회 이상 실시하고 있어야 합니다」.
//   근거 4건 중 3건이 **사내 승인 문답**이고, 그 3건의 원문은 답이 아니라 **점검 질문**이었다.
//   숫자의 뿌리는 안내서의 **「예시: 연 2회」** — 예시 → 점검질문 → 의무 단정으로 3단 변질.
//   ⚠ ⑮(경고 없는 % 단정)는 원리상 못 본다 — 이 답에는 **%가 없다**(「연 2회」는 횟수다).
describe("★★ ⑰ 사내 문답이 근거를 독점했나 — 자리 배분 수리의 **바깥 눈**", () => {
  it("★ 라이브 실물 구성(4건 중 3건이 승인 문답)이 걸린다", () => {
    expect(사내문답이근거를독점했나([
      "GIJO_지식_보안인식교육.md", "승인문답:dtmtljmeoejfjk6d",
      "승인문답:dtmtl3i5edcunqrw", "승인문답:dtmtlfr7ku2xhezz",
    ])).toBe(true);
  });

  it("★★ 사내 문답이 **드는 것 자체는 정상**이다 — 한 건은 통과시킨다", () => {
    // 사람이 승인한 문답이 근거로 서는 것이 이 기능의 목적이다. 잡는 것은 **다수결로 답을
    // 뒤집는 구성**뿐이라, 과반이 아니면 안 걸린다(가족 몫도 하한 1을 남긴다 — 같은 정신).
    expect(사내문답이근거를독점했나(["a.md", "b.md", "승인문답:x1"])).toBe(false);
    expect(사내문답이근거를독점했나(["a.md", "승인문답:x1"])).toBe(false); // 딱 절반은 과반이 아니다
  });

  it("근거가 아예 없으면 이 규칙이 볼 것이 아니다(그건 「근거없음」이 따로 센다)", () => {
    expect(사내문답이근거를독점했나([])).toBe(false);
    expect(사내문답이근거를독점했나(undefined as unknown as string[])).toBe(false);
  });

  it("★★ 근거가 **딱 한 건**이고 그게 승인 문답이어도 안 걸린다 — 위 약속과 코드가 어긋나 있었다", () => {
    // 2026-09-07 검토관 적발: 과반만 보면 1×2 > 1 이라 true였다. 그런데 자리 배분 수리 뒤
    // topK=4의 가족 몫은 1이라 **승인 문답은 top-4에 최대 1건**이고, 그 1건만 관련성 게이트를
    // 통과하면 sources가 딱 그것 하나가 된다(dispatcher가 documentId로 중복 제거까지 한다).
    // 그 정상 답을 빨강으로 만들면 야간 회귀에 「1건 중 과반」이라는 말이 안 되는 빨강이 뜬다.
    expect(사내문답이근거를독점했나(["승인문답:dtmtljmeoejfjk6d"])).toBe(false);
    // 두 건이 전부 승인 문답이면 그건 진짜 독점이다 — 하한이 규칙을 통째로 끄지 않는다.
    expect(사내문답이근거를독점했나(["승인문답:x1", "승인문답:x2"])).toBe(true);
  });
});

