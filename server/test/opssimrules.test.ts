/** 하네스 `내용판정`이 ⑰ 문항에 대해 내는 판정을 그대로 다시 짠다(같은 함수를 부른다). */
function 열일곱판정(행: (typeof 열일곱재료)[number]): string[] {
  const e = 열일곱기대[행.q];
  const 어긋남: string[] = [];
  if (e.포함 && !e.포함.test(행.답)) 어긋남.push("있어야 할 말 없음");
  if (e.금지 && e.금지.test(행.답)) 어긋남.push("있으면 안 되는 말");
  if (e.잣대.includes("사내문답과반금지") && 사내문답이근거를독점했나(행.근거)) 어긋남.push("ⓐ 사내 문답이 근거를 독점");
  if (e.잣대.includes("의무단정금지") && 의무라고못박았나(행.답, e.주제)) 어긋남.push("ⓓ 의무라고 못박음");
  if (e.잣대.includes("근거없는의무단정금지") && 근거없는의무단정인가(행.답)) 어긋남.push("ⓑ 근거 없는 의무 단정");
  if (e.잣대.includes("연2회조건없는단정금지") && 조건없는연2회의무인가(행.답)) 어긋남.push("ⓒ 예시를 의무로");
  return 어긋남;
}

