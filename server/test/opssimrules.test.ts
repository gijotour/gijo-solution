// ★★ ⑰ 「의무가 아니다」를 말하랬더니 **의무라고 못박은** 답 (2026-09-07 재수리)
//
// 위 식에 「추천 사항」·「자율」을 더하면서 **틀린 답 하나가 초록이 됐다**(검토관 적발):
//   「피싱 모의훈련은 의무이며 추천 사항으로도 널리 쓰입니다」 — 옛 식은 빨강, 넓힌 식은 통과.
//   그 문항의 기대에는 근거없는의무단정금지가 안 붙어 있어 **이 포함 하나가 유일한 잣대**였다.
// ⚠ ⓑ(근거없는의무단정금지)로 막으면 안 된다 — 실물 정답이 「…증명해야 합니다」라 ⓑ에 걸리고
//   「보안 관리 기준·감독규정」은 근거이름_RE에 없어 **맞는 답이 빨강**이 된다(실측).
