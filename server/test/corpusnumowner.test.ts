// RAG 코퍼스 — **밖에서 가져온 백분율에는 주인이 붙어 있는가** (2026-09-06 · A3 · 계획서 전-4)
//
// ■ 무엇을 푸는가
//   코퍼스 문서에 실린 **업계 평균·외부 조사 수치**가 고객 답변에서 **사내 실적**으로 읽혔다.
//   라이브 4표본 중 3표본이 남의 통계 조각을 근거로 「강함」 배지를 달고 확정 %를 냈다
//   (서약서 제출률 · 피싱 클릭률 · 백신 설치율). 값 자체는 조각에 실재하므로 **숫자 관문은
//   원리상 못 막는다** — 있긴 있고, 주어가 남일 뿐이다.
//
// ■ 왜 라우팅만으로는 안 끝나는가
//   막을 수 있는 층으로 라우팅이 있지만, 라우팅은 **「율/률」이 붙은 말투**만 잡는다.
//   「피싱 훈련 결과 어때?」처럼 지표 이름을 안 대는 물음은 그대로 RAG로 가서 같은 조각을 만난다.
//   그래서 **문서 층에서 한 겹 더** 막는다: 숫자와 주인을 **같은 줄에** 둔다.
//
// ■ 왜 하필 「같은 줄」인가
//   검색은 문서를 조각으로 잘라 근거로 붙인다. 주인 표시를 문장 끝이나 다음 줄에 달아 두면
//   **자르는 자리에 따라 숫자만 실린 조각**이 생긴다. 줄 단위로 못 박으면 그 경우가 없다.
//
// ■ 잡는 범위 — 넓히면 오탐이 쏟아진다
//   백분율이 있다고 다 잡지 않는다(EPSS 0~100% · 과징금 3% · 임계값 20%↑는 정의·기준이지
//   실적 통계가 아니다). **밖을 가리키는 말**(업계·평균·조사·벤치마크·타사·동종·글로벌)이
//   백분율과 **같은 줄**에 있을 때만 주인을 요구한다. 이 좁힘으로 전 코퍼스 오탐 0을 확인했다.
//   ⚠ 초록 통과가 「남의 수치 오인 없음」의 증거는 아니다 — 반입 뒤 실물 하네스로 다시 잰다.
import { describe, it, expect } from "vitest";
import fs from "node:fs";
import path from "node:path";

const 뿌리 = path.join(__dirname, "../..");
const manifest = JSON.parse(fs.readFileSync(path.join(뿌리, "server/docs-manifest.json"), "utf8"));

/** corpusleak.test.ts와 **같은 방식**으로 훑는다 — 두 시험이 보는 모집단이 갈리면 안 된다. */
function 코퍼스문서(): { file: string; 본문: string }[] {
  const 목록: string[] = [];
  (function 훑기(o: unknown): void {
    if (Array.isArray(o)) { o.forEach(훑기); return; }
    if (o && typeof o === "object") {
      const f = (o as { file?: unknown }).file;
      if (typeof f === "string" && f.endsWith(".md")) 목록.push(f);
      Object.values(o as Record<string, unknown>).forEach(훑기);
    }
  })({ ...manifest, _제외: undefined });
  const out: { file: string; 본문: string }[] = [];
  for (const f of 목록) {
    for (const d of [뿌리, path.join(뿌리, "docs")]) {
      const p = path.join(d, f);
      if (fs.existsSync(p)) { out.push({ file: f, 본문: fs.readFileSync(p, "utf8") }); break; }
    }
  }
  return out;
}

const 백분율 = /\d+(?:\.\d+)?\s*%/;
const 밖을가리키는말 = /업계|평균|조사|벤치마크|타사|동종|글로벌|설문 결과/;
/** 주인 표시 — 이 중 하나가 **같은 줄**에 있어야 한다. */
const 주인표시 = /업계 참고값|우리 회사 실적이 아니|사내 실적이 아니|사내 집계|외부 발표|폐지된 옛 기준/;

function 주인없는줄(본문: string): { 번호: number; 줄: string }[] {
  return 본문.split("\n")
    .map((줄, i) => ({ 번호: i + 1, 줄 }))
    .filter(({ 줄 }) => 백분율.test(줄) && 밖을가리키는말.test(줄) && !주인표시.test(줄));
}

describe("RAG 코퍼스 — 밖에서 온 백분율에는 주인이 같은 줄에 있다", () => {
  it("코퍼스 문서에 주인 없는 외부 통계 백분율이 없다", () => {
    const 걸린것: string[] = [];
    for (const { file, 본문 } of 코퍼스문서()) {
      for (const { 번호, 줄 } of 주인없는줄(본문)) {
        걸린것.push(`${file}:${번호}: ${줄.trim().slice(0, 110)}`);
      }
    }
    expect(
      걸린것,
      "이 줄이 통째로 조각이 되어 고객 답변의 근거로 붙는다 — 주어가 없으면 **사내 실적으로 읽힌다**(실측).\n" +
      "  고치는 법: 숫자와 **같은 줄**에 주인을 적는다 — 「(**업계 참고값** 약 33%)」처럼.\n" +
      "  줄 끝이나 다음 줄에 달면 조각이 잘리는 자리에 따라 떨어져 나간다.\n\n  " +
      걸린것.join("\n  ")
    ).toEqual([]);
  });

  it("이 감시가 헛돌고 있지 않다", () => {
    // ⚠ 매니페스트 파싱이 빈손이면 위 시험은 통과하면서 아무것도 안 본다(corpusleak과 같은 이유).
    const 문서 = 코퍼스문서();
    expect(문서.length, "코퍼스 문서를 하나도 못 읽었다 — 빈 검사다").toBeGreaterThanOrEqual(8);

    // ⚠ 탐지기 자체가 죽어 있어도 위 시험은 초록이다. 실제로 잡히는지 심어서 확인한다.
    //   아래 세 줄은 **수리 전 이 문서에 실제로 있던 글**이다(2026-09-06 검토관 적발 · 그때 3건 적발).
    const 심은것 = [
      "- 훈련을 받기 전 기준선에서 열 명 중 서넛가량이 훈련 메일에 반응했다는 조사가 있다(약 33%) —",
      "- 같은 조사에서 인원 250명 이하 조직과 1만명 이상 조직의 기준선이 약 25%와 약 40%로 갈렸다 —",
      "- 모의 피싱 메일을 신고 창구로 알린 비율이 평균 20%에 못 미쳤다는 조사가 있다 —",
    ].join("\n");
    expect(주인없는줄(심은것).length, "탐지기가 죽었다 — 옛 문장 3줄을 하나도 못 잡는다").toBe(3);

    // 주인을 붙이면 통과해야 한다(가드를 빼면 다시 빨개지는지의 반대 방향).
    expect(
      주인없는줄("  (**업계 참고값** 약 33%). **우리 회사 실적이 아니다.**").length,
      "주인을 붙였는데도 잡힌다 — 규칙이 너무 넓다"
    ).toBe(0);

    // 정의·기준 수치는 **안 잡아야** 한다 — 넓히면 오탐이 쏟아진다(전 코퍼스 실측으로 좁힌 값).
    expect(주인없는줄("악용 확률을 0~100%로 낸다").length, "정의 범위를 잡았다").toBe(0);
    expect(주인없는줄("전체 매출액의 3% 이내 과징금").length, "법정 기준을 잡았다").toBe(0);
  });
});
