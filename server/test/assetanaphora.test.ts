// 「이 서버 어떤 서비스 돌고 있어?」 — [2026-08-06 · 147상황 실측이 잡은 결함]
//
// 실측: 47초를 쓰고 **질문과 어긋난 답**이 나왔다 —
//   물음은 "어떤 서비스가 도는가", 답은 "이 자산에서 발견된 1개 취약점 중 우선순위가 낮은 것은 1건".
// 원인: 어느 서버인지 **말하지 않았는데** 모델이 아무 도구나 골랐다.
//   기존 「대명사뿐인가」는 뒤에 내용("어떤 서비스 돌고 있어")이 붙어 안 걸렸다.
// 계약: 대상을 안 밝힌 자산 질문은 **답이 아니라 되묻기**다(27초 사고와 같은 병).
import { describe, it, expect, vi } from "vitest";

vi.mock("../src/engine/assets", async (importOriginal) => {
  const mod = (await importOriginal()) as Record<string, unknown>;
  return { ...mod, listAssets: () => [{ id: "a1", name: "안전대부 웹서버" }, { id: "a2", name: "샘플-웹서버" }] };
});

import { 가리킨자산이없나 } from "../src/engine/agentloop";

describe("대상을 안 밝힌 자산 질문 — 되묻는다", () => {
  it("★ 실측 문장이 잡힌다 — 대상을 안 밝히고 **속성을 캐묻는** 말", () => {
    expect(가리킨자산이없나("이 서버 어떤 서비스 돌고 있어?")).toBe(true);
    expect(가리킨자산이없나("그 자산 무슨 용도야?")).toBe(true);
    expect(가리킨자산이없나("해당 장비 어디에 있어?")).toBe(true);
  });

  it("★★ 갈 도구가 분명한 지시는 삼키지 않는다 — 되묻기로 막으면 그게 더 나쁘다", () => {
    // 2026-08-06 회귀: 이 조건 없이 만들었다가 기존 되묻기 시험이 그 자리에서 잡았다.
    expect(가리킨자산이없나("이 자산 취약점 알려줘")).toBe(false);
    expect(가리킨자산이없나("그 서버 담당자 배정해줘")).toBe(false);
  });

  it("★★ 특정한 질문은 안 삼킨다 — 진짜 지시를 되묻기로 막으면 그게 더 나쁘다", () => {
    expect(가리킨자산이없나("192.168.219.98 어떤 서비스 돌고 있어?"), "IP로 특정했다").toBe(false);
    expect(가리킨자산이없나("안전대부 웹서버 어떤 서비스 돌고 있어?"), "등록된 이름으로 특정했다").toBe(false);
    expect(가리킨자산이없나("전체 자산 목록 보여줘"), "대상이 하나가 아니다").toBe(false);
    expect(가리킨자산이없나("모든 서버 점검했어?")).toBe(false);
  });

  it("자산을 가리키지 않는 말은 애초에 대상이 아니다", () => {
    expect(가리킨자산이없나("오늘 뭐부터 볼까?")).toBe(false);
    expect(가리킨자산이없나("이 문서 등급 바꾸려면?"), "문서는 자산이 아니다").toBe(false);
    expect(가리킨자산이없나("이번 주 예정된 점검 있어?")).toBe(false);
  });
});
