// 법령 조문 본문 조립(조문본문) — **77% 누락 사고의 회귀 시험** (2026-08-13 · 계획서 전-2 계열)
//
// ■ 실사고: 파서가 `조문내용`만 읽어 **항이 여럿인 조문은 제목 줄만 남았다**(max 발견).
//   개인정보 보호법 126건 중 97건(77%)·시행령 140건 중 96건(69%)이 본문 0자.
//   빠진 자리에 「유출 신고 72시간」(시행령 제40조①)이 있어 제품이
//   "법령에 명시되어 있지 않다"고 **단정**했다 — 과태료가 걸린 법정 기한이다.
// ■ 왜 픽스처인가: 실제 법제처 API는 인증키·외부망이 필요해 시험에서 못 부른다.
//   대신 응답 모양(항[].항내용 · 호[].호내용 · 목[].목내용)을 그대로 본떠
//   **실제 조립 함수**(조문본문)를 부른다 — 로직을 베껴 쓰면 드리프트한다.
import { describe, it, expect } from "vitest";
import * as fs from "fs";
import { 조문본문 } from "../src/engine/lawinfo";

describe("조문본문 — 항·호·목이 전부 본문에 들어온다", () => {
  it("★ 항이 여럿인 조문 — 제목 줄만 남던 유형(77% 누락 사고)", () => {
    // 시행령 제40조 모양 그대로(내용은 축약) — 본문이 항[].항내용에 있다.
    const u = {
      조문번호: "40",
      조문제목: "개인정보 유출등의 신고",
      조문내용: "제40조(개인정보 유출등의 신고)", // ← 예전 파서는 이 줄만 남겼다
      항: [
        { 항번호: "①", 항내용: "① 개인정보처리자는 … 72시간 이내에 … 신고해야 한다." },
        {
          항번호: "②",
          항내용: "② 제1항에도 불구하고 다음 각 호의 사항을 …",
          호: [
            { 호번호: "1.", 호내용: "1. 유출등이 된 개인정보의 항목" },
            {
              호번호: "2.",
              호내용: "2. 유출등이 된 시점과 그 경위",
              목: [{ 목번호: "가.", 목내용: "가. 유출 경로의 세부 구분" }],
            },
          ],
        },
      ],
    };
    const text = 조문본문(u);
    expect(text).toContain("72시간"); // 단정 오답을 만든 바로 그 값
    expect(text).toContain("유출등이 된 개인정보의 항목"); // 호
    expect(text).toContain("유출 경로의 세부 구분"); // 목
    expect(text.length).toBeGreaterThan(100); // 제목 한 줄(22자)이 아니라 본문 전체
  });

  it("항이 없는 단항 조문 — 예전에도 살아남던 유형이 그대로 산다", () => {
    const u = { 조문번호: "1", 조문제목: "목적", 조문내용: "제1조(목적) 이 법은 …을 목적으로 한다." };
    expect(조문본문(u)).toBe("제1조(목적) 이 법은 …을 목적으로 한다.");
  });

  it("항이 하나뿐(배열 아님)이어도 편다 — 법제처는 1건이면 객체로 준다(arr가 받친다)", () => {
    const u = {
      조문내용: "제5조(다른 법률과의 관계)",
      항: { 항번호: "①", 항내용: "① 개인정보 보호에 관하여는 … 이 법에서 정하는 바에 따른다." },
    } as Record<string, unknown>;
    expect(조문본문(u)).toContain("이 법에서 정하는 바에 따른다");
  });

  it("조문내용이 배열로 와도 합친다(옛 응답 호환)", () => {
    const u = { 조문내용: ["제2조(정의)", "이 법에서 사용하는 용어의 뜻은 다음과 같다."] };
    const text = 조문본문(u);
    expect(text).toContain("제2조(정의)");
    expect(text).toContain("용어의 뜻은 다음과 같다");
  });
});

// ── 본문이 살아나자 드러난 것 둘 (2026-08-13 운영 실측) ─────────────────────────
//
// 배포 뒤 운영에 「개인정보 보호법 시행령 제40조 알려줘」를 실제로 던져 보고 찾았다.
// 시험이 아니라 **제품을 태워 보고** 나온 것이라 여기 못박는다.
describe("가지번호·머리줄 — 본문이 살아나며 드러난 것", () => {
  const 소스 = fs.readFileSync(new URL("../src/engine/lawinfo.ts", import.meta.url), "utf8");

  it("★ 제40조와 제40조의2를 가른다 — 조문번호가 둘 다 40이라 섞여 나왔다", () => {
    // 법제처는 가지 조문에 **같은 조문번호**를 주고 `조문가지번호`로만 구분한다.
    // 「제40조」를 물었는데 제40조의2(노출 개인정보 삭제 요청 기관)가 함께 나왔고,
    // 형식이 그것까지 「제40조」로 찍어 **엉뚱한 조문을 물어본 조문인 양** 보여 줬다.
    expect(소스).toContain("조문가지번호");
    expect(소스).toMatch(/\$\{번호\}의\$\{가지\}/);
  });

  it("★ 머리줄을 두 번 찍지 않는다 — 제목이 두 줄로 나왔다", () => {
    // 본문에 조문내용(제목 줄)이 들어오면서 형식의 헤더와 겹쳤다.
    // ⚠ text를 깎지 않고 헤더를 건너뛴다 — 제1조처럼 제목과 본문이 한 줄인 조문이 있다.
    expect(소스).toMatch(/if \(!a\.text\.startsWith\(`제\$\{a\.no\}조`\)\) lines\.push\(머리\)/);
  });
});
