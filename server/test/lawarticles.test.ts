// 법령 조문 본문 조립(조문본문) — **77% 누락 사고의 회귀 시험** (2026-08-13 · 계획서 전-2 계열)
//
// ■ 실사고: 파서가 `조문내용`만 읽어 **항이 여럿인 조문은 제목 줄만 남았다**(max 발견).
//   개인정보 보호법 126건 중 97건(77%)·시행령 140건 중 96건(69%)이 본문 0자.
//   빠진 자리에 「유출 신고 72시간」(시행령 제40조①)이 있어 제품이
//   "법령에 명시되어 있지 않다"고 **단정**했다 — 과태료가 걸린 법정 기한이다.
// ■ 왜 픽스처인가: 실제 법제처 API는 인증키·외부망이 필요해 시험에서 못 부른다.
//   대신 응답 모양(항[].항내용 · 호[].호내용 · 목[].목내용)을 그대로 본떠
//   **실제 조립 함수**(조문본문)를 부른다 — 로직을 베껴 쓰면 드리프트한다.
import { describe, it, expect } from "vitest";
import * as fs from "fs";
import { 조문본문 } from "../src/engine/lawinfo";

describe("조문본문 — 항·호·목이 전부 본문에 들어온다", () => {
  it("★ 항이 여럿인 조문 — 제목 줄만 남던 유형(77% 누락 사고)", () => {
    // 시행령 제40조 모양 그대로(내용은 축약) — 본문이 항[].항내용에 있다.
    const u = {
      조문번호: "40",
      조문제목: "개인정보 유출등의 신고",
      조문내용: "제40조(개인정보 유출등의 신고)", // ← 예전 파서는 이 줄만 남겼다
      항: [
        { 항번호: "①", 항내용: "① 개인정보처리자는 … 72시간 이내에 … 신고해야 한다." },
        {
          항번호: "②",
          항내용: "② 제1항에도 불구하고 다음 각 호의 사항을 …",
          호: [
            { 호번호: "1.", 호내용: "1. 유출등이 된 개인정보의 항목" },
            {
              호번호: "2.",
              호내용: "2. 유출등이 된 시점과 그 경위",
              목: [{ 목번호: "가.", 목내용: "가. 유출 경로의 세부 구분" }],
            },
          ],
        },
      ],
    };
    const text = 조문본문(u);
    expect(text).toContain("72시간"); // 단정 오답을 만든 바로 그 값
    expect(text).toContain("유출등이 된 개인정보의 항목"); // 호
    expect(text).toContain("유출 경로의 세부 구분"); // 목
    expect(text.length).toBeGreaterThan(100); // 제목 한 줄(22자)이 아니라 본문 전체
  });

  it("항이 없는 단항 조문 — 예전에도 살아남던 유형이 그대로 산다", () => {
    const u = { 조문번호: "1", 조문제목: "목적", 조문내용: "제1조(목적) 이 법은 …을 목적으로 한다." };
    expect(조문본문(u)).toBe("제1조(목적) 이 법은 …을 목적으로 한다.");
  });

  it("항이 하나뿐(배열 아님)이어도 편다 — 법제처는 1건이면 객체로 준다(arr가 받친다)", () => {
    const u = {
      조문내용: "제5조(다른 법률과의 관계)",
      항: { 항번호: "①", 항내용: "① 개인정보 보호에 관하여는 … 이 법에서 정하는 바에 따른다." },
    } as Record<string, unknown>;
    expect(조문본문(u)).toContain("이 법에서 정하는 바에 따른다");
  });

  it("조문내용이 배열로 와도 합친다(옛 응답 호환)", () => {
    const u = { 조문내용: ["제2조(정의)", "이 법에서 사용하는 용어의 뜻은 다음과 같다."] };
    const text = 조문본문(u);
    expect(text).toContain("제2조(정의)");
    expect(text).toContain("용어의 뜻은 다음과 같다");
  });
});

// ── 본문이 살아나자 드러난 것 둘 (2026-08-13 운영 실측) ─────────────────────────
//
// 배포 뒤 운영에 「개인정보 보호법 시행령 제40조 알려줘」를 실제로 던져 보고 찾았다.
// 시험이 아니라 **제품을 태워 보고** 나온 것이라 여기 못박는다.
describe("가지번호·머리줄 — 본문이 살아나며 드러난 것", () => {
  const 소스 = fs.readFileSync(new URL("../src/engine/lawinfo.ts", import.meta.url), "utf8");

  it("★ 제40조와 제40조의2를 가른다 — 조문번호가 둘 다 40이라 섞여 나왔다", () => {
    // 법제처는 가지 조문에 **같은 조문번호**를 주고 `조문가지번호`로만 구분한다.
    // 「제40조」를 물었는데 제40조의2(노출 개인정보 삭제 요청 기관)가 함께 나왔고,
    // 형식이 그것까지 「제40조」로 찍어 **엉뚱한 조문을 물어본 조문인 양** 보여 줬다.
    expect(소스).toContain("조문가지번호");
    expect(소스).toMatch(/\$\{번호\}의\$\{가지\}/);
  });

  it("★ 머리줄을 두 번 찍지 않는다 — 제목이 두 줄로 나왔다", () => {
    // 본문에 조문내용(제목 줄)이 들어오면서 형식의 헤더와 겹쳤다.
    // ⚠ text를 깎지 않고 헤더를 건너뛴다 — 제1조처럼 제목과 본문이 한 줄인 조문이 있다.
    expect(소스).toMatch(/if \(!a\.text\.startsWith\(`제\$\{a\.no\}조`\)\) lines\.push\(머리\)/);
  });
});

// ─────────────────────────────────────────────────────────────────────────────
// ★ 조문 번호 **없는** 실무 질문에도 본문이 붙는가 (2026-08-13 · 전-2 계열)
//
// ■ 파서를 고쳤는데도 왜 여전히 틀렸나 (max 재측정, 인계_win_법령조문_본문누락 §6)
//   본문은 질문에 조문 번호가 있을 때만(`조문번호()` → `lawArticleAnswer`) 탔다.
//   담당자의 실무 질문 「개인정보 유출되면 며칠 안에 신고해야 돼?」에는 번호가 없다 —
//   **고친 파서에 닿기 전에 흐름이 끝나** 제목·링크만 나갔다.
//   그리고 본문이 없으니 모델이 빈자리를 지어냈다(실측):
//     "최대 **5일 이내**에 신고 … 개인정보 보호법 **시행령 제16조**에 근거"
//   5일도 제16조도 없는 것을 지어낸 것이다 — **조문 번호까지 조작**했다.
//
// ■ 여기서 재는 것: 어느 조문을 고르는가(제목점수). 실제 API는 못 부르므로 순수 함수를 본다.
//   ⚠ 겹침을 **제목 → 물음** 방향으로 본다. 반대는 어미 때문에 거의 안 걸린다:
//     물음 「유출되면」 ⊄ 제목 「유출 등의 통지·신고」  ·  제목 낱말 「유출」 ⊂ 물음 ✅
import { 제목점수 } from "../src/engine/lawinfo";

describe("★ 번호 없는 실무 질문 — 어느 조문을 고르나 (제목점수)", () => {
  const 물음 = "개인정보 유출되면 며칠 안에 신고해야 돼?";

  it("★ 유출·신고 조문이 무관한 조문을 이긴다 — 72시간이 여기 있다", () => {
    const 맞는것 = 제목점수("개인정보 유출 등의 통지ㆍ신고", 물음);
    const 무관 = 제목점수("영상정보처리기기의 설치ㆍ운영 제한", 물음);
    expect(맞는것, "유출·신고 조문이 안 걸린다").toBeGreaterThan(0);
    expect(맞는것, "무관한 조문이 더 높다 — 엉뚱한 본문이 붙는다").toBeGreaterThan(무관);
  });

  it("★ 어미가 붙은 물음도 걸린다 (「유출되면」에서 「유출」을 집는다)", () => {
    // 이 한 줄이 방향을 못박는다. 반대 방향(물음 낱말 → 제목)이면 여기서 0이 된다.
    expect(제목점수("유출 등의 신고", "개인정보가 유출되었을 때 신고해야 하나요")).toBeGreaterThan(0);
  });

  it("겹치는 말이 없으면 0 — 무관한 조문은 아예 안 붙인다", () => {
    expect(제목점수("영상정보처리기기의 설치ㆍ운영 제한", "방화벽 정책 어떻게 짜?")).toBe(0);
  });

  it("같은 낱말을 여러 번 써도 한 번만 센다 — 반복으로 점수를 부풀리지 않는다", () => {
    expect(제목점수("신고 신고 신고", "신고")).toBe(1);
  });
});

// ─────────────────────────────────────────────────────────────────────────────
// ★ 본법만 보면 72시간을 영영 못 찾는다 — **시행령을 함께 본다** (2026-08-13, max 정밀 진단)
//
// ■ 무엇이 남아 있었나
//   파서(768e33e)도 번호없는 질문에 조문 붙이기(f7d4fcc)도 들어갔는데 lt-seed-law는 여전히 실패했다.
//   max가 정밀 진단: **72시간은 「개인정보 보호법 시행령」 제40조①에 있다** — 본법이 아니다.
//   그런데 f7d4fcc는 검색 **1위 법령의 조문만** 당겼다. 검색 실측:
//     「개인정보 보호법」 → 1위 **본법** · 2위 **시행령**
//   그래서 72시간이 컨텍스트에 안 들어가고 모델이 빈자리를 지어냈다(제30조·고시 제2023-6호 등).
//
// ■ ⚠ 운영에서는 통과해 보였다 — **사내 문서(RAG)가 메워 줬기 때문**이다(도구 [law_lookup, 사내지식]).
//   **빈 DB인 신규 고객사에서는 실패한다.** 내가 잰 환경이 운좋게 통과한 것이었다.
//
// ■ 고침의 핵심: 법령마다 **가장 잘 맞는 것 하나씩** 고른 뒤 점수순으로 자른다.
//   그냥 점수순이면 본법에서 두 건이 뽑혀 시행령이 밀린다.
describe("★ 시행령이 밀리지 않는다 — 법령별 한 건씩 고르는 규칙", () => {
  // 실제 조문 제목으로 점수를 대조한다(제목점수는 순수 함수라 API 없이 잰다).
  const 물음 = "개인정보 유출되면 며칠 안에 신고해야 돼?";

  it("본법·시행령 두 조문 모두 물음과 겹친다(둘 다 후보가 된다)", () => {
    const 본법 = 제목점수("개인정보 유출 등의 통지ㆍ신고", 물음);
    const 시행령 = 제목점수("개인정보 유출등의 신고", 물음);
    expect(본법, "본법 제34조가 안 걸린다").toBeGreaterThan(0);
    expect(시행령, "시행령 제40조가 안 걸린다 — 72시간이 여기 있다").toBeGreaterThan(0);
  });

  it("★ 코드가 법령별로 하나씩 고른다 — 본법 두 건에 시행령이 밀리지 않게", () => {
    const src = fs.readFileSync(new URL("../src/engine/lawinfo.ts", import.meta.url), "utf8");
    expect(src, "법령별 최고점 고르기가 없다 — 점수순만이면 시행령이 밀린다").toContain("법령별최고");
    expect(src, "여러 법령을 뒤지지 않는다").toMatch(/조회할법령/);
    // 호출부가 hits 전체를 넘기는가 — hits[0]만 넘기면 시행령에 닿을 길이 없다.
    expect(src, "1위 법령만 넘긴다").toMatch(/물음에맞는조문본문\(query, hits\)/);
    expect(src, "아직 hits[0]만 넘기는 자리가 남아 있다").not.toMatch(/물음에맞는조문본문\(query, hits\[0\]\)/);
  });
});
