//   「접속기록은 몇 년 보관하고 근거 법령은?」에 답이 1년/2년은 맞히면서 **조문 번호를 안 댔다.**
//   문맥에는 「개인정보 보호법 시행령 제30조」가 **2조각이나 들어 있었는데** 모델이 다른 조각
//   (해설 89·63)을 골라 썼다. 담당자가 원한 건 조문 번호다 — 근거를 물었으니까.
//
// ⚠ **모델에게 「조문을 대라」고 시키지 않는다.** 7B/14B에 프롬프트 규칙을 더해 행동을 고치려던
//   시도는 이 저장소에서 반복해 실패했다(CLAUDE.md). 같은 파일의 법령한계를밝힌다와 같은 방식이다.
// ⚠ **짓지 않는다.** 우리가 읽은 조각에 **글자 그대로 있는 표기**만 복사한다 — 이게 급소다.
import { describe, it, expect } from "vitest";
import { 조문근거를보탠다 } from "../src/engine/agentloop";

const 사내 = (result: string) => [{ tool: "사내지식", args: {}, result }] as never;

describe("★★ 짓지 않는다 — 읽은 조각에 있는 것만 붙인다", () => {
  it("조각에 조문이 없으면 **아무것도 안 붙인다**", () => {
    const 답 = "접속기록은 1년 이상 보관해야 합니다.";
    expect(조문근거를보탠다(답, 사내("접속기록은 오래 보관해야 한다는 설명만 있습니다.")), "없는 조문을 지어냈다")
      .toBe(답);
  });

  it("사내 근거를 아예 안 읽었으면 안 붙인다", () => {
    const 답 = "접속기록은 1년 이상입니다.";
    expect(조문근거를보탠다(답, [] as never)).toBe(답);
    expect(조문근거를보탠다(답, [{ tool: "law_lookup", args: {}, result: "시행령 제30조" }] as never))
      .toBe(답);
  });

  it("빈 답에는 손대지 않는다", () => {
    expect(조문근거를보탠다("", 사내("시행령 제30조"))).toBe("");
    expect(조문근거를보탠다("   ", 사내("시행령 제30조"))).toBe("   ");
  });
});

describe("★ 조문이 있고 답에 없으면 붙인다", () => {
  const 조각 =
    "근거 계통 — 개인정보 보호법 제29조(안전조치의무), 개인정보 보호법 시행령 제30조(개인정보의 안전성 확보 조치), " +
    "개인정보의 안전성 확보조치 기준 제8조(접속기록의 보관 및 점검).";

  it("시행령 제30조를 붙인다", () => {
    const 답 = "접속기록은 최소 1년, 조건에 따라 2년 이상 보관합니다.";
    const 결과 = 조문근거를보탠다(답, 사내(조각));
    expect(결과, "조문을 안 붙였다").toMatch(/제\s*30\s*조/);
    expect(결과, "원래 답을 잃었다").toContain("최소 1년");
    expect(결과, "어디서 온 건지 안 밝힌다").toContain("사내 자료에 적힌 근거 조문");
  });

  it("★ 답에 **이미 있는** 조문은 다시 안 붙인다", () => {
    const 답 = "근거는 개인정보 보호법 시행령 제30조와 안전성 확보조치 기준 제8조입니다.";
    const 결과 = 조문근거를보탠다(답, 사내(조각));
    // 29조는 답에 없으니 붙고, 30·8조는 이미 있으니 안 붙는다
    const 붙은것 = 결과.slice(답.length);
    expect(붙은것, "이미 있는 30조를 또 붙였다").not.toMatch(/제\s*30\s*조/);
    expect(붙은것, "이미 있는 8조를 또 붙였다").not.toMatch(/제\s*8\s*조/);
  });

  it("답에 모든 조문이 이미 있으면 그대로 둔다", () => {
    const 답 = "법 제29조 · 시행령 제30조 · 고시 제8조가 근거입니다.";
    expect(조문근거를보탠다(답, 사내(조각))).toBe(답);
  });

  it("★ 너무 많이 붙이지 않는다(4개까지)", () => {
    const 많음 = "시행령 제1조 시행령 제2조 시행령 제3조 시행령 제4조 시행령 제5조 시행령 제6조";
    const 결과 = 조문근거를보탠다("답입니다.", 사내(많음));
    const 개수 = (결과.match(/제\s*\d+\s*조/g) ?? []).length;
    expect(개수, "붙는 조문이 너무 많다 — 답이 조문 목록에 묻힌다").toBeLessThanOrEqual(4);
  });
});

