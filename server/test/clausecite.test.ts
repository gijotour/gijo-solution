describe("★★ 「자주 나는 오해」로 적힌 조문을 베끼지 않는다", () => {
  // 이 저장소의 근거 문서들은 **틀린 답을 일부러 적어 둔다**. 문맥을 안 보고 조문만 긁으면
  // 그 틀린 답을 근거로 붙인다 — 2026-09-01에 실제로 fin-mangbunri 회귀가 그 자리에서 깨졌다.
  it("망분리 — 「정보통신망법 제12조가 근거라고 답하면 틀리다」를 베끼지 않는다", () => {
    const 조각 =
      "전자금융감독규정 제15조(해킹 등 방지대책)가 금융권 망분리의 근거다.\n" +
      "⚠ 자주 나는 오해: 「정보통신망법 제12조」가 근거라고 답하면 틀리다.";
    const 결과 = 조문근거를보탠다("망분리 근거를 설명합니다.", 사내(조각));
    expect(결과, "틀린 답으로 적힌 조문을 근거로 붙였다").not.toMatch(/정보통신망법\s*제\s*12\s*조/);
    expect(결과, "맞는 조문은 붙어야 한다").toMatch(/제\s*15\s*조/);
  });

  it("접속기록 — 「개인정보 보호법 제30조라 하면 틀리다」 문장은 건너뛴다", () => {
    const 조각 =
      "근거는 개인정보 보호법 시행령 제30조와 안전성 확보조치 기준 제8조다.\n" +
      "⚠ 자주 나는 오해: 「개인정보 보호법」 제30조라고 답하면 틀리다.";
    const 결과 = 조문근거를보탠다("접속기록은 1년 이상입니다.", 사내(조각));
    expect(결과, "맞는 근거를 못 붙였다").toMatch(/시행령 제\s*30\s*조/);
    expect(결과, "오해 문장의 표기까지 붙였다").not.toMatch(/개인정보 보호법 제\s*30\s*조/);
  });

  it("부정말이 문장 전체를 죽이지는 않는다 — 다른 문장의 조문은 살아 있다", () => {
    const 조각 = "시행령 제30조가 근거다.\n이건 틀린 설명이 아니다.\n고시 제8조도 근거다.";
    const 결과 = 조문근거를보탠다("답.", 사내(조각));
    expect(결과).toMatch(/제\s*30\s*조/);
    expect(결과).toMatch(/제\s*8\s*조/);
  });
});
