// 「담당자를 ○○로 지정해줘」가 오늘 목록으로 흡수되지 않는가.
//
// 실사고(2026-08-09 파일럿 첫날 리허설): 키트 대본 24~30분이 바로 이 문장인데
//   "가장 급한 취약점 담당자를 김도희로 지정해줘"
// → 결재판이 안 뜨고 **오늘 조치 우선순위 목록**이 나왔다. 고객 앞에서 그 자리에서 깨진다.
//
// 원인: 배정 판별이 「담당자」 뒤 2글자까지만 봐서 사이에 낀 사람 이름을 못 넘었다.
// 「배정」이 든 말은 걸렸지만 「지정」은 못 걸렸다.
import { describe, it, expect } from "vitest";
import { forcedToolFor } from "../src/engine/agentloop";

describe("배정·지정 지시가 조회로 흡수되지 않는다", () => {
  const 시키는말 = [
    "가장 급한 취약점 담당자를 김도희로 지정해줘",
    "이 취약점 담당자를 홍길동으로 배정해줘",
    "담당자를 정요한으로 정해줘",
    "가장 급한 것 담당자·기한 배정해줘",
  ];
  for (const m of 시키는말) {
    it(`「${m}」 → today로 못박지 않는다`, () => {
      expect(forcedToolFor(m)?.tool, "쓰기 지시가 조회 도구로 흡수됐다").not.toBe("today");
    });
  }

  // 세는 질문은 그대로 조회다 — 넓히다가 이쪽을 끌고 오면 안 된다.
  const 묻는말 = ["고위험인데 담당자 없는 거 있어?", "미배정 몇 건이야?", "담당자 미배정 취약점 몇 개?"];
  for (const m of 묻는말) {
    it(`「${m}」 → 조회 그대로`, () => {
      const t = forcedToolFor(m)?.tool;
      expect(t === undefined || t === "finding_status" || t === "today" || t === "list_assets",
        `조회 질문이 엉뚱한 도구로 갔다: ${t}`).toBe(true);
    });
  }
});
