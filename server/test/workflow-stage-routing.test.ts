// 업무 흐름 5단계 — 「무슨 절차든 뭐냐고 물으면 내 것」을 좁힌다 (2026-09-08 · 계획서 중-1)
//
// ★★ 무엇이 틀렸었나 (2026-09-08 가로채기 라운드 실측)
//   FORCED_INTENTS[28](workflow_status)에 `(단계|절차)…(뭐|뭘|무엇|해야)` 갈래가 있었다.
//   **주어를 안 보는 규칙**이라 남의 절차·단계까지 전부 삼켰다 — 「등급 5단계 뭐야?」(공급망) ·
//   「이관 절차 뭐야?」(인수인계) · 「대응 절차 뭐야?」(로그 분석) · 「학습 루프 4단계 뭐야?」(학습)에
//   우리 업무 5단계의 **현황 숫자**가 나갔다. **뜻을 물었는데 숫자를 준 것**이다.
//   그 넷은 **제 화면 안에서만** 화면 안내(isHelpIntent)가 막아 줬다 — panelname.test의 명부
//   네 줄이 그 자리를 「정체물음」 사유로 봐주고 있었다. 그런데 화면 안내는 **그 화면에서 물을
//   때만** 이기므로, 대화창이나 다른 화면에서 같은 말을 하면 그대로 샜다.
//
// ★ 판정은 **제품 함수**(forcedToolFor)가 한다 — 정규식을 떼어 혼자 재면 앞 규칙이 가로채는
//   것을 못 본다(helpers/routing.ts 머리글). 여기서는 실제도착()만 쓴다.
//
// ⚠ 이 시험이 **헛돌지 않는지**도 함께 잰다(아래 마지막 describe) — 놓아주기로 한 다섯이
//   애초에 규칙에 안 걸리는 말이었다면 「고쳤다」는 거짓이 된다. 옛 갈래를 글자 그대로 들고
//   와서 「그때는 걸렸다」를 못 박는다.
import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { 실제도착, 가로챈규칙 } from "./helpers/routing";

const 뿌리 = join(__dirname, "..", "src", "engine");
const agentloop = readFileSync(join(뿌리, "agentloop.ts"), "utf8");
const workflow = readFileSync(join(뿌리, "workflow.ts"), "utf8");

/** 2026-09-08 이전의 넓은 갈래 — **글자 그대로**. 반증용이라 제품에서 읽지 않는다. */
const 옛갈래 = /(단계|절차)[^.\n]{0,8}(뭐|뭘|무엇|해야)/;

describe("★★ 우리 5단계를 **이름으로** 가리키는 말은 그대로 잡는다", () => {
  // ⚠ 이 묶음의 모집단은 **단계 이름을 앞세운 꼴**뿐이다(발견·수집·우선순위·조치·검증·보고).
  //   지시어 꼴(「지금/이/그 단계…」)은 아래 별도 묶음이 잰다 — 이름을 넓게 달아 놓고 좁게 재면
  //   다음 사람이 이 초록을 「지시어 꼴도 지켜진다」로 읽는다(2026-09-08 검토관 [낮음] 적발).
  // 2026-08-03/04 실측 4건 + 2차 3건 — 규칙에 안 걸려 33~36초씩 쓰고 남의 제품 가이드를 읽어 줬다.
  const 잡아야 = [
    "지금 우리 어느 단계가 제일 밀렸어?",
    "발견 단계에서 뭘 해야 해?",
    "이 취약점 다음 단계가 뭐야?",
    "우선순위 정하려면 뭘 봐야 해?",
    "조치까지 갔는데 그다음은?",
    "보고까지 끝내려면 뭐가 남았어?",
    "검증은 어떻게 하는 거야?",
  ];
  for (const q of 잡아야) {
    it(`「${q}」 → workflow_status`, () => {
      const 도둑 = 가로챈규칙(q, "workflow_status");
      expect(실제도착(q), 도둑 ? `앞 규칙 [${도둑.차례}] ${도둑.도구}가 가로챘다` : "아무 규칙에도 안 걸린다 — 좁히다가 잘라 먹었다")
        .toBe("workflow_status");
    });
  }

  // 좁히면서 **새로 확인한 말들** — 단계 이름을 앞세운 꼴은 어느 단계든 걸려야 한다.
  it("단계 이름 + 「단계」 꼴은 다섯 단계 전부 걸린다", () => {
    for (const 이름 of ["발견", "수집", "우선순위", "조치", "검증", "보고"]) {
      expect(실제도착(`${이름} 단계에서 뭘 해야 해?`), `${이름} 단계가 빠졌다`).toBe("workflow_status");
    }
  });

  it("「지금 어느 단계가 밀렸어?」·「보고까지 뭐가 남았어?」도 그대로", () => {
    expect(실제도착("지금 어느 단계가 밀렸어?")).toBe("workflow_status");
    expect(실제도착("보고까지 뭐가 남았어?")).toBe("workflow_status");
  });

  it("「업무 절차 뭐야?」는 우리 것이다 — 주어가 우리 업무다", () => {
    expect(실제도착("업무 절차 뭐야?")).toBe("workflow_status");
  });
});

describe("★★ 우리 업무를 **가리키는 말**(지시어)도 잡는다 — 이름을 안 부르는 게 사람의 말투다", () => {
  // ★★ 2026-09-08 검토관 [중] 적발. 좁히기 1차가 주어를 **단계 이름**으로만 못 박아,
  //   같은 것을 가리키는 지시어 꼴을 함께 놓아줬다 — 「지금 단계에서 뭘 해야 해?」가 null이 됐다.
  //   그 자리는 이 규칙이 생긴 이유(2026-08-04: 28~35초 쓰고 남의 제품 가이드를 읽어 주던 자리)
  //   그대로다. 같은 가족인 「어느 단계에서 뭘 해야 해?」·「다음 단계에서 뭘 해야 해?」는 제 갈래가
  //   따로 있어 멀쩡히 살아 있었으니, **같은 부류인데 답이 갈리던** 것이기도 하다.
  const 잡아야 = [
    "지금 단계에서 뭘 해야 해?",
    "현재 단계에서 뭘 해야 해?",
    "이번 단계에서 뭘 해야 해?",
    "이 단계에서 뭘 해야 해?",
    "그 단계에서 뭘 해야 해?",
    "지금 단계 뭐야?",
    "현재 절차 뭐야?",
    "우리 절차 뭐야?",
    "전체 절차 뭐야?",
  ];
  for (const q of 잡아야) {
    it(`「${q}」 → workflow_status`, () => {
      const 도둑 = 가로챈규칙(q, "workflow_status");
      expect(실제도착(q), 도둑 ? `앞 규칙 [${도둑.차례}] ${도둑.도구}가 가로챘다` : "아무 규칙에도 안 걸린다 — 좁히다가 잘라 먹었다")
        .toBe("workflow_status");
    });
  }

  it("같은 가족끼리 답이 갈리지 않는다 — 「어느/다음 단계에서 뭘 해야 해?」와 한 몸", () => {
    for (const q of ["어느 단계에서 뭘 해야 해?", "다음 단계에서 뭘 해야 해?", "지금 단계에서 뭘 해야 해?"]) {
      expect(실제도착(q), `${q}만 답이 다르다`).toBe("workflow_status");
    }
  });

  it("★ 지시어를 붙여도 **남의 절차**는 안 삼킨다 — 좁히기가 풀린 게 아니다", () => {
    // 지시어를 더하면서 1차가 놓아준 것을 도로 물면 좁히기가 헛일이 된다.
    for (const q of ["이관 절차 뭐야?", "대응 절차 뭐야?", "등급 5단계 뭐야?", "학습 루프 4단계 뭐야?"]) {
      expect(실제도착(q), `${q}: 지시어를 넓히다가 도로 삼켰다`).toBeNull();
    }
  });

  it("★ 그은 선 — 홑지시어 + 「뭐야?」(뜻 물음)는 그대로 놓아준다", () => {
    // 「이 절차 뭐야?」는 **보고 있는 화면의 절차**를 묻는 말일 수 있다(이관·대응·학습 루프).
    //   뜻을 묻는 말이라 화면 안내·지식의 몫이다. 지시어를 잡는 것은 **「해야」(무엇을 할까)**
    //   이거나, 우리 것이 분명한 지시어(지금·현재·이번·우리·전체)일 때로 한정한다.
    expect(실제도착("이 절차 뭐야?"), "뜻을 물었는데 업무 5단계 숫자가 나간다").toBeNull();
    expect(실제도착("그 절차 뭐야?"), "뜻을 물었는데 업무 5단계 숫자가 나간다").toBeNull();
  });
});

describe("★★ 다른 주어의 절차·단계는 놓아준다 — 뜻을 물었으면 뜻을 답한다", () => {
  // 2026-09-08 가로채기 라운드에서 실제로 샌 넷 + 사내 규정 한 꼴.
  const 놓아야: [string, string][] = [
    ["등급 5단계 뭐야?", "공급망 라이선스 등급 — supplychain 화면의 뜻풀이다"],
    ["이관 절차 뭐야?", "인수인계 마법사 — handover 화면의 뜻풀이다"],
    ["대응 절차 뭐야?", "이벤트 유형별 대응 — loganalysis 화면의 뜻풀이다"],
    ["학습 루프 4단계 뭐야?", "학습 루프 — learnloop 화면의 뜻풀이다"],
    ["ISMS 절차 뭐야?", "사내 규정·인증 절차 — 지식(RAG)의 몫이다"],
  ];
  for (const [q, 왜] of 놓아야) {
    it(`「${q}」는 업무 현황이 아니다 (${왜})`, () => {
      expect(실제도착(q), "뜻을 물었는데 업무 5단계 현황 숫자가 나간다").not.toBe("workflow_status");
    });
  }

  it("놓아준 말이 **딴 도구로도** 안 샌다 — 강제 규칙에 아예 안 걸린다", () => {
    // 하나를 막고 다른 하나로 새면 고친 것이 아니다. 화면 안내·RAG가 받아야 할 자리다.
    for (const [q] of 놓아야) {
      expect(실제도착(q), `${q}: 강제 규칙이 아직 물고 있다`).toBeNull();
    }
  });

  it("종전 계약 그대로 — 「이 취약점 조치하려면?」은 그 건의 조치 절차다", () => {
    expect(실제도착("이 취약점 조치하려면?")).not.toBe("workflow_status");
    expect(실제도착("이 취약점 조치 어떻게 해?")).not.toBe("workflow_status");
  });
});

describe("⚠ 이 시험이 헛돌지 않는가", () => {
  it("★★ 놓아준 다섯은 **옛 갈래에는 걸렸다** — 애초에 안 걸리던 말이 아니다", () => {
    for (const q of ["등급 5단계 뭐야?", "이관 절차 뭐야?", "대응 절차 뭐야?", "학습 루프 4단계 뭐야?", "ISMS 절차 뭐야?"]) {
      expect(옛갈래.test(q), `${q}: 옛 갈래에도 안 걸렸다면 이 시험은 아무것도 증명하지 않는다`).toBe(true);
    }
  });

  it("★ 옛 갈래가 소스에서 실제로 사라졌다 — 되돌아오면 위 다섯이 다시 샌다", () => {
    // ⚠ 「(단계|절차)[^.\n]{0,8}(뭐…)」만 찾으면 **좁힌 갈래 안에도 그 글자가 들어 있어** 늘 걸린다.
    //   앞의 갈림표(|)까지 함께 본다 — 주어 없이 홀로 선 갈래만이 옛 꼴이다.
    expect(agentloop, "주어 없는 넓은 갈래가 그대로 남아 있다").not.toContain(String.raw`|(단계|절차)[^.\n]{0,8}(뭐|뭘|무엇|해야)`);
    expect(agentloop, "좁힌 갈래가 없다 — 그러면 「발견 단계에서 뭘 해야 해?」가 죽는다")
      .toContain(String.raw`(발견|수집|우선순위|조치|검증|보고|업무|지금|현재|이번|우리|전체)\s*\d*\s*(단계|절차)[^.\n]{0,8}(뭐|뭘|무엇|해야)`);
    // 홑지시어 갈래는 **「해야」에만** 붙어 있어야 한다 — 여기에 「뭐」가 붙는 순간 「이 절차 뭐야?」가
    //   다시 업무 현황으로 간다(그은 선이 소리 없이 지워지는 자리라 글자로 못 박는다).
    expect(agentloop, "홑지시어 갈래가 없거나 꼬리가 바뀌었다")
      .toContain(String.raw`(?<![가-힣])(이|그)\s*(단계|절차)[^.\n]{0,8}해야`);
  });

  it("★ 홑지시어 앞의 `(?<![가-힣])`가 **일을 한다** — 조사 「이」를 지시어로 읽지 않는다", () => {
    // 없으면 낱말 끝의 「이」(주격 조사)가 지시어로 읽힌다: 「…점이 절차 어떻게 해야 해?」에서
    //   「점**이** 절차」가 「이 절차」로 잡힌다. 그 말은 그 건의 조치 절차라 여기 것이 아니다.
    expect(실제도착("이 취약점이 절차 어떻게 해야 해?"), "조사 「이」를 지시어로 읽었다").not.toBe("workflow_status");
  });

  it("★★ 주어 낱말이 **업무 흐름 5단계에서 온 것**이다 — 잣대는 workflow.ts 한 곳", () => {
    // 규칙이 제 나름의 단계 이름을 지어 쓰면 단계 이름을 고칠 때 한쪽만 바뀐다.
    for (const 이름 of ["발견", "수집", "우선순위", "조치", "검증", "보고"]) {
      expect(workflow, `「${이름}」이 workflow.ts의 단계 이름에 없다 — 규칙이 딴 낱말을 쓴다`)
        .toMatch(new RegExp(`label:\\s*"[^"]*${이름}`));
    }
  });
});
