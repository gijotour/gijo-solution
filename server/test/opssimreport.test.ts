// server/test/opssimreport.test.ts — 야간 회귀 보고서(ops-sim.md)의 **내용 실패 상세**를 시험이 문다.
//
// 왜 생겼나 (2026-09-06 · D4):
//   하네스는 「내용이 다름」·「경고 없는 % 단정」을 **판정까지 해 놓고**, 사람이 읽는 md에는
//   종류 이름만 실었다. 무엇을 기대했고 무엇이 왔는지는 `ops-sim.json`에만 있었다 —
//   야간 회귀(03:00 KST)가 끝나고 보고서만 읽는 사람은 **그 짝을 볼 길이 아예 없었다.**
//   재는 규칙을 늘려 놓고 사람이 읽는 자리에 안 실으면 안 만든 것과 같다.
//
// ★ 왜 이 시험이 있어야 하나: 조립이 ops-sim.mjs 안에 있으면 시험이 못 부른다(그 파일은
//   불러들이는 순간 하네스를 통째로 돌린다). 형제 파일 opssim-rules.mjs를 가른 것과 **같은 이유**로
//   opssim-report.mjs를 갈랐고, 여기서 **가짜 결과로 md를 만들어** 상세 줄이 실제로 나오는지 본다.
//
// 계획서: 중-3(평가 게이트) 곁가지 — 야간 회귀 보고서가 고칠 수 있는 말을 하는가.
import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { 내용실패상세, 기대적기, 상세대상종류 } from "../../tools/opssim-report.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const 뿌리 = join(__dirname, "..", "..");

// 라이브 실물을 본뜬 가짜 회차 — 2026-09-06 「제출률은 92%입니다」 사고 문장 계열.
const 긴답 =
  "사내 보안서약서 제출률은 92%입니다. " +
  "이는 전년 대비 개선된 수치이며 남은 인원에 대해서는 추가 안내가 필요합니다. " +
  "부서별로는 영업본부가 가장 낮고 개발본부가 가장 높은 것으로 나타납니다.";

const 가짜결과 = [
  {
    마당: "⑥ 보고 — 위에 올릴 것",
    q: "보안서약서 제출률 얼마야?",
    out: 긴답,
    도구: [],
    근거세기: "강함",
    근거없음: undefined,
    불편: [{ 종류: "내용이 다름", 상세: "경고 없는 % 단정 — 도구도 근거 표식도 없이 숫자를 확정했다" }],
  },
  {
    마당: "① 아침 — 오늘 뭐부터",
    q: "오늘 뭐부터 해야 해?",
    out: "미조치 취약점 3건이 있습니다. 대시보드에서 확인하세요.",
    도구: ["kpi_status"],
    근거세기: "",
    근거없음: undefined,
    불편: [], // 불편 없음 — 상세에 끼면 안 된다
  },
  {
    마당: "④ 조치 — 손대기",
    q: "이번 주 보고서 썼어?",
    out: "확인해 보겠습니다.",
    도구: [],
    근거세기: "약함",
    근거없음: "사내 근거 없음",
    불편: [
      { 종류: "너무 짧음", 상세: "12자" }, // 상세 대목의 대상이 아니다
      { 종류: "내용이 다름", 상세: "도구 report_activity 기대 · 실제 없음" },
    ],
  },
  {
    // 기계 데이터 누출 — 같은 판정기(내용판정)가 내는 실패라 상세가 함께 실려야 한다.
    // ⚠ 이 줄은 **재검색이 안 돈 답**(근거세기 빈 값)이다 — 그 사실을 감추면 안 된다.
    마당: "③ 파고들기 — 왜 위험한가",
    q: "그 취약점 원본 데이터 보여줘",
    out: '조회 결과입니다. {"doc_id": "kb:aa11", "_distance": 0.1342}',
    도구: [],
    근거세기: "",
    근거없음: undefined,
    불편: [{ 종류: "기계 데이터 누출", 상세: "저장소 내부 표현이 답에 그대로" }],
  },
];

const 가짜기대 = {
  "보안서약서 제출률 얼마야?": { 경고없는퍼센트금지: true },
  "이번 주 보고서 썼어?": { 도구: ["report_activity"], 포함: [/보고서/] },
};

describe("★★ 보고서에 내용 실패 상세가 실린다 — 종류 이름만으로는 못 고친다", () => {
  const 줄 = 내용실패상세(가짜결과, 가짜기대);
  const 본문 = 줄.join("\n");

  it("실패 항목마다 문항이 실린다", () => {
    expect(본문).toContain("「보안서약서 제출률 얼마야?」");
    expect(본문).toContain("「이번 주 보고서 썼어?」");
  });

  it("★ 기대가 실린다 — json을 안 열고도 「무엇을 기대했나」를 안다", () => {
    expect(본문, "경고 없는 % 단정 잣대가 걸린 문항인데 기대가 안 보인다").toContain("경고 없는 % 단정 금지");
    expect(본문, "도구 기대가 안 보인다").toContain("도구 report_activity");
    expect(본문, "포함 기대가 안 보인다").toContain("있어야 할 말 /보고서/");
  });

  it("★ 실제 답이 앞 120자까지 실린다 — 표 칸의 70자로는 판정 사유가 잘린다", () => {
    const 실제줄 = 줄.find((l: string) => l.startsWith("- 실제(앞 120자): ") && l.includes("제출률은 92%"));
    expect(실제줄, "실제 답 줄이 없다").toBeTruthy();
    const 몸 = 실제줄!.replace("- 실제(앞 120자): ", "");
    expect(몸.length, "120자보다 길게 실렸다").toBeLessThanOrEqual(120);
    // 70자에서 끊기면 못 보는 대목이 실제로 보여야 한다(이 시험이 재는 것의 핵심).
    expect(몸.length, "70자에서 끊는 옛 표와 다를 게 없다").toBeGreaterThan(70);
  });

  it("★ 근거세기·근거없음이 함께 실린다 — 「경고 없는 %」는 그 두 칸을 봐야 이해된다", () => {
    expect(본문).toContain("근거세기: 강함");
    expect(본문).toContain("근거세기: 약함");
    expect(본문, "근거없음 표식이 안 보인다").toContain("근거없음 표식: 사내 근거 없음");
    expect(본문, "표식이 없을 때 「없음」이라고 말하지 않는다").toContain("근거없음 표식: 없음");
    expect(본문, "재검색이 안 돌았다는 사실을 감춘다").toContain("근거세기: 없음(재검색 안 돎)");
  });

  it("사유(상세)를 그대로 싣는다 — 「내용이 다름」에서 멈추지 않는다", () => {
    expect(본문).toContain("경고 없는 % 단정 — 도구도 근거 표식도 없이 숫자를 확정했다");
    expect(본문).toContain("도구 report_activity 기대 · 실제 없음");
  });

  it("같은 판정기가 내는 「기계 데이터 누출」도 함께 싣는다", () => {
    expect(본문).toContain("기계 데이터 누출 — 저장소 내부 표현이 답에 그대로");
  });

  it("불편 없는 문항은 안 싣는다 — 보고서가 길어지면 안 읽는다", () => {
    expect(본문, "멀쩡한 문항이 상세에 끼었다").not.toContain("오늘 뭐부터 해야 해?");
  });

  it("상세 대목의 대상이 아닌 불편(너무 짧음)은 사유로 안 적는다", () => {
    expect(본문).not.toContain("너무 짧음");
    expect(상세대상종류.has("내용이 다름")).toBe(true);
    expect(상세대상종류.has("너무 짧음")).toBe(false);
  });

  it("실패가 없으면 없다고 말한다 — 빈 대목을 남기지 않는다", () => {
    const 없는판 = 내용실패상세([{ 마당: "①", q: "잘 되나?", out: "네", 불편: [] }], {});
    expect(없는판.join("\n")).toContain("이번 회차에는 내용 실패가 없습니다");
  });

  it("기대가 안 적힌 문항은 「미기재」라고 말한다 — 없는 기대를 지어내지 않는다", () => {
    expect(기대적기(undefined)).toContain("기대 미기재");
    expect(기대적기({})).toContain("기대 미기재");
  });

  it("여러 줄 답도 한 줄로 눕힌다 — 마크다운 목록이 깨지지 않는다", () => {
    const 판 = 내용실패상세(
      [{ 마당: "①", q: "여러 줄", out: "첫 줄\n둘째 줄\r\n셋째 줄", 불편: [{ 종류: "내용이 다름", 상세: "x" }] }],
      {},
    );
    const 실제줄 = 판.find((l: string) => l.startsWith("- 실제(앞 120자): "));
    expect(실제줄).toBe("- 실제(앞 120자): 첫 줄 둘째 줄 셋째 줄");
  });
});

// ★ 만들어 놓고 안 쓰면 없는 것과 같다 — 이 저장소가 반복해 겪은 실패라 **쓰는 것까지** 감시한다.
describe("★ 하네스가 이 대목을 실제로 싣는다", () => {
  const src = readFileSync(join(뿌리, "tools", "ops-sim.mjs"), "utf8");
  const 코드 = src.split("\n").filter((l) => !l.trim().startsWith("//")).join("\n");

  it("ops-sim.mjs가 내용실패상세를 불러서 md에 넣는다", () => {
    expect(코드, "상세 조립을 import하지 않는다").toContain("opssim-report.mjs");
    expect(코드, "md 조립에서 안 부른다 — 모듈만 있고 보고서는 그대로다").toMatch(/\.\.\.내용실패상세\(/);
  });

  it("사본을 두지 않는다 — 상세 머리글은 조립 파일 한 곳에서만 온다", () => {
    expect(코드, "ops-sim.mjs가 같은 대목을 또 적는다(사본은 곧 어긋난다)")
      .not.toContain("## 내용 실패 상세");
  });
});
