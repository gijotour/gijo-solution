import { describe, it, expect } from "vitest";
import fs from "node:fs";
import path from "node:path";
import { guardCitations } from "../src/engine/citeguard";
import { 새인용원천수거, 인용원천을수거하며, 인용원천보고 } from "../src/engine/citesource";

// ─────────────────────────────────────────────────────────────────────────────
// 🔎 **가드가 본 원천을 qa 응답에 싣는 배관** (2026-09-08 · 갈래 E)
//
// ■ 무엇을 지키나
//   citeguard.test의 「실전 답 기록으로 잰 오탐」은 하네스 기록의 답을 재생한다. 그런데 기록에는
//   근거의 **이름**만 있고 본문이 없어, 「챗 경로 + 조각 있었음」 41건을 통째로 건너뛰고 있었다 —
//   재생이 `guardCitations(t, [])`로 도는데 라이브는 조각을 갖고 돌았으니 재면 **없는 오탐**이 난다.
//   이제 서버가 qa 응답에 「가드가 본 그 두 배열」을 싣고(citesource.ts) 하네스가 행에 적는다.
//
// ■ 왜 소스 감시가 절반인가
//   이 배관의 끝(라우트)은 로그인·LLM·운영 서버가 있어야 돌고, 그건 직렬 자원이라 시험이 못 만진다.
//   그래서 **잎(ALS 통로)은 진짜로 돌려 보고**, 그 사이의 세 고리(llm 보고 · 라우트 싣기 ·
//   하네스 적기)는 코드에 그대로 있는지를 문다. 2026-09-08 검토관이 toolevidence에서 잡은
//   「가운데 고리에 가드가 없어 배선이 끊겨도 초록」을 여기서 처음부터 막는다.
// ─────────────────────────────────────────────────────────────────────────────

const 읽기 = (rel: string) => fs.readFileSync(path.join(__dirname, "..", "src", rel), "utf8");
const disp소스 = 읽기("engine/dispatcher.ts");
const llm소스 = 읽기("engine/llm.ts");
const 하네스소스 = fs.readFileSync(path.join(__dirname, "..", "..", "tools", "ops-sim.mjs"), "utf8");
const 재생시험소스 = fs.readFileSync(path.join(__dirname, "citeguard.test.ts"), "utf8");

describe("★ 잎 통로 — 그릇이 있을 때만 담는다(사람 응답에는 아무 일도 안 난다)", () => {
  it("그릇이 없으면 무동작이다 — 보고해도 아무 데도 안 쌓인다", () => {
    // 비-qa 요청이 지나는 길 그 자체다. 던져도 조용해야 한다.
    expect(() => 인용원천보고(["조각"], ["원천"])).not.toThrow();
  });

  it("담은 값은 **가드에게 준 그 두 배열**이다(모양을 바꾸지 않는다)", () => {
    const 그릇 = 새인용원천수거();
    const 조각 = ["전사 이수율은 82.3%입니다."];
    const 추가 = ["KEV — 실제 공격에 악용된 취약점 목록"];
    인용원천을수거하며(그릇, () => 인용원천보고(조각, 추가));
    expect(그릇.값).toEqual({ 조각, 추가원천: 추가, 보고횟수: 1 });
  });

  it("`조각: null`(판정 보류)과 `[]`(0건)을 뭉개지 않는다", () => {
    // 뭉개면 「검색이 고장 났다」를 「지어냈다」로 단정하게 된다(llm.ragContextFor와 같은 규율).
    const 보류 = 새인용원천수거();
    인용원천을수거하며(보류, () => 인용원천보고(null, []));
    expect(보류.값?.조각, "null이 []로 뭉개졌다 — 재생이 라이브와 다른 판정을 낸다").toBeNull();
    const 영건 = 새인용원천수거();
    인용원천을수거하며(영건, () => 인용원천보고([], []));
    expect(영건.값?.조각).toEqual([]);
  });

  it("★ 첫 보고만 담고 **횟수는 계속 센다** — 한 턴에 여러 번 돌면 시험이 그 사실을 알아야 한다", () => {
    const 그릇 = 새인용원천수거();
    인용원천을수거하며(그릇, () => {
      인용원천보고(["첫 조각"], []);
      인용원천보고(["둘째 조각"], []);
      인용원천보고(["셋째 조각"], []);
    });
    expect(그릇.값?.조각, "나중 보고가 첫 보고를 덮었다").toEqual(["첫 조각"]);
    expect(그릇.값?.보고횟수, "횟수를 안 세면 재생이 엉뚱한 조각으로 잰다(잰 척하는 초록)").toBe(3);
  });

  it("비동기 안에서 보고해도 담긴다(chat은 await 너머에서 보고한다)", async () => {
    const 그릇 = 새인용원천수거();
    await 인용원천을수거하며(그릇, async () => {
      await new Promise((r) => setTimeout(r, 1));
      인용원천보고(["늦게 온 조각"], []);
    });
    expect(그릇.값?.조각).toEqual(["늦게 온 조각"]);
  });

  it("그릇끼리 안 섞인다 — 요청 하나에 그릇 하나", () => {
    const A = 새인용원천수거(), B = 새인용원천수거();
    인용원천을수거하며(A, () => 인용원천보고(["A"], []));
    인용원천을수거하며(B, () => 인용원천보고(["B"], []));
    expect([A.값?.조각, B.값?.조각]).toEqual([["A"], ["B"]]);
  });
});

describe("★ 이 배관이 **값을 내는지** — 조각을 되먹이면 판정이 달라진다", () => {
  // 이 시험이 초록이어야 「41건을 모집단에 넣는다」는 이번 변경에 뜻이 생긴다.
  // 빨강이면 되먹임이 판정을 못 바꾼다는 뜻이라, 배관을 놓을 이유 자체가 사라진다.
  const 정의 = "전사 보안 교육 이수율은 82.3%입니다.";
  const 답 = `교육 현황을 정리했습니다.\n[1]에 따르면 "${정의}"`;

  it("라이브 조건(조각 있음) — 정상 인용을 안 뗀다", () => {
    const g = guardCitations(답, [정의], []);
    expect(g.removed, "라이브와 같은 조건인데 정상 인용을 뗐다").toHaveLength(0);
    expect(g.text).toBe(답);
  });

  it("옛 재생(조각 없음) — **거짓 빨강**이 난다(그래서 41건을 건너뛰고 있었다)", () => {
    const g = guardCitations(답, [], []);
    expect(g.removed.length, "조각 없이도 살아남았다 — 이 라운드의 전제가 바뀌었다").toBeGreaterThan(0);
  });
});

describe("★ 가운데 고리 — 소스 감시(배선이 끊기면 조용히 옛 상태로 돌아간다)", () => {
  it("고리 ① llm이 **가드에게 준 그 두 값**을 보고한다", () => {
    expect(llm소스, "잎 통로를 안 부른다 — 기록이 영영 안 생긴다").toContain("인용원천보고(가드조각, 가드추가원천);");
    expect(llm소스, "가드가 다른 값을 본다 — 기록과 라이브가 어긋난다").toContain("guardCitations(reply, 가드조각, 가드추가원천)");
    // ⚠ llm.ts가 아니라 **잎 모듈**에서 가져와야 한다(아래 고리 ②의 이유와 한 몸이다).
    expect(llm소스, "잎 통로를 다른 곳에서 가져왔다").toMatch(/인용원천보고[^\n]*from "\.\/citesource"/);
  });

  it("★★ 고리 ② dispatcher가 **llm이 아니라 잎 모듈**에서 가져온다(66개 목 함정)", () => {
    // llm을 통째로 흉내 내는 시험이 66파일이고 그 목은 표면을 손으로 나열한다 —
    // 여기서 llm의 심볼을 하나만 더 가져오면 그 66개가 통째로 죽는다(dispatcher.ts:23의 경고).
    expect(disp소스, "잎 모듈에서 안 가져온다").toContain('import { 새인용원천수거, 인용원천을수거하며 } from "./citesource";');
    const llm가져오기 = disp소스.match(/import \{([^}]*)\} from "\.\/llm";/);
    expect(llm가져오기?.[1].trim(), "llm import에 심볼이 늘었다 — 목 66개가 통째로 죽는다").toBe("chat");
  });

  it("★★ 고리 ③ 라우트가 **qa일 때만** 그릇을 놓는다(사람 응답에는 칸조차 안 생긴다)", () => {
    expect(disp소스, "그릇을 qa와 무관하게 놓는다 — 사람 응답에 조각 본문이 실릴 수 있다")
      .toContain("const 근거그릇 = qa ? 새인용원천수거() : null;");
    expect(disp소스, "그릇을 씌우지 않는다 — 보고가 갈 곳이 없어 기록이 늘 빈다")
      .toContain("const work = 근거그릇 ? 인용원천을수거하며(근거그릇, 태우기) : 태우기();");
    expect(disp소스, "담긴 것이 없어도 싣는다 — 빈 칸이 「가드가 안 돌았다」와 뒤섞인다")
      .toContain("if (근거그릇?.값) first.근거원천 = 근거그릇.값;");
  });

  it("응답 타입에 근거원천 칸이 있다(계산만 하고 버리면 하네스가 못 쓴다)", () => {
    expect(disp소스, "DispatchResult에 근거원천 칸이 없다")
      .toMatch(/근거원천\?:\s*\{\s*조각:\s*string\[\]\s*\|\s*null;\s*추가원천:\s*string\[\];\s*보고횟수:\s*number\s*\}/);
  });

  it("★★ 고리 ④ 하네스가 그 칸을 **세 칸 그대로** 행에 적는다", () => {
    expect(하네스소스, "하네스가 근거원천을 안 받는다 — 서버가 실어 줘도 기록에 안 남는다")
      .toContain("{ 근거조각: j.근거원천.조각, 추가원천: j.근거원천.추가원천, 가드횟수: j.근거원천.보고횟수 }");
    // ⚠ 자르지 않는다 — 겹침 판정 창이 20자라 조각 꼬리를 자르면 라이브엔 없던 빨강이 난다.
    const 적는줄 = 하네스소스.slice(하네스소스.indexOf("j.근거원천.조각") - 200, 하네스소스.indexOf("j.근거원천.보고횟수") + 60);
    expect(적는줄, "조각을 잘라 적는다 — 겹침 창(20자)이 깨져 없던 빨강이 난다").not.toMatch(/\.slice\(/);
  });

  it("★★ 고리 ⑤ 재생 시험이 **그 조각으로** 재생하고, 모집단 규칙이 그 칸을 본다", () => {
    expect(재생시험소스, "조각 기록을 안 읽는다 — 새 칸이 생겨도 재생은 옛 갈래로 돈다")
      .toContain("guardCitations(t, 조각기록(r), 추가원천기록(r))");
    expect(재생시험소스, "모집단 (a)가 조각 기록을 안 본다 — 되먹일 수 있는데도 건너뛴다")
      .toContain("if (도구.length === 0 && !조각기록있나(r)) {");
    expect(재생시험소스, "가드가 여러 번 돈 답을 안 거른다 — 어느 호출의 조각인지 모른 채 잰다")
      .toContain("한 턴에 가드가 ${횟수}번(어느 호출의 조각인지 못 가린다)");
  });
});
