// ─────────────────────────────────────────────────────────────────────────────
// ★★★ **잴 수 없는 기록이 「잰 것」으로 세어지지 않는가** (2026-09-08 검토관 [높음]·[중간] 수리)
//   두 자물쇠를 각각 잠근다 — 생산자(citesource가 null을 안 담는다)와 소비자(재생이 배열만
//   「있는 기록」으로 센다). 한쪽만 두면 재료 출처가 바뀔 때 조용히 뚫린다.
// ─────────────────────────────────────────────────────────────────────────────
describe("★★★ 잴 수 없는 기록 — 생산자와 소비자 양쪽에서 막는다", () => {
  it("★ null 조각으로는 가드가 **한 글자도 못 잰다** — 그래서 null은 「잰 것」에 못 든다", () => {
    // 이 실증이 두 자물쇠의 **이유** 전부다. 주석만 두면 다음 사람이 「null도 기록이니 세자」로 되돌린다.
    const 답 = `정리했습니다.\n[1]에 따르면 "있지도 않은 근거입니다."`;
    expect(guardCitations(답, null, []).removed, "null인데 무언가를 쟀다 — citeguard.ts:922가 바뀌었다")
      .toHaveLength(0);
    expect(guardCitations(답, null, []).text, "null인데 글자가 바뀌었다").toBe(답);
    // 같은 답을 []로 재면 실제 판정이 난다 — 즉 null 행은 **절대 빨강이 될 수 없다.**
    const 영건 = guardCitations(답, [], []);
    expect(영건.removed.length + 영건.보류.length, "0건으로도 판정이 안 난다 — 이 실증의 전제가 바뀌었다")
      .toBeGreaterThan(0);
  });

  it("★ 자물쇠 ① 생산자 — 잎 모듈이 `조각 === null`인 보고를 걸러 낸다", () => {
    expect(잎소스, "null 보고를 담는다 — 분류기(routeIntent)의 null이 답의 조각을 가로챈다")
      .toContain("if (조각 === null) return;");
  });

  it("★ 자물쇠 ② 소비자 — 재생이 **배열인가**로 「있는 기록」을 가른다(`in`이 아니다)", () => {
    expect(재생시험소스, '`"근거조각" in r`로 세면 값이 null이어도 참이라 잴 수 없는 행이 문턱을 채운다')
      .toContain("const 조각기록있나 = (r: Record<string, unknown>): boolean => 조각기록(r) !== null;");
    expect(재생시험소스, "배열이 아닌 기록을 사유 없이 삼킨다 — 삼켜진 건너뜀은 없는 시험과 같다")
      .toContain("챗 경로 + 가드 판정 보류(근거조각이 배열이 아니다 — 되먹일 것이 없다)");
  });

  it("회차 로그가 되먹임을 **도구 경로 괄호 밖**에서 갈래별로 찍는다(부분집합으로 안 읽히게)", () => {
    // 「도구 경로 94 … · 그중 조각 되먹임 41건」은 도구의 부분집합처럼 읽힌다 — 실제로는 전부 챗이었다.
    expect(재생시험소스, "되먹임을 갈래별로 안 나눈다 — 로그가 다시 뭉개진다")
      .toContain("(챗 ${챗되먹임} · 도구 ${도구되먹임}");
    const 로그줄 = 재생시험소스.slice(재생시험소스.indexOf("📊 실전 답 오탐 시험"));
    const 괄호 = 로그줄.slice(로그줄.indexOf("(챗 경로"), 로그줄.indexOf("예방 그물") + 6);
    expect(괄호, "되먹임이 도구 경로 괄호 **안**에 있다 — 「도구 N 중 M」으로 읽힌다")
      .not.toContain("되먹임");
  });
});
