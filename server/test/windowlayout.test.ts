// 대화 창을 뺄 때 셸이 자리를 비켜 주는 계산 — 실앱에서 못 보는 쪽을 여기서 본다.
//
// ⚠ 2026-08-01: 예전엔 셸이 안 비켜 줘서 **대화 창이 셸 위를 덮었다.** 모니터 한 대에서
//   앱을 최대화해 두면 오른쪽 4분의 1이 가려졌다 — "창으로 뺐더니 화면이 잘렸다"가 된다.
//
// ⚠ 개발 머신이 세로 모니터(1080×1920)라 **실앱에서는 "안 비켜 주는 쪽"만 확인된다**
//   (420+900=1320 > 1080이라 애초에 자리가 없다). 비켜 주는 쪽은 이 시험이 유일한 근거다.
import { describe, it, expect } from "vitest";
import { 겹치나, 셸옮길자리 } from "../../client/src/util/layout";

const 사각 = (x: number, y: number, width: number, height: number) => ({ x, y, width, height });

describe("겹침 판정", () => {
  it("맞닿기만 하면 안 겹친 것", () => {
    expect(겹치나(사각(0, 0, 100, 100), 사각(100, 0, 100, 100))).toBe(false);
  });
  it("1px라도 물리면 겹친 것", () => {
    expect(겹치나(사각(0, 0, 100, 100), 사각(99, 0, 100, 100))).toBe(true);
  });
  it("세로가 어긋나면 안 겹친다", () => {
    expect(겹치나(사각(0, 0, 100, 100), 사각(50, 200, 100, 100))).toBe(false);
  });
});

describe("셸을 어디로 옮기나", () => {
  it("가로 모니터(1920) — 셸이 왼쪽으로 줄어든다", () => {
    // 1920 화면에서 대화 창이 오른쪽 538px(28%)을 쓰면 셸에 1382px이 남는다.
    const 셸 = 사각(0, 0, 1920, 1080);
    const 대화창 = 사각(1382, 0, 538, 1080);
    const r = 셸옮길자리(셸, 대화창);
    expect(r, "가로 모니터인데 안 비켜 준다").not.toBeNull();
    expect(r!.width).toBe(1382);
    expect(겹치나(r!, 대화창), "옮긴 뒤에도 겹친다").toBe(false);
    // 세로와 왼쪽 위치는 그대로 — 창이 위아래로 튀면 담당자가 놀란다.
    expect(r!.x).toBe(셸.x);
    expect(r!.y).toBe(셸.y);
    expect(r!.height).toBe(셸.height);
  });

  it("세로 모니터(1080) — 자리가 없으면 건드리지 않는다", () => {
    // ★ 이 개발 머신의 실제 값이다. 셸이 640px로 쪼그라들면 우리 표가 안 들어간다.
    //   표가 안 들어가는 폭으로 밀어 넣느니 겹치는 게 낫다 — 겹침은 창을 옮겨 풀 수 있지만
    //   못 읽는 표는 풀 방법이 없다.
    const 셸 = 사각(20, 486, 1040, 900);
    const 대화창 = 사각(660, 0, 420, 1872);
    expect(겹치나(셸, 대화창), "이 배치는 실제로 겹친다").toBe(true);
    expect(셸옮길자리(셸, 대화창), "좁은데도 밀어 넣었다").toBeNull();
  });

  it("애초에 안 겹치면 건드리지 않는다", () => {
    // 두 번째 모니터에 대화 창을 둔 경우 — 멀쩡한 창을 흔들지 않는다.
    const 셸 = 사각(0, 0, 1920, 1080);
    const 대화창 = 사각(1920, 0, 538, 1080);
    expect(셸옮길자리(셸, 대화창)).toBeNull();
  });

  it("최소폭 경계 — 딱 맞으면 옮기고, 1px 모자라면 안 옮긴다", () => {
    const 셸 = 사각(0, 0, 1500, 1000);
    expect(셸옮길자리(셸, 사각(900, 0, 600, 1000))!.width).toBe(900);
    expect(셸옮길자리(셸, 사각(899, 0, 601, 1000))).toBeNull();
  });
});
