// 낱말 경계 그물 — 「얘기」의 「얘」가 물린 것과 같은 사고를 잡는다 (2026-08-09, 계획서 전-7).
//
// 무슨 일이 있었나: 선택 치환의 지시어 정규식이 `얘`를 대명사로 잡는 바람에
// 「그냥 아무 **얘기**나 해봐」가 자산 목록 조회로 갔다. 평가 게이트가 아니었으면
// 조용히 나갈 뻔했다. 고친 방법은 낱말 뒤에 한글이 붙으면 다른 낱말로 보는 것 —
//   (?![가-힣])
//
// ⚠ 이 시험은 **정규식 모양을 보지 않는다.** 평범한 말을 넣어 걸리는지로 본다.
//   모양 검사는 새 규칙이 생기면 못 따라가지만, 말을 넣는 검사는 규칙이 늘어도 그대로 산다.
//   사고가 난 방식(사람이 평범하게 말했다)과 같은 방식으로 재는 것이 핵심이다.
//
// 새 라우팅 규칙을 더할 때 여기 말을 몇 개 보태 두면, 다음 사람이 같은 함정에 안 빠진다.
import { describe, it, expect, vi } from "vitest";

vi.mock("../src/engine/assets", async (importOriginal) => {
  const mod = (await importOriginal()) as Record<string, unknown>;
  return { ...mod, listAssets: () => [{ id: "vuln:sample-web01", name: "sample-web01" }] };
});

import { 선택을박는다, forcedToolFor } from "../src/engine/agentloop";

/** 대명사·지시어를 **낱말 속에 품고 있는** 평범한 말. 전부 그냥 지나가야 한다. */
const 평범한말 = [
  // 「얘」 — 실제 사고가 난 자리
  "그냥 아무 얘기나 해봐", "얘기 좀 들어줘", "재미있는 얘깃거리 없어?",
  // 「이거」·「이것」
  "이것저것 알려줘", "이거참 어렵네", "이곳은 어디야",
  // 「그 거」
  "그 거리 어디야?", "그거참 신기하네", "그런데 말이야",
  // 「요」 — 「필요·중요·주요·소요」에 다 들어 있다
  "필요 자산 목록 보여줘", "중요 항목이 뭐야", "주요 서버 알려줘", "소요 시간 얼마나 걸려",
  // 「해당」·「저」
  "해당사항 없음", "저장 공간 얼마나 남았어", "저녁에 뭐 먹지",
  // 「자산」이 든 긴 낱말
  "자산관리 어떻게 해", "자산가치 평가 방법",
  // 「선택」·「고른」·「지금」
  "선택지가 뭐가 있어", "선택권은 누구한테 있어", "고른 사람이 누구야",
  "지금 몇 시야", "지금까지 고생했어",
  // 「항목」·「시스템」이 든 일반어
  "항목별로 설명해줘", "시스템 공학이 뭐야",
  // 순수 잡담
  "고마워", "안녕하세요", "오늘 날씨 어때", "점심 뭐 먹을까", "수고했어요",
];

describe("선택 치환이 평범한 말을 대명사로 오인하지 않는다", () => {
  it.each(평범한말)("그대로 지나간다 — %s", (말) => {
    expect(선택을박는다(말, "자산 sample-web01")).toBe(말);
  });

  it("★ 진짜 대명사는 여전히 바뀐다 — 막느라 기능을 죽이면 안 된다", () => {
    expect(선택을박는다("얘 취약점 알려줘", "자산 A")).toBe("자산 A 취약점 알려줘");
    expect(선택을박는다("이것 조치해줘", "자산 A")).toBe("자산 A 조치해줘");
    expect(선택을박는다("이 자산 미조치 몇 건이야?", "자산 A")).toBe("자산 A 미조치 몇 건이야?");
  });
});

describe("잡담이 도구로 새지 않는다", () => {
  // 업무 질문은 도구로 가는 게 맞다 — 여기 담은 건 도구가 돌면 안 되는 말들만.
  const 잡담 = [
    "그냥 아무 얘기나 해봐", "얘기 좀 들어줘", "재미있는 얘깃거리 없어?",
    "이것저것 알려줘", "이거참 어렵네", "그 거리 어디야?", "그거참 신기하네",
    "저녁에 뭐 먹지", "고마워", "안녕하세요", "오늘 날씨 어때", "점심 뭐 먹을까",
    "수고했어요", "지금 몇 시야", "지금까지 고생했어", "선택권은 누구한테 있어",
  ];
  it.each(잡담)("강제 라우팅에 안 걸린다 — %s", (말) => {
    expect(forcedToolFor(말)).toBeNull();
  });
});
