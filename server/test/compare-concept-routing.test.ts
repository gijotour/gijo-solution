import { describe, it, expect } from "vitest";
import { 결정적도착지 } from "../src/engine/dispatcher";
import { forcedToolFor, 비교개념질문 } from "../src/engine/agentloop";
import { 실제도착, 가로챈규칙 } from "./helpers/routing";

describe("★ 「A랑 B 뭐가 달라?」류는 explain(topic=원문)으로 결정적으로 간다", () => {
  const 양성 = [
    "스캔 실패랑 취약점이 뭐가 달라?", // ← B7 라이브 재현 문장 그대로
    "EPSS랑 VPR 뭐가 달라?",
    "KEV랑 EPSS 뭐가 달라?",
    "VPN과 제로트러스트의 차이를 비교해줘",
    "취약점이랑 위협이 어떻게 달라?",
    "위협과 리스크의 차이가 뭐야",
    "EDR하고 백신이 뭐가 다른가요",
    "SIEM과 SOAR의 차이점 알려줘",
    "CVSS와 EPSS 차이 설명해줘",
    "제로트러스트랑 VPN 차이가 뭔지 궁금해",
    "오탐이랑 미탐 뭐가 달라?",
    "ISMS-P랑 ISO27001 차이가 뭐야?",
    "취약점 점검이랑 모의해킹 뭐가 달라?",
    "자산이랑 부품은 어떻게 다른가요",
    "패치랑 완화조치 뭐가 다른지",
    "KEV와 VPR 어떤 점이 다른가요",
    "스캔 실패와 취약점의 차이점을 설명해줘",
    "EPSS와 VPR을 비교해줘",
  ];
  // 18문장 전부 착수 전 route-explain 실측 ∅(걸리는 규칙 없음) — 이 시험이 새로 닫는 자리다.
  for (const 문장 of 양성) {
    it(`「${문장}」 → explain(topic=원문)`, async () => {
      const 도둑 = 가로챈규칙(문장, "explain");
      const 걸림 = await 결정적도착지(문장, { 역할: "admin" });
      const 첫 = 걸림[0];
      const 사유 = 도둑
        ? `앞 규칙 [${도둑.차례}] ${도둑.도구}가 가로챘다`
        : `강제 규칙엔 걸린다(forcedToolFor=${실제도착(문장)}) — 앞선 특수경로가 먼저 채 갔다: ${걸림.map((x) => x.도착).join(" → ") || "(아무것도 안 걸림)"}`;
      expect(첫?.도착 ?? null, 사유).toBe("explain");
      // topic이 지시문 전체(원문)임을 못 박는다 — 「A vs B」로 합성하지 않는다(설계관 근거).
      const 강제 = forcedToolFor(문장, { role: "admin" } as never);
      expect(강제?.args?.topic, "topic은 지시문 원문이어야 한다(합성하지 않는다)").toBe(문장);
    });
  }
});

