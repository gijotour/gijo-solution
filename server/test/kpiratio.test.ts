    // 우리 것은 그대로 지나간다 — 주어 배제가 세는 지표를 삼키면 안 된다.
    expect(안세는지표찾기("조치 완료율 어때?")).toEqual([]);
    expect(안세는지표찾기("규정 준수율 얼마야?")).toEqual([]);
