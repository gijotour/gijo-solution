// 사내 지표율 — **있는 값을 지어내지 않는다 · 없는 값을 있는 척하지 않는다** (2026-09-06 · 전-4)
//
// ■ 사고(실측): 「보안 교육 이수율은 82.3%입니다 · 작년 대비 12.5% 증가 · 36.4%」가 그대로 나갔다.
//   그 숫자는 chat_logs 5,998행·운영 문서 전수에 **0건** — 모델이 지어냈다.
//   그런데 kpi.ts는 조치율·SLA 준수율·컴플라이언스 이행률을 **이미 계산해 두고 있었다.**
//   뿌리는 라우팅이다: [7]은 「보안 KPI·보안 지표·보안 점수」라는 제품 이름을 댈 때만 잡고,
//   [16]은 어제·지난주 비교만 잡아, **지표 이름으로 부르는 말**이 통째로 모델 재량으로 샜다.
//
// ■ 두 방향을 함께 잰다
//   ① 세는 지표는 도구로 못 박힌다(값이 나온다)   ② 안 세는 지표는 「아직 집계하지 않습니다」라고 말한다
//   그리고 ③ **가로채면 안 되는 말**(절차·방법·법령)은 이 규칙이 안 건드린다.
import { describe, it, expect } from "vitest";
import { forcedToolFor } from "../src/engine/agentloop";
import { 안세는지표찾기, runKpiStatus } from "../src/engine/agenttools/handlers";

const 강제 = (말: string) => forcedToolFor(말);

describe("★ 라우팅 — 지표 이름으로 물어도 kpi_status로 간다", () => {
  // 사고 문장 계열 + 담당자가 실제로 쓰는 말투 10개(변형 표본).
  const 가야하는말 = [
    "조치 완료율 어때?",
    "조치율 얼마나 돼?",
    "SLA 준수율 몇 %야?",
    "SLA 준수 현황 보여줘",
    "보안 교육 이수율 알려줘",
    "패치 적용률 얼마야?",
    "자산 등록률 어떻게 돼?",
    "작년 대비 나아졌어?",
    "올해 대비 어때?",
  ];
  for (const 말 of 가야하는말) {
    it(`「${말}」 → kpi_status`, () => {
      expect(강제(말)?.tool, "모델 재량으로 새면 그날그날 다른 %가 나온다").toBe("kpi_status");
    });
  }

  it("★ 물음을 그대로 넘긴다 — 안 넘기면 「안 세는 지표」를 정직하게 말할 수 없다", () => {
    expect(강제("보안 교육 이수율 알려줘")?.args.q).toBe("보안 교육 이수율 알려줘");
  });

  // ⚠ 반대편 — 넓게 잡으면 남의 영토를 삼킨다(낱말 가로채기 계보).
  const 가면안되는말: [string, string][] = [
    ["조치율 계산 기준이 뭐야?", "기준을 묻는 말은 지식의 영토다"],
    ["조치 완료율 올리는 방법 알려줘", "개선 방법은 지식·절차의 영토다"],
    ["개인정보 보호법 제29조 알려줘", "법령은 law_lookup의 영토다"],
    ["환율 얼마야?", "「율」 홑낱말을 잡으면 이런 말까지 삼킨다"],
    ["취약점 조치 절차 알려줘", "절차는 플레이북의 영토다"],
    // ⚠ 아래 일곱은 2026-09-06 검토가 잡은 **약속-코드 불일치**다. 주석·커밋·routes 표가 셋 다
    //   「조치율 어떻게 올려?」를 예로 들었는데, 배제어에 사전형(올리·구하)만 적어 두어
    //   활용형(올려·올릴·구해)이 안 걸렸다 — 개선 방법을 묻는 말에 숫자표가 나가고 있었다.
    ["조치율 어떻게 올려?", "활용형 — 세 곳이 약속한 바로 그 예문이다"],
    ["조치 완료율 어떻게 올릴까?", "같은 말의 다른 활용"],
    ["조치율 어떻게 구해?", "산출 방법을 묻는 말"],
    ["SLA 준수율 어떻게 개선해?", "개선 방법은 지식의 영토"],
    ["조치율이 무슨 뜻이야?", "뜻풀이는 지식의 영토 — 형제 규칙(VEX)과 같은 배제"],
    ["SLA 준수율이란?", "같은 갈래"],
    ["이행률 뭐야?", "같은 갈래(낱말 가로채기 계보)"],
  ];
  for (const [말, 왜] of 가면안되는말) {
    it(`「${말}」 → kpi_status가 아니다 (${왜})`, () => {
      expect(강제(말)?.tool).not.toBe("kpi_status");
    });
  }

  it("옛 규칙 둘은 그대로 산다 — 새 규칙을 배열 끝에 뒀다(앞을 가로채지 않는다)", () => {
    expect(강제("보안 KPI 현황")?.tool).toBe("kpi_status");     // [7]
    expect(강제("어제와 비교해줘")?.tool).toBe("kpi_status");   // [16]
  });

  it("★ 「컴플라이언스 이행률」은 **컴플라이언스 도구**가 이긴다 — 내 기대가 틀렸던 자리", () => {
    // 처음엔 이 말도 kpi_status로 가야 한다고 적었다가 시험이 잡았다(2026-09-06).
    // 제품이 옳다: compliance_status[12]가 배열에서 앞이고, 그 도구는 **항목별 이행 현황**을
    // 준다(kpi는 이행률 한 숫자만 준다). 기대표는 **제품을 보고** 적는다 — 내 짐작을 적으면
    // 시험이 제품을 모함한다(ops-sim 기대표가 2026-08-09에 배운 그 교훈).
    expect(강제("컴플라이언스 이행률 알려줘")?.tool).toBe("compliance_status");
  });
});

describe("★ 정직 — 안 세는 지표를 있는 척하지 않는다", () => {
  it("안세는지표찾기: 세는 것은 지나가고 안 세는 것만 걸린다", () => {
    expect(안세는지표찾기("조치 완료율 어때?")).toEqual([]);
    expect(안세는지표찾기("SLA 준수율 몇 %야?")).toEqual([]);
    expect(안세는지표찾기("컴플라이언스 이행률 알려줘")).toEqual([]);
    expect(안세는지표찾기("보안 교육 이수율 알려줘")).toEqual(["교육 이수율"]);
    expect(안세는지표찾기("패치 적용률 얼마야?")).toEqual(["패치 적용률"]);
    expect(안세는지표찾기("보안 KPI 현황")).toEqual([]);
    expect(안세는지표찾기(undefined)).toEqual([]);
  });

  it("★ 주어를 본다 — 「교육 완료율」은 「조치 완료율」이 아니다(2026-09-06 검토 적발)", () => {
    // 표가 낱말(완료율·준수율)만 보고 주어를 안 봐서, 제품이 세지도 않는 지표가 **세는 것으로**
    // 분류돼 정직 문장이 빠졌다. 같은 지표를 다른 말투로 물으면 답이 갈리는 상태였다.
    expect(안세는지표찾기("교육 완료율 알려줘")).toEqual(["교육 완료율"]);
    expect(안세는지표찾기("점검 완료율 어때?")).toEqual(["점검 완료율"]);
    expect(안세는지표찾기("훈련 이수 완료율 알려줘")).toEqual(["이수 완료율"]);
    expect(안세는지표찾기("인식 교육 준수율 얼마야?")).toEqual(["교육 준수율"]);
    // 우리 것은 그대로 지나간다 — 주어 배제가 세는 지표를 삼키면 안 된다.
    expect(안세는지표찾기("조치 완료율 어때?")).toEqual([]);
    expect(안세는지표찾기("규정 준수율 얼마야?")).toEqual([]);
    expect(안세는지표찾기("완료율 얼마야?")).toEqual([]);
  });

  it("★ 답이 그 사실을 말한다 — 「아직 집계하지 않습니다」", async () => {
    const 답 = await runKpiStatus("보안 교육 이수율 알려줘");
    expect(답).toContain("아직 집계하지 않습니다");
    expect(답).toContain("교육 이수율");
    // ⚠ 그러면서도 **아는 값은 준다** — 「모른다」만 하고 끝내면 담당자는 빈손으로 돌아선다.
    expect(답).toContain("보안 KPI 현황");
  });

  it("세는 지표를 물으면 그 사실을 말하지 않는다 — 없는 경고를 만들지 않는다", async () => {
    expect(await runKpiStatus("조치 완료율 어때?")).not.toContain("아직 집계하지 않습니다");
    expect(await runKpiStatus()).not.toContain("아직 집계하지 않습니다");
  });

  it("★ 부르는 이름이 달라도 같은 값임을 잇는다 — 답에 「조치율」만 있으면 딴 얘기로 읽힌다", async () => {
    const 답 = await runKpiStatus("조치 완료율 어때?");
    expect(답).toContain("조치율");
    expect(답, "동의어 줄이 없으면 「조치 완료율」로 물은 사람이 자기 값을 못 찾는다").toContain("조치 완료율");
  });
});
