// 「기한 지난 ○○」 — 세 영토가 실제로 갈리는가 (2026-09-07 · 야간 회귀 ① 수리)
//
// ★★ 왜 이 시험이 필요한가 (실측 사고)
//   agentloop.ts의 finding_status 규칙 주석은 예전부터 이렇게 약속해 두었다:
//     「⚠ 취약점|건|거 앵커 필수 — 「기한 지난 점검 일정」(maintenance)·「기한 지난 일」(할 일)은
//       다른 영토라 삼키지 않는다.」
//   그런데 **삼키지 않기만 했지 그 두 영토로 보내는 규칙이 없었다.** 둘 다 아무 규칙에도
//   안 걸려 모델 판단으로 흘렀고(제품 함수 forcedToolFor로 실측: 둘 다 null),
//   2026-09-06 야간 회귀에서 「기한 지난 일 있어?」가 **system_log_status**로 가서
//   「올린 문서에 숨은 지시문 발견」 같은 **시스템 처리 실패 6건**을 할 일이라며 나열했다.
//   담당자가 기한 지난 자기 일을 물었는데 제품 내부 로그가 나온 것이다.
//   ⚠ 09-06까지 초록이던 이유는 그날 실패가 0건이라 답에 「없」이 들어가 기대표를
//     우연히 통과했기 때문이다 — 기능이 맞아서가 아니었다.
//
// ★ 판정은 **제품 함수**(forcedToolFor)가 한다 — 정규식을 떼어 혼자 재면 앞 규칙이
//   가로채는 것을 못 본다(helpers/routing.ts 머리글).
import { describe, it, expect } from "vitest";
import { 실제도착, 가로챈규칙 } from "./helpers/routing";

describe("★★ 「기한 지난」 세 영토", () => {
  it("「기한 지난 일 있어?」 → 할 일(urgent_todo)", () => {
    const 문장 = "기한 지난 일 있어?";
    const 도둑 = 가로챈규칙(문장, "urgent_todo");
    expect(실제도착(문장), 도둑 ? `앞 규칙 [${도둑.차례}] ${도둑.도구}가 가로챘다` : "아무 규칙에도 안 걸린다 — 모델이 시스템 로그를 고른다")
      .toBe("urgent_todo");
  });

  it("「기한 지난 점검 일정 알려줘」 → 점검(maintenance_status)", () => {
    const 문장 = "기한 지난 점검 일정 알려줘";
    const 도둑 = 가로챈규칙(문장, "maintenance_status");
    expect(실제도착(문장), 도둑 ? `앞 규칙 [${도둑.차례}] ${도둑.도구}가 가로챘다` : "아무 규칙에도 안 걸린다")
      .toBe("maintenance_status");
  });

  it("「기한 지난 취약점 있어?」 → 종전 그대로 finding_status", () => {
    expect(실제도착("기한 지난 취약점 있어?"), "새 규칙이 옛 영토를 삼켰다").toBe("finding_status");
    expect(실제도착("조치 기한 넘긴 취약점 있어?"), "새 규칙이 옛 영토를 삼켰다").toBe("finding_status");
  });
});

describe("★ 새 규칙이 남의 말을 삼키지 않는다", () => {
  // 기한이 안 걸린 말은 종전 길 그대로여야 한다 — 새 규칙은 「기한 지난」이 있을 때만 산다.
  it("「승인 기다리는 것 있어?」는 그대로 maintenance_status", () => {
    expect(실제도착("승인 기다리는 것 있어?")).toBe("maintenance_status");
  });
  it("「지금 손댈 일 뭐야?」는 그대로 urgent_todo", () => {
    expect(실제도착("지금 손댈 일 뭐야?")).toBe("urgent_todo");
  });
  it("쓰기 지시는 삼키지 않는다 — 「기한 지난 조치 마무리를 할 일로 담아줘」", () => {
    expect(실제도착("기한 지난 조치 마무리를 할 일로 담아줘"), "조회 규칙이 쓰기 재료 흐름을 가로챘다")
      .not.toBe("urgent_todo");
  });
  it("절차 질문은 삼키지 않는다 — 「기한 지난 점검 절차 알려줘」", () => {
    expect(실제도착("기한 지난 점검 절차 알려줘"), "지식 질문을 현황 도구가 가로챘다")
      .not.toBe("maintenance_status");
  });
});

// ── 검토관 라운드 수리 (2026-09-07) — **배정(쓰기) 지시를 삼키면 한 수로 끝난다** ──────────
//
// ★★ 왜: 강제 경로는 도구를 부르고 **즉시 끝난다**(runAgentLoop의 빠른 길). 조회 도구로 못
//   박히면 「조회 → 배정」 2수 흐름이 통째로 죽어, 시킨 일은 안 되고 목록만 나간다.
//   같은 파일에 선례가 있다 — `if (f.tool === "today" && isAssign) continue;`
//   (2026-08-09 파일럿 리허설: today 강제가 배정 명령을 흡수해 대본이 그 자리에서 깨졌다).
//   새 규칙 둘에 그 배제가 없었고, **옛 urgent_todo 규칙도 같은 구멍**이었다.
describe("★ 배정(쓰기) 지시는 조회 도구로 못 박지 않는다", () => {
  const 쓰기말 = [
    "기한 지난 점검 있으면 담당자한테 배정해줘",
    "기한 지난 점검 목록 뽑아서 김보안한테 배정해줘",
    "기한 지난 일 있으면 김보안한테 배정해줘",
    "밀린 점검 있으면 담당자 지정해줘",
    "기한 지난 점검 현황 보고 담당자를 김도희로 지정해줘",
    "지금 손댈 일 김보안한테 배정해줘",
  ];
  for (const 문장 of 쓰기말) {
    it(`「${문장}」 — 조회로 끝내면 배정이 영영 안 된다`, () => {
      expect(["urgent_todo", "maintenance_status", "today"]).not.toContain(실제도착(문장));
    });
  }

  it("조회는 그대로다 — 「미배정 점검 몇 건이야?」는 시키는 말이 아니다", () => {
    expect(실제도착("기한 지난 일 있어?")).toBe("urgent_todo");
    expect(실제도착("기한 지난 점검 일정 알려줘")).toBe("maintenance_status");
  });
});
