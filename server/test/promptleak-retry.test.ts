// 복창 그물 3차 — **재작성 지시문**과 **번호로 늘어놓은 규칙**.
//
// 왜 또 필요한가(2026-08-03 실전 147상황, 담당자 화면에 그대로 나간 답 두 개):
//   ① "실제로 악용되는 것만 골라줘" →
//      `직전에 작성된 답변은 영어로 작성되었습니다. 이어서 한국어로 다시 작성하십시오. …`
//      우리가 모델에게 준 **재작성 지시문**이 답이 됐다.
//   ② "상관분석 결과 보여줘" →
//      `당신의 질문에 대해서는 다음과 같이 답변합니다. 1. GIJO AS는 … 4. 개인이름·페르소나는 …
//       9. 무관한 내용은 절대 언급하지 말고 배제하세요.`
//      시스템 프롬프트의 번호 목록을 **골라 베꼈다**(1·4·5·6·7·9·10 — 번호가 건너뛴다).
//
// ★ 둘 다 **원문 대조(n-gram)로는 못 잡는다** — 모델이 바꿔 말했기 때문이다.
//   축자 일치를 늘리는 길은 이미 네 번 실패했다(07-20 · 07-30 · 08-02 · 08-03).
//   그래서 **뜻**으로 잡는다: 자기 답변에게 다시 쓰라고 시키는 문장 / 건너뛴 번호의 규칙 목록.
import { describe, it, expect } from "vitest";
import fs from "node:fs";
import path from "node:path";
import { hasPromptLeak } from "../src/engine/llm";
// 건너뛸 사유 문구는 **한 곳**에 산다 — 파일마다 따로 적으면 어긋난다(2026-09-08).
import { 건너뛸사유 } from "../../tools/opssim-evidence.mjs";

describe("복창 그물 — 실제로 새어 나간 두 답을 잡는다", () => {
  it("재작성 지시문 복창을 잡는다", () => {
    const 실제 =
      "직전에 작성된 답변은 영어로 작성되었습니다. 이어서 한국어로 다시 작성하십시오. 영어 문장을 사용하지 마세요. " +
      "코드, 명령어, CVE, 제품명, 버전 같은 고유 표기는 원문대로 유지하세요.";
    expect(hasPromptLeak(실제), "재작성 지시문이 답으로 나가는데 못 잡는다").toBe(true);
  });

  it("번호로 늘어놓은 규칙 복창을 잡는다", () => {
    const 실제 = [
      "당신의 질문에 대해서는 다음과 같이 답변합니다.",
      "",
      "1. GIJO AS는 AI 자산 보안 관리 플랫폼에서 AI 지식·모델 관리 및 우선순위 판단을 담당하는 보안 AI입니다.",
      "4. 개인이름·페르소나는 사용하지 않고, 한국어로만 쓴다.",
      "5. 사내 지식 베이스 또는 네 사전지식을 우선 근거로 삼아 답하고, 무관한 내용은 무시합니다.",
      "6. 대상은 기업 보안담당자입니다.",
      "7. 같은 결론이나 판단은 반복하지 않습니다.",
      "9. 무관한 내용은 절대 언급하지 말고 배제하세요.",
    ].join("\n");
    expect(hasPromptLeak(실제), "규칙 목록이 답으로 나가는데 못 잡는다").toBe(true);
  });
});

describe("★ 오탐 방지 — 정상 답을 복창으로 몰지 않는다", () => {
  const 정상 = [
    // 번호 목록은 정상 답에 흔하다 — 번호가 이어지면 건드리면 안 된다.
    "조치 순서입니다.\n1. 영향 자산·범위 확인\n2. 벤더 권고·패치 확인\n3. 우선순위에 따라 일정 배정\n4. 조치 후 재점검",
    // "다시 작성"이 들어가도 자기 답변 얘기가 아니면 정상이다.
    "보고서를 다시 작성하시려면 \"이번 주 취약점 보고서 만들어줘\"라고 말씀해 주세요.",
    "이전 점검 결과를 다시 확인하세요 — 기한이 지난 항목이 5건 있습니다.",
    "미조치 취약점은 14건입니다. 그중 실제 악용(KEV)으로 분류된 것이 8건입니다.",
    "저는 GIJO AS의 보안 어시스턴트입니다. 자산·취약점·점검 현황을 물어보시면 됩니다.",
  ];
  for (const 답 of 정상) {
    it(`통과 — "${답.split("\n")[0].slice(0, 30)}…"`, () => {
      expect(hasPromptLeak(답), "정상 답이 복창으로 막혔다").toBe(false);
    });
  }
});

// ── 실전 전체 대조 ────────────────────────────────────────────────────────
// 표본을 내가 고르면 내 그물에 안 걸리는 것만 고르게 된다. 실전 기록을 통째로 넣는다.
const 기록 = path.join(__dirname, "../../.tmp-reports/ops-sim.json");
const 답들: { q: string; out: string }[] = (() => {
  if (!fs.existsSync(기록)) return [];
  try {
    const j = JSON.parse(fs.readFileSync(기록, "utf8"));
    return (Array.isArray(j) ? j : j.results || [])
      .map((x: { q?: string; out?: string }) => ({ q: String(x.q ?? ""), out: String(x.out ?? "") }))
      .filter((x: { out: string }) => x.out.trim().length > 0);
  } catch {
    return [];
  }
})();

// ⏭ **왜 건너뛰는지를 로그에 찍는다**(2026-09-08). skipped 한 글자만 보이면 다음 사람은
//   고장으로 읽고 재료를 옮기려 든다 — 그런데 gb10 사본에서 재료가 없는 것은 **일부러다**
//   (이 기록에 등급 C 사내 문답 조각이 평문으로 담겨 원격으로 안 내보낸다). 그 사실을 여기서 말한다.
const 사유 = 건너뛸사유(기록, 답들.length);
if (사유) console.log(`⏭ 프롬프트 복창 — 실전 답 대조를 건너뜁니다 · ${사유}`);

describe.skipIf(답들.length < 50)(`실전 답 ${답들.length}건 대조`, () => {
  it("새 그물이 잡는 것은 **정말로 복창인 것**뿐이다", () => {
    // 새 규칙 둘만 따로 잰다 — 기존 그물이 잡던 것과 섞으면 새 규칙의 오탐을 못 본다.
    const 재작성 = /(직전|이전)(에)?\s*(작성된\s*)?답변[이은는의을를에]?[^\n]{0,40}(다시\s*(작성|기술|서술)|한국어로만?\s*(다시\s*)?(작성|기술))|다시\s*작성하(십시오|세요|시기)/;
    const 걸린것 = 답들.filter((a) => 재작성.test(a.out));
    // 실전에서 이 그물에 걸리는 것은 **실제 누출 1건**이어야 한다. 더 걸리면 오탐을 보라.
    const 보고 = 걸린것.map((a) => `  「${a.q.slice(0, 26)}」 → ${a.out.slice(0, 70).replace(/\n/g, " ")}`).join("\n");
    expect(걸린것.length, `재작성 그물에 ${걸린것.length}건 — 오탐인지 보라:\n${보고}`).toBeLessThanOrEqual(2);
  });

  it("이 대조가 헛돌고 있지 않다", () => {
    expect(답들.length, "실전 기록을 못 읽었다").toBeGreaterThanOrEqual(50);
  });
});
