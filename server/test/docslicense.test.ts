// 고객 설치본에 실리는 문서의 **재배포 권리**를 지킨다 (2026-08-22 신설).
//
// ■ 왜 생겼나 — 우리는 상용 제품인데 「배포하면 안 되는」 문서 7종을 싣고 있었다
//   공공기관 가이드를 PDF→마크다운으로 바꿔 지식 번들에 담아 **고객 설치본과 함께 배포**했다.
//   판권면을 실제로 열어 보니:
//     · SW 공급망 보안 가이드라인 → **CC BY-NC-ND**(비영리·변경금지)
//     · ISMS-P 인증기준 안내서   → **공공누리 제4유형**(상업적 이용금지·변경금지)
//     · 랜섬웨어 대응 가이드라인 → 「진흥원의 **허가 없이** 무단전재 및 복사를 금하며…」
//     · 침해사고·가명정보·영향평가 → 전부 「무단전재를 금하며…」
//     · 제로트러스트 2.0        → **표기 자체가 없음**(허락이 없다는 뜻이다)
//
//   ⚠ **가장 아픈 것**: 그 문장들이 **우리가 변환한 .md 안에 이미 들어 있었다.**
//     랜섬웨어 문서 1002행에 「허가 없이 무단전재 및 복사를 금하며」가 그대로 있었고,
//     우리는 그 문장을 실은 채로 배포했다.
//
//   ⚠ 뿌리: 머리말에 「라이선스: **공개 배포**」라고만 적어 두고 그것을 판정으로 여겼다.
//     그 말은 「무료로 받을 수 있다」는 뜻이지 **「재배포·변환해도 된다」가 아니다.**
//     사람의 주의로는 또 놓친다 — 그래서 기계로 막는다.
import { describe, it, expect } from "vitest";
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { 상용사용금지, 변경금지조건 } from "../src/engine/licenserisk.js";

const 서버루트 = path.resolve(fileURLToPath(new URL("..", import.meta.url)));
const 저장소 = path.resolve(서버루트, "..");

/** 문서가 **자기 이용조건을 선언한 줄**만 뽑는다.
 *
 *  ⚠ 「라이선스」라는 낱말이 나오는 줄을 전부 긁으면 안 된다 — 우리가 쓴 문서의 머리말 주석에는
 *    「CC BY-NC-ND에 걸려 걷어냈다」는 **설명**이 들어 있고, 그것을 그 문서의 라이선스로 읽으면
 *    우리 문서가 통째로 위반으로 잡힌다(실제로 그렇게 났다).
 *  ★ 그래서 ① `<!-- -->` 주석을 걷어내고 ② 「라이선스: X」 꼴의 **선언**만 본다. */
function 이용조건줄(원문: string): string {
  const 머리 = 원문.slice(0, 3000).replace(/<!--[\s\S]*?-->/g, "");
  return 머리.split("\n")
    .filter((l) => /^\s*[>\-*|#]*\s*\**\s*(라이선스|이용\s*조건|이용\s*허락|licen[cs]e|copyright)\s*\**\s*[:：]/i.test(l))
    .join(" | ");
}

function 매니페스트() {
  return JSON.parse(fs.readFileSync(path.join(서버루트, "docs-manifest.json"), "utf8")) as {
    files: { file: string; why?: string }[];
    _제외?: { file?: string; why?: string; removed?: string }[];
  };
}

describe("배포 문서 라이선스 — 실을 권리가 있는 것만 싣는다", () => {
  it("★★ 「배포하면 안 된다」고 확인된 문서가 목록에 없다", () => {
    // 판권면을 직접 열어 확인한 것들. 되살리려면 발행처 허락 근거를 먼저 받아야 한다.
    const 금지 = [
      "KISA_SW_공급망_보안_가이드라인.md",
      "KISA_ISMS-P_인증기준_안내서.md",
      "KISA_침해사고_분석절차_안내서.md",
      "KISA_랜섬웨어_대응_가이드라인.md",
      "개인정보위_가명정보_처리_가이드라인.md",
      "개인정보위_영향평가_수행안내서.md",
      "KISA_제로트러스트_가이드라인_2.0.md",
    ];
    const 실리는것 = 매니페스트().files.map((f) => path.basename(f.file));
    const 걸린것 = 금지.filter((n) => 실리는것.includes(n));
    expect(걸린것, `상용 배포가 금지된 문서가 목록에 있다:\n${걸린것.join("\n")}\n` +
      `근거는 docs-manifest.json의 _제외에 있다. 되살리려면 발행처 허락 근거를 먼저 적을 것.`).toEqual([]);
  });

  it("★ 「공개 배포」를 라이선스 판정으로 쓰지 않는다 — 그건 판정이 아니다", () => {
    // 이 표기가 바로 7종을 통과시킨 뿌리다. 「무료로 받을 수 있다」와 「재배포해도 된다」는 다르다.
    const 걸린것: string[] = [];
    for (const f of 매니페스트().files) {
      const p = path.join(저장소, f.file);
      if (!fs.existsSync(p)) continue;
      const 머리 = fs.readFileSync(p, "utf8").slice(0, 2500);
      // 「**라이선스**: 공개 배포」 꼴만 잡는다 — 본문에 그 말이 나오는 것은 무관하다.
      if (/\*\*라이선스\*\*\s*:?\s*공개\s*배포|라이선스\s*[:：]\s*공개\s*배포/.test(머리)) {
        걸린것.push(f.file);
      }
    }
    expect(걸린것, `「라이선스: 공개 배포」는 판정이 아니다 — 공공누리 유형(제0~4) 또는 CC 식별자를\n` +
      `판권면에서 읽어 그대로 적을 것:\n${걸린것.join("\n")}`).toEqual([]);
  });

  it("★ 남의 문서를 실을 때는 **판권면 근거**가 머리말에 있다", () => {
    // 우리가 쓴 문서(GIJO_*)는 대상이 아니다 — 저작권자가 우리다.
    const 남의것 = 매니페스트().files.filter((f) => !/GIJO/.test(path.basename(f.file)));
    const 근거없음: string[] = [];
    for (const f of 남의것) {
      const p = path.join(저장소, f.file);
      if (!fs.existsSync(p)) continue;
      const 머리 = fs.readFileSync(p, "utf8").slice(0, 2500);
      // 쓸 수 있는 근거: 공공누리 유형 · CC 식별자 · 자유이용 명시 · 법령(저작권 대상 아님)
      const 근거있나 =
        /공공누리|KOGL|제\s*[0-4]\s*유형|자유이용/.test(머리) ||
        /CC[\s-]?(BY|0)|Creative\s*Commons|CC0/i.test(머리) ||
        /법령|조문|법률\s*원문/.test(머리);
      if (!근거있나) 근거없음.push(f.file);
    }
    expect(근거없음, `남의 문서인데 판권면 근거가 머리말에 없다 — 실을 권리가 있는지 확인할 것:\n${근거없음.join("\n")}`)
      .toEqual([]);
  });

  it("★★ 근거가 **있어도 그 내용을 판정한다** — 「공공누리 제4유형」이라 정직하게 적으면 통과하던 구멍", () => {
    // ⚠ 2026-08-22 검토관 [중]. 위 시험은 「라이선스 표시가 **있나**」만 본다.
    //   그래서 판권면을 성실히 옮겨 「공공누리 제4유형(상업적 이용금지)」이라고 적어 둔 문서가
    //   **그 정직함 덕분에 통과**한다 — 표시가 있으니까. 우리를 문 것이 정확히 그 조건인데.
    //   ★ 판정은 licenserisk 한 곳에서 한다(여기 정규식을 새로 쓰지 않는다).
    const 걸린것: string[] = [];
    for (const f of 매니페스트().files) {
      const p = path.join(저장소, f.file);
      if (!fs.existsSync(p)) continue;
      const 조건줄 = 이용조건줄(fs.readFileSync(p, "utf8"));
      if (!조건줄) continue;
      if (상용사용금지(조건줄)) 걸린것.push(`${f.file}\n      → 상업적 이용 금지(NC): ${조건줄.slice(0, 120)}`);
      else if (변경금지조건(조건줄)) 걸린것.push(`${f.file}\n      → 변경 금지(ND): ${조건줄.slice(0, 120)}`);
    }
    expect(걸린것,
      `상용 제품에 실을 수 없는 이용조건이 적힌 문서가 목록에 있다:\n${걸린것.join("\n")}\n` +
      `  ⚠ NC(비영리)는 소스를 공개해도 안 풀린다. ND(변경금지)는 **형식 변환도 「고침」**이라\n` +
      `     PDF→마크다운 변환 자체가 걸린다 — 우리가 실제로 걸린 것이 이것이다.`).toEqual([]);
  });

  it("★★ 그 감시가 **실제로 작동한다** — 헛도는 감시를 두지 않는다", () => {
    // ⚠ 첫 판은 「라이선스」라는 낱말이 나오는 **모든 줄**을 긁어서, 우리가 쓴 문서의
    //   머리말 주석(「CC BY-NC-ND에 걸려 걷어냈다」는 설명)까지 그 문서의 라이선스로 읽고
    //   **우리 문서 7종을 전부 위반으로 잡았다.** 감시가 과포착하면 사람이 곧 꺼 버린다.
    //   그래서 ① 설명 주석은 빼고 ② 「라이선스: X」 꼴의 **선언 줄만** 본다.
    //   ★ 좁힌 뒤에는 **원래 잡아야 할 것을 여전히 잡는지** 반드시 확인한다 — 이 시험이 그것이다.
    expect(상용사용금지(이용조건줄("# 문서\n\n**라이선스**: 공공누리 제4유형(출처표시-상업적이용금지-변경금지)\n")),
      "판권면을 정직하게 옮긴 문서를 잡아야 한다").toBe(true);
    expect(상용사용금지(이용조건줄("---\n이용조건: CC BY-NC-ND 2.0 KR\n---\n")),
      "머리말(frontmatter)에 적힌 것도 잡아야 한다").toBe(true);
    expect(변경금지조건(이용조건줄("라이선스: 공공누리 제3유형(출처표시-변경금지)\n")),
      "ND는 변경금지로 잡아야 한다").toBe(true);

    // 반례 — 우리가 쓴 문서의 **설명 주석**은 잡으면 안 된다(그 과포착이 실제로 났다).
    const 우리문서 = "<!-- 2026-08-22 신규 작성. 이유: 공공기관 가이드가 CC BY-NC-ND·공공누리 4유형에\n" +
      "     걸려 걷어냈다. 그 자리를 우리가 직접 썼다. -->\n# 침해사고 대응\n";
    expect(상용사용금지(이용조건줄(우리문서)), "우리 문서의 설명 주석을 위반으로 읽으면 안 된다").toBe(false);
    expect(이용조건줄("# 그냥 문서\n\n본문에 라이선스 이야기가 나온다.\n"), "선언이 없으면 빈 값").toBe("");
  });

  it("_제외에는 **왜 뺐는지**가 있다 — 이유 없는 제외는 다음 사람이 되돌린다", () => {
    for (const x of 매니페스트()._제외 ?? []) {
      if (!x.file) continue;   // 묶음 설명 항목(_왜_한꺼번에)은 건너뛴다
      expect(String(x.why ?? "").length, `${x.file}: 뺀 이유가 없다`).toBeGreaterThan(20);
    }
  });

  it("보류 폴더에 규칙이 적혀 있다 — 파일만 옮겨 두면 다음 사람이 도로 넣는다", () => {
    const p = path.join(저장소, "knowledge", "_라이선스보류", "README.md");
    expect(fs.existsSync(p), "knowledge/_라이선스보류/README.md 가 있어야 한다").toBe(true);
    const s = fs.readFileSync(p, "utf8");
    expect(s, "다시 넣지 말라는 말이 있어야 한다").toContain("다시 넣지 마세요");
    expect(s, "되살리는 길도 적어야 한다 — 영영 못 쓴다는 뜻이 아니다").toContain("되살리려면");
  });
});

describe("지식 번들 고지 — **문서만 감사하고 나머지 절반을 건너뛰지 않는다**", () => {
  // ⚠ 2026-08-22 검토관 [중]. 이날 우리는 knowledge/ 문서 7종을 감사해 걷어냈는데,
  //   같은 번들의 **나머지 절반**(온톨로지 시드 트리플)은 안 봤다. 그 시드의 출처가
  //   KISA 「AI 보안 위협 대응 매뉴얼」이고, 코드 주석이 스스로 이렇게 적어 두고 있었다:
  //     「공공누리 유형이 미확인이다. 유형2·4는 상업적 이용을 금지하므로,
  //      확인 전까지 유상 배포 번들에 싣지 않는 것이 안전하다(법무 검토 대상 1순위).」
  //   그런데 **싣고 있다.** 오늘 문서에서 걸린 것과 정확히 같은 모양이다.
  //
  // ★ 이 시험은 「지금 당장 빼라」가 아니다 — 그 판단은 법무·사장님 몫이다.
  //   이 시험이 하는 일은 **미해결 목록이 조용히 늘어나지 못하게 못 박는 것**이다.
  //   새로운 「확인 중」 출처가 붙으면 여기서 빨개진다.
  const BUNDLE = path.join(서버루트, "src", "engine", "knowledgebundle.ts");

  /** 아직 이용조건을 확정하지 못한 채 싣고 있는 것 — **이 목록은 늘어나면 안 된다.**
   *  줄이려면: 판권면을 확인해 유형을 적거나, 발행처 허락을 받거나, 빼야 한다.
   *  ★ 2026-08-22 현재 **비어 있다** — KISA 매뉴얼 건은 「사실만 싣는다」로 판정을 끝냈다
   *    (knowledgebundle.ts의 근거 주석 참고). 아래 「서술을 안 옮긴다」 시험이 그 전제를 지킨다. */
  const 미해결: string[] = [];

  it("★ 「확인 중」인 출처가 **알려진 것보다 늘지 않았다**", () => {
    const s = fs.readFileSync(BUNDLE, "utf8");
    const 확인중 = [...s.matchAll(/^\s*"([^"]*(?:확인\s*중|미확인|확인이?\s*필요)[^"]*)"/gm)].map((m) => m[1]);
    const 뜻밖 = 확인중.filter((줄) => !미해결.some((알려진) => 줄.includes(알려진)));
    expect(뜻밖,
      `이용조건을 확정하지 않은 출처가 새로 늘었다:\n${뜻밖.join("\n")}\n` +
      `  ⚠ 「확인 중」인 채로 상용 번들에 실으면 2026-08-22 문서 사고와 같은 일이 된다.\n` +
      `     판권면을 확인해 유형을 적거나, 허락을 받거나, 빼고 나서 이 목록을 고칠 것.`).toEqual([]);
  });

  it("★ 판정 근거가 코드에 적혀 있다 — 「괜찮다」만 적으면 다음 사람이 검증할 수 없다", () => {
    const s = fs.readFileSync(BUNDLE, "utf8");
    expect(s, "공공누리 유형2·4가 상업적 이용을 금지한다는 사실이 적혀 있어야 한다")
      .toMatch(/공공누리[\s\S]{0,300}상업적?\s*이용/);
    expect(s, "왜 걸리지 않는지(사실은 저작권 대상이 아니다)가 적혀 있어야 한다")
      .toMatch(/사실\s*자체는\s*저작권\s*대상이\s*아니/);
  });
});

describe("★★ 온톨로지 시드는 **사실만** 싣는다 — 이 조건이 라이선스 판정을 떠받친다", () => {
  // ■ 왜 이 시험이 있나 (2026-08-22)
  //   KISA 「AI 보안 위협 대응 매뉴얼」에서 온 위협 분류를 상용 번들에 싣는다.
  //   그 매뉴얼의 공공누리 유형이 오래 「확인 중」이었는데, 실제로 무엇을 싣는지 세어 보니
  //   **코드·짧은 이름·분류뿐이고 서술문이 0건**이었다 — 사실은 저작권 대상이 아니므로 걸리지 않는다.
  //
  // ★ 그런데 그 판정은 **「서술을 안 옮긴다」는 조건 위에** 서 있다.
  //   누군가 「설명을 붙이면 검색이 잘 되겠다」며 원문 문장을 가져다 붙이는 순간 무너진다.
  //   법적 판단을 **기계가 지킬 수 있는 불변식**으로 바꿔 두는 것이 이 시험의 전부다.
  it("위협 항목에 **긴 서술문**이 없다 — 원문 설명을 옮기면 여기서 빨개진다", async () => {
    const { THREAT_CATALOG } = await import("../src/engine/compliance.js");
    const 긴것: string[] = [];
    for (const t of THREAT_CATALOG as Record<string, unknown>[]) {
      for (const [키, 값] of Object.entries(t)) {
        if (typeof 값 === "string" && 값.length > 60) 긴것.push(`${t.code}.${키}: ${값.slice(0, 70)}…`);
        if (Array.isArray(값)) {
          for (const v of 값) if (typeof v === "string" && v.length > 80) 긴것.push(`${t.code}.${키}[]: ${v.slice(0, 70)}…`);
        }
      }
    }
    expect(긴것,
      `위협 카탈로그에 긴 서술이 생겼다:\n${긴것.join("\n")}\n` +
      `  ⚠ 이 시드의 라이선스 판정은 **「코드·이름·분류 같은 사실만 싣는다」**를 전제로 한다.\n` +
      `     원문의 설명·문장을 옮기면 그 전제가 무너지고 공공누리 조건이 되살아난다.\n` +
      `     설명이 필요하면 **우리 말로 새로 써서** knowledge/ 문서에 둘 것.`).toEqual([]);
  });

  it("★ 시드가 실제로 무언가를 싣고 있다 — 0건이면 위 시험이 헛돈다", async () => {
    const { THREAT_CATALOG } = await import("../src/engine/compliance.js");
    expect((THREAT_CATALOG as unknown[]).length, "카탈로그가 비면 「서술 없음」이 공짜로 통과한다")
      .toBeGreaterThan(10);
  });
});
