// RAG 코퍼스에 **개발 문서가 섞이지 않는가.**
//
// 왜 필요한가(2026-08-02 하루 실전 시뮬레이션에서 발견):
//   docs-manifest.json 머리말은 스스로 경고한다 — "개발 맥락(소스 경로·빌드 명령·내부 계획·
//   미구현 기능)이 담긴 문서는 최종 사용자 답변에 그대로 인용돼 새어 나간다(실측:
//   server/src/engine/assets.ts 경로가 사용자에게 노출됐다)".
//   **그런데 바로 그 문서가 목록에 있었다.** 경고를 적어 두는 것과 지키는 것은 다르다.
//
//   같은 날 또 하나: 용어사전에 개발 이력("609건 중 608건이 스캔 오류였다")을 적었더니
//   담당자 질문의 답으로 그 문장이 그대로 나왔다. **내가 넣은 것이 그대로 고객에게 갔다.**
//
// ★ 여기서 지키는 것: 코퍼스 문서에 **소스 경로·빌드 명령·개발 이력**이 없을 것.
//   문서 자체를 못 넣게 막는 게 아니라, 넣으려면 그 문장을 사용자 말로 고치게 만든다.
//
// ⚠ 매니페스트 훑기는 **helpers/corpus.ts 한 곳**에 있다(2026-09-07). 예전엔 이 파일과
//   corpusnumowner.test.ts가 같은 코드를 두 벌 들고 있었다 — 저쪽 머리글이 「같은 방식으로
//   훑는다」고 적어 두고도 복사한 것이라, 한쪽만 고쳐지면 다른 시험이 **딴 모집단을 보면서
//   초록**이 될 자리였다. 아래 「이 감시가 헛돌고 있지 않다」가 그 헬퍼의 결과를 숫자로 못 박는다.
import { describe, it, expect } from "vitest";
import { 코퍼스문서, 코퍼스매니페스트 } from "./helpers/corpus";

const manifest = 코퍼스매니페스트();

/** 고객 답변에 나가면 안 되는 것들. 이유를 함께 둔다 — 무엇이 왜 문제인지 알아야 고친다. */
const 새는말: { 이름: string; re: RegExp; 왜: string }[] = [
  { 이름: "소스 경로", re: /\b(server|client|tools)\/src\/[\w./-]+|\b[\w-]+\.(ts|tsx|mjs)\b/, 왜: "담당자에게 코드 경로는 아무 뜻이 없고, 우리 내부 구조를 알려 준다" },
  { 이름: "빌드·실행 명령", re: /\bnpm (run |ci|install)|\bnpx \b|\btsc\b|\bvitest\b/, 왜: "제품을 쓰는 사람은 빌드하지 않는다" },
  { 이름: "개발 이력·실측 기록", re: /실측\s*\(?\s*20\d\d-\d\d-\d\d|실사고|회귀 하네스|커밋 [0-9a-f]{7}/, 왜: "우리 개발 뒷이야기가 고객 답변에 인용된다(실제로 나갔다)" },
  { 이름: "미구현·계획 표현", re: /미구현|아직 없습니다만|구현 예정|TODO|남은 건 .{0,20}조립/, 왜: "없는 기능을 있는 것처럼, 또는 제품이 미완성인 것처럼 읽힌다" },
  // ★ 2026-08-22 추가 — 성숙도 게이트(productfaq product-status)가 막는 것은 「언제 GA?」같은 직접 물음뿐이다.
  //   「GIJO AS 소개해줘」류는 게이트를 통과해 RAG로 가고, 코퍼스 문서가 근거로 붙어 시험 수·내부 버전 같은
  //   개발 성숙도 신호가 고객 답변에 실릴 수 있었다(제품소개 5줄·사용자매뉴얼 4줄 실측 — 이 시험이 못 잡던 부류).
  //   ⚠ 이 두 규칙은 **「앵커 있는 형태」만 잡는 좁은 그물**이다 — 초록 통과가 「코퍼스 누출 없음」의 증거가 아니다.
  //     버전은 절 번호(5.5.1)·조항 코드((4.1.4))·제3자 SW버전(imagemagick v6.8.2)·「이전 버전 : 5.7.11」과 갈라야
  //     오탐이 안 나므로(전 코퍼스 실측) **우리 제품 앵커(v접두·「제품 X 시점」)만** 잡는다. 그래서 맨-괄호 `(5.15.0)`·
  //     「버전 5.15.0」(v 없음)은 **일부러 안 잡는다**(손수리 몫). 코퍼스 전수 위생은 별건(용어사전 §5 개발섹션 — task_56bacd03).
  { 이름: "개발 성숙도·시험 수치", re: /(자동화\s*)?(시험|테스트)[^.\n]{0,8}[\d,]+\s*\+?\s*(개|건)\s*\+?\s*\**\s*통과|통과\s*[·,]\s*실패\s*0|전수조사\s*\d+\s*계층/, 왜: "몇 개 통과·실패 0·N계층 같은 내부 QA 지표는 성숙도 신호다 — 고객 답변에 나갈 것이 아니다(개·건, +위치 변형까지)" },
  { 이름: "제품·문서 버전", re: /버전\s*[:：]\s*\**\s*v\d+\.\d+\.\d+|\(\s*v\d+\.\d+\.\d+\s*\)|GIJO\s*AS\s*v\d+\.\d+\.\d+|제품\s+\d+\.\d+\.\d+\s*시점/, 왜: "제품·문서 버전 번호는 성숙도 신호 — 도입·버전·출시 상담은 영업으로 유도(내부 상태 미노출)" },
];

describe("RAG 코퍼스 — 개발 문서가 섞이지 않는다", () => {
  it("코퍼스 문서에 소스 경로·빌드 명령·개발 이력이 없다", () => {
    const 걸린것: string[] = [];
    for (const { file, 본문 } of 코퍼스문서()) {
      for (const { 이름, re, 왜 } of 새는말) {
        const 줄 = 본문.split("\n").map((l, i) => [i + 1, l] as const).filter(([, l]) => re.test(l));
        if (줄.length) {
          걸린것.push(`${file} — ${이름} ${줄.length}줄 (${왜})\n      ${줄[0][0]}: ${줄[0][1].trim().slice(0, 90)}`);
        }
      }
    }
    expect(
      걸린것,
      "코퍼스 문서는 **고객 답변의 근거**가 된다 — 여기 적힌 문장은 그대로 인용돼 나간다.\n" +
      "  개발 맥락이면 문서를 코퍼스에서 빼거나, 그 문장을 사용자 말로 고칠 것:\n\n  " +
      걸린것.join("\n  ")
    ).toEqual([]);
  });

  it("이 감시가 헛돌고 있지 않다", () => {
    // ⚠ 매니페스트 파싱이 빈손이면 위 시험은 통과하면서 아무것도 안 본다.
    const 문서 = 코퍼스문서();
    expect(문서.length, "코퍼스 문서를 하나도 못 읽었다 — 빈 검사다").toBeGreaterThanOrEqual(8);
    expect(문서.every((d) => d.본문.length > 100), "본문이 비어 있는 문서가 있다").toBe(true);

    // ★ 공용 헬퍼(helpers/corpus.ts)의 결과를 **숫자로 못 박는다**(2026-09-07).
    //   이 헬퍼 하나를 corpusleak·corpusnumowner 두 감시가 함께 쓴다 — 훑기가 조용히 좁아지면
    //   (중첩을 못 타거나 docs/ 갈래를 잃거나 _제외를 잘못 반영하면) 두 감시가 **함께** 눈이 먼다.
    //   바닥값(≥8)만으로는 31→9로 줄어도 초록이라, 정확한 수를 적어 변화를 드러낸다.
    //   ★ 2026-09-07 31→32 · knowledge 19→20 — 「AI 시대 소프트웨어 보안 점검표」를 새로 써서
    //     넣었다(공개된 점검표가 없어 우리 글로 쓴 것). 늘린 문서가 이것 하나임을 여기 남긴다.
    //   ⚠ 여기가 빨개지면 **먼저 매니페스트를 의심**한다. 문서를 일부러 늘리거나 뺐다면
    //     아래 두 숫자를 그때 고친다(고칠 때 무엇을 왜 늘렸는지 커밋 메시지에 적을 것).
    expect(문서.length, "코퍼스 문서 수가 달라졌다 — 매니페스트를 고쳤으면 이 숫자도 함께 고친다").toBe(32);
    expect(
      문서.filter((d) => d.file.startsWith("knowledge/")).length,
      "knowledge/ 지식 문서 수가 달라졌다 — 매니페스트를 고쳤으면 이 숫자도 함께 고친다",
    ).toBe(20);
  });

  it("코퍼스에서 뺀 문서는 이유가 남아 있다", () => {
    // ⚠ 이유를 안 남기면 다음 사람이 "빠졌네" 하고 도로 넣는다.
    for (const x of (manifest._제외 ?? []) as { file?: string; why?: string }[]) {
      expect(x.file, "제외 목록에 파일명이 없다").toBeTruthy();
      expect((x.why ?? "").length, `${x.file} 제외 사유가 너무 짧다`).toBeGreaterThan(30);
    }
  });
});
