import { describe, it, expect } from "vitest";
import { 결정적도착지 } from "../src/engine/dispatcher";
import { forcedToolFor } from "../src/engine/agentloop";
import { 실제도착, 가로챈규칙 } from "./helpers/routing";

describe("★ 「우선순위 기준」 물음은 explain(topic=취약점 우선순위)으로 결정적으로 간다", () => {
  const 양성 = [
    "취약점 조치 우선순위를 정할 때 무엇을 먼저 봐?", // ← 게이트 문항 그대로
    "취약점 우선순위 정하는 기준이 뭐야?",
    "우선순위 기준 알려줘",
    "취약점 우선순위 어떤 순서로 봐야 해?",
    "우선순위 판단 지표가 뭐뭐 있어?",
    "우선순위 매길 때 기준이 뭐지?",
    "EPSS는 우선순위에 어떻게 반영해?",
    "취약점 우선순위 무슨 순서로 봐?",
    "우선순위 정할 때 기준이 뭐야?",
    "취약점 우선순위 어떻게 판단해?",
    "우선 순위 기준 뭐야?", // 띄어쓰기 변형
    "취약점 우선순위 뭘 먼저 봐야 해?",
    "우선순위 정하는 기준 설명해줘",
    "취약점 조치 우선순위 기준이 어떻게 돼?",
    "자산 중요도는 우선순위에 어떻게 반영해?",
  ];
  // 15문장 전부 착수 전 실측 ∅(HEAD 06abf6dd) — 이 시험이 새로 닫는 자리다.
  for (const 문장 of 양성) {
    it(`「${문장}」 → explain(topic=취약점 우선순위)`, async () => {
      const 도둑 = 가로챈규칙(문장, "explain");
      const 걸림 = await 결정적도착지(문장, { 역할: "admin" });
      const 첫 = 걸림[0];
      const 사유 = 도둑
        ? `앞 규칙 [${도둑.차례}] ${도둑.도구}가 가로챘다`
        : `강제 규칙엔 걸린다(forcedToolFor=${실제도착(문장)}) — 앞선 특수경로가 먼저 채 갔다: ${걸림.map((x) => x.도착).join(" → ") || "(아무것도 안 걸림)"}`;
      expect(첫?.도착 ?? null, 사유).toBe("explain");
      // 도구만 맞고 topic이 지시문 전체면 온톨로지 부분문자열 매칭이 원리상 안 걸린다
      // (설계관 risks [상]) — 고정 문자열인지 함께 못 박는다.
      const 강제 = forcedToolFor(문장, { role: "admin" } as never);
      expect(강제?.args?.topic, "topic은 고정 문자열 「취약점 우선순위」여야 한다(지시문 전체 아님)").toBe("취약점 우선순위");
    });
  }
});

