  // 이 뽑기는 백분율·율/률 뒤 맨수만 보므로 이 꼴은 원리상 못 잡는다(뽑아도 1151.44가 facts에
  // 글자 그대로 있어 배너가 안 붙는다 — citeguard.ts 머리말이 금지한 "뜻 대조"가 있어야 잡힌다).
  // 그래서 이 사고는 여기가 아니라 handlers.ts(우선순위태그)에서 고쳤다 — 이 시험은 **왜 여기서
