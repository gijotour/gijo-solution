    expect(실적수치뽑기("관련 법률 3조에 따릅니다.")).toEqual([]);
    expect(실적수치뽑기("점검을 2회 돌렸고 2차 결과입니다.")).toEqual([]);
    // ⚠ 정직한 한계 — 단위가 아예 없으면 못 가른다(「발생 확률 5 정도」의 5는 지금도 뽑힌다).
