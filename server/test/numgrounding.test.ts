    //   숫자로 남아 한 파일 안에서 두 숫자가 달랐다. 사람이 읽는 잣대가 낡으면 시험이 초록이어도
    //   다음 사람은 틀린 크기로 판단한다. 세는 값은 아래 `메타`(하네스가 적는 단일 출처)를 본다.
