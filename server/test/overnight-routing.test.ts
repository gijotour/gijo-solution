// 🌙 「간밤에 뭐 터진 거 있어?」 — 밤사이 **우리 환경**의 일을 답하는가 (2026-09-08 · 야간 회귀 ① 수리)
//
// ★★ 왜 이 시험이 필요한가 (실측 사고)
//   아침에 가장 먼저 치는 말인데 **아무 규칙에도 안 걸렸다**(제품 함수 forcedToolFor 실측 null).
//   09-03부터 모델 판단으로 샜고, 모델은 낱말 「터진」만 보고 📚 침해사고 히스토리
//   (incident_cases)를 골랐다 — 그건 **남의 회사 사고를 모아 둔 외부 사례 DB**다.
//     · 2026-09-07 03:04 회차 → 「20건 중 「터진」에 걸리는 사례가 없습니다」(123자)
//     · 2026-09-08 03:04 회차 → 타사 사례 5건 2,983자
//   같은 말에 답이 이렇게 갈리는 것 자체가 모델 재량의 값이다. 담당자가 물은 것은
//   **우리 환경에서 밤사이 생긴 일**인데 2024년 타사 랜섬웨어 사례가 나온다.
//
// ★ 도착지는 briefing(FORCED_INTENTS[87] briefing) — 후보 핸들러를 전부 읽어 고른 결과다.
//   「지난 이후 새로 생긴 것」을 실제로 세는 곳은 briefing.ts:66 newFindings(지난 스냅샷 대비
//   차집합) 하나뿐이다. urgent_todo·analysis_status·threats는 시간창이 아예 없고,
//   scan_status의 「신규」는 재스캔 대비라 잣대가 다르며, system_log_status는 2026-09-06에
//   「기한 지난 일」이 새어 제품 내부 실패 6건을 할 일이라 답한 자리라 금지다.
//
// ★ 판정은 **제품 함수**(forcedToolFor)가 한다 — 정규식을 떼어 혼자 재면 앞 규칙이
//   가로채는 것을 못 본다(helpers/routing.ts 머리글). 이 규칙은 배열 **끝**이라
//   앞자리 규칙이 곧 방어다: 그 방어가 살아 있는지도 아래에서 함께 잰다.
import { describe, it, expect } from "vitest";
import { 실제도착, 가로챈규칙 } from "./helpers/routing";

describe("★★ 「간밤·밤새」 물음은 밤사이 우리 환경의 일로 간다", () => {
  // 야간어 5꼴 × 사건어를 섞은 여섯 꼴 이상 — 담당자가 실제로 치는 말투 그대로.
  const 밤말 = [
    "간밤에 뭐 터진 거 있어?",
    "밤새 뭐 생긴 거 있어?",
    "어젯밤에 무슨 일 있었어?",
    "지난밤에 일어난 일 알려줘",
    "밤사이 터진 거 뭐야?",
    "밤새 사고 났어?",
    "간밤에 새로 생긴 거 정리해줘",
    "밤사이 뭐 터졌는지 보여줘",
  ];
  for (const 문장 of 밤말) {
    it(`「${문장}」 → briefing`, () => {
      const 도둑 = 가로챈규칙(문장, "briefing");
      expect(
        실제도착(문장),
        도둑
          ? `앞 규칙 [${도둑.차례}] ${도둑.도구}가 가로챘다`
          : "아무 규칙에도 안 걸린다 — 모델이 외부 사례 DB(incident_cases)를 고른다",
      ).toBe("briefing");
    });
  }
});

describe("★ 앞자리가 곧 방어다 — 옛 영토 넷이 그대로여야 한다", () => {
  // ⚠ 새 규칙은 배열 **끝**이라 아래 넷은 자리로 지켜진다. 자리를 앞으로 옮기면
  //   그 순간 전부 깨진다 — 그것을 여기서 못 박는다(배제어는 이중 방어일 뿐이다).
  it("「밤사이 로그에 이상 있었어?」는 그대로 로그 갈래(analysis_status)", () => {
    expect(실제도착("밤사이 로그에 이상 있었어?"), "새 규칙이 로그 영토를 삼켰다").toBe("analysis_status");
  });
  it("「밤새 새로 올라온 문서 있어?」는 그대로 문서 갈래(recent_documents)", () => {
    expect(실제도착("밤새 새로 올라온 문서 있어?"), "새 규칙이 문서 영토를 삼켰다").toBe("recent_documents");
  });
  it("「간밤에 터진 사고 사례 알려줘」는 그대로 외부 사례(incident_cases)", () => {
    expect(실제도착("간밤에 터진 사고 사례 알려줘"), "밤말이 붙었다고 외부 사례를 뺏으면 안 된다").toBe("incident_cases");
  });
  it("「오늘 브리핑 해줘」는 종전 규칙 그대로 briefing", () => {
    expect(실제도착("오늘 브리핑 해줘")).toBe("briefing");
  });
});

describe("★ 새 규칙이 남의 말을 삼키지 않는다", () => {
  it("밤말이 없으면 안 걸린다 — 「침해사고 사례 있어?」", () => {
    expect(실제도착("침해사고 사례 있어?"), "밤말도 없는 말을 브리핑이 가로챘다").not.toBe("briefing");
  });
  it("사건어가 없으면 안 걸린다 — 「간밤 뉴스 알려줘」", () => {
    expect(실제도착("간밤 뉴스 알려줘"), "밤말만 있는 말을 브리핑이 가로챘다").not.toBe("briefing");
  });
  it("매체 낱말은 비켜 준다 — 「간밤에 터진 뉴스 알려줘」", () => {
    expect(실제도착("간밤에 터진 뉴스 알려줘"), "매체를 묻는 말에 우리 브리핑이 나가면 안 된다").not.toBe("briefing");
  });
  it("절차 질문은 삼키지 않는다 — 「밤새 사고 나면 신고 절차가 어떻게 돼?」", () => {
    expect(실제도착("밤새 사고 나면 신고 절차가 어떻게 돼?"), "지식 질문을 현황 도구가 가로챘다").not.toBe("briefing");
  });
});

// ── 쓰기 2수 흐름 — **조회로 못 박으면 시킨 일이 영영 안 된다** ─────────────────────
//
// ★★ 왜: 강제 경로는 도구를 부르고 **즉시 끝난다**. 조회 도구로 못 박히면 「조회 → 배정」
//   2수 흐름이 통째로 죽어, 시킨 일은 안 되고 목록만 나간다(2026-08-09 파일럿 리허설에서
//   today 강제가 배정 명령을 흡수해 대본이 그 자리에서 깨졌다 · 2026-09-07에 urgent_todo·
//   maintenance_status가 같은 구멍이었음이 드러났다).
//   막는 자리는 새 규칙의 정규식이 아니라 **잣대 한 곳**인 `조회로못박지않을것` Set이다.
describe("★ 배정(쓰기) 지시는 브리핑으로 못 박지 않는다", () => {
  const 쓰기말 = [
    "밤새 터진 거 있으면 김보안한테 배정해줘",
    "간밤에 생긴 거 담당자를 김도희로 지정해줘",
    "오늘 브리핑 보고 제일 급한 거 담당자 배정해줘", // ⚠ 옛 규칙 [13]도 원래 같은 구멍이었다
  ];
  for (const 문장 of 쓰기말) {
    it(`「${문장}」 — 조회로 끝내면 배정이 영영 안 된다`, () => {
      expect(실제도착(문장), "조회 규칙이 쓰기 재료 흐름을 가로챘다").not.toBe("briefing");
    });
  }

  it("할 일로 담는 말도 삼키지 않는다 — 「간밤에 생긴 취약점 할 일로 담아줘」", () => {
    expect(실제도착("간밤에 생긴 취약점 할 일로 담아줘")).not.toBe("briefing");
  });

  it("조회는 그대로다 — 시키는 말이 아니면 브리핑으로 간다", () => {
    expect(실제도착("간밤에 뭐 터진 거 있어?")).toBe("briefing");
    expect(실제도착("오늘 브리핑 해줘")).toBe("briefing");
  });
});
