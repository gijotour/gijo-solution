// 「임원 보고용 세 줄 요약」류 라우팅 — B4 수리(2026-09-11, 평가 게이트 kr-report-tone 23/24 ·
// 계획서 중-3 평가 게이트 · 전-6 정직).
//
// ■ 뿌리
//   「임원 보고용으로 이번 주 보안 현황을 세 줄로 요약해줘」가 route-explain 실측
//   「걸리는 규칙 없음 → ⑨ 모델 선택」이었다 — 회차마다 도구가 갈려(09-10은 모델 작문
//   16.0/53.9초, 09-11은 briefing 1,380ms) 게이트가 답이 아니라 **운**을 쟀다. briefing은
//   directAnswer라 그 도구를 고른 날은 영어 취약점 이름·IP 목록 원문이 그대로 담당자에게
//   나갔다(한글 비율 10%). exec_brief(FORCED_INTENTS[89])가 그 자리를 결정적으로 채운다.
//
// ■ 판정은 제품 함수로 한다 — helpers/routing.ts 머리글(정규식을 떼어 혼자 재면
//   앞 규칙이 가로채는 것을 못 본다). 「이웃 갈래」 그룹은 forcedToolFor보다 **앞선
//   dispatcher 특수경로**(취약점 목록 고르기·자산 현황·리포트 만들기 등)까지 함께 재야
//   하므로 결정적도착지(dispatcher.ts)를 그대로 부른다(approval-routing.test.ts와 같은 방식).
import { describe, it, expect } from "vitest";
import { 결정적도착지 } from "../src/engine/dispatcher";
import { 실제도착, 가로챈규칙 } from "./helpers/routing";

describe("★ 「임원 보고용 세 줄 요약」류는 exec_brief로 결정적으로 간다", () => {
  const 양성 = [
    "임원 보고용으로 이번 주 보안 현황을 세 줄로 요약해줘",
    "경영진 보고용으로 짧게 요약해줘",
    "이번 주 보안 현황 간단히 알려줘",
    "보안 현황 요약해줘",
    "전체 보안 상황 간단히 정리해줘",
    "임원 보고용 요약 부탁해",
    // 착수 전 실측에서 함께 결정적이 되어야 한다고 못 박은 세 꼴(live_checks).
    "이번 주 보안 현황 한 줄로 정리해줘",
    "윗분께 보고할 건데 세 줄로 정리해줘",
    "상급자 보고용으로 정리해줘",
  ];
  // ★ 2026-09-11 검토관 [하] 수리 — **양성도 체인 전체로 잰다.**
  //   첫 판은 양성 9문장만 forcedToolFor 단독(실제도착)으로 쟀다. 그러면 forcedToolFor보다
  //   **앞선** dispatcher 특수경로(screenNameCard·isOpsStatusAsk·isAssetStatusAsk·REPORT_CREATE_RE·
  //   planInstruction 등 30여 단계) 중 하나가 넓어지는 날, 시험은 초록인데 제품은 exec_brief에
  //   안 닿는다 — 평가 게이트만 다시 빨개지고 시험은 아무 말을 안 한다. 아래 「이웃 갈래」
  //   그룹은 처음부터 결정적도착지로 쟀다 — **잣대를 둘로 두지 않는다.**
  for (const 문장 of 양성) {
    it(`「${문장}」 → exec_brief`, async () => {
      const 도둑 = 가로챈규칙(문장, "exec_brief");
      const 걸림 = await 결정적도착지(문장, { 역할: "admin" });
      const 첫 = 걸림[0];
      const 사유 = 도둑
        ? `앞 규칙 [${도둑.차례}] ${도둑.도구}가 가로챘다`
        : `강제 규칙엔 걸린다(forcedToolFor=${실제도착(문장)}) — 앞선 특수경로가 먼저 채 갔다: ${걸림.map((x) => x.도착).join(" → ") || "(아무것도 안 걸림)"}`;
      expect(첫?.도착 ?? null, 사유).toBe("exec_brief");
    });
  }
});

describe("★ 앞자리가 곧 방어다 — 이웃 여덟 갈래를 한 건도 안 뺏는다", () => {
  // 전부 착수 전 route-explain 실측값(설계관 지시서 live_checks) — exec_brief 신설 뒤에도
  // 그대로여야 한다. forcedToolFor만으로는 안 보이는 갈래(dispatcher 특수경로)가 섞여
  // 있어 결정적도착지 전체 체인으로 잰다 — 첫 번째로 걸린 단계가 곧 실제 도착지다.
  const 이웃 = [
    { 문장: "오늘 브리핑 보여줘", 기대: "briefing" },
    { 문장: "지금 상황 요약해줘", 기대: "briefing" },
    { 문장: "취약점 현황 요약해줘", 기대: "findingListAnswer(목록+체크칸)" },
    { 문장: "자산 현황 요약해줘", 기대: "assetStatusAnswer(카드)" },
    { 문장: "최근 위협 인텔 요약해줘", 기대: "threats" },
    { 문장: "컴플라이언스 현황 요약해줘", 기대: "compliance_status" },
    { 문장: "보안 현황 보고서 만들어줘", 기대: "generateReport" },
    { 문장: "주간 보안 리포트 작성해줘", 기대: "generateReport" },
    { 문장: "임원 보고용 리포트 만들어줘", 기대: "generateReport" },
    { 문장: "보안 KPI 현황 알려줘", 기대: "kpi_status" },
  ];
  for (const { 문장, 기대 } of 이웃) {
    it(`「${문장}」 → ${기대}(exec_brief에게 안 뺏긴다)`, async () => {
      const 걸림 = await 결정적도착지(문장, { 역할: "admin" });
      const 첫 = 걸림[0];
      expect(첫, "아무 갈래에도 안 걸린다").toBeTruthy();
      expect(첫!.도착, `첫 걸림이 exec_brief라면 새 규칙이 이 갈래를 삼켰다는 뜻이다`).toBe(기대);
      expect(첫!.도착).not.toBe("exec_brief");
    });
  }
});

describe("★ 남의 영토는 안 삼킨다 — 「요약」 낱말만으로 끌어오지 않는다", () => {
  it("「이 문서 세 줄로 요약해줘」는 여전히 explain이다(문서지목질문 갈래)", () => {
    expect(실제도착("이 문서 세 줄로 요약해줘")).toBe("explain");
  });

  // ⚠ 위 한 줄로는 **배제어를 못 잰다**(2026-09-11 검토관 [중]): 「이 문서」는 FORCED 배열보다
  //   **앞선** 문서지목질문 분기(agentloop.ts 지시문서RE)가 잡아 [89]에 도달조차 안 한다 —
  //   배제어를 통째로 지워도 저 줄은 초록이다. 아래 문장들은 그 앞 분기에 안 걸리고(문서유형어
  //   뒤에 조사도 지시어도 없다) [89]의 앵커·요약어를 **둘 다 만족**하므로, 배제어가 빠지는
  //   순간 exec_brief로 샌다 — 배제어 계약을 실제로 재는 자리는 여기다.
  const 배제어계약 = [
    "보안 현황 매뉴얼 세 줄로 요약해줘",
    "보안 현황 가이드 간단히 정리해줘",
    "임원 보고용 지침 세 줄로 요약해줘",
  ];
  for (const 문장 of 배제어계약) {
    it(`「${문장}」 → exec_brief 아님(배제어가 유일한 방어다)`, () => {
      expect(
        실제도착(문장),
        "배제어가 빠졌다 — 제목지목질문(explain)은 배열 뒤라 앞자리가 안 막아 준다",
      ).not.toBe("exec_brief");
    });
  }

  // 나머지 다섯은 지금(착수 전) 실측이 전부 ∅(모델 재량)다 — exec_brief가 **새로 뺏지
  // 않는다**는 것이 이 시험의 뜻이다. 배제어(회의·CVE-·로그·법령·이번 주 단독)가 없으면
  // 이 다섯이 exec_brief로 새어 「법령 요약」·「CVE 요약」 같은 남의 영토를 삼킨다.
  const 남의영토 = [
    "회의록 요약해줘",
    "CVE-2021-44228 요약해줘",
    "로그 요약해줘",
    "개인정보보호법 제29조 요약해줘",
    "이번 주 요약해줘",
    // ★ 2026-09-11 검토관 [중] 수리 — 배제어에 「자료」가 없었다. 이 제품은 문서를 「사내 자료」라고도
    //   부르는데(citeguard.ts 자료없음안내), 그 말로 문서를 가리킨 물음까지 이 규칙이 채 갔다.
    //   ⚠ 이 방어가 중요한 이유: 제목지목질문(explain)은 FORCED 배열을 **다 본 뒤**에 오므로
    //     앞자리가 막아 주지 않는다 — 배제어가 유일한 방어다(agentloop.ts [89] 머리글).
    "보안 현황 자료 세 줄로 정리해줘",
    "임원 보고 자료 간단히 정리해줘",
  ];
  for (const 문장 of 남의영토) {
    it(`「${문장}」 → exec_brief 아님`, () => {
      expect(실제도착(문장)).not.toBe("exec_brief");
    });
  }
});

