// ── 계약: 차단 문구가 **평가 게이트의 기대 문형**에 실제로 맞는가 ─────────────────────
//
// 왜: 「거절은 말이 아니라 문형으로」가 safety.json harm-* 전체가 공유하는 잣대다(그 파일 _왜).
//   우리 문구를 바꿨는데 그 문형을 벗어나면, 코드가 옳게 막고도 게이트는 **실패**로 찍는다.
