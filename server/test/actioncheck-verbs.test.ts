// 행동 대조 — 「~해도 되나」를 **담당자가 실제로 쓰는 동사 전부**에서 잡는가.
//
// 왜 필요한가(2026-08-03 실전 147상황):
//   "클라우드에 백업 올려도 되나?"가 판정을 안 타고 **Tenable 벤더 매뉴얼**을 물어와
//   "지원하지 않습니다"라고 답했다 — 우리 사내 규정이 아니라 남의 제품 설명이 판정처럼 나갔다.
//   제품 차별 기능(○/△/×)이 통째로 비껴간 것이다.
//
// ★ 낱말 하나가 아니라 **한 갈래가 통째로** 빠져 있었다. 「이-어간」 동사(올리다·내리다·
//   돌리다·알리다·옮기다·맡기다·남기다…)는 -어도가 **려도/겨도**로 줄어드는데 그 꼴이 없었다.
//   재 보니 보안 업무 동사 24개 중 **9개(37.5%)를 놓치고 있었다.**
//
// ⚠ 이 시험이 하는 일은 목록을 **측정으로 채우는** 것이다. 손으로 늘리면 반드시 또 샌다 —
//   담당자가 쓸 동사를 여기 적어 두고, 놓치면 여기서 먼저 깨진다.
import { describe, it, expect } from "vitest";
import { ACTION_CHECK_RE, 읽을수있는발췌 } from "../src/engine/actioncheck";

// 보안담당자가 「해도 되나」를 붙여 물을 법한 동사 — 실제 업무 문장으로 적는다.
const 잡아야: [string, string][] = [
  ["올리다", "클라우드에 백업 올려도 되나?"],
  ["내리다", "이 서비스 내려도 되나?"],
  ["지우다", "로그 지워도 되나?"],
  ["바꾸다", "비밀번호 정책 바꿔도 되나?"],
  ["보내다", "협력사에 보내도 되나?"],
  ["주다", "담당자 명단 줘도 되나?"],
  ["열다", "방화벽 포트 열어도 되나?"],
  ["닫다", "서비스 포트 닫아도 되나?"],
  ["끄다", "백신 잠깐 꺼도 되나?"],
  ["켜다", "원격 접속 켜도 되나?"],
  ["옮기다", "데이터 옮겨도 되나?"],
  ["돌리다", "업무시간에 스캔 돌려도 되나?"],
  ["시키다", "외주에 시켜도 되나?"],
  ["맡기다", "협력사에 맡겨도 되나?"],
  ["알리다", "고객에게 알려도 되나?"],
  ["남기다", "기록 남겨도 되나?"],
  ["반출하다", "고객 정보 반출해도 돼?"],
  ["삭제하다", "감사로그 삭제해도 되나?"],
  ["공유하다", "외부에 공유해도 되나?"],
  ["복사하다", "USB로 복사해도 되나?"],
  ["내보내다", "데이터 내보내도 되나?"],
  ["멈추다", "서비스 멈춰도 되나?"],
  ["풀다", "암호 풀어도 되나?"],
  ["세우다", "장비 세워도 되나?"],
];

describe("★ 보안 업무 동사 전수 — 하나도 안 놓친다", () => {
  for (const [동사, 물음] of 잡아야) {
    it(`${동사} — "${물음}"`, () => {
      expect(ACTION_CHECK_RE.test(물음), "판정을 안 타고 일반 답으로 샌다").toBe(true);
    });
  }

  it("놓치는 것이 하나도 없다(한눈에)", () => {
    const 놓친것 = 잡아야.filter(([, q]) => !ACTION_CHECK_RE.test(q)).map(([v]) => v);
    expect(놓친것, `놓치는 동사:\n  ${놓친것.join(", ")}`).toEqual([]);
  });
});

describe("★ 오탐 방지 — 평범한 물음을 판정으로 몰지 않는다", () => {
  // ⚠ 명사+보조사 '도'까지 삼키면 "이것도 돼?" 같은 말이 판정 불가(NA)로 튄다.
  //   판정 불가 답은 담당자에게 아무 쓸모가 없다 — 놓치는 것만큼 나쁘다.
  const 안잡아야 = [
    "이것도 돼?",
    "나도 돼?",
    "매도 관련 규정 알려줘",          // 매도(賣渡) — 명사
    "채도 조정 어떻게 해",            // 채도(彩度) — 명사
    "그 태도 문제 아닌가",            // 태도 — 명사
    "미조치 취약점 몇 건이야?",
    "오늘 뭐부터 해야 해?",
    "EPSS가 뭐야?",
    "백업 언제 돌았어?",
  ];
  for (const 물음 of 안잡아야) {
    it(`통과 — "${물음}"`, () => {
      expect(ACTION_CHECK_RE.test(물음), "평범한 물음이 판정으로 튄다").toBe(false);
    });
  }
});

describe("이 시험이 헛돌고 있지 않다", () => {
  it("정규식이 살아 있다", () => {
    expect(ACTION_CHECK_RE.test("고객 정보 반출해도 돼?"), "긍정 대조가 죽었다").toBe(true);
    expect(ACTION_CHECK_RE.test("오늘 날씨 어때"), "부정 대조가 죽었다").toBe(false);
    expect(잡아야.length, "표본이 너무 적다").toBeGreaterThanOrEqual(20);
  });
});

describe("★ 읽을 수 없는 발췌는 보여 주지 않는다", () => {
  // 실측(2026-08-03): 참고 자료가
  //   "ted onaTenableSecurityCenterwiththehostnameExample1toaTenableSecurityCenterwith…"
  //   로 나갔다. PDF에서 글자를 뽑을 때 띄어쓰기가 사라진 덩어리다.
  //   담당자는 읽을 수 없고, **읽을 수 없는 근거는 근거가 아니다.**
  it("띄어쓰기가 뭉개진 라틴 덩어리는 버린다", () => {
    const 뭉개짐 = "ted onaTenableSecurityCenterwiththehostnameExample1toaTenableSecurityCenterwiththehostnam";
    expect(읽을수있는발췌(뭉개짐), "못 읽는 글자를 근거라고 보여 준다").toBe("");
  });

  it("정상 영문은 그대로 보여 준다", () => {
    const 정상 = "The scan policy must be reviewed before applying it to production assets.";
    expect(읽을수있는발췌(정상)).toContain("scan policy");
  });

  it("★ 한글 문서는 버리지 않는다 — 우리말은 원래 붙여 쓸 수 있다", () => {
    const 한글 = "사내 규정상 고객 개인정보는 외부 클라우드에 저장할 수 없으며, 반출 시 정보보호책임자의 승인을 받아야 합니다.";
    expect(읽을수있는발췌(한글), "우리 규정 문서를 버렸다 — 판정 근거가 사라진다").toContain("사내 규정");
  });

  it("빈 값은 빈 값으로", () => {
    expect(읽을수있는발췌("")).toBe("");
    expect(읽을수있는발췌(undefined as never)).toBe("");
  });
});
