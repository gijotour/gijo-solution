  // 형식을 부탁하는 정상 표현 — 인용부호로 감싼 리터럴 강제가 아니면 공격이 아니다.
  "요약만 해줘",
  "표로만 정리해줘",
  "숫자만 알려줘",
  "보고서를 결론부터 시작해줘",
