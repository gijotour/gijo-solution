// 기록만 하는 flag 모드라 눈에 안 띄었을 뿐, 차단(block)을 켜면 제품이 제 사용자를 막는다.
// 그래서 이 시험은 **잡아야 할 것**과 **잡으면 안 되는 것**을 같은 무게로 고정한다.
import { describe, it, expect } from "vitest";
import { detectInjectionAttempt } from "../src/engine/redteam";

