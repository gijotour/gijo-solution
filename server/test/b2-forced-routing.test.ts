// ★ 판정은 **제품 함수**가 한다 — 정규식을 떼어 혼자 재면 앞 규칙이 가로채는 것을 못 본다
//   (helpers/routing.ts 머리글). 이웃 갈래까지 봐야 하는 줄은 결정적도착지(dispatcher)를 부른다.
import { describe, it, expect } from "vitest";
import { 결정적도착지 } from "../src/engine/dispatcher";
import { forcedToolFor } from "../src/engine/agentloop";
import { 실제도착, 가로챈규칙 } from "./helpers/routing";

const 도착 = async (문장: string) => (await 결정적도착지(문장, { 역할: "admin" }))[0]?.도착 ?? null;
const 인자 = (문장: string) => forcedToolFor(문장, { role: "admin" } as never)?.args ?? {};

// ═══════════════════════════════════════════════════════════════════════════════
//  [91] suggest_command · [92] run_redteam — 새로 세운 두 규칙의 양성·음성
// ═══════════════════════════════════════════════════════════════════════════════
describe("★ [91] CLI 명령 제안 — 제품이 스스로 적어 둔 예시가 결정적으로 닿는다", () => {
  const 양성 = ["점검 명령 추천해줘", "포트 스캔 명령 알려줘", "방화벽 차단 명령 알려줘"];
  for (const 문장 of 양성) {
    it(`「${문장}」 → suggest_command`, () => {
      const 도둑 = 가로챈규칙(문장, "suggest_command");
      expect(실제도착(문장), 도둑 ? `앞 규칙 [${도둑.차례}] ${도둑.도구}가 가로챘다` : "아무 규칙에도 안 걸린다").toBe("suggest_command");
    });
  }

  // ⚠ 이 도구는 registry.ts에서 directAnswer:true — **결재판 없이 PowerShell 한 줄이 바로 나간다.**
  //   절차·이력·결과를 물은 담당자에게 실행하라는 명령문이 답으로 가면 안 된다(검토관 적발 ⑤⑬).
  const 음성 = [
    "명령 승인 절차 알려줘", // 승인 절차를 묻는 말
    "명령 실행 이력 알려줘", // 감사 이력 조회
    "스크립트 실행 결과 알려줘", // 결과 조회
    "이 스크립트 뭐 하는지 알려줘", // 지식 물음
    "점검 명령이 뭐야?", // N20 — 지식 물음
    "명령어 설명해줘", // routes.ts 「왜」가 방어를 약속한 문장
    "이 명령 뭐 하는 거야?", // 같은 약속
  ];
  for (const 문장 of 음성) {
    it(`「${문장}」 → suggest_command 아님(지식·이력·절차는 이 도구의 영토가 아니다)`, () => {
      expect(실제도착(문장)).not.toBe("suggest_command");
    });
  }
});

