// B10-① — 「지식/문서/규정/제목 조회 + 쓰기 지시」 결합 문장이 explain 한 수로 끝나지 않는다
// (2026-09-12 설계관 지시서 · 계획서 전-4/중-3 · B5·B7 라운드에서 두 번 이관된 구멍).
//
// ■ 뿌리
//   agentloop.forcedToolFor 안, FORCED_INTENTS 배열 **밖**에 손수 explain로 못 박는 분기 다섯이
//   있다 — 제품설정질문·문서지목질문·사내규정질문(배열 **앞**) · 비교개념질문·제목지목질문
//   (배열 **뒤**). 「조회로못박지않을것」Set은 `.has(f.tool)` 한 줄에서만 쓰이고 그 줄이
//   FORCED_INTENTS 루프 **안**이라, 배열 밖 다섯은 이 가드를 원리상 안 지난다. 비교개념질문만
//   2026-09-12 앞선 수리로 잣대(그때 이름 isAssign·isWriteOrder)를 손으로 걸어 닫혀 있었고,
//   나머지 넷은 열려 있었다 — 그래서 「접속기록 보관 규정 알려주고 김보안한테 배정해줘」류가
//   explain 한 수로 끝나 배정·승인·조치가 영영 안 갔다(착수 전 실측, 아래 양성 전부 재현).
//
// ■ 수리
//   지역 const 셋(isAssignQuery·isAssign·isWriteOrder)을 모듈 최상위 `agentloop.쓰기흐름인가()`
//   하나로 뽑아(정규식 글자는 그대로) 다섯 분기 + FORCED 루프가 **같은 함수**를 부르게 했다.
//   지역 const를 그대로 앞머리 분기에서 참조하면 TDZ로 즉사하므로 함수로 뽑는 것이 유일한 길이다.
//
// ■ 도착지는 **∅**(B7 선례와 같은 계약) — 결합 문장을 쓰기 도구로 못 박지 않는다. 모델이
//   쓰기 도구를 고르고 결재판이 사람에게 승인을 묻는다(쓰기는 전부 사람 승인).
//
// ■ 판정은 제품 함수로 한다 — helpers/routing.ts 머리글(정규식을 떼어 혼자 재면 앞 규칙이
//   가로채는 것을 못 본다). 제목지목 갈래(T1~T4)는 문서 목록(DB)에 달린 갈래라
//   titlescope-routing.test.ts:27-62와 같은 방식으로 memory_documents를 seed한다.
import { describe, it, expect, beforeAll } from "vitest";
import { 결정적도착지 } from "../src/engine/dispatcher";
import { forcedToolFor, 쓰기흐름인가 } from "../src/engine/agentloop";
import { 실제도착, 가로챈규칙 } from "./helpers/routing";

// 제목지목 갈래(T1·T2·T3)를 위한 최소 시드 — 이 파일 전용(다른 시험의 시드와 안 섞는다).
// ⚠ 문장은 **침해사고·유지보수·점검 같은 낱말을 피한다** — dispatcher 특수경로(침해사고질문인가·
//   MAINT_PROCEDURE_RE)가 제목지목질문보다 먼저 돌아, 그 낱말이 있으면 이 라운드와 무관한
//   **다른** 갈래에 먼저 걸려 이 시험의 증거력이 흐려진다(실측으로 확인 — 「침해사고 대응절차」는
//   dispatcher.침해사고질문인가가, 「유지보수절차」는 agentloop.MAINT_PROCEDURE_RE가 먼저 챈다.
//   둘 다 이 라운드 범위 밖의 별개 갈래라 손대지 않는다).
const 문서들: [string, string][] = [
  // T1·T2 — "취약점 식별체계 기준"을 콕 집는다(식별체계=4자↑ 하나로 성립).
  ["GIJO_지식_취약점_식별체계_기준.md", "builtin"],
  // T3 — "제로트러스트 구현 로드맵"을 콕 집는다(제로트러스트=6자↑ 단독으로 성립).
  ["GIJO_지식_제로트러스트_구현_로드맵.md", "builtin"],
];

beforeAll(async () => {
  const { db } = await import("../src/db");
  const ins = db.prepare(
    "INSERT OR REPLACE INTO memory_documents (documentId, scope, chunks, ingestedAt, origin) VALUES (?, 'global', 1, datetime('now'), ?)",
  );
  for (const [id, origin] of 문서들) ins.run(id, origin);
});

// 양성 — 착수 전 전부 explain 한 수로 끝났다(구멍 실증). 분기별 최소 1문장 + 어느 판별자가
// 잡던 것인지 주석에 적는다.
const 양성: [string, string][] = [
  // 사내규정질문(배열 앞) — routes.ts "사내 규정 조회"
  ["P01", "접속기록 보관 규정 알려주고 김보안한테 배정해줘"],
  ["P02", "비밀번호 정책 알려주고 김도희한테 할당해줘"],
  ["P03", "사내 보안 지침 확인하고 승인해줘"],
  ["P04", "재택근무 보안 규정 알려주고 담당자 정해줘"], // isAssign만 아는 말(맡겨·정해)
  ["P05", "접속기록 보관 규정 알려주고 김보안한테 맡겨줘"], // isAssign만 아는 말 — 행동의도RE·isWriteOrder 둘 다 모른다
  ["P15", "취약점관리 지침 항목 알려주고 승인해줘"],
  ["P16", "개인정보 보호 정책 알려주고 김도희한테 배정해줘"],
  // 문서지목질문(배열 앞) — routes.ts "문서 지목 내용 질문"
  ["P06", "이 매뉴얼에서 암호화 대상 알려주고 담당자 배정해줘"],
  ["P07", "이 안내서 점검 항목 알려주고 김보안한테 할당해줘"],
  ["P08", "보고서에서 미조치 건 알려주고 승인해줘"],
  ["P09", "이 가이드에 있는 대응 절차 알려주고 정요한한테 배정해줘"],
  ["P10", "첨부한 점검표에서 빠진 항목 알려주고 조치해줘"], // isWriteOrder만 아는 말
  // 제품설정질문(배열 앞) — routes.ts "제품 설정 확인"
  ["P11", "방화벽 룰셋 어떻게 확인해? 김보안한테 배정해줘"],
  ["P12", "WAF 정책 확인 방법 알려주고 승인해줘"],
  ["P14", "백신 예외 정책 어떻게 보는지 알려주고 김보안한테 할당해줘"],
  // 제목지목질문(배열 뒤, DB 의존) — routes.ts "제목으로 문서 지목"
  ["T1", "취약점 식별체계 기준 알려주고 김보안한테 맡겨줘"], // 행동의도RE·잣대 둘 다 모르던 「맡겨」의 결정적 증거
  ["T2", "취약점 식별체계 기준 알려주고 담당자 정해줘"],
  ["T3", "제로트러스트 구현 로드맵 알려주고 김보안한테 맡겨줘"],
];

describe("★ 조회+쓰기 결합은 explain 한 수로 끝나지 않는다 — 배열 밖 분기 다섯", () => {
  for (const [id, 문장] of 양성) {
    it(`${id} 「${문장}」 → explain 아님(∅ — 모델이 쓰기 도구를 고른다)`, () => {
      const 도둑 = 가로챈규칙(문장, "explain");
      const 실제 = 실제도착(문장, "admin");
      expect(
        실제,
        도둑 ? `앞 규칙 [${도둑.차례}] ${도둑.도구}가 가로챘다(별개 문제)` : `여전히 explain로 못 박힌다`,
      ).not.toBe("explain");
    });
  }

  it("★★ 결정적도착지의 첫 걸림도 null이다(P13 제외 — 그건 [20] 화면안내 층, 이 라운드 범위 밖)", async () => {
    for (const [id, 문장] of 양성) {
      const 걸림 = await 결정적도착지(문장, { 역할: "admin" });
      expect(걸림[0]?.도착 ?? null, `${id} 「${문장}」 — 실제: ${걸림.map((x) => x.도착).join(" → ") || "(없음)"}`).toBeNull();
    }
  });

  // 반대쪽 못 — 이게 없으면 「전부 ∅로 만들기」로 고쳐도 이 describe가 초록이 된다.
  const 순수조회 = [
    "접속기록 보관 규정 알려줘", // N06
    "이 매뉴얼에서 암호화 대상 뭐야", // N07
    "방화벽 룰셋 어떻게 확인해?", // N08 — ops-sim ④ 문항
    "비밀번호 정책 알려줘", // N09
    "이 안내서에 랜섬웨어 대응 절차 있어?", // N10
    "사내 규정 목록 보여줘", // S10
  ];
  for (const 문장 of 순수조회) {
    it(`(대조군) 「${문장}」 → 그대로 explain(순수 조회는 안 건드린다)`, () => {
      expect(실제도착(문장, "admin")).toBe("explain");
    });
  }

  // 잣대 직접 — 이 함수가 쓰기 흐름 판정의 유일한 권위다.
  it("쓰기흐름인가() 직접 호출", () => {
    expect(쓰기흐름인가("접속기록 보관 규정 알려주고 김보안한테 맡겨줘")).toBe(true);
    expect(쓰기흐름인가("취약점 식별체계 기준 알려주고 담당자 정해줘")).toBe(true);
    expect(쓰기흐름인가("패스워드 지침 확인해줘")).toBe(false);
    expect(쓰기흐름인가("이 매뉴얼에서 암호화 대상 뭐야")).toBe(false);
  });
});

