const 규범 = fs.readFileSync(path.join(__dirname, "../../GIJO_AS_대화창_말투규범.md"), "utf8");

describe("말투 규범 — 문서와 코드가 어긋나지 않는다", () => {
  it("코드의 표식이 전부 문서에 적혀 있다", () => {
    const 빠진것 = Object.values(표식).filter((s) => !규범.includes(s));
    expect(빠진것, `문서에 없는 표식을 코드가 쓴다:\n  ${빠진것.join(" ")}`).toEqual([]);
  });

  it("문서의 판정 머리표가 코드에도 있다", () => {
    for (const 이름 of 판정머리표) {
      expect(규범.includes(`【 】`) || 규범.includes(이름), `${이름}이 문서에 없다`).toBe(true);
    }
  });

  it("금지 목록에 전부 이유와 대안이 있다", () => {
    // ⚠ 이유 없는 금지는 지킬 수도 고칠 수도 없다.
    for (const g of 금지말투) {
      expect(g.왜.length, `${g.이름}의 이유가 너무 짧다`).toBeGreaterThan(15);
      expect(g.대신.length, `${g.이름}의 대안이 없다`).toBeGreaterThan(5);
    }
  });

  it("이 대조가 헛돌고 있지 않다", () => {
    expect(Object.keys(표식).length).toBeGreaterThanOrEqual(6);
    expect(금지말투.length).toBeGreaterThanOrEqual(5);
    expect(규범.length, "규범 문서를 못 읽었다").toBeGreaterThan(1000);
  });
});

