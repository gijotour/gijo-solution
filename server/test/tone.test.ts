// ── B9 겹치는기호 소스 감시 (2026-09-12 야간 회귀) ──────────────────────────────────
//
// 왜: tone.겹치는기호가 「✅·☑·✔은 ✓와 뜻이 겹친다」고 이미 적어 뒀는데도, 실전 답 3건
// (runApprovalStatus·VEX 안내·조치 검증·AI-BOM 기입 — 원천은 겹친다)이 화면 메뉴 라벨의
// ✅를 그대로 옮기거나 글자 ✅를 새로 박아 걸렸다. 사전 상수(표식.좋음 ✓)를 두고도 코드가
// 계속 글자를 새로 박으면 사전은 장식일 뿐이다 — 그래서 **박는 자리 자체가 없는지**를 소스에서 잰다.
describe("★ B9 — 상태 기호 리터럴 소스 감시 (사전 상수로만 쓴다)", () => {
  // ⚠ ☑·❌는 2026-09-12 B9 후속(설계관 실측)까지는 **일부러 뺐었다** — 그때 근거로 든
  //   「screenguide.ts가 이 둘을 화면의 실제 조작 요소 이름표로 쓴다」는 절반만 맞았다.
  //   실측: mydocs.html:1032·1038·1054·1062의 문서 지정 체크박스는 **네이티브
  //   `<input type="checkbox">`**라 화면 어디에도 글자 ☑가 없다 — llm.ts:950·noevidence.ts:35·
  //   screenguide.ts:164·732·749의 「문서 지정(☑)」은 서버가 지어낸 기호였다(산문으로 고쳤다).
  //   남는 예외는 **정말로 화면 글자인 둘뿐**이다 — dashboard.html:338의 「☑ 오늘 할 일」(판
  //   제목)과 chatparts.js:879의 「❌ 틀린 답」(단추 라벨). 그래서 이제 ☑·❌도 스캔 대상에
  //   넣고, 이 둘만 tone.화면요소인용으로 마스킹해 예외를 좁게 유지한다(아래 스캔 루프).
  const 사전밖상태기호 = /[✅✔✖❎☑❌]/u; // ✅ ✔ ✖ ❎ ☑ ❌ — 화면요소인용에 등록된 문구만 스캔 전에 지운다
  const ENGINE = path.join(__dirname, "..", "src", "engine");

  /** 블록(/* *\/)·줄(//) 주석을 코드에서 걷어낸다. 줄 수가 안 밀리도록 지운 자리는 공백으로 채운다. */
  function 코드만(src: string): string {
    const 블록없음 = src.replace(/\/\*[\s\S]*?\*\//g, (m) => m.replace(/[^\n]/g, " "));
    return 블록없음
      .split("\n")
      .map((l) => {
        if (l.trim().startsWith("//")) return "";
        const m = /(?<!:)\/\//.exec(l);
        return m ? l.slice(0, m.index) : l;
      })
      .join("\n");
  }

  it("엔진 전체를 훑고 있다 — 감시가 헛돌지 않는다", () => {
    const files = (fs.readdirSync(ENGINE, { recursive: true }) as string[]).filter((f) => f.endsWith(".ts"));
    expect(files.length, "엔진 파일을 못 읽었다 — 감시가 헛돈다").toBeGreaterThan(50);
  });

  it("답을 만드는 .ts 파일에 ✅·✔·✖·❎·☑·❌ 글자가 없다(주석·tone.ts 사전·화면요소인용 예외 제외)", () => {
    const files = (fs.readdirSync(ENGINE, { recursive: true }) as string[]).filter((f) => f.endsWith(".ts"));
    const 걸린것: string[] = [];
    for (const f of files) {
      if (path.basename(f) === "tone.ts") continue; // 사전 정의 자리
      const 코드 = 코드만(fs.readFileSync(path.join(ENGINE, f), "utf8"));
      코드.split("\n").forEach((line, i) => {
        // 런타임 예외(말투위반)와 **같은 배열**로 지우고 잰다 — 같은 사실을 두 곳에 적지 않는다.
        const 검사줄 = 화면요소인용.reduce((acc, q) => acc.split(q).join(""), line);
        if (사전밖상태기호.test(검사줄)) 걸린것.push(`${f}:${i + 1}: ${line.trim().slice(0, 90)}`);
      });
    }
    expect(
      걸린것,
      `사전 상수(표식.좋음 ✓ · 표식.나쁨 ✗) 대신 글자를 새로 박은 자리 — tone.표식을 import해 쓸 것(화면 실물 인용은 tone.화면요소인용에 등록):\n  ${걸린것.join("\n  ")}`,
    ).toEqual([]);
  });

  // 헛돌기 방지(T3) — 화면요소인용 마스킹을 안 하면 남겨 둔 예외 셋(541·543·1447)이
  // 실제로 걸리는지를 이 시험 안에서 직접 확인한다. 이게 안 걸리면 위 시험이 「원래부터
  // 안 걸렸을 것」을 마스킹 덕으로 착각하게 된다.
  it("★ 헛돌기 방지 — 화면요소인용을 안 지우면 예외 셋이 실제로 걸린다", () => {
    const f = "screenguide.ts";
    const 코드 = 코드만(fs.readFileSync(path.join(ENGINE, f), "utf8"));
    const 무마스킹걸린줄: number[] = [];
    코드.split("\n").forEach((line, i) => {
      if (사전밖상태기호.test(line)) 무마스킹걸린줄.push(i + 1);
    });
    expect(무마스킹걸린줄.length, "마스킹 없이도 0건이면 이 시험이 헛돈다 — 예외가 실제로 무언가를 가리고 있는지 못 잰다").toBeGreaterThan(0);
    // 541·543(급한 것·오늘 할 일 — 「☑ 오늘 할 일」)·1447(이 답 이상해요 — 「❌ 틀린 답」).
    expect(무마스킹걸린줄).toEqual(expect.arrayContaining([541, 543, 1447]));
  });
});

