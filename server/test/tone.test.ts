// 대화창 말투 규범 — 문서와 코드가 같은 것을 말하는가, 그리고 실제 답이 그것을 지키는가.
//
// 왜 필요한가(2026-08-02 하루 실전 147상황 실측):
//   답변에 **최소 일곱 가지 목소리**가 섞여 있었다. 도구 즉답은 담백한데 LLM 재작성은
//   "먼저, 알아야 할 것은…" 하고 번호를 매기고, 거절은 내부 사정을 말했다.
//   **말투가 코드 경로를 드러내고 있었다** — 담당자는 우리 코드 구조를 알 이유가 없다.
//
// ⚠ 이 시험의 절반은 **오탐 방지**다. 정상 답을 위반으로 몰면 담당자는 답을 못 받는다 —
//   놓치는 것만큼 나쁘다. 그래서 실제 운영 답변을 그대로 넣어 확인한다.
import { describe, it, expect } from "vitest";
import fs from "node:fs";
import path from "node:path";
import { 표식, 허용표식, 판정머리표, 금지말투, 말투위반, 소개서두 } from "../src/engine/tone";

const 규범 = fs.readFileSync(path.join(__dirname, "../../GIJO_AS_대화창_말투규범.md"), "utf8");

describe("말투 규범 — 문서와 코드가 어긋나지 않는다", () => {
  it("코드의 표식이 전부 문서에 적혀 있다", () => {
    const 빠진것 = Object.values(표식).filter((s) => !규범.includes(s));
    expect(빠진것, `문서에 없는 표식을 코드가 쓴다:\n  ${빠진것.join(" ")}`).toEqual([]);
  });

  it("문서의 판정 머리표가 코드에도 있다", () => {
    for (const 이름 of 판정머리표) {
      expect(규범.includes(`【 】`) || 규범.includes(이름), `${이름}이 문서에 없다`).toBe(true);
    }
  });

  it("금지 목록에 전부 이유와 대안이 있다", () => {
    // ⚠ 이유 없는 금지는 지킬 수도 고칠 수도 없다.
    for (const g of 금지말투) {
      expect(g.왜.length, `${g.이름}의 이유가 너무 짧다`).toBeGreaterThan(15);
      expect(g.대신.length, `${g.이름}의 대안이 없다`).toBeGreaterThan(5);
    }
  });

  it("이 대조가 헛돌고 있지 않다", () => {
    expect(Object.keys(표식).length).toBeGreaterThanOrEqual(6);
    expect(금지말투.length).toBeGreaterThanOrEqual(5);
    expect(규범.length, "규범 문서를 못 읽었다").toBeGreaterThan(1000);
  });
});

describe("말투 감시 — 어긴 것을 잡는다", () => {
  const 잡아야: [string, string][] = [
    ["예고", "취약점 현황을 정리해 드리겠습니다. 미조치 14건입니다."],
    ["자기소개", "우선 안녕하세요. 저는 GIJO AS의 보안 AI입니다. 취약점은 14건입니다."],
    ["내부 사정", "모델 판정이 형식을 지키지 못해 보류합니다."],
    ["소스 경로", "자세한 내용은 server/src/engine/assets.ts를 보세요."],
    ["내부 식별자", "가장 급한 것은 id=vuln:10.10.20.41 입니다."],
    ["영문 상태값", '이 취약점의 상태는 "pending"입니다.'],
  ];
  for (const [이름, 답] of 잡아야) {
    it(`${이름}을 잡는다`, () => {
      const v = 말투위반(답);
      expect(v.length, `못 잡았다: ${답}`).toBeGreaterThan(0);
      expect(v.some((x) => x.이름.includes(이름.split(" ")[0]))).toBe(true);
    });
  }

  it("사전에 없는 표식을 줄 앞에 쓰면 잡는다", () => {
    expect(말투위반("🚀 취약점 14건입니다.").length).toBeGreaterThan(0);
  });
});

describe("★ 예고 예외 — 긴 작업의 접수 통지는 예고가 아니다", () => {
  // 왜(2026-09-04, 실전 답 152건 감시): 「중복된 문서 있어?」의 답이 예고로 걸렸다.
  //   dispatcher가 30초를 넘긴 작업에 내보내는 접수 문구다(2026-07-26 사용자 결정).
  //   긴 작업은 그 자리에서 답을 줄 수가 없어 「받았다·끝나면 알린다」가 곧 답이다 —
  //   예고 규칙은 **본론을 뒤로 미루는 서두**를 막는 것이지 접수 통지를 막는 것이 아니다.
  it("실제로 나간 접수 통지가 통과한다", () => {
    const v = 말투위반("시간이 걸리는 작업이라 리포트로 작성해 드리겠습니다. 다 되면 알려드릴게요 — 다른 일 보셔도 됩니다.");
    expect(v, `접수 통지가 막혔다: ${v.map((x) => x.이름).join(", ")}`).toEqual([]);
  });

  it("끝나면 어디서 보는지 알려 주는 꼴도 통과한다", () => {
    expect(말투위반("오래 걸리는 작업이라 리포트로 작성해 드리겠습니다. 끝나면 작업 내역에서 확인하실 수 있습니다.")).toEqual([]);
  });

  it("★ 반례 — 서두 예고는 여전히 걸린다(예외가 규칙을 통째로 풀지 않았다)", () => {
    for (const 답 of [
      "먼저, 취약점 목록을 알려드리겠습니다. 미조치 14건입니다.",
      "우선 현황을 설명해 드리겠습니다. 자산 57건입니다.",
      "결과를 리포트로 작성해 드리겠습니다.",                    // 접수의 반쪽 — 끝나면 알린다는 말이 없다
      "다 되면 알려드릴게요. 그전에 설명해 드리겠습니다.",        // 반대쪽 반쪽 — 긴 작업이라는 말이 없다
    ]) {
      expect(말투위반(답).some((x) => x.이름 === "예고"), `못 잡았다: ${답}`).toBe(true);
    }
  });

  it("★ 예외는 답 첫머리에만 — 긴 안내 글 속에 같은 문구가 있다고 예고 감시가 꺼지지 않는다", () => {
    // 실측: 첫머리로 안 묶었더니 실전 답 152건 중 7건이 걸렸고 6건이 화면 사용 안내였다.
    //   그 글들은 끝에 "…리포트로 작성해 저장하고, 다 되면 알려드립니다"를 달고 있을 뿐이다.
    const 안내 = "자산 목록 — 이 화면 사용 안내\n먼저, 화면 구성을 설명해 드리겠습니다.\n30초가 넘는 작업은 리포트로 작성해 저장하고, 다 되면 알려드립니다.";
    expect(말투위반(안내).some((x) => x.이름 === "예고"), "긴 글 속 문구 하나로 감시가 통째로 꺼졌다").toBe(true);
  });
});

