    //   목록만 나가고 승인·배정은 영영 안 갔다(같은 커밋의 B10-①이 닫았다고 적은 바로 그 사고가
    //   다른 파일에서 열린 것). 지금은 isFindingListAsk 입구에서 writeflow.쓰기흐름인가
    //   (agentloop와 **같은 함수**)가 막는다 — 낱말 목록을 두 벌 두지 않는다.
