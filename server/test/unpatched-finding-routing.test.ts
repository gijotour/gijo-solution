//   방치)를 **요구**해 시간어 없는 같은 뜻을 원리상 못 받는다. 그래서 「패치 안 한 취약점
//   알려줘」는 착수 전 ∅(⑨ 모델 선택)이었다 — B7 ② 이웃 문장인데 그 라운드가 못 닫은 구멍
//   (picklist.ts:145-149 「남은 구멍(알고 둔다)」 주석이 스스로 적어 뒀다).
//
// ■ 수리
//   LIST_VERB_RE에 「알려」를 넣지 않는다 — 실측(R21 「미조치 취약점 목록 보여줘」가 이미
//   [14]로 간다)이 보이듯 [14]는 dispatcher 체인에서 [37] 강제도구보다 **앞**이라, 넣으면
//   agentloop.상태어취약점(finding_status) 영토(미조치·고위험·KEV…)를 통째로 뺏는다.
//   대신 오래미조치물음과 같은 모양의 좁은 술어 `picklist.미패치물음()`을 신설해 isFindingListAsk
//   에 OR로 더했다 — 자리가 아니라 **배제어**로 막는다(등급·KEV·비취약점 대상·지식 물음은 비켜 준다).
//
// ■ 판정은 제품 함수(결정적도착지)로 한다 — helpers/routing.ts·aged-finding-routing.test.ts와
//   같은 방식.
import { describe, it, expect } from "vitest";
import { 결정적도착지 } from "../src/engine/dispatcher";
import { isFindingListAsk, 미패치물음 } from "../src/engine/picklist";
import { 물음속심각도 } from "../src/engine/tone";

describe("★ 「패치 안 한/안 된 취약점 알려줘」는 [14] findingListAnswer로 간다", () => {
  const 양성 = [
    "패치 안 한 취약점 알려줘", // Q01 — B7 ②가 못 닫은 그 구멍
    "패치 안 된 취약점 알려줘", // Q02
    "패치 못 한 취약점 알려줘", // Q03
    "아직 패치 안 한 취약점 알려줘", // Q04
    "안 고친 취약점 알려줘", // S02
    "패치 안 한 거 알려줘", // S04 — 대상이 「거」인 꼴(오래미조치물음이 이미 같은 꼴을 받는다)
    "아직 안 고친 거 알려줘", // S05
    "패치 안 한 취약점 정리해줘", // S06 — 「정리」도 조회동사로 받기로 정함
    // 이미 [14]였던 이웃 4문장 — 회귀 못박기(말투만 다르고 같은 뜻).
    "패치 안 된 취약점 목록 보여줘", // Q05
    "패치 안 한 취약점 뭐 있어?", // Q06
    "패치 안 한 취약점 목록 알려줘", // R14
    "패치 안 된 취약점 현황 알려줘", // R15
  ];
  for (const 문장 of 양성) {
    it(`「${문장}」 → findingListAnswer(목록+체크칸)`, async () => {
      const 걸림 = await 결정적도착지(문장, { 역할: "admin" });
      expect(걸림[0]?.도착 ?? null, `실제 걸림: ${걸림.map((x) => x.도착).join(" → ") || "(아무것도 안 걸림)"}`).toBe(
        "findingListAnswer(목록+체크칸)",
      );
    });
  }
});

