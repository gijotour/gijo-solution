describe("★ 잎 함수 직접 — 미패치물음", () => {
  it('미패치물음("패치 안 한 취약점 알려줘") === true', () => {
    expect(미패치물음("패치 안 한 취약점 알려줘")).toBe(true);
  });
  it('미패치물음("패치 안 된 고위험 취약점 알려줘") === false (등급 조건 — findingListAnswer가 못 거른다)', () => {
    expect(미패치물음("패치 안 된 고위험 취약점 알려줘")).toBe(false);
  });
  it('미패치물음("패치 안 된 자산 알려줘") === false (비취약점 대상)', () => {
    expect(미패치물음("패치 안 된 자산 알려줘")).toBe(false);
  });
  it('미패치물음("조치 안 된 취약점 알려줘") === false ("조치"는 신호에서 뺀다 — finding_status·상태어취약점 영토와 겹쳐 이 라운드 범위 밖)', () => {
    expect(미패치물음("조치 안 된 취약점 알려줘")).toBe(false);
  });
  it('물음속심각도("패치 안 된 고위험 취약점 알려줘") === null (왜 비켜 주는지의 전제)', () => {
    expect(물음속심각도("패치 안 된 고위험 취약점 알려줘")).toBeNull();
  });
  it('isFindingListAsk("패치 안 한 취약점 알려줘") === true (전체 배선 확인)', () => {
    expect(isFindingListAsk("패치 안 한 취약점 알려줘")).toBe(true);
  });
  // ★ 2026-09-12 검토관 [중] 수리 — 대상 없이 성립시키는 신호는 「패치」뿐이다.
  it('미패치물음("패치 안 한 거 알려줘") === true / 미패치물음("수정 안 한 거 알려줘") === false', () => {
    expect(미패치물음("패치 안 한 거 알려줘")).toBe(true);
    expect(미패치물음("수정 안 한 거 알려줘")).toBe(false);
    expect(미패치물음("수정 안 한 취약점 알려줘")).toBe(true); // 대상을 말하면 받는다
  });
  it('미패치물음("설정 수정 안 한 거 알려줘") === false (배제 대상에 설정·정책·룰 추가)', () => {
    expect(미패치물음("설정 수정 안 한 거 알려줘")).toBe(false);
    expect(미패치물음("정책 수정 안 한 거 알려줘")).toBe(false);
  });
  it('미패치물음("패치 안 한 취약점 통계 알려줘") === false (세는 물음·추이는 목록이 아니다)', () => {
    expect(미패치물음("패치 안 한 취약점 통계 알려줘")).toBe(false);
    expect(미패치물음("패치 안 한 취약점 추이 알려줘")).toBe(false);
  });
  // ★★ 2026-09-12 검토관 [상] 수리 — 쓰기 흐름은 **잣대 한 곳**이 막는다(낱말 목록이 아니다).
  it('isFindingListAsk("패치 안 한 취약점 알려주고 승인해줘") === false (writeflow.쓰기흐름인가)', () => {
    expect(isFindingListAsk("패치 안 한 취약점 알려주고 승인해줘")).toBe(false);
    expect(isFindingListAsk("패치 안 한 취약점 알려주고 김보안한테 맡겨줘")).toBe(false);
    expect(미패치물음("패치 안 한 취약점 알려주고 승인해줘")).toBe(true); // 잎 함수는 그대로 — 막는 자리는 입구다
  });
});
