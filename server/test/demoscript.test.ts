// 시연 대본(GIJO_AS_시연_패키지.md, 계획서 전-1)의 지시문이 **결정적 분기에 안 뺏기는가**.
//
// ★ 왜 이 시험이 필요한가
//   계획서의 「전」 단계 통과 기준이 "파일럿 1곳에서 시나리오 ①~③이 실데이터로 시연됨"이다.
//   그런데 시연에서 쓰는 문장은 대본에 못 박혀 있고, 우리는 라우팅 앞단에 결정적 분기를
//   계속 더한다(2026-08-01 하루에만 5개). 앞단 분기 하나가 넓으면 **시연 문장이 엉뚱한
//   기능으로 새고, 그건 고객 앞에서 드러난다.**
//
//   실제로 오늘 이 자리에서 두 번 데었다 — "점검" 두 글자가 일감에 걸렸고,
//   "오늘 할 일 없어?"가 메뉴 폐지 공지로 샜다. 대본 문장을 시험으로 박아 둔다.
//
// ⚠ 이 시험은 **LLM을 부르지 않는다.** 결정적 분기(내 할 일 완료·절차)만 본다 —
//   최종 답의 품질은 평가 게이트(중-3)가 재고, 여기서는 "가로채기"만 막는다.
import { describe, it, expect, beforeEach } from "vitest";
import { 내할일절차질문, 내할일완료말 } from "../src/engine/dispatcher";
import { isMyWorkAsk } from "../src/engine/picklist";
import { createTask, resetTasksForTests } from "../src/engine/tasks";

// 대본에서 담당자가 실제로 치는 문장(GIJO_AS_시연_패키지.md 발췌).
const 대본문장 = [
  // 시연 ① 혼자 남은 월요일 아침
  "오늘 뭐부터 볼까?",
  "미조치 취약점 알려줘",
  "이번 주 예정된 점검 있어?",
  "오늘 브리핑 해줘",
  // 시연 ② 인수인계
  "ASA 106023 로그가 한 IP에서 계속 올라오는데 무슨 의미야?",
  // 시연 ③ 규정·법령 대조
  "USB 반출 정책 완화해도 돼?",
  "개인정보 시스템 접속기록 보관 주기를 6개월로 줄여도 돼?",
  "접속기록 보관 기간 규정 알려줘",
  "KEV 등재 취약점 조치 기한 근거 지침이 뭐야?",
  // 시연 ④ 보고
  "내부 검토용 주간 리포트 작성해줘",
];

describe("★ 시연 대본이 내 할 일 분기에 안 뺏긴다 (계획서 전-1)", () => {
  beforeEach(() => {
    resetTasksForTests();
    // 시연 환경과 같게 — 목록에 점검·취약점 이름의 일감이 실제로 들어 있는 상태로 시험한다.
    // (일감이 없으면 이름 대조가 늘 실패해서 시험이 통과해 버린다 — 거짓 통과 방지.)
    createTask({ text: "10.10.20.41 — 취약점 점검" });
    createTask({ text: "방화벽 정책 정기 점검" });
    createTask({ text: "제품유지보수" });
  });

  for (const 문장 of 대본문장) {
    it(`"${문장}"`, async () => {
      expect(await 내할일완료말(문장), "완료 분기가 시연 문장을 가로챈다").toBeNull();
      expect(await 내할일절차질문(문장), "절차 분기가 시연 문장을 가로챈다").toBeNull();
    });
  }

  it("★ 목록 경로도 시연 문장을 가로채지 않는다", () => {
    // "오늘 뭐부터 볼까?"가 내 할 일 목록으로 새면 취약점 우선순위(today)가 안 나온다 —
    // 시연 ①의 핵심 대사가 통째로 죽는다.
    for (const 문장 of 대본문장) {
      expect(isMyWorkAsk(문장), `목록 경로가 "${문장}"을 가로챈다`).toBe(false);
    }
  });
});

describe("★ 그래도 내 할 일 문장은 여전히 잡힌다 (반대 방향)", () => {
  beforeEach(() => {
    resetTasksForTests();
    createTask({ text: "10.10.20.41 — 취약점 점검" });
  });

  it("가로채기를 막느라 정작 할 일을 놓치지 않았는지 함께 본다", async () => {
    expect(await 내할일완료말("10.10.20.41 — 취약점 점검 완료")).toBeTruthy();
    expect(await 내할일절차질문("10.10.20.41 — 취약점 점검 어떻게 해?")).toBeTruthy();
    expect(isMyWorkAsk("오늘 할 일")).toBe(true);
  });
});
