// 가리킬 것이 없는 대명사 — "그거 어떻게 해"에 27초를 쓰지 않는다.
//
// 실측(2026-08-03 실전 147상황): 이 말에 모델이 **27.9초**를 쓰고
//   "질문을 구체적으로 알려주시면 도와드리겠습니다"를 내놓았다.
//   되묻는 것은 **맞는 답**이다 — 맥락이 없는데 아무거나 골라 답하면 엉뚱한 자산을 손댄다.
//   틀린 것은 답이 아니라 **27초**다. 되묻는 데 모델이 필요할 리 없다.
//
// ★ 이 시험이 지키는 것 둘:
//   ① 맥락이 없으면 즉시 되묻고, 되묻되 **예시를 준다**("구체적으로"만 하면 또 막힌다)
//   ② 직전 대상이 **있으면** 여기 안 걸린다 — 그건 #8 대화 맥락이 이어받아야 한다
import { describe, it, expect, beforeEach } from "vitest";
import { 가리킬것없는대명사, 되물음, setLastTarget, resetContextForTests } from "../src/engine/agentloop";

beforeEach(() => resetContextForTests());

describe("맥락이 없을 때 — 즉시 되묻는다", () => {
  for (const 말 of ["그거 어떻게 해", "그거 어떻게 해?", "이거 뭐야", "아까 그거", "그것 좀 보여줘"]) {
    it(`잡는다 — "${말}"`, () => {
      expect(가리킬것없는대명사(말), "못 잡아서 모델이 27초를 쓴다").toBe(true);
    });
  }

  it("되묻는 말이 **무엇을 말하면 되는지**까지 준다", () => {
    const out = 되물음();
    expect(out).toContain("되묻습니다");
    expect(out, "다음 걸음이 없다").toContain("▸");
    // "구체적으로 알려주세요"만 하면 담당자는 또 막힌다 — 그대로 쓸 문장을 준다.
    expect((out.match(/"/g) ?? []).length, "그대로 쓸 예시 문장이 없다").toBeGreaterThanOrEqual(6);
  });
});

describe("★ 안 잡아야 하는 것 — 여기서 잘못 잡으면 기능이 죽는다", () => {
  it("직전 대상이 있으면 안 잡는다 (#8 대화 맥락이 이어받는다)", () => {
    setLastTarget("fraud-detect-llm", "프롬프트 인젝션", "취약점 배정");
    expect(가리킬것없는대명사("아까 그거 이영희로 바꿔"), "맥락 기능을 가로챈다").toBe(false);
    expect(가리킬것없는대명사("그거 어떻게 해"), "맥락 기능을 가로챈다").toBe(false);
  });

  it("대명사 말고 **내용이 있으면** 안 잡는다", () => {
    for (const 말 of [
      "그 취약점 담당자 배정해줘",
      "이 자산 취약점 알려줘",
      "그거 조치완료로 바꿔줘",
      "이번 달 보고서 만들어줘",
      "오늘 뭐부터 해야 해?",
    ]) {
      expect(가리킬것없는대명사(말), `진짜 지시를 되묻기로 삼킨다: ${말}`).toBe(false);
    }
  });

  it("대명사가 아예 없으면 안 잡는다", () => {
    expect(가리킬것없는대명사("미조치 취약점 몇 건이야?")).toBe(false);
    expect(가리킬것없는대명사("")).toBe(false);
  });

  it("이 시험이 헛돌고 있지 않다", () => {
    // 위 부정 단언만 있으면 함수가 항상 false를 돌려줘도 통과한다.
    expect(가리킬것없는대명사("그거 어떻게 해"), "긍정 대조가 죽었다").toBe(true);
  });
});

describe("★ 대화 맥락은 사람마다 따로 — 남의 「아까 그거」가 새면 안 된다", () => {
  // 예전에는 전역 1건이었고 주석에 "1인 운영 전제"라고 적혀 있었다. 그 전제는 낡았다 —
  // 지금은 보안담당자 여럿이 각자 대화창을 쓴다. 전역이면 담당자 A가 방금 다룬 취약점을
  // **담당자 B의 "아까 그거"가 가리킨다** — 남의 맥락으로 남의 자산에 쓰기 지시가 나갈 수 있다.
  it("A가 남긴 대상이 B에게 안 보인다", () => {
    setLastTarget("fraud-detect-llm", "프롬프트 인젝션", "취약점 배정", "u:1");
    // A는 맥락이 있으니 되묻지 않는다
    expect(가리킬것없는대명사("그거 어떻게 해", "u:1"), "A의 맥락이 사라졌다").toBe(false);
    // B는 맥락이 없으니 되묻는다 — A의 대상을 물려받으면 안 된다
    expect(가리킬것없는대명사("그거 어떻게 해", "u:2"), "★ 남의 맥락이 새어 들어왔다").toBe(true);
  });

  it("대화 열쇠를 안 주면 예전처럼 기본 대화를 쓴다(더 나빠지지 않는다)", () => {
    setLastTarget("a-01", "취약점", "라벨");            // 기본 대화
    expect(가리킬것없는대명사("그거 어떻게 해")).toBe(false);
    expect(가리킬것없는대명사("그거 어떻게 해", "u:9")).toBe(true);
  });

  it("이 시험이 헛돌고 있지 않다", () => {
    // 열쇠를 무시하고 항상 같은 것을 보면 위 시험이 통과할 수 없다 — 그래도 한 번 더 못 박는다.
    setLastTarget("x-01", "취약점", "라벨", "u:7");
    expect(가리킬것없는대명사("그거 어떻게 해", "u:7")).toBe(false);
    expect(가리킬것없는대명사("그거 어떻게 해", "u:8")).toBe(true);
  });
});
