// 조사 자동 선택 — 결재판 문구의 「을(를)」을 뿌리 뽑은 자리(2026-08-22).
// 계획서: 전-7(보여 주기) — 사람이 가장 자주 보는 화면(결재판)의 말이 어색하면 제품이 덜 완성돼 보인다.
import { describe, it, expect } from "vitest";
import fs from "fs";
import path from "path";
import { 조사, 말조사 } from "../src/util/josa.js";

describe("조사 — 한글 받침", () => {
  it("받침이 없으면 를·가·는·와", () => {
    expect(말조사("지식화", "을")).toBe("지식화를");
    expect(말조사("보안제품 등록", "이")).toBe("보안제품 등록이"); // 록 = ㄱ받침
    expect(말조사("차단하기", "이")).toBe("차단하기가");
    expect(말조사("메모", "은")).toBe("메모는");
    expect(말조사("자산 정보", "와")).toBe("자산 정보와");
  });

  it("받침이 있으면 을·이·은·과", () => {
    expect(말조사("보고서", "을")).toBe("보고서를"); // 서 = 받침 없음
    expect(말조사("문서 반입", "을")).toBe("문서 반입을");
    expect(말조사("점검", "이")).toBe("점검이");
    expect(말조사("취약점", "은")).toBe("취약점은");
    expect(말조사("자산", "와")).toBe("자산과");
  });

  it("실제로 고장 나 있던 문구가 바르게 나온다", () => {
    // 「링크 지식화을(를) 진행합니다」 — 라이브에서 이 말이 나갔다(2026-08-22).
    expect(`${말조사("링크 지식화", "을")} 진행합니다`).toBe("링크 지식화를 진행합니다");
    expect(`${말조사("정기점검 일정 잡기", "을")} 준비했습니다`).toBe("정기점검 일정 잡기를 준비했습니다");
  });
});

describe("조사 — 숫자·영문은 읽는 소리로 가른다", () => {
  it("숫자: 영·일·삼·육·칠·팔은 받침이 있다", () => {
    expect(말조사("자산 1", "이")).toBe("자산 1이"); // 일
    expect(말조사("자산 2", "이")).toBe("자산 2가"); // 이
    expect(말조사("포트 3", "이")).toBe("포트 3이"); // 삼
    expect(말조사("등급 4", "이")).toBe("등급 4가"); // 사
    expect(말조사("CVE-2024-6", "을")).toBe("CVE-2024-6을"); // 육
    expect(말조사("버전 9", "을")).toBe("버전 9를"); // 구
  });

  it("영문: l·m·n·r만 받침이 있다", () => {
    expect(말조사("web-01", "이")).toBe("web-01이"); // 1 = 일
    expect(말조사("firewall", "이")).toBe("firewall이"); // l = 엘
    expect(말조사("qwen", "이")).toBe("qwen이"); // n = 엔
    expect(말조사("server", "이")).toBe("server이"); // r = 알
    expect(말조사("scan", "을")).toBe("scan을"); // n
    expect(말조사("pdf", "을")).toBe("pdf를"); // f = 에프 → 받침 없음(헷갈리는 자리)
    expect(말조사("Metal", "으로")).toBe("Metal로"); // l = ㄹ
    expect(말조사("qwen2.5-72b", "을")).toBe("qwen2.5-72b를"); // b = 비
  });

  // ⚠ 이 규칙의 한계를 정직하게 못 박아 둔다.
  //   영문은 **글자를 하나씩 읽는다고 보고** 가른다(r=알, l=엘). 그런데 사람은 낱말을 통째로
  //   읽기도 한다 — server를 「서버」로 읽으면 받침이 없어 「서버가」가 된다.
  //   둘 다 맞는 자리라 발음 사전 없이는 완벽할 수 없다. 우리 데이터에서 실제로 흔한 끝글자는
  //   **숫자**(자산 web-01)와 b(모델 …-72b)라 이 규칙으로 충분하고, 한글·숫자는 정확하다.
  it("한계 — 영문 낱말을 통째로 읽는 경우까지는 맞추지 못한다", () => {
    expect(조사("server", "이"), "글자 읽기(알) 기준 — 「서버」로 읽으면 「가」가 맞다").toBe("이");
  });
});

describe("조사 — 「으로」는 ㄹ 받침이 예외", () => {
  it("ㄹ 받침이면 「로」, 다른 받침이면 「으로」, 받침 없으면 「로」", () => {
    expect(말조사("파일", "으로")).toBe("파일로");
    expect(말조사("서울", "으로")).toBe("서울로");
    expect(말조사("문서", "으로")).toBe("문서로");
    expect(말조사("검색", "으로")).toBe("검색으로");
    expect(말조사("지식", "으로")).toBe("지식으로");
  });
});

describe("조사 — 끝에 붙은 부호는 건너뛴다", () => {
  it("따옴표·괄호로 끝나도 안쪽 글자에 맞춘다", () => {
    // 「자산 "web-01"을(를) 찾을 수 없습니다」가 실제로 있던 문구다.
    expect(말조사('자산 "web-01"', "을")).toBe('자산 "web-01"을'); // 1 = 일
    expect(말조사('제품 "방화벽"', "이")).toBe('제품 "방화벽"이');
    expect(말조사("모델(qwen2.5)", "을")).toBe("모델(qwen2.5)를"); // 5 = 오
  });

  it("모르는 글자·빈 값은 받침 없는 쪽으로 읽는다", () => {
    expect(조사("", "을")).toBe("를");
    expect(조사("🔒", "이")).toBe("가");
  });
});

// ── 소스 감시 — 「세 번째면 소스 감시」(사용자 확립 원칙) ────────────────────────
// 16곳이나 있었다는 것은 사람이 그때그때 손으로 적어 온 자리라는 뜻이다.
// 새로 쓰는 문구가 같은 함정에 빠지지 않게 소스에서 직접 막는다.
describe("소스 감시 — 안 고른 조사 표기가 다시 생기지 않는다", () => {
  const 뿌리 = path.resolve(__dirname, "../src");

  function ts파일들(디렉터리: string, 모음: string[] = []): string[] {
    for (const e of fs.readdirSync(디렉터리, { withFileTypes: true })) {
      const p = path.join(디렉터리, e.name);
      if (e.isDirectory()) ts파일들(p, 모음);
      else if (e.name.endsWith(".ts")) 모음.push(p);
    }
    return 모음;
  }

  it("사용자에게 나가는 문구에 「을(를)」류가 없다", () => {
    const 금지 = /을\(를\)|이\(가\)|은\(는\)|와\(과\)|과\(와\)|으로\(로\)|로\(으로\)/;
    const 걸린것: string[] = [];
    for (const f of ts파일들(뿌리)) {
      if (f.endsWith(`util${path.sep}josa.ts`)) continue; // 이 파일은 그 표기를 설명한다
      const 줄들 = fs.readFileSync(f, "utf-8").split("\n");
      줄들.forEach((줄, i) => {
        if (!금지.test(줄)) return;
        if (/^\s*(\/\/|\*|\/\*)/.test(줄)) return; // 주석은 사용자가 안 본다
        걸린것.push(`${path.relative(뿌리, f)}:${i + 1}  ${줄.trim().slice(0, 90)}`);
      });
    }
    expect(걸린것, `조사를 손으로 적은 자리가 남아 있다 — util/josa.ts의 말조사()를 쓸 것:\n${걸린것.join("\n")}`).toEqual([]);
  });
});
