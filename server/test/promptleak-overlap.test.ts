// ── 「근거 약함」 배너 문구가 측정 도구와 싸우지 않는가 (2026-08-05) ──────────────────────
//
// 이 자리는 **같은 사고를 두 번** 겪었다. 처음 쓴 「직접적인 사내 자료는 찾지 못했습니다」가
// 서랍 점검의 폴백 문구 목록(drawer-audit.mjs FAIL_MARKS)에 그대로 있어 **좋은 답에 실패
// 딱지**가 붙었다. 반대로 평가 게이트는 `없|찾지 못|확인되지`를 정직 표현으로 **인정**한다 —
// 같은 말이 한쪽에선 벌, 한쪽에선 상이었다.
//
// 그래서 문구를 **사람이 기억하는 것**에 맡기지 않고 코드가 지킨다.
describe("근거 약함 배너 — 두 측정 도구와 어긋나지 않는가", () => {
  // ⚠ 주석에 같은 글자를 쓰면 **조용히 주석을 검사**하게 된다(2026-08-05 검토 지적).
  //   주석(//)이 아닌 줄에서만 찾고, 실제로 답에 붙는 자리(reply = `…`)인지도 본다.
  const 배너 = fs.readFileSync(new URL("../src/engine/llm.ts", import.meta.url), "utf8")
    .split("\n")
    .filter((l) => !l.trim().startsWith("//"))
    .find((l) => l.includes("**근거 약함") && l.includes("reply =")) ?? "";
  // ⚠ 서랍 점검의 실패 문구를 **복사하지 않고 원본에서 읽는다**(2026-08-05 검토 지적).
  //   베껴 두면 저쪽이 늘어날 때 이 시험은 모른 채 통과한다 — 같은 사고를 세 번 겪게 된다.
  const 실패딱지 = (() => {
    const src = fs.readFileSync(new URL("../../tools/drawer-audit.mjs", import.meta.url), "utf8");
    const 시작 = src.indexOf("const FAIL_MARKS = [");
    const 끝 = src.indexOf("];", 시작);
    expect(시작, "FAIL_MARKS를 못 찾았다 — 이 시험이 헛돌고 있다").toBeGreaterThan(0);
    return [...src.slice(시작, 끝).matchAll(/"([^"]+)"/g)].map((m) => m[1]);
  })();

  it("배너 줄을 실제로 찾았다 — 이 시험이 헛돌지 않는다", () => {
    expect(배너, "배너 문구를 못 찾았다(문구가 바뀌었나?)").toContain("근거 약함");
  });

  it("★ 평가 게이트가 정직 표현으로 인정하는 말이 들어 있다", () => {
    expect(배너, "게이트는 없|찾지 못|확인되지 중 하나를 본다").toMatch(/없|찾지 못|확인되지/);
  });

  it("★ 서랍 점검이 실패로 세는 말은 들어 있지 않다", () => {
    const 걸린것 = 실패딱지.filter((m) => 배너.includes(m));
    expect(걸린것, `배너에 폴백 문구가 섞였다 — 좋은 답에 실패 딱지가 붙는다: ${걸린것.join(", ")}`)
      .toEqual([]);
  });
});

// 잡는 규칙과 **걷어내는 규칙이 같은가** — 다르면 본문까지 버려진다(2026-08-05 검토 지적).
describe("복창을 걷어내고 본문은 살리는가", () => {
  it("규칙 한 줄이 뒤에 붙어도 본문은 살아남는다", () => {
    const 답 = [
      "미조치 취약점은 총 152건입니다.",
      "그중 KEV 등재는 3건이라 먼저 처리해야 합니다.",
      "또한, 자신의 이름이나 어떤 사람이 작성했는지 나타내는 것은 금지입니다.",
    ].join("\n");
    const 살린것 = dropEchoSentences(답);
    expect(살린것, "본문까지 버렸다 — 담당자는 아무것도 못 받는다").toBeTruthy();
    expect(살린것).toContain("152건");
    expect(살린것).not.toContain("금지입니다");
  });
});
