      "익명 신고 제도에서는 누가 작성했는지 나타내지 않습니다.",
      "감사 로그에서 누가 작성했는지 지우는 것은 금지입니다.",
      "제보자는 자신의 이름을 밝히지 않아도 됩니다.",
      // 낱말 끝 음절 「제」에 걸리던 것들
      "통제 이름을 임의로 바꾸는 것은 금지입니다.",
      "게시판 실명제 작성자 정보는 드러내지 않습니다.",
      "보고서에 담당자 이름을 드러내는 것은 사내 규정상 금지입니다. 직책만 적으세요.",
      "개인정보보호법에 따라 제보자 이름을 공개하는 것은 금지입니다.",
      "저는 방화벽 정책을 확인했습니다. 인바운드 22번이 열려 있습니다.",
