// ★ **덮지 못하는 자리를 글자로 못박는다** (2026-09-05 검토관 적발 · 고치지 않기로 한 것)
//   복합 지시(오케스트레이션) 답은 단계마다 머리표를 달아 잇는다:
//     `【1. 스캔】 …\n\n【2. 우선순위 분석】 ⚠배너…`
//   배너가 **본문 중간**이라 판정기가 못 읽고 표식이 null이 된다. 아래는 그 사실을 「지금은
//   이렇다」로 고정한 시험이지 「이게 옳다」는 뜻이 아니다 — 사유는 noevidence.ts 머리말에 있다.
//   ⚠ **머리표를 벗겨 판정하도록** 고치면 이 시험이 빨개진다. 그때 반드시 먼저 읽을 것:
//     표식이 붙으면 화면은 **답 전체**를 옅게 하는데, 같은 답의 1단계 출력은
//     "3개 자산 스캔 완료 — 발견 0건"처럼 **진짜 세어 온 숫자**다. 그것을 「모델 추정치」로
//     회색 처리하면 없던 거짓말이 새로 생긴다. 제대로 닫으려면 표식에 **범위**가 실려야 한다.
describe("★ 알려진 공백 — 복합 지시 답의 배너는 본문 중간이라 못 읽는다", () => {
  const 복합답 = `【1. 스캔】 3개 자산 스캔 완료 — 발견 0건 (web01, web02, db01)\n\n【2. 우선순위 분석】 ${자료요청배너}\n\n일반적으로 만족도는 75점 수준입니다.`;

  it("지금은 표식이 안 붙는다(=화면도 아무것도 안 옅게 한다 — 종전 동작)", () => {
    expect(근거없음종류판정(복합답), "복합 답에 표식이 붙기 시작했다 — 위 주석을 읽고 판단할 것").toBeNull();
  });

  it("dispatcher가 단계 머리표로 잇는다는 사실 자체는 지킨다 — 꼴이 바뀌면 이 공백도 다시 본다", () => {
    expect(disp소스, "단계 머리표 꼴이 바뀌었다").toMatch(/【\$\{i \+ 1\}\. \$\{r\.label\}】/);
  });
});

