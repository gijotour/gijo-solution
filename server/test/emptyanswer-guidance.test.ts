// 「데이터 0건」 답이 **다음 행동을 말하는가** — 소스 감시(2026-08-12).
//
// ■ 왜 소스를 보나
//   운영 DB에는 데이터가 있어서 빈 상태를 실측할 수 없다(자산 58·취약점 4,890건).
//   고객의 **첫날**이 바로 그 빈 상태인데, 우리는 그 화면을 한 번도 못 본다.
//   그래서 문구를 소스에서 본다.
//
// ■ 무엇이 문제였나
//   `handlers.ts`에 이미 이렇게 적혀 있었다: 「⚠ 0건일 때 "없습니다"로 끝내면
//   "그래서 뭘 하지"가 남는다」. 그런데 지켜진 곳과 안 지켜진 곳이 섞여 있었다 —
//   전수로 세어 보니 **여섯 자리**가 그냥 "없습니다."로 끝났다.
//   담당자는 그걸 **「우리 환경엔 없구나」**로 읽는다. 사실은 **아직 안 넣은 것**이다.
//   (2026-08-12: max가 「읽는 데이터가 회사 것이면」 기준으로 24개 도구를 짚어 준 데서 시작했다.)
//
// ■ ⚠ 원칙을 주석으로만 적어 두면 또 어긋난다 — 그래서 시험으로 못박는다.
//   새 도구를 만들 때 이 시험이 빨개지면, 문구에 **다음 행동**을 한 줄 붙이면 된다.
import { describe, it, expect } from "vitest";
import fs from "node:fs";
import path from "node:path";

const 소스 = fs.readFileSync(path.join(__dirname, "../src/engine/agenttools/handlers.ts"), "utf8");

// 「길이가 0이면 곧바로 문자열을 돌려준다」 꼴을 찾는다.
const 빈답 = [...소스.matchAll(/\.length === 0\)\s*return\s+(?:assetId \? [^:]+: )?"([^"]{6,200})"/g)].map((m) => m[1]);

// 다음 행동을 말하는 표지. 하나라도 있으면 「그래서 뭘 하지」가 남지 않는다.
const 안내표지 = /아직|하세요|하시면|넣으면|올리면|추가하면|불러오면|업로드|등록하|▸|뜻입니다|뜻이 아닙니다/;

describe("★ 0건 답은 「없다」가 아니라 「아직 안 넣었다」를 말한다", () => {
  it("빈 결과 문구를 실제로 찾아냈다(감시가 헛돌지 않는지)", () => {
    // 감시가 0개를 훑고 「전부 통과」라고 말하는 것이 가장 나쁘다.
    expect(빈답.length, "빈 결과 문구를 하나도 못 찾았다 — 정규식이 소스와 어긋났다").toBeGreaterThanOrEqual(5);
  });

  for (const 문구 of 빈답) {
    it(`다음 행동을 말한다: "${문구.slice(0, 30)}…"`, () => {
      expect(안내표지.test(문구), `「그래서 뭘 하지」가 남는 문구다 — 다음 행동을 한 줄 붙일 것: "${문구}"`).toBe(true);
    });
  }
});

