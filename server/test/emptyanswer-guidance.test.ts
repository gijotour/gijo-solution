// ★ 정직 문구가 **우리 점검 도구의 실패 문구**와 겹치지 않는가 (2026-08-13 소스 감시)
//
// ■ 무엇이 있었나
//   제품이 정직하게 「근거가 없다」고 말하는 자리가 둘이다:
//     · actioncheck.ts — 행동 대조의 「판단 불가」(계획서 전-2의 NA 계약)
//     · llm.ts        — 「⚠ 근거 약함」 배너
//   그런데 서랍 점검(tools/drawer-audit.mjs)은 **폴백 문구 목록(FAIL_MARKS)** 으로 나쁜 답을
//   가려낸다. 그 목록에 「찾지 못했습니다」가 있다.
//   → 제품이 **옳게** 답한 「판단 불가 — … 근거를 찾지 못했습니다」에 **실패 딱지**가 붙었다.
//
// ■ 왜 시험으로 못박나
//   llm.ts는 이 함정을 이미 겪고 문구를 골랐고 그 이유를 주석에 길게 적어 두었다.
//   그런데 actioncheck.ts는 그대로였다 — **같은 함정을 한 곳에서만 피한 것**이다.
//   주석은 옆 파일까지 지켜 주지 못한다. 「같은 것을 여러 곳에 적으면 어긋난다」의 한 판이다.
//
// ■ ⚠ 지금 안 터진다고 안전한 게 아니다
//   운영에는 규정 문서가 있어 이 갈래가 잘 안 난다. 그러나 **신규 고객사 첫 설치는 규정 0건**이라
//   모든 행동 대조가 「판단 불가」가 되고, 품질 점검이 **전부 빨간불로 시작**한다.
//   이 파일의 다른 시험과 같은 관심사다 — 우리가 못 보는 「고객의 첫날」.
//
// ■ 단일 출처
//   FAIL_MARKS를 여기 베껴 적지 않는다. drawer-audit.mjs에서 **읽어서** 대조한다 —
//   베껴 적으면 목록이 늘 때 이 시험만 옛 목록을 보고 헛통과한다.
const 점검도구 = fs.readFileSync(path.join(__dirname, "../../tools/drawer-audit.mjs"), "utf8");
const FAIL_MARKS = (() => {
  const m = 점검도구.match(/const FAIL_MARKS = \[([\s\S]*?)\];/);
  return m ? [...m[1].matchAll(/"([^"]+)"/g)].map((x) => x[1]) : [];
})();

// 사람에게 나가는 **정직 문구**만 본다. 주석·변수명은 대상이 아니다.
const 정직문구: { 자리: string; 글: string }[] = [];
{
  const ac = fs.readFileSync(path.join(__dirname, "../src/engine/actioncheck.ts"), "utf8");
  for (const m of ac.matchAll(/"(판단 불가[^"]{0,200})"/g)) 정직문구.push({ 자리: "actioncheck 판단불가", 글: m[1] });
  const llm = fs.readFileSync(path.join(__dirname, "../src/engine/llm.ts"), "utf8");
  for (const m of llm.matchAll(/`([^`]{0,80}근거 약함[^`]{0,200})`/g)) 정직문구.push({ 자리: "llm 근거약함 배너", 글: m[1] });
}

// ★ 2026-08-13 — **같은 함정을 세 번 겪었다.** 문구를 하나씩 잡는 것으로는 안 끝난다.
//   llm.ts(근거 약함) → actioncheck.ts(판단 불가) → lawinfo.ts(법령 0건·조문 없음).
//   셋 다 「제품이 정직하게 없다고 말하는 자리」인데, 각자 따로 문구를 골랐고 두 곳이 함정을 밟았다.
//   → **파일 전체**를 본다: 사람에게 나가는 문자열에 실패 문구가 있으면 잡는다.
//   ⚠ 주석은 뺀다 — 이 규칙을 설명하는 주석이 그 말을 인용하기 때문이다(오늘 두 번 겪었다).
//   ⚠ 새 파일을 여기 더할 때는 「사람에게 나가는 안내를 내는 파일」인지 보고 더한다.
//   ★ 2026-08-14 handlers.ts 편입 — **네 번째 재발**(llm→actioncheck→lawinfo→handlers)을 계기로
//     23곳 전수 교정(데이터-없음 17·입력값 3·능력경계 2·빈상태 2 → 「검색되지 않았습니다」 계열).
//     도구 출력은 composeFinal 폴백(「그대로 보여 드립니다」)으로 원문이 사람에게 직접 간다.
const 정직파일 = ["actioncheck.ts", "llm.ts", "lawinfo.ts", "agenttools/handlers.ts"];
const 코드만 = (src: string) =>
  src
    .split("\n")
    .filter((l) => !/^\s*[*/]/.test(l))
    .map((l) => l.replace(/(^|[^:])\/\/.*$/, "$1"))
    .join("\n");

describe("★ 제품의 정직한 답을 우리 점검 도구가 벌주지 않는다 (2026-08-13)", () => {
  it("대조할 것을 실제로 찾아냈다(감시가 헛돌지 않는지)", () => {
    expect(FAIL_MARKS.length, "drawer-audit에서 FAIL_MARKS를 못 읽었다 — 목록 꼴이 바뀌었다").toBeGreaterThanOrEqual(10);
    expect(정직문구.length, "정직 문구를 하나도 못 찾았다 — 정규식이 소스와 어긋났다").toBeGreaterThanOrEqual(2);
  });

  for (const { 자리, 글 } of 정직문구) {
    it(`실패 문구를 안 쓴다: ${자리}`, () => {
      const 겹침 = FAIL_MARKS.filter((m) => 글.includes(m));
      expect(
        겹침,
        `이 문구가 서랍 점검의 실패 목록과 겹쳐 **좋은 답에 실패 딱지**가 붙는다.\n` +
          `  자리: ${자리}\n  문구: "${글}"\n  겹친 말: ${겹침.join(" · ")}\n` +
          `  → 겹치지 않는 말로 바꿀 것(예: 「찾지 못했습니다」 → 「검색되지 않았습니다」).`,
      ).toEqual([]);
    });
  }
});

describe("★ 정직 문구 파일 전체 대조 — 문구를 하나씩 잡다가 세 번 밟았다 (2026-08-13)", () => {
  // ⚠ **예외에는 이유를 강제한다**(이 저장소의 소스 감시 원칙).
  //   「진짜 실패」의 오류문은 실패 문구를 써도 옳다 — 임베딩 서버가 죽었으면 실패가 맞고,
  //   점검 도구가 그걸 실패로 세는 것이 이 목록의 존재 이유다. 금지 대상은
  //   **정직한 「없다」 답변**(제품이 옳게 답했는데 실패로 찍히는 것)뿐이다.
  //   예외로 두려면 그 줄 **위에** `FAIL_MARKS-예외:` 주석으로 이유를 적는다 — 그 표시가 있는
  //   지점부터 다음 빈 줄까지 건너뛴다. 이유 없는 예외는 없다.
  const 예외제외 = (src: string): string => {
    const lines = src.split("\n");
    const out: string[] = [];
    let 건너뛰는중 = false;
    for (const l of lines) {
      if (/FAIL_MARKS-예외:/.test(l)) { 건너뛰는중 = true; continue; }
      if (건너뛰는중 && l.trim() === "") 건너뛰는중 = false;
      if (!건너뛰는중) out.push(l);
    }
    return out.join("\n");
  };

  for (const 파일 of 정직파일) {
    it(`${파일} 의 출력 문자열에 실패 문구가 없다`, () => {
      const src = fs.readFileSync(path.join(__dirname, "../src/engine/", 파일), "utf8");
      const 몸 = 코드만(예외제외(src));
      const 걸린것 = FAIL_MARKS.filter((m) => 몸.includes(m));
      expect(
        걸린것,
        `${파일} 이 서랍 점검의 실패 문구를 쓴다 — 제품의 정직한 답에 실패 딱지가 붙는다.\n` +
          `  겹친 말: ${걸린것.join(" · ")}\n` +
          `  → 정직한 「없다」 답변이면 겹치지 않는 말로(「찾지 못했습니다」→「검색되지 않았습니다」).\n` +
          `  → 진짜 실패의 오류문이면 그 줄 위에 \`FAIL_MARKS-예외: <이유>\` 주석을 붙일 것.`,
      ).toEqual([]);
    });
  }
});
