/** 판정불가 조각의 요구 칸 — **진짜 모름**은 요구문장.판정불가, **알아본 판정불가**는 그 조건 문장.
 *  조건이 둘(NC+ND)이면 둘 다 적는다. 알아봤는데 조건 표시가 없으면 LicenseRef(개별 라이선스)다. */
function 판정불가요구(p: 조각판정, 강제조건: boolean): string {
  if (!p.알아봄) return 요구문장.판정불가;
  const 말: string[] = [];
  if (p.상용불가) 말.push(강제조건 ? 조건문장.NC.강제 : 조건문장.NC.선택);
  if (p.변경불가) 말.push(강제조건 ? 조건문장.ND.강제 : 조건문장.ND.선택);
  if (!말.length) 말.push(조건문장.개별);
  return 말.join(" ");
}

