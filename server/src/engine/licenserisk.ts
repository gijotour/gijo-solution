/**
 * 라이선스 표기 하나를 판정한다. **식(expression)도 받는다.**
 *
 * @example 등급판정("AGPL-3.0-only") → 서비스도공개
 * @example 등급판정("Apache-2.0 AND AGPL-3.0-only") → 서비스도공개 (AND는 둘 다 지켜야 하니 무거운 쪽)
 * @example 등급판정("AGPL-3.0-only OR Artifex-Commercial") → 가벼운 쪽 (고를 수 있으니)
 * @example 등급판정("NOASSERTION") → 판정불가
 */
export function 등급판정(원문표기: string | null | undefined): 라이선스판정 {
  const 원문 = String(원문표기 ?? "").trim();
  if (라이선스모름(원문)) {
    return { 등급: "판정불가", 받게되는요구: 요구문장.판정불가, spdxId: "", 알아봄: false, 원문,
      근거: "라이선스가 적혀 있지 않거나 「확인 안 됨(NOASSERTION)」입니다.", 확인필요: true };
  }

  // ⚠ **길다고 자르고 판정하면 안 된다.** 실측 571자짜리가 있고, 뒤에 붙은 `AND AGPL-3.0-only`가
  //   잘려 나가면 판정이 조용히 뒤집힌다(packagescan.ts의 60자 컷은 **표시 전용**이다).
  //   여기서는 원문 그대로 본다.

  // WITH(예외 조항)는 의무를 **줄인다** — 예외가 붙었으면 사람이 봐야 한다.
  const 예외있음 = /\sWITH\s/i.test(원문);

  // OR는 **고를 수 있다**(이중 라이선스) → 가벼운 쪽. AND는 **둘 다** → 무거운 쪽.
  //   ⚠ 괄호 중첩까지는 안 푼다. 섞여 있으면 안전하게 **무거운 쪽 + 확인필요**로 둔다.
  const OR있음 = /\sOR\s/i.test(원문);
  // ⚠ **쉼표·슬래시·세미콜론도 갈라야 한다**(2026-08-22 게시 전 검토관 [높음]).
  //   규칙이 접두 매칭이라(`/^BSD-[0-9]/`) 안 가르면 **첫 토큰에서 걸리고 나머지가 통째로 버려진다.**
  //   실증: 우리가 지금 출하하는 pypdfium2의 실제 표기가
  //   `BSD-3-Clause, Apache-2.0, dependency licenses`인데 「고지만·확인 불필요」로 초록이었다.
  //   더 나쁜 갈래: `MIT, AGPL-3.0`이 **「고지만」으로 통과**한다 — 관문이 고지만은 안 막으니
  //   카피레프트가 exit 0으로 나간다. 이 파일이 위에서 「뒤에 붙은 AGPL이 잘리면 판정이 조용히
  //   뒤집힌다」고 못 박은 그 사고가, 자르기가 아니라 **접두 매칭**으로 재현된 것이다.
  //   쉼표로 이은 목록은 「이것들이 함께 적용된다」는 뜻이라 AND로 본다(무거운 쪽).
  const 구분자 = /\s+(?:AND|OR)\s+|\s*[,;/]\s*/i;
  const AND있음 = /\sAND\s/i.test(원문) || /[,;/]/.test(원문);
  const 조각들 = 원문.split(구분자).map((s) => s.replace(/\s+WITH\s+.*$/i, "").trim()).filter(Boolean);
  const 판정들 = 조각들.map(한개판정);
  if (!판정들.length) {
    return { 등급: "판정불가", 받게되는요구: 요구문장.판정불가, spdxId: "", 알아봄: false, 원문,
      근거: "라이선스 표기를 읽지 못했습니다.", 확인필요: true };
  }

  // ★★ **「알아보지 못한」의 셈을 여기서 바로잡는다**(2026-08-22 검토관 [중]).
  //   NC·ND·LicenseRef는 등급이 「판정불가」지만 **무엇인지는 안다.** 그런데 아래 두 갈래가
  //   판정불가를 전부 「모르는 것」으로 세어 왔다. 실측한 거짓 출력:
  //     `MIT AND CC-BY-NC-4.0` → 등급 🟢**고지만** + 근거 「그중 1개는 **알아보지 못한 표기**」
  //   알아봤다. 그것도 **가장 중요한 조각**을 알아봤는데 「못 읽었다」고 말한 것이다.
  //   게다가 게시 관문은 원문에 상용사용금지()를 걸어 **막는데** 화면은 초록을 보여
  //   같은 입력에 두 창구가 다른 답을 냈다. SPDX 반입은 선언≠확정이면 AND로 이어 붙이므로
  //   (sbomimport.ts) 이 조합은 드문 것이 아니라 **흔한 것**이다.
  const 진짜모르는수 = 판정들.filter((p) => !p.알아봄).length;
  const 상용불가조각 = 판정들.filter((p) => p.상용불가);
  const 변경불가조각 = 판정들.filter((p) => p.변경불가);

  // ⚠ 조각판정 통째로 든다 — 알아봄·상용불가·변경불가가 아래 요구 칸 조립에 필요하다(등급·근거만 들면 그 셈을 잃는다).
  let 고른것: 조각판정;
  let 셈근거 = "";
  if (OR있음 && !AND있음) {
    // 고를 수 있으니 **가장 가벼운 것**. 단 판정불가는 「가볍다」가 아니므로 후보에서 뺀다.
    const 아는것 = 판정들.filter((p) => p.등급 !== "판정불가");
    const 모르는수 = 진짜모르는수;
    고른것 = (아는것.length ? 아는것 : 판정들).slice().sort((a, b) => 등급순위[a.등급] - 등급순위[b.등급])[0];
    셈근거 = " (여러 라이선스 중 **고를 수 있어** 가벼운 쪽으로 봤습니다 — 이중 라이선스일 수 있습니다.)";
    // ⚠ **AND 갈래에만 달아 두었던 경고를 여기에도 단다**(2026-08-22 검토관 [중] — 반쪽 수리였다).
    //   모르는 조각을 조용히 버리고 「가벼운 쪽으로 봤다」고만 하면 담당자는
    //   「이보다 무거운 건 없다」로 읽는다. 실제로는 못 읽은 조각이 남아 있다.
    if (모르는수 && 아는것.length) {
      셈근거 += ` ⚠ 그중 ${모르는수}개는 알아보지 못한 표기라 **더 무거울 수도 있습니다** — 원문을 확인하세요.`;
      고른것 = { ...고른것, 확인필요: true };
    }
  } else {
    // AND이거나 단일 — **가장 무거운 것**.
    //
    // ⚠ 단, **아는 것 중에서** 고른다(2026-08-22, 이 파일의 시험이 잡은 설계 결함).
    //   실제 표기는 `LGPL-2.1-or-later AND SunPro AND … AND AGPL-3.0-only`처럼 정본이 아닌
    //   조각이 섞여 온다. 「판정불가」를 가장 무거운 것으로 두면 그 한 조각이
    //   **「여기 AGPL이 있다」는 사실을 통째로 삼킨다** — 담당자가 가장 알아야 할 것이 사라진다.
    //   그래서 아는 것 중 무거운 쪽을 등급으로 세우고, 모르는 조각이 있다는 것은
    //   **확인 필요 + 근거 문장**으로 함께 말한다. 둘 다 말하는 것이 정직하다.
    const 아는것 = 판정들.filter((p) => p.등급 !== "판정불가");
    const 모르는수 = 진짜모르는수;
    고른것 = (아는것.length ? 아는것 : 판정들).slice().sort((a, b) => 등급순위[b.등급] - 등급순위[a.등급])[0];
    if (AND있음) 셈근거 = " (여러 라이선스를 **함께 지켜야 해서** 가장 무거운 쪽으로 봤습니다.)";
    if (모르는수 && 아는것.length) {
      셈근거 += ` ⚠ 그중 ${모르는수}개는 알아보지 못한 표기라 **더 무거울 수도 있습니다** — 원문을 확인하세요.`;
      고른것 = { ...고른것, 확인필요: true };
    }
  }

  // ★ **상용 라이선스로 풀 수 있는 건지 말해 준다**(2026-08-22 검토관 [높음]).
  //   ⚠ ⓘ 패널과 도구 설명이 「소스 공개 요구·**상용 라이선스 구매 요구**」라고 약속해 놓고
  //     코드에는 그 말이 한 번도 없었다. 하필 이 기능의 계기인 PyMuPDF가 정확히 그 경우다
  //     (「AGPL 또는 Artifex 상용」). 담당자가 **살 수 있는 부품을 못 쓰는 부품으로** 판단하거나,
  //     반대로 표시가 없으니 상용 선택지가 없다고 결론 내린다. 안내한 말은 실제로 돼야 한다.
  //   판정은 보수적으로 — **이중 라이선스로 보이는 신호가 있을 때만** 말한다(지어내지 않는다).
  const 상용여지 =
    /commercial|proprietary|상용|dual\s*licen[cs]e|이중\s*라이선스|artifex|enterprise\s*licen[cs]e/i.test(원문) ||
    (OR있음 && 판정들.some((p) => p.등급 === "판정불가"));

  // ★ **NC·ND는 어느 등급이 뽑혔든 반드시 말한다.** 등급 5단계는 「소스를 어디까지 공개하나」를
  //   재는 자인데 이 둘은 그 축에 없다 — 등급만 보면 🟢으로 보이고 조건은 사라진다.
  //   ⚠ AND(함께 지켜야 함)일 때만 강제 조건이다. OR(고를 수 있음)이면 다른 쪽을 고르면 되므로
  //     「그런 선택지도 있다」로만 말한다 — 안 그러면 이중 라이선스에서 헛경보가 난다.
  //   ⚠ 말하는 자리는 **요구 칸 한 곳**이다(2026-09-03 검토관 [중]). 전에는 근거 칸에도 같은 말을 덧붙여
  //     단일 NC(고른것 자체가 NC 규칙)에서 규칙 근거 + NC말이 겹쳐 같은 조건을 세 번 읽게 했다.
  //     근거 칸은 「왜 이 등급인가」 — 규칙의 근거와 셈(AND·OR·WITH)만 둔다.
  //   ⚠ 고른것 자체가 그 조건(단일 NC·ND)이면 요구 칸의 기본 문장이 이미 그 조건이라 덧붙이지 않는다.
  const 강제조건 = !(OR있음 && !AND있음);
  const NC말 = 상용불가조각.length && !고른것.상용불가
    ? (강제조건
        ? " ★ **비영리(NC) 조건이 함께 걸려 있습니다 — 상용 제품에는 쓸 수 없습니다.** 소스를 공개해도 풀리지 않습니다."
        : ` ${조건문장.NC.선택}`)
    : "";
  const ND말 = 변경불가조각.length && !고른것.변경불가
    ? (강제조건
        ? " ★ **변경금지(ND) 조건이 걸려 있습니다 — 고쳐서 내보낼 수 없습니다.** 원본 그대로면 배포는 됩니다(형식 변환도 「고침」이 될 수 있습니다)."
        : ` ${조건문장.ND.선택}`)
    : "";
  // 요구 칸의 기본 문장 — 등급이 있으면 등급 문장, 판정불가면 「진짜 모름」과 「알아본 판정불가」를 가른다.
  const 기본요구 = 고른것.등급 === "판정불가" ? 판정불가요구(고른것, 강제조건) : 요구문장[고른것.등급];

  const 확인 = 고른것.확인필요 || 예외있음 || (OR있음 && AND있음) ||
    (강제조건 && (상용불가조각.length > 0 || 변경불가조각.length > 0));
  const 예외말 = 예외있음 ? " ⚠ 예외 조항(WITH)이 붙어 있어 의무가 줄 수 있습니다 — 원문을 확인하세요." : "";
  const 섞임말 = (OR있음 && AND있음) ? " ⚠ AND와 OR가 섞여 있어 사람이 확인해야 합니다." : "";

  // 무거운 등급이면서 상용 여지가 보이면 **선택지를 함께** 말한다.
  //   가벼운 등급에는 안 붙인다 — 「고지만 하면 되는데 돈을 내라」로 읽히면 안 된다.
  const 상용말 =
    상용여지 && 등급순위[고른것.등급] >= 등급순위["전체소스공개"]
      ? " 다만 이 부품은 **상용 라이선스를 구매하면** 그 의무에서 벗어날 수 있는 이중 라이선스로 보입니다 — 공급사에 확인하세요."
      : "";

  return {
    등급: 고른것.등급,
    받게되는요구: 기본요구 + 상용말 + NC말 + ND말,
    // ⚠ 조각이 하나라도 **정본 식별자일 때만** spdxId로 쓴다 — 안 그러면 원문 문장이
    //   식별자 칸에 그대로 들어간다(`dependency licenses` 같은 것이 SPDX id로 보인다).
    spdxId: (조각들.length === 1 && 규칙.some((r) => r.re.test(조각들[0]))) ? 조각들[0] : "",
    원문,
    // 근거 = 규칙의 근거 + 셈. 조건(NC·ND)은 요구 칸이 말한다 — 여기 덧붙이지 않는다(위 주석).
    근거: 고른것.근거 + 셈근거 + 예외말 + 섞임말,
    확인필요: 확인,
    알아봄: 진짜모르는수 === 0,
  };
}

/** **상용 제품에 실을 수 없는 조건인가** — 비영리(NC)·변경금지(ND) 계열.
 *
 *  ⚠ 등급 5단계와 **다른 축**이다. 등급은 「이렇게 하면 쓸 수 있다」를 말하는데
 *    NC는 「상용으로는 못 쓴다」라 조건을 지켜도 안 풀린다. 그래서 따로 묻는다.
 *  ★ 판정을 두 벌 두지 않으려고 **여기서만** 판단한다 — 관문(tools/gen-sbom-self.mjs)이
 *    이 함수를 불러 쓴다. 관문에 정규식을 복사하면 반드시 하나가 낡는다.
 */
export function 상용사용금지(원문표기: string | null | undefined): boolean {
  const 원문 = String(원문표기 ?? "").trim();
  if (!원문) return false;
  // ⚠ **OR(고를 수 있음)이면 막지 않는다** — 「AGPL 또는 상용」처럼 NC가 **선택지 중 하나**로
  //   들어오면 다른 쪽을 고르면 된다. 여기서 막으면 정당한 게시가 헛되이 멈춘다.
  //   쉼표·슬래시로 이은 목록은 「함께 적용」이라 AND로 본다(등급판정과 같은 잣대).
  const OR있음 = /\sOR\s/i.test(원문);
  const AND있음 = /\sAND\s/i.test(원문) || /[,;/]/.test(원문);
  if (OR있음 && !AND있음) return false;
  return 상용금지패턴.test(원문);
}

/** **고쳐서 내보낼 수 없는 조건인가** — 변경금지(ND).
 *  ⚠ 상용 배포 자체는 막지 않는다. 우리가 PDF를 마크다운으로 바꾼 것이 여기 걸렸다 —
 *    **형식 변환도 「고침」이 될 수 있다.** 그래서 문서를 다룰 때 특히 중요하다. */
export function 변경금지조건(원문표기: string | null | undefined): boolean {
  const 원문 = String(원문표기 ?? "").trim();
  if (!원문) return false;
  const OR있음 = /\sOR\s/i.test(원문);
  const AND있음 = /\sAND\s/i.test(원문) || /[,;/]/.test(원문);
  if (OR있음 && !AND있음) return false;
  return 변경금지패턴.test(원문);
}

/** 목록 전체를 세어 요약한다 — 화면 KPI·카드·리포트가 **이 한 곳**의 숫자를 쓴다. */
export function 등급요약(판정들: 라이선스판정[]): {
  전체: number; 등급별: Record<라이선스등급, number>; 확인필요: number; 무거운것: 라이선스판정[];
  /** 판정불가 중 **알아본** 것(NC·ND·LicenseRef) — 「알 수 없는 부품」 셈에서 빼야 거짓이 안 된다. */
  알아본판정불가: number;
} {
  const 등급별 = { 의무없음: 0, 고지만: 0, 고친파일공개: 0, 전체소스공개: 0, 서비스도공개: 0, 판정불가: 0 } as Record<라이선스등급, number>;
  for (const p of 판정들) 등급별[p.등급]++;
  return {
    전체: 판정들.length,
    등급별,
    확인필요: 판정들.filter((p) => p.확인필요).length,
    알아본판정불가: 판정들.filter((p) => p.등급 === "판정불가" && p.알아봄).length,
    // 「지금 당장 봐야 하는 것」 — 서비스도공개·전체소스공개·판정불가.
    무거운것: 판정들.filter((p) => 등급순위[p.등급] >= 등급순위["전체소스공개"]),
  };
}

