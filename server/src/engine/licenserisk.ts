/** **대표 목록이 덮지 못한 규칙 갈래** — 빈 배열이어야 한다(licensedoc.test가 지킨다).
 *
 *  ■ 왜 (2026-09-03 검토관 [낮음]) — 위 「갈래를 늘리면 여기도 늘린다」는 주석뿐이었고 기계 감시가 없었다.
 *    규칙에 갈래를 하나 더하고 대표를 안 더하면 표에서 그 갈래가 조용히 빠진다 — 문서·팀원이 그 라이선스를 못 배운다.
 *  ⚠ 한개판정과 같은 「첫 규칙에서 멈춤」 셈으로 센다 — 정규식이 걸리기만 하는 것으로 세면
 *    `CC-BY-NC-ND`가 ND 규칙까지 덮은 것으로 잘못 세인다(실제 판정은 NC 규칙에서 돌아온다). */
export function 등급표덮음빠짐(): string[] {
  const 덮인규칙 = new Set<RegExp>();
  for (const id of 등급표대표.flat()) {
    const 첫 = 규칙.find((r) => r.re.test(id));
    if (첫) 덮인규칙.add(첫.re);
  }
  return 규칙.filter((r) => !덮인규칙.has(r.re)).map((r) => r.re.source);
}

/** 마크다운 표 칸에 넣을 수 있게 다듬는다 — 세로줄은 표를 깨고, 개행은 줄을 깬다. */
function 표칸(s: string): string {
  return s.replace(/\|/g, "｜").replace(/\r?\n/g, " ").trim();
}

/**
 * 지식 문서에 싣는 **등급표(마크다운)** — 등급 · 대표 라이선스 · 실제로 받게 되는 요구 · 근거.
 *
 * 문구는 전부 등급판정()이 준 것이다(요구 문장·근거를 여기서 다시 짓지 않는다). 이 함수가 보태는 것은
 * 표의 뼈대와 표식(이모지·굵게), 그리고 확인필요를 드러내는 꼬리표뿐이다.
 * ⚠ 결과는 결정적이어야 한다(같은 규칙 → 같은 표) — 시험이 문서와 글자 단위로 대조한다.
 */
export function 등급표문서(): string {
  const 줄: string[] = [
    "| 등급 | 대표 라이선스 | 실제로 받게 되는 요구 | 근거 |",
    "|---|---|---|---|",
  ];
  for (const 묶음 of 등급표대표) {
    const 판정들 = 묶음.map((id) => 등급판정(id));
    const 첫 = 판정들[0];
    // 묶음은 판정이 같을 때만 한 줄이다 — 규칙이 갈렸는데 뭉쳐 적으면 문서가 거짓이 된다.
    for (let i = 1; i < 판정들.length; i++) {
      const p = 판정들[i];
      if (p.등급 !== 첫.등급 || p.받게되는요구 !== 첫.받게되는요구 || p.근거 !== 첫.근거 || p.확인필요 !== 첫.확인필요) {
        throw new Error(`등급표 묶음이 갈렸습니다: 「${묶음[0]}」과 「${묶음[i]}」의 판정이 다릅니다 — 묶음을 나누세요`);
      }
    }
    // ⛔ — 등급이 아니라 조건(NC·ND). 등급판정은 판정불가로 두고 근거로 말하므로 표식만 여기서 가른다.
    const 조건걸림 = 묶음.some((id) => 상용사용금지(id) || 변경금지조건(id));
    const 표식 = 조건걸림 ? "⛔" : 등급표식[첫.등급];
    // 확인필요를 표에서 드러낸다 — LGPL이 대표다(「링크 방식에 따라 달라집니다」). 그 밖의 확인필요는 이유를 안 지어낸다.
    const 꼬리 = 첫.확인필요 && 첫.등급 !== "판정불가"
      ? (/링크 방식/.test(첫.근거) ? " (링크 방식 확인)" : " (확인 필요)")
      : "";
    줄.push(`| ${표식} **${첫.등급}**${꼬리} | ${묶음.map(표칸).join(" · ")} | ${표칸(첫.받게되는요구)} | ${표칸(첫.근거)} |`);
  }
  return 줄.join("\n");
}
