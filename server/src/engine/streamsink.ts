//
// 답이 생성되는 대로 글자 토막을 화면으로 흘려보내는 요청별 통로다.
// AsyncLocalStorage를 쓰는 이유: 토막을 받을 곳은 라우트(SSE 응답)인데 토막이 나는 곳은
// llm.ts chat()이다 — 그 사이 dispatcher→agentloop→composeFinalAnswer 서명을 전부 바꿔
// 콜백을 실어 나르면 중간 계층 전체가 스트리밍을 알아야 한다. 요청별 컨텍스트에 싱크를
// 두면 chat()이 제 자리에서 꺼내 쓰고, 동시 요청은 각자 자기 싱크만 본다(섞임 없음).
//
// ⚠ 정직 규칙(시안에 명시):
//  · 흘린 글자는 「쓰는 중」 표시일 뿐 — 최종 답은 출구 관문(거짓 완료·내부키 치환·말투 감시)을
//    지난 done의 output이고, 화면은 반드시 그것으로 갈아 끼운다.
//  · 쓰기 지시는 흘리지 않는다 — 결재판 경로는 산문 생성이 없어 자연히 아무것도 흐르지 않는다.
//  · 스키마 강제 호출(JSON 결정 프롬프트)은 흘리지 않는다 — 담당자에게 보일 글이 아니다.
import { AsyncLocalStorage } from "node:async_hooks";

export interface 스트림싱크 {
  /** 새 산문 생성이 시작됨 — 화면은 흐르던 글자를 비운다(한 지시에 산문 호출이 여러 번일 수 있다). */
  시작(): void;
  /** 생성된 글자 토막. */
  토막(text: string): void;
}

export const 스트림자리 = new AsyncLocalStorage<스트림싱크>();
