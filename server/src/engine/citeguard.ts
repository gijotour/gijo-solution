/** 겹침 창 크기 — 이 값이 「20자」 잣대의 단일 출처다(사유 문자열도 이 상수로 짓는다). */
export const OVERLAP_CHARS = 20;

/** 겹침 창을 미는 폭. overlap20(tools/distill-precheck.mjs)과 **같은 4칸**이라야 답이 갈리지 않는다. */
export const 겹침걸음 = 4;

/**
 * 인용 토막을 **대조할 수 있는** 최소 길이 = 23자(= 창 20 + 걸음 4 − 1).
 *
 * ★ 왜 20이 아닌가(2026-09-05 검토관 실측): 창은 20자인데 걸음이 4칸이라 원천의 **4의 배수
 *   자리에서만** 창이 시작한다. 그래서 원문을 글자 하나 안 틀리고 옮긴 짧은 인용이 자리에 따라
 *   「겹침없음」으로 떨어졌다 — 무공백 20자 6/23(26%) · 21자 11/22(50%) · 22자 16/21(76%) ·
 *   **23자 20/20(100%)** · 24자 19/19(100%).
 *   23자부터는 [p, p+L−20] 구간에 4의 배수가 반드시 하나 있어 빠짐없이 잡힌다.
 * ⚠ 걸음을 1로 줄이는 쪽은 **일부러 안 골랐다** — 근거겹침은 overlap20(증류기)·관문 ⑧이 함께
 *   쓰는 잣대라, 여기서 걸음을 바꾸면 사다리 회전 1~4의 옛 판정과 값이 갈린다. 재는 자를
 *   흔드는 대신 **판정 하한을 올려** 대조 못 할 것을 안 건드리는 쪽이 안전하다.
 */
export const 대조하한 = OVERLAP_CHARS + 겹침걸음 - 1;

/**
 * 답이 근거 본문과 20자 이상 그대로 겹치는가 — 겹친 창을 돌려준다(없으면 null). 공백은 무시.
 * ⚠ 사본이 셋이다(여기 · tools/distill-precheck.mjs overlap20 · gates.mjs가 그것을 import).
 *   distillprecheck.test.ts:38이 두 함수가 **같은 답**을 내는지 대조한다 — 규칙을 고치면 함께 고친다.
 * ⚠ 걸음이 4칸이라 「20자를 그대로 옮겼는데 못 찾는」 자리가 있다 — 그래서 이 함수를 **판정**에
 *   쓸 때는 위 `대조하한`(23자)을 함께 걸어야 한다.
 */
export function 근거겹침(answer: string, sourceText: string): string | null {
  const a = String(answer ?? "").replace(/\s+/g, "");
  const s = String(sourceText ?? "").replace(/\s+/g, "");
  if (a.length < OVERLAP_CHARS || s.length < OVERLAP_CHARS) return null;
  for (let i = 0; i + OVERLAP_CHARS <= s.length; i += 겹침걸음) {
    const w = s.slice(i, i + OVERLAP_CHARS);
    if (a.includes(w)) return w;
  }
  return null;
}

/** 「원문:」 꼬리표 — gates.mjs 원문꼬리표와 **글자 그대로 같다**(짝 시험이 대조). */
export const 원문꼬리표 = /원문\s*[:：]/;
/** 제품 규약 꼬리표 「[n]에 따르면」 — gates.mjs 제품인용꼬리표와 **글자 그대로 같다**. */
export const 제품인용꼬리표 = /\[\d+\]\s*에\s*따르면/;

/** 따옴표 여는 글자 → 닫는 글자. gates.mjs 인용토막들의 네 가지에 『』·《》·굽은 홑따옴표를 더했다. */
const 따옴표쌍: Record<string, string> = {
  '"': '"', "“": "”", "「": "」", "『": "』",
  "《": "》", "'": "'", "‘": "’",
};
const 여는따옴표 = Object.keys(따옴표쌍).join("");

/**
 * **인용 주장**을 찾는 정규식 — 세 갈래를 한 번에 훑는다(자리 순서를 지키려고 하나로 합쳤다).
 *   ⓐ 번호 꼬리표: 「[n]에 따르면/에서는/에 의하면/에는/에서/의 내용은/ 문서에는」 (따옴표 없어도 주장이다)
 *   ⓑ 번호 + 곧바로 따옴표: 「자료 [1]: "…"」·「[1] "…"」
 *   ⓒ 표식 도입: 「원문:」·「출처:」·「사내 문서에 따르면,」 (**따옴표가 붙었을 때만** 뗀다)
 *
 * ★ 왜 넓혔나(2026-09-05 검토관 실측): 첫 판은 「원문:」과 「[n]에 따르면/에서는/에 의하면」 셋뿐이라
 *   「[1]의 내용은 "…"」·「출처: "…"」·「사내 문서에 따르면 "…"」 8꼴이 **조각 0건에서도 그대로**
 *   나갔고, 그때 계수기까지 0이라 감독 화면에서는 「지어낸 인용 없음」으로 읽혔다(조용한 고장).
 *   실물 표본에서도 관문 ⑨가 잡은 46건 중 **1건(사내 문서에 따르면, "…")**을 제품이 놓쳤다.
 * ⚠ 왜 이 이상 안 넓히나 — **실측이 막았다**: 표식 낱말과 따옴표 사이에 아무 말이나 10자까지
 *   허용하는 관문 방식(인용표식)을 그대로 쓰면, 실전 답 기록(.tmp-reports/ops-sim.json 152답)에서
 *   「…새로 들어온 **문서** 알려줘"라고 물으면…」 같은 **안내 문구 9건**이 인용으로 걸린다.
 *   그래서 표식 낱말 **바로 뒤에 도입 어구**(에 따르면·에는·:)가 붙은 꼴만 본다 — 실측 재측정 0건.
 * (아래 두 상수가 그 규칙이다 — 낱말표 먼저, 그다음 세 갈래.)
 */

/**
 * 표식 낱말 — gates.mjs 인용표식과 **같은 여섯 낱말**에, 우리 답이 실제로 붙여 쓰는 꾸밈말을
 * 함께 먹는다(「**사내** 문서에 따르면」·「**참고** 자료 [1]:」). 꾸밈말을 안 먹으면 뗀 자리에
 * 「사내」·「자료」만 덩그러니 남는다(실측).
 * ⚠ 꾸밈말과 낱말 사이는 **줄바꿈을 안 넘는 공백**만 허용한다(`[ \t]`). `\s*`로 뒀다가 짝 시험이
 *   잡았다: 앞 줄 끝의 줄바꿈부터 매치가 시작돼 **줄이 합쳐지고 앞 줄까지 손질을 먹었다.**
 */
const 표식낱말 = "(?:(?:사내|참고|관련|해당|위|아래)[ \\t]*)?(?:원문|인용|출처|근거|자료|문서)";

/** 위 ⓐⓑⓒ 세 갈래를 한 번에 훑는다 — 잡은 자리 순서를 지키려고 하나로 합쳤다. */
const 주장_RE = new RegExp(
  `(?:(?:${표식낱말}[ \\t]*)?\\[(\\d+)\\]\\s*(?:에\\s*따르면|에\\s*의하면|에서는|에\\s*나와|에\\s*적혀|의\\s*내용은|[ \\t]*문서에는|에는|에서))` +
    `|(?:(?:${표식낱말}[ \\t]*)?\\[(\\d+)\\][ \\t]*[:：]?[ \\t]*(?=[${여는따옴표}]))` +
    `|(?:${표식낱말}[ \\t]*(?:에[ \\t]*따르면|에[ \\t]*의하면|에서는|에는|[:：]))`,
  "g",
);

/** 꼬리표와 따옴표 사이에 낄 수 있는 말 — 줄바꿈·문장끝은 넘지 않는다(다른 문장의 따옴표를 안 삼키려고). */
const 사이말_RE = new RegExp(`^[^${여는따옴표}\\n.。!?]{0,40}`);
/** 「그냥 붙었다」고 볼 수 있는 짧은 이음새 — 이보다 길면 인용 토막 길이를 함께 요구한다. */
const 짧은이음새_RE = /^[\s,·:：]{0,12}$/;

export type 뗀사유종류 = "블록없음" | "범위밖" | "겹침없음" | "자기인용";

export interface 뗀인용 {
  kind: 뗀사유종류;
  /** 가리킨 번호 — 「원문:」 꼴이면 없다. */
  n?: number;
  /** 뗀 인용 토막(따옴표 안). 따옴표가 없던 참조면 빈 문자열. */
  quote: string;
  /** 사람이 읽는 한 줄 — llm:event(kind=cite)의 detail에 실린다. */
  reason: string;
}

export interface CiteGuardResult {
  text: string;
  removed: 뗀인용[];
  /**
   * **뗐어야 하는데 못 뗀 것** — 답이 통째로 인용이라 원답을 그대로 둔 자리(⑤).
   * 세지 않으면 「가드를 지난 깨끗한 답」과 구별이 안 된다(검토관 지적: 관측 공백).
   */
  보류: 뗀인용[];
}

/** 코드블록(```)의 [시작,끝) 구간 — 이 안은 손대지 않는다. */
function 코드구간(text: string): [number, number][] {
  const out: [number, number][] = [];
  const re = /```[\s\S]*?(?:```|$)/g;
  let m: RegExpExecArray | null;
  while ((m = re.exec(text)) !== null) out.push([m.index, m.index + m[0].length]);
  return out;
}

/**
 * 꼬리표 **뒤에 붙은 인용 토막**을 찾는다(없으면 null).
 *
 * ⚠ 세 가지를 실측으로 고쳤다(2026-09-05 검토관):
 *   · 사이에 말이 끼면(「[1]에 따르면 다음과 같이 규정합니다: "…"」) 첫 판은 **꼬리표만 떼고
 *     지어낸 인용문은 남겼다** — 출처만 사라지고 주장은 제품 단정으로 읽혀 더 나빠졌다.
 *     그래서 줄바꿈·문장끝을 안 넘는 40자까지는 이음새로 본다(길면 토막 길이를 함께 요구한다).
 *   · 인용 안에 따옴표가 또 있으면(「"관리자 계정은 "필수"로 …한다."」) 첫 판은 앞 토막만
 *     떼어 고아 따옴표를 남겼다 → 닫는 따옴표 **바로 뒤가 글자면** 다음 닫는 따옴표까지 잇는다.
 *   · 닫는 따옴표가 아예 없으면(모델이 토큰 한도에서 잘린 실물 3건) 끝까지가 인용이다.
 */
function 뒤따른인용(tail: string): { quote: string; 길이: number; 이음새: string } | null {
  const 이음새 = 사이말_RE.exec(tail)?.[0] ?? "";
  const 여는자리 = 이음새.length;
  const 여는 = tail[여는자리];
  if (!여는 || !(여는 in 따옴표쌍)) return null;
  const 닫는 = 따옴표쌍[여는];
  let 끝 = tail.indexOf(닫는, 여는자리 + 1);
  if (끝 < 0) return { quote: tail.slice(여는자리 + 1), 길이: tail.length, 이음새 }; // 잘린 인용
  for (let i = 0; i < 3; i++) {
    const 다음글자 = tail[끝 + 1];
    if (!다음글자 || !/[\p{L}\p{N}]/u.test(다음글자)) break; // 낱말이 이어지면 안쪽 따옴표였다
    const 더 = tail.indexOf(닫는, 끝 + 1);
    if (더 < 0) break;
    끝 = 더;
  }
  return { quote: tail.slice(여는자리 + 1, 끝), 길이: 끝 + 1, 이음새 };
}

/**
 * **지어낸 인용을 뗀다.** 순수 함수 — 입력만 보고 판단하며 아무것도 부르지 않는다.
 *
 * @param answer  모델이 낸 답(후처리를 이미 지난 최종 문자열)
 * @param chunks  이 답에 실제로 붙여 준 **번호 붙은** 참고 자료 조각들(ragBlock의 [1]…[n]).
 *                `[]`=검색했는데 0건, `null`=RAG를 안 돌림(판정 보류 — 위 머리 주석).
 * @param 추가원천 번호는 없지만 **같은 프롬프트에 실린 글**(온톨로지 「관련 규칙·관계」·확정 용어
 *                정의·📎 첨부한 지난 작업). 프롬프트 ⓐ가 온톨로지도 인용 대상으로 안내하므로,
 *                여기서 그대로 옮긴 문장은 **지어낸 것이 아니다**(검토관 지적). 번호 범위 판정에는
 *                안 쓴다 — 번호는 ragBlock에서만 나온다.
 *
 * 규칙(위에서부터):
 *   ⓪ 실증 우선 — 인용 토막이 **어느 원천과든** 23자 이상 그대로 겹치면 살린다. 번호가 틀렸어도
 *                  내용이 실제로 있으면 참인 문장이다(번호 오기는 지어냄이 아니다).
 *   ① 블록 없음 — 조각이 0건인데 인용 꼬리표를 썼다. 가리킬 것이 없으므로 뗀다.
 *   ② 범위 밖   — [n]이 1..조각수 밖이다(실증 못 한 인용만 해당). 없는 번호는 찾아볼 수도 없다.
 *   ③ 겹침 없음 — 대조 가능한 토막인데 **어느 원천과도** 안 겹친다. 지어낸 원문이다.
 *   ④ 자기 인용 — ③인데 그 토막이 **자기 앞 문장**과 겹친다. 제 말을 남의 원문이라 우긴 것.
 *   ⑤ 빈 답 방지 — 다 떼서 **글자가 하나도 안 남을 때만** 원답을 그대로 둔다(답 전체가 인용뿐).
 *                 ⚠ 문턱을 「20자 미만」으로 뒀다가 짝 시험이 잡았다: 「패치는 빨리 설치해야
 *                 합니다. [5]에 따르면 "…"」처럼 **짧은 진짜 답 + 지어낸 인용**이 통째로 되돌아와
 *                 없는 출처가 그대로 나갔다. 짧고 참인 답이 길고 거짓인 답보다 낫다 —
 *                 보안 제품에서 지어낸 출처는 오답보다 나쁘다.
 *                 되돌린 자리는 `보류`에 실어 **셀 수 있게** 남긴다.
 */
export function guardCitations(
  answer: string,
  chunks: string[] | null,
  추가원천?: readonly (string | null | undefined)[],
): CiteGuardResult {
  const text = String(answer ?? "");
  const 없음: CiteGuardResult = { text, removed: [], 보류: [] };
  if (!text.trim()) return 없음;
  // 근거를 모르는 자리(RAG 미실행)에서는 판정하지 않는다.
  if (chunks === null || chunks === undefined) return 없음;

  const 원천 = [
    ...chunks.map((c) => String(c ?? "")),
    ...(추가원천 ?? []).map((c) => String(c ?? "")),
  ].filter(Boolean);

  const 보호 = 코드구간(text);
  const 보호와겹치나 = (a: number, b: number) => 보호.some(([x, y]) => a < y && b > x);

  const removed: 뗀인용[] = [];
  const 지울구간: [number, number][] = [];

  주장_RE.lastIndex = 0;
  let 마지막끝 = 0; // 이미 뗀 구간 안에서 또 잡지 않는다(인용 토막 안에 꼬리표가 또 있는 꼴)
  let m: RegExpExecArray | null;
  while ((m = 주장_RE.exec(text)) !== null) {
    if (m.index < 마지막끝) continue;
    const 꼬리표끝 = m.index + m[0].length;
    const n = m[1] !== undefined ? Number(m[1]) : m[2] !== undefined ? Number(m[2]) : undefined;
    const 번호갈래 = n !== undefined;
    const 뒤 = 뒤따른인용(text.slice(꼬리표끝));
    // 이음새가 길면(말이 끼었으면) 인용 토막이 **대조 가능한 길이**일 때만 한 덩어리로 본다.
    const 붙었나 = 뒤 !== null
      && (짧은이음새_RE.test(뒤.이음새) || 뒤.quote.replace(/\s+/g, "").length >= 대조하한);
    const quote = 붙었나 && 뒤 ? 뒤.quote : "";
    const 구간끝 = 붙었나 && 뒤 ? 꼬리표끝 + 뒤.길이 : 꼬리표끝;

    // 번호 없는 표식(「원문:」·「출처:」)은 **따옴표가 붙었을 때만** 뗀다 — 한국어 낱말이기도 하다.
    if (!번호갈래 && !붙었나) continue;
    // 지울 구간이 코드블록을 삼키면 판정을 보류한다(「한 글자도 안 건드린다」가 위치만 보던 구멍).
    if (보호와겹치나(m.index, 구간끝)) continue;

    const 대조가능 = quote.replace(/\s+/g, "").length >= 대조하한;
    // ⓪ 실증 — 내용이 실제로 있으면 번호가 어떻든 살린다.
    if (대조가능 && 원천.some((c) => 근거겹침(quote, c) !== null)) continue;

    let kind: 뗀사유종류 | null = null;
    if (chunks.length === 0) kind = "블록없음";
    else if (n !== undefined && (n < 1 || n > chunks.length)) kind = "범위밖";
    else if (대조가능) kind = 근거겹침(quote, text.slice(0, m.index)) !== null ? "자기인용" : "겹침없음";
    if (!kind) continue;

    removed.push({
      kind,
      n,
      quote,
      reason:
        kind === "블록없음" ? `참고 자료가 0건인데 인용 꼬리표를 썼다(${m[0].trim()})`
        : kind === "범위밖" ? `참고 자료는 ${chunks.length}개인데 [${n}]을 가리켰다`
        : kind === "자기인용" ? `인용 토막이 자기 앞 문장과 ${OVERLAP_CHARS}자 겹친다(제 말을 원문이라 인용)`
        : `인용 토막이 어느 참고 자료와도 ${OVERLAP_CHARS}자 안 겹친다`,
    });
    지울구간.push([m.index, 구간끝]);
    마지막끝 = 구간끝;
  }

  if (!지울구간.length) return 없음;

  let out = "";
  let 커서 = 0;
  const 자국: number[] = []; // 뗀 자리(결과 문자열 기준) — 손질은 **이 줄들에만** 건다.
  for (const [a, b] of 지울구간) { out += text.slice(커서, a); 자국.push(out.length); 커서 = b; }
  out += text.slice(커서);

  // 뗀 자리에 남는 겹공백·홀로 남은 문장부호를 정리한다.
  // ⚠ **뗀 줄에만** 건다(2026-09-05 수리). 첫 판은 글 전체에 걸어 본문의 「가 · 나」 표기를
  //   「가· 나」로 조용히 바꿨고(이 제품이 문서·화면에서 늘 쓰는 표기다), 그 손질에는 시험이
  //   하나도 없어 통째로 지워도 33개가 전부 초록이었다(돌연변이 실측). 이제 가운뎃점은
  //   건드리지 않고, 줄 앞 들여쓰기도 남긴다.
  const 손질 = (line: string) => line.replace(/(?<=\S)[ \t]{2,}/g, " ").replace(/[ \t]+([.,;])/g, "$1").trimEnd();
  const 줄들: [number, number][] = [];
  for (const i of 자국) {
    const s = out.lastIndexOf("\n", Math.max(0, i - 1)) + 1;
    const e = out.indexOf("\n", i) < 0 ? out.length : out.indexOf("\n", i);
    if (!줄들.some(([a]) => a === s)) 줄들.push([s, e]);
  }
  줄들.sort((x, y) => x[0] - y[0]);
  let 정리 = "";
  let p = 0;
  for (const [s, e] of 줄들) {
    if (s < p) continue;
    정리 += out.slice(p, s) + 손질(out.slice(s, e));
    p = e;
  }
  정리 = (정리 + out.slice(p)).trim();

  // ⑤ 빈 답 방지 — **글자가 하나도 안 남을 때만** 원답을 유지한다.
  //   문턱을 길이로 두면 짧은 진짜 답까지 되돌려 지어낸 인용을 함께 통과시킨다(짝 시험이 잡았다).
  //   ⚠ 되돌려도 **세는 것은 남긴다**(보류) — 안 세면 이 부류가 기록에서 사라진다.
  if (!/[\p{L}\p{N}]/u.test(정리)) return { text, removed: [], 보류: removed };
  return { text: 정리, removed, 보류: [] };
}

/**
 * llm:event(kind=cite)의 detail에 실을 한 줄 — 건수와 사유 종류만. 인용 원문은 안 싣는다.
 * ⚠ 지금 이 값을 **그리는 화면은 없다**(감독·레일 로스터는 kind=chat만 읽는다).
 *   원천(llm_activity_daily)에는 쌓이므로 나중에 셀 수 있다 — 「미노출」이지 「누락」이 아니다.
 */
export function 뗀인용요약(removed: 뗀인용[], 보류: 뗀인용[] = []): string {
  const 종류: Record<string, number> = {};
  for (const r of removed) 종류[r.kind] = (종류[r.kind] ?? 0) + 1;
  const 목록 = Object.entries(종류).map(([k, v]) => `${k} ${v}`).join(" · ");
  const 앞 = removed.length ? `근거 없는 인용 ${removed.length}건 제거 — ${목록}` : "";
  const 뒤 = 보류.length ? `원답유지 ${보류.length}건 — 답이 통째로 인용이라 못 뗐다` : "";
  return [앞, 뒤].filter(Boolean).join(" · ");
}
