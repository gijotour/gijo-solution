/**
 * 코드블록(``` … ```)과 **인라인 코드**(`…`)의 [시작,끝) 구간 — 이 안은 손대지 않는다.
 * ★ 인라인 코드를 더한 이유(2026-09-05 검토관 실측): 「`rules[0]`」의 대괄호 숫자를 맨 [n] 규칙이
 *   범위 밖 인용으로 보고 지웠다(옛 판에는 없던 새 회귀). 스캔 로그·설정 경로를 그대로 적는 것은
 *   보안 제품 답의 정상 업무다.
 */
function 코드구간(text: string): [number, number][] {
  const out: [number, number][] = [];
  for (const re of [/```[\s\S]*?(?:```|$)/g, /`[^`\n]+`/g]) {
    let m: RegExpExecArray | null;
    while ((m = re.exec(text)) !== null) out.push([m.index, m.index + m[0].length]);
  }
  return out;
}

/**
 * 꼬리표 **뒤에 붙은 인용 토막**을 찾는다(없으면 null).
 *
 * ⚠ 세 가지를 실측으로 고쳤다(2026-09-05 검토관):
 *   · 사이에 말이 끼면(「[1]에 따르면 다음과 같이 규정합니다: "…"」) 첫 판은 **꼬리표만 떼고
 *     지어낸 인용문은 남겼다** — 출처만 사라지고 주장은 제품 단정으로 읽혀 더 나빠졌다.
 *     그래서 줄바꿈·문장끝을 안 넘는 40자까지는 이음새로 본다(길면 토막 길이를 함께 요구한다).
 *   · 인용 안에 따옴표가 또 있으면(「"관리자 계정은 "필수"로 …한다."」) 첫 판은 앞 토막만
 *     떼어 고아 따옴표를 남겼다 → 닫는 따옴표 **바로 뒤가 글자면** 다음 닫는 따옴표까지 잇는다.
 *   · 닫는 따옴표가 아예 없으면(모델이 토큰 한도에서 잘린 실물 3건) 끝까지가 인용이다.
 * ⚠ `줄넘김허용`은 **부르는 쪽이 좁혀서** 넘긴다(줄머리 + 출처|원문) — 사이말줄넘김_RE 주석 참고.
 */
function 뒤따른인용(tail: string, 줄넘김허용 = false): { quote: string; 길이: number; 이음새: string } | null {
  const 이음새 = (줄넘김허용 ? 사이말줄넘김_RE : 사이말_RE).exec(tail)?.[0] ?? "";
  const 여는자리 = 이음새.length;
  const 여는 = tail[여는자리];
  if (!여는 || !(여는 in 따옴표쌍)) return null;
  const 닫는 = 따옴표쌍[여는];
  let 끝 = tail.indexOf(닫는, 여는자리 + 1);
  if (끝 < 0) return { quote: tail.slice(여는자리 + 1), 길이: tail.length, 이음새 }; // 잘린 인용
  for (let i = 0; i < 3; i++) {
    const 다음글자 = tail[끝 + 1];
    if (!다음글자 || !/[\p{L}\p{N}]/u.test(다음글자)) break; // 낱말이 이어지면 안쪽 따옴표였다
    const 더 = tail.indexOf(닫는, 끝 + 1);
    if (더 < 0) break;
    끝 = 더;
  }
  return { quote: tail.slice(여는자리 + 1, 끝), 길이: 끝 + 1, 이음새 };
}

/**
 * 답이 **자기 번호 목록을 스스로 붙였나** — 「[1] tool: …」·「[1] 승인문답:… — "…"」 꼴.
 *
 * ★ 왜 필요한가(2026-09-05 실측): 맨 [n]을 범위로 판정하기 시작하면 **코드가 매긴 번호**까지
 *   범위 밖으로 몰린다. 실전 답 기록 152건 중 6건이 행동 대조(actioncheck)가 스스로 오려 붙인
 *   「사내 근거(원문 발췌)」 목록이었고, 도구 경로(agentloop composeFinalAnswer)는
 *   「[i+1] 도구이름: …」 꼴로 자기 번호를 매긴다. 그 번호는 우리 조각 번호가 아니다.
 * ⚠ 「[1]에 따르면」처럼 **도입 어구가 붙은 줄머리**는 목록이 아니다 — 그것까지 목록으로 보면
 *   마크다운 답에서 맨 [n] 판정이 통째로 꺼진다. 그래서 **번호 뒤에 이름과 콜론**이 오는
 *   꼴만 목록으로 인정한다(위 두 생산자가 실제로 내는 모양).
 */
const 자기목록_RE = /^[ \t>*·-]*\[\d+\][ \t]+[^"“「『《'\s]/m;
/**
 * 한 자리에서 본 「[n] 이름:」 꼴 — 줄머리가 아니어도 도구가 매긴 번호일 수 있어 자리마다 본다.
 * ⚠ 줄 단위(자기목록_RE)보다 **좁게** 잡는다. 여기까지 넓히면 「[8] 계정명을 바꾼다」 같은
 *   평범한 문장이 전부 목록으로 읽혀 맨 [n] 판정이 통째로 꺼진다 — 고치려던 구멍이 도로 열린다.
 */
const 목록정의_RE = /^[ \t]*[^\s:：]{1,40}[ \t]*[:：]/;

/**
 * 줄머리 **목록 표시** — 「- 」·「1) 」·「가) 」·「(1) 」·「a. 」.
 *
 * ★ 왜 생겼나(2026-09-05 검토관 실측): 자국 손질의 ±3칸 창이 목록 표시의 닫는 괄호를 **자국으로
 *   오인해** 지웠다. 「가) **"…"** (출처: …)」가 답 전체 「가」 한 글자로 나갔고, 남은 「가」가
 *   글자라서 통째 교체도 안 걸렸다. 커밋은 「3칸 창으로 막았다」고 적었지만 3칸은 빈도만 줄일 뿐
 *   **인용이 표시 바로 옆에 있는 경우를 못 막는다**(돌연변이로도 확인 — 창을 999로 넓혀도 81개 초록).
 * ⚠ 한글은 「가)」만 본다 — 「다. 그러므로…」 같은 정상 문장을 목록으로 오인하지 않으려는 것이다.
 */
const 목록표시_RE = /^[ \t]*(?:[-*·>][ \t]*)*(?:[(（]?(?:\d{1,2}|[a-zA-Z]|[가-힣])[)）]|(?:\d{1,2}|[a-zA-Z])[.])[ \t]*/;

/**
 * 뗀 자리에 남은 **자국**을 정리한다 — 뗀 줄에만, 그리고 짝 잃은 기호는 **자국 옆에서만**.
 *
 * ★ 왜 이 함수가 생겼나(2026-09-05 라이브·배포 dist 재현): 인용을 떼면 그 자리에 껍데기가 남았다.
 *   · 「(출처: "지어낸 제목")」 → 「()」      (표지 안쪽만 사라지고 괄호가 남는다)
 *   · 「**"…"**」               → 「**」      (여는 쪽 굵게가 이음새로 함께 사라진다)
 *   · 「발견·평가 (** (출처: …)」            (앞 두 가지가 한 줄에서 겹친 실물 꼴)
 *   껍데기는 그냥 지저분한 게 아니라 **없는 출처가 있었던 흔적**이라, 담당자가 「무언가 근거가
 *   있었는데 잘렸다」고 읽는다. 지어낸 인용을 뗀 값어치를 깎는다.
 * ⚠ 짝 잃은 괄호·홀로 남은 굵게는 **자국에서 3칸 안**일 때만 뗀다. 줄 전체에서 짝을 맞추면
 *   「1) 첫째」 같은 정상 목록 표시의 닫는 괄호를 지운다 — 우리가 안 만든 자국까지 손대게 된다.
 * ⚠ 가운뎃점은 건드리지 않는다. 첫 판의 손질이 본문의 「가 · 나」를 「가· 나」로 조용히 바꿨고,
 *   그 손질에는 시험이 하나도 없어 통째로 지워도 33개가 전부 초록이었다(돌연변이 실측).
 */
function 자국손질(line: string, 자리들: number[]): string {
  // 줄머리 목록 표시(「1) 」·「가) 」)는 **우리가 만든 자국이 아니다** — 그 안쪽은 자국으로 안 본다.
  const 표시끝 = 목록표시_RE.exec(line)?.[0].length ?? 0;
  const 가깝나 = (i: number) => i >= 표시끝 && 자리들.some((p) => Math.abs(i - p) <= 3);
  const 뗄자리 = new Set<number>();

  // ① 짝을 못 찾은 괄호 — 자국 옆에 있는 것만
  for (const [열, 닫] of [["(", ")"], ["（", "）"], ["[", "]"]] as const) {
    const 스택: number[] = [];
    for (let i = 0; i < line.length; i++) {
      if (line[i] === 열) 스택.push(i);
      else if (line[i] === 닫) { if (스택.length) 스택.pop(); else if (가깝나(i)) 뗄자리.add(i); }
    }
    for (const i of 스택) if (가깝나(i)) 뗄자리.add(i);
  }

  // ② 홀로 남은 굵게 표식 — 줄의 「**」 개수가 홀수일 때, 자국에 가장 가까운 하나만
  const 굵게: number[] = [];
  for (let i = 0; i + 1 < line.length; i++) if (line[i] === "*" && line[i + 1] === "*") { 굵게.push(i); i++; }
  if (굵게.length % 2 === 1) {
    let 후보 = -1;
    let 거리 = Number.POSITIVE_INFINITY;
    for (const i of 굵게) for (const p of 자리들) { const d = Math.abs(i - p); if (d < 거리) { 거리 = d; 후보 = i; } }
    if (후보 >= 0 && 거리 <= 3) { 뗄자리.add(후보); 뗄자리.add(후보 + 1); }
  }

  let s = "";
  for (let i = 0; i < line.length; i++) if (!뗄자리.has(i)) s += line[i];

  // ★ 한 번으로는 안 끝난다(실측): 「(**** )」는 **빈 굵게를 먼저 떼야** 빈 괄호가 드러난다.
  //   그래서 더 이상 안 바뀔 때까지 돌린다(최대 세 바퀴 — 규칙이 서로를 드러내는 깊이가 둘이다).
  const 한바퀴 = (t: string) =>
    t
      // ③ 빈 굵게 — 「****」. **가장 먼저** 떼야 그 안쪽 껍데기가 드러난다.
      //   ⚠ 양옆이 다 글자면 **붙어 있는 두 굵게의 경계**다(「**중요****주의**」) — 안 건드린다.
      .replace(/\*{4}/g, (칸, 자리: number, 온줄: string) =>
        /[\p{L}\p{N}]/u.test(온줄[자리 - 1] ?? "") && /[\p{L}\p{N}]/u.test(온줄[자리 + 4] ?? "") ? 칸 : "")
      // ④ 알맹이가 사라진 표지 — 「(출처: )」·「[근거:]」
      //   ⚠ 정직한 기록(2026-09-05): guardCitations를 거쳐 이 꼴이 남는 입력을 **못 찾았다**
      //     (표지꼴은 괄호째 떼고, 대괄호 꼴은 아래 ⑥이 먹는다). 돌연변이로 지워도 시험이
      //     안 붉어진다 — 즉 지금은 **보험**이고, 표지 처리가 바뀌면 다시 필요해질 자리다.
      .replace(/[(（[][ \t]*(?:원문|인용|출처|근거|자료|문서)[ \t]*[:：]?[ \t]*[)）\]]/g, "")
      // ⑤ 껍데기만 남은 구두점 — 「(, 2023년 4월)」·「, ,」
      .replace(/([(（[])[ \t]*[,，][ \t]*/g, "$1")
      .replace(/[ \t]*[,，][ \t]*([)）\]])/g, "$1")
      .replace(/([,，])[ \t]*(?=[,，])/g, "")
      // ⑥ 빈 괄호 — 위 셋을 지나야 「( )」로 드러나는 자리가 있다.
      .replace(/\([ \t]*\)|（[ \t]*）|\[[ \t]*\]/g, "");
  for (let k = 0; k < 3; k++) {
    const 전 = s;
    s = 한바퀴(s);
    if (s === 전) break;
  }
  s = s.replace(/[ \t]+([.,;:，。])/g, "$1");
  // 표 줄(「| 항목 | 값 |」)의 정렬 공백은 안 건드린다 — 뗀 줄이라는 이유로 표가 어긋난다(검토관).
  if (!/^[ \t]*\|/.test(s)) s = s.replace(/(?<=\S)[ \t]{2,}/g, " ");
  s = s.trimEnd();

  // ⑦ 글자가 하나도 안 남은 줄(목록 표시만 남은 「- 」·「1)」·「가)」)은 빈 줄로 돌려준다.
  //   ⚠ **목록 표시를 걷어내고** 본다(2026-09-05 검토관): 「가」·「1」은 글자·숫자라 그냥 보면
  //     「내용이 남았다」로 읽혀 통째 교체가 안 걸리고, 사용자에게 **한 글자짜리 답**이 나갔다.
  return /[\p{L}\p{N}]/u.test(s.replace(목록표시_RE, "")) ? s : "";
}

/**
 * **지어낸 인용을 뗀다.** 순수 함수 — 입력만 보고 판단하며 아무것도 부르지 않는다.
 *
 * @param answer  모델이 낸 답(후처리를 이미 지난 최종 문자열)
 * @param chunks  이 답에 실제로 붙여 준 **번호 붙은** 참고 자료 조각들(ragBlock의 [1]…[n]).
 *                []=검색했는데 0건, null=RAG를 안 돌림(판정 보류 — 위 머리 주석).
 * @param 추가원천 번호는 없지만 **같은 프롬프트에 실린 글**(온톨로지 「관련 규칙·관계」·확정 용어
 *                정의·📎 첨부한 지난 작업). 프롬프트 ⓐ가 온톨로지도 인용 대상으로 안내하므로,
 *                여기서 그대로 옮긴 문장은 **지어낸 것이 아니다**(검토관 지적). 번호 범위 판정에는
 *                안 쓴다 — 번호는 ragBlock에서만 나온다.
 *
 * 규칙(위에서부터):
 *   ⓪ 실증 우선 — 인용 토막이 **어느 원천과든** 실제로 있으면 살린다(23자↑=겹침, 8~22자=그대로).
 *                  번호가 틀렸어도 내용이 있으면 참인 문장이다(번호 오기는 지어냄이 아니다).
 *   ① 블록 없음 — 조각이 0건인데 인용 꼬리표를 썼다. 가리킬 것이 없으므로 뗀다.
 *   ② 범위 밖   — [n]이 1..조각수 밖이다(실증 못 한 인용만 해당). 없는 번호는 찾아볼 수도 없다.
 *   ③ 겹침 없음 — 대조 가능한 토막인데 **어느 원천에도 없다**. 지어낸 원문이다.
 *   ④ 자기 인용 — ③인데 그 토막이 **자기 앞 문장**에 있다. 제 말을 남의 원문이라 우긴 것.
 *   ⑤ 맨 [n]    — 따옴표도 도입 어구도 없는 번호 표지. **범위만** 본다(글자 대조는 불가능하다).
 *                 문장은 그대로 두고 대괄호 표지만 뗀다.
 *   ⑥ 통째 교체 — 다 떼서 **글자가 하나도 안 남으면** 원답 대신 자료없음안내로 바꾼다.
 *                 ⚠ 2026-09-05까지는 여기서 **원답을 그대로 내보냈다**(보류). 그 자리에서
 *                 지어낸 「클릭률 15%」가 사용자에게 나갔다 — 세기만 하고 막지는 못했다.
 */
export function guardCitations(
  answer: string,
  chunks: string[] | null,
  추가원천?: readonly (string | null | undefined)[],
  옵션?: { 원천없는출구?: boolean },
): CiteGuardResult {
  const text = String(answer ?? "");
  const 없음: CiteGuardResult = { text, removed: [], 보류: [] };
  if (!text.trim()) return 없음;
  // 근거를 모르는 자리(RAG 미실행)에서는 판정하지 않는다.
  if (chunks === null || chunks === undefined) return 없음;

  // ★ 원천도 **강조를 걷어** 대조한다(2026-09-05 검토관 — 강조걷은글 주석의 9.5% 오탐).
  //   여기서 만든 글은 **대조에만** 쓰이고 사용자에게 돌아가는 답은 언제나 원문 text다.
  const 원천 = [
    ...chunks.map((c) => String(c ?? "")),
    ...(추가원천 ?? []).map((c) => String(c ?? "")),
  ].filter(Boolean).map(강조걷은글);

  // ★ 원천이 **원리상 비는 출구**인가(클라우드 — cloudllm.askCloud). 2026-09-05 검토관.
  //   이 자리에서는 chunks=[]가 「자료가 없다」가 아니라 「대조할 것을 애초에 안 싣는다」다.
  //   그래서 **번호 인용만** 본다 — [n]은 있지도 않은 근거 블록을 가리키므로 확정된 거짓이지만,
  //   따옴표 인용·맨몸 출처 이름은 **대조 자체가 불가능**하다. 이 파일의 규율 그대로
  //   「대조 못 할 것은 안 건드린다」 — 확인 못 한 것을 코드가 가짜라고 단정하지 않는다.
  const 원천없는출구 = 옵션?.원천없는출구 === true;

  const 보호 = 코드구간(text);
  const 보호와겹치나 = (a: number, b: number) => 보호.some(([x, y]) => a < y && b > x);

  // ★ J1 — 찾는 것은 **판정본**(강조 표식을 걷어낸 사본)에서, 지우는 것은 **원문**에서.
  //   아래 `판`으로 시작하는 자리는 판정본 좌표, 그냥 `시작·구간끝`은 원문 좌표다. 섞으면 딴 데를 지운다.
  const 사본 = 판정사본만들기(text, 보호);
  const 판글 = 사본.글;

  /** 뗄 자리와 그 사유 — 마지막에 자리 순으로 모아 한 번에 자른다(**원문 좌표**). */
  const 조각들: { a: number; b: number; r: 뗀인용 }[] = [];
  /** 주장_RE가 **본** 자리(뗐든 살렸든) — 맨 [n] 훑기가 같은 번호를 두 번 보지 않게(**원문 좌표**). */
  const 본자리: [number, number][] = [];

  주장_RE.lastIndex = 0;
  let 판마지막끝 = 0; // 이미 뗀 구간 안에서 또 잡지 않는다(인용 토막 안에 꼬리표가 또 있는 꼴)
  let m: RegExpExecArray | null;
  while ((m = 주장_RE.exec(판글)) !== null) {
    if (m.index < 판마지막끝) continue;
    const 판꼬리표끝 = m.index + m[0].length;
    const n = m[1] !== undefined ? Number(m[1]) : m[2] !== undefined ? Number(m[2]) : undefined;
    const 번호갈래 = n !== undefined;
    // ★ 좁힘 두 가지를 **한 곳에서** 만든다(2026-09-05 검토관): 표식이 줄머리인가 · 낱말이
    //   출처|원문인가. 첫 판은 이 좁힘을 J2 줄끝 갈래에만 걸고 J1 줄바꿈·J2 괄호 갈래에는
    //   안 걸어, **같은 위험 판단이 세 갈래에서 서로 달랐다**. 같은 것을 여러 곳에 적으면 어긋난다.
    const 줄머리 = /(?:^|\n)[ \t]*(?:[-*·>][ \t]*)*$/.test(판글.slice(0, m.index));
    const 출처원문 = /(?:출처|원문)/.test(m[0]);
    const 뒤 = 뒤따른인용(판글.slice(판꼬리표끝), 줄머리 && 출처원문);
    // 이음새가 길면(말이 끼었으면) 인용 토막이 **대조 가능한 길이**일 때만 한 덩어리로 본다.
    const 붙었나 = 뒤 !== null
      && (짧은이음새_RE.test(뒤.이음새) || 뒤.quote.replace(/\s+/g, "").length >= 대조하한);
    let quote = 붙었나 && 뒤 ? 뒤.quote : "";
    let 판시작 = m.index;
    let 판구간끝 = 붙었나 && 뒤 ? 판꼬리표끝 + 뒤.길이 : 판꼬리표끝;

    // 「(출처: "제목", 2023년 4월)」 — 여는 괄호로 시작한 표지는 **괄호째** 뗀다.
    //   안 그러면 「(, 2023년 4월)」가 남아 **없는 출처의 연월만 살아남는다**(라이브 실물 꼴).
    //   닫는 괄호를 못 찾으면 여는 괄호는 건드리지 않는다 — 남의 괄호를 열어 두지 않는다.
    //   ★ K3 — 여는 글자가 `(`·`（`만이 아니다(`[출처: …]`·`【출처】`). 닫는 글자는 **짝 표**로 받는다.
    //   ⚠ **번호 대괄호는 여는 괄호가 아니다**(2026-09-05 K3 자기적발): `[`를 그냥 열어 두면
    //     「[1]에 따르면」의 `[`가 표지 여는 괄호로 읽혀 표지꼴이 참이 되고, 겹침없음·자기인용이
    //     통째로 「출처미확인」으로 바뀐다(짝 시험 4개가 그 자리에서 붉었다). 숫자가 오면 번호다.
    const 여는괄호원 = /^[(（【][ \t]*|^\[[ \t]*(?!\d)/.exec(m[0]);
    const 닫는글자 = 여는괄호원 ? (표지닫는[여는괄호원[0][0]] ?? "") : "";
    // 「【출처】」는 표지가 **자기 안에서 닫힌다** — 뒤에서 닫는 괄호를 또 찾으면 안 되고,
    //   여는 글자를 도로 남겨서도 안 된다(「【」만 덩그러니 남는다).
    //   ⚠ **닫는 글자가 들어 있다고 자기 안에서 닫힌 것이 아니다**(2026-09-05 검토관). `includes`만
    //     보던 첫 판은 「[출처 [1]: "제목"]」에서 **안쪽 번호 대괄호의 `]`**에 걸려 자체닫힘=참이 됐고,
    //     그 바람에 표지꼴이 우연히 켜져 「표지 앞 인용문도 함께 뗌」까지 갔다(실측: 옛 판은 앞 인용을
    //     남겼는데 새 판은 앞 인용까지 지웠다). 깊이를 세면 「[출처]:」는 참, 「[출처 [1]:」은 거짓이다.
    const 자체닫힘 = !!(닫는글자 && 여는괄호원 && 자기안에서닫히나(m[0], 여는괄호원[0][0], 닫는글자));
    const 여는괄호 = 자체닫힘 ? null : 여는괄호원;
    let 표지꼴 = 자체닫힘; // 「(출처: "제목", 연월)」처럼 **괄호째** 잡은 자리인가
    let 맨몸 = false;   // ★ J2 — 따옴표 없이 이름만 적은 표지인가
    if (여는괄호 && 닫는글자) {
      const c = 정규식글자(닫는글자);
      const 꼬리 = 붙었나
        ? new RegExp(`^[ \\t]*(?:[,，][^${c}\\n]{0,40})?[ \\t]*${c}`).exec(판글.slice(판구간끝))
        : null;
      if (꼬리) { 판구간끝 += 꼬리[0].length; 표지꼴 = true; }
    }

    // ★ J2 — 따옴표가 안 붙은 표식이라도 **이름을 적은 표지**면 판정한다.
    //   「(출처: CSOOnline, 2021년 11월 25일)」·「출처: CSOOnline」이 배포 dist에서 뗌 0이던 자리다.
    //   ⚠ 줄 끝 갈래는 **표식이 줄머리에 있을 때만** 본다. 문장 한복판의 「…자료: 」까지 보면
    //     실전 답의 정상 문장이 걸린다(모집단 실측으로 좁힌 조건이다).
    //   ⚠ **괄호 갈래에도 낱말 좁힘을 건다**(2026-09-05 검토관). 첫 판은 줄끝 갈래에만 걸어서
    //     「(근거: 위 표)」·「(자료: 내부 스캔 결과)」·「(문서: 담당자 확인)」처럼 문서가 아닌
    //     **정당한 괄호 주석**까지 뗐다(실측 3건, 옛 판 0건). J2가 노린 실물은 둘 다 「출처」다.
    //   ⚠ **「참고」는 이름이 바깥 기관·매체처럼 생겼을 때만** 본다(2026-09-05 K3 — 기관이름꼴_RE 주석).
    //     「(참고: CSOOnline)」은 실물 지어낸 출처지만 「(참고: 위 표)」는 정당한 주석이다.
    const 기관표지 = /참고/.test(m[0]);
    if (!번호갈래 && !붙었나 && (출처원문 || 기관표지) && !원천없는출구) {
      const 꼬리 = 여는괄호 && 닫는글자
        ? 맨몸괄호꼬리_RE(닫는글자).exec(판글.slice(판꼬리표끝))
        : (줄머리 && !여는괄호 ? 맨몸줄끝_RE.exec(판글.slice(판꼬리표끝)) : null);
      const 이름들 = 꼬리 ? 출처이름들(꼬리[1]) : [];
      const 기관꼴 = 이름들.length > 0 && 이름들.every((n) => 기관이름인가(n));
      if (꼬리 && (출처원문 || 기관꼴) && 맨몸출처판정(꼬리[1], 원천) === "미확인") {
        판구간끝 = 판꼬리표끝 + 꼬리[0].length;
        quote = 이름들.join(", ");
        맨몸 = true;
      }
    }
    if (여는괄호 && !표지꼴 && !맨몸) 판시작 += 여는괄호[0].length;

    let 시작 = 원문시작(사본, 판시작, text);
    // ★ L1 — 실제로 **떼기 시작하는** 판정본 자리. 아래 「표지 앞 인용문도 함께」가 왼쪽으로
    //   넓히면 이 값도 같이 옮긴다. 귀속 꼬리의 마침표를 남길지는 **이 앞 글자**가 정한다.
    let 판떼는시작 = 판시작;
    const 구간끝 = 원문끝(사본, 판구간끝, text.length);
    본자리.push([시작, 구간끝]);

    // 번호 없는 표식(「원문:」·「출처:」)은 **따옴표나 이름이 붙었을 때만** 뗀다 — 한국어 낱말이기도 하다.
    if (!번호갈래 && !붙었나 && !맨몸) continue;
    // ★ 원천이 원리상 비는 출구에서는 **번호 인용만** 본다(위 원천없는출구 주석).
    //   따옴표 인용·출처 이름을 여기서 떼면 「확인 못 했다」를 「가짜다」로 바꿔 말하는 것이고,
    //   사용자가 **일부러 고른** 외부 지식 경로에서 출처 표기가 통째로 사라진다(실측: 출처를 단
    //   답마다 매번). 뗀 것이 아니라 못 뗀 것을 정직하게 두는 쪽을 고른다.
    if (원천없는출구 && !번호갈래) continue;
    // 지울 구간이 코드블록을 삼키면 판정을 보류한다(「한 글자도 안 건드린다」가 위치만 보던 구멍).
    if (보호와겹치나(시작, 구간끝)) continue;

    const 무공백 = quote.replace(/\s+/g, "").length;
    const 대조가능 = !맨몸 && 무공백 >= 짧은대조하한;
    // 출처 **표지의 제목**은 8자 하한을 안 건다(2026-09-05 구멍 H2 재수리 — 제목그대로있나 주석 참고).
    const 제목판정 = 표지꼴 && 무공백 >= 제목하한;
    // ⓪ 실증 — 내용이 실제로 있으면 번호가 어떻든 살린다.
    //   ⚠ 맨몸 표지는 위에서 이미 「미확인」으로 가려 왔다(맨몸출처판정) — 다시 대조하지 않는다.
    const 실증됨 = !맨몸 && (대조가능
      ? 원천.some((c) => 원천에있나(quote, c))
      : 제목판정 && 원천.some((c) => 제목그대로있나(quote, c)));
    if (실증됨) continue;

    let kind: 뗀사유종류 | null = null;
    // ★ 맨몸 표지는 **조각 수와 무관하게** 출처미확인이다(2026-09-05 J2). 「블록없음」으로 몰면
    //   「번호를 가리켰는데 가리킬 게 없다」와 「이름을 댔는데 그 이름을 못 찾겠다」가 한 숫자로
    //   섞인다 — 감독 화면이 사유로 가르지 못하게 된다.
    if (맨몸) kind = "출처미확인";
    else if (chunks.length === 0) kind = "블록없음";
    else if (n !== undefined && (n < 1 || n > chunks.length)) kind = "범위밖";
    else if (제목판정) kind = "출처미확인";
    else if (대조가능) kind = 원천에있나(quote, 판글.slice(0, 판시작)) ? "자기인용" : "겹침없음";
    if (!kind) continue;

    // ★ 「"지어낸 인용문" (출처: "없는 제목")」 — 표지만 떼면 **주장이 제품 단정으로 남는다**.
    //   그래서 표지 앞에 바로 붙은 인용문을 되짚어 **같은 잣대**로 다시 보고, 그것도 원천에
    //   없으면 함께 뗀다. 원천에 있으면 인용문은 살린다(제목이 파일명이라 조각 본문에 없을 때).
    //   ⚠ **맨몸 표지에는 이 되짚기를 안 건다**(2026-09-05 J2 — 상위 결정). 이름만 적힌 표지는
    //     앞 문장이 인용부호로 묶여 있지 않은 경우가 대부분이라, 되짚어 떼면 **답 자체가 사라진다.**
    //     표지를 떼고 계수로 관측하는 데서 멈춘다 — 「단정으로 남는다」는 알면서 고른 대가다.
    let 앞도뗌 = "";
    if (표지꼴) {
      const 판줄머리 = 판글.lastIndexOf("\n", Math.max(0, 판시작 - 1)) + 1;
      const 앞 = 앞인용_RE.exec(판글.slice(판줄머리, 판시작));
      const 앞토막 = 앞?.[1] ?? "";
      const 판앞시작 = 판줄머리 + (앞?.index ?? 0);
      const 앞시작 = 앞 ? 원문시작(사본, 판앞시작, text) : 시작;
      if (
        앞 && 판앞시작 >= 판마지막끝
        && 앞토막.replace(/\s+/g, "").length >= 짧은대조하한
        && !원천.some((c) => 원천에있나(앞토막, c))
        && !보호와겹치나(앞시작, 시작)
      ) {
        시작 = 앞시작;
        판떼는시작 = 판앞시작;
        앞도뗌 = ` · 표지 앞 인용문도 원천에 없어 함께 뗐다`;
        // 함께 뗀 자리의 사유는 **인용문이 지어낸 것**이다 — 제목 미확인이 아니다.
        if (kind === "출처미확인") kind = "겹침없음";
      }
    }

    // ★ K1 — 뗀 자리 **바로 뒤에 붙은 귀속 꼬리**(「 by Brian Krebs, 2021-04-29」)를 같은 덩어리로 뗀다.
    //   여기서 하는 이유: 뗄 것이 정해진 **뒤**라야, 살릴 인용의 귀속까지 잘라 내지 않는다.
    let 끝 = 구간끝;
    let 판끝 = 판구간끝;
    //   ⚠ 앞 글자를 함께 넘긴다(L1) — 앞이 이미 마침표면 꼬리의 마침표를 남기면 「..」가 된다.
    //     8자면 충분하다(공백 몇 칸을 걷어 내고 문장부호 하나를 보는 것이 전부다).
    const 꼬리길이 = 귀속꼬리길이(판글.slice(판구간끝), 원천, 판글.slice(Math.max(0, 판떼는시작 - 8), 판떼는시작));
    if (꼬리길이 > 0) {
      const 늘린판끝 = 판구간끝 + 꼬리길이;
      const 늘린끝 = 원문끝(사본, 늘린판끝, text.length);
      if (!보호와겹치나(구간끝, 늘린끝)) { 판끝 = 늘린판끝; 끝 = 늘린끝; }
    }

    조각들.push({
      a: 시작,
      b: 끝,
      r: {
        kind,
        n,
        quote,
        reason:
          kind === "블록없음" ? `참고 자료가 0건인데 인용 꼬리표를 썼다(${m[0].trim()})`
          : kind === "범위밖" ? `참고 자료는 ${chunks.length}개인데 [${n}]을 가리켰다`
          : kind === "자기인용" ? `인용 토막이 자기 앞 문장에 그대로 있다(제 말을 원문이라 인용)`
          : kind === "출처미확인" ? (맨몸
            ? `출처로 댄 이름을 어느 원천에서도 확인할 수 없다(따옴표 없는 표지 — 표지만 뗐다)`
            : `출처 제목을 어느 원천에서도 확인할 수 없다`)
          : `인용 토막이 어느 참고 자료에도 없다(무공백 ${무공백}자 대조)`,
      },
    });
    if (앞도뗌) 조각들[조각들.length - 1].r.reason += 앞도뗌;
    if (판끝 > 판구간끝) 조각들[조각들.length - 1].r.reason += ` · 뒤에 붙은 귀속(누가·언제)도 함께 뗐다`;
    판마지막끝 = 판끝;
  }

  // ★ J2ⓒ — 표식 낱말이 없는 **줄표 귀속** 「— CSOOnline, 2021년 11월 25일」.
  //   주장_RE는 표식 낱말에서 출발하므로 이 꼴을 원리상 못 본다. 날짜를 **필수**로 걸어
  //   평범한 줄표 문장(「— 자세한 내용은 …」)이 안 걸리게 한다(실물 세 뭉치에서 걸린 것 0건).
  //   ⚠ 클라우드 출구에서는 이 갈래도 끈다 — 맨몸 표지와 **같은 부류**라 대조할 원천이 없다.
  if (!원천없는출구) {
    줄표출처_RE.lastIndex = 0;
    let d: RegExpExecArray | null;
    while ((d = 줄표출처_RE.exec(판글)) !== null) {
      const 판a = d.index + (d[0].startsWith("\n") ? 1 : 0);
      const 판b = d.index + d[0].length;
      const a = 원문시작(사본, 판a, text);
      const b = 원문끝(사본, 판b, text.length);
      if (본자리.some(([x, y]) => a < y && b > x)) continue; // 주장_RE가 이미 판정한 자리
      if (보호와겹치나(a, b)) continue;
      if (맨몸출처판정(d[1], 원천) !== "미확인") continue;
      조각들.push({
        a, b,
        r: {
          kind: "출처미확인", quote: 출처이름들(d[1]).join(", "),
          reason: `출처로 댄 이름을 어느 원천에서도 확인할 수 없다(줄표 귀속 표지 — 표지만 뗐다)`,
        },
      });
    }
  }

  // ⑤ 따옴표도 도입 어구도 없는 **맨 [n]** — 주석은 「번호 범위만 본다」였는데 코드는 범위조차
  //   안 봤다(구멍 ④). 조각이 4개인데 [1]~[8]이 그대로 나간 실물이 있다. 여기서 주석과 맞춘다.
  //   ⚠ **표지만** 뗀다 — 문장은 그대로 둔다. 번호가 틀린 것이지 문장이 거짓이라는 증거는 없다.
  {
    // 번호는 두 자리까지만 인용 번호로 본다 — 「[2024]」 같은 연도를 참고 번호로 오인하지 않는다.
    const 맨번호_RE = /\[(\d{1,2})\]/g;
    let b: RegExpExecArray | null;
    while ((b = 맨번호_RE.exec(text)) !== null) {
      const a0 = b.index;
      const a1 = a0 + b[0].length;
      if (본자리.some(([x, y]) => a0 < y && a1 > x)) continue; // 주장_RE가 이미 판정한 자리
      if (보호와겹치나(a0, a1)) continue;                       // 코드블록·인라인 코드 안
      if (text[a1] === "(") continue;                           // 마크다운 링크 「[1](…)」
      // 낱말에 **붙은** 대괄호는 배열 자리·조항 번호지 인용 번호가 아니다(「logs[0]」·「[12]항」).
      //   ⚠ 2026-09-05 검토관 실측: 이걸 안 봐서 「logs[0]을 확인하세요」가 「logs을 확인하세요」로
      //     나갔고, 그 제거가 「근거 없는 인용」 계수에까지 실렸다(옛 판에는 없던 새 회귀).
      if (/[\p{L}\p{N}_)\]]/u.test(text[a0 - 1] ?? "")) continue;
      if (/[\p{L}\p{N}_]/u.test(text[a1] ?? "")) continue;
      if (목록정의_RE.test(text.slice(a1))) continue;            // 「[1] tool: …」 도구가 매긴 번호
      // ⚠ 자기 번호 목록 보류는 **그 줄에만** 건다(2026-09-05 검토관). 예전엔 답 어딘가에 그런 줄이
      //   하나만 있어도 답 **전체**의 맨 [n] 판정이 꺼져서, 모델이 끝에 참고문헌 목록을 붙이면
      //   본문의 지어낸 번호가 통째로 살아났다. 정작 지키려던 두 생산자(actioncheck·agentloop)의
      //   답은 애초에 이 가드에 닿지도 않는다(chunks=null이거나 chat() 출구를 안 지난다).
      const 줄s = text.lastIndexOf("\n", Math.max(0, a0 - 1)) + 1;
      const 줄e = text.indexOf("\n", a0) < 0 ? text.length : text.indexOf("\n", a0);
      if (자기목록_RE.test(text.slice(줄s, 줄e))) continue;
      const n = Number(b[1]);
      if (n >= 1 && n <= chunks.length) continue;               // 범위 안이면 정상 참조다
      조각들.push({
        a: a0,
        b: a1,
        r: { kind: "범위밖", n, quote: "", reason: `참고 자료는 ${chunks.length}개인데 [${n}]을 가리켰다(번호 표지만 뗐다)` },
      });
    }
  }

  if (!조각들.length) return 없음;
  조각들.sort((x, y) => x.a - y.a);

  const removed: 뗀인용[] = [];
  let out = "";
  let 커서 = 0;
  const 자국: number[] = []; // 뗀 자리(결과 문자열 기준) — 손질은 **이 줄들에만** 건다.
  for (const 조각 of 조각들) {
    if (조각.a < 커서) continue; // 겹치는 자리는 앞선 것이 이미 먹었다
    out += text.slice(커서, 조각.a);
    자국.push(out.length);
    커서 = 조각.b;
    removed.push(조각.r);
  }
  out += text.slice(커서);

  // 뗀 자리에 남는 껍데기·겹공백을 정리한다 — **뗀 줄에만** 건다(2026-09-05 수리).
  const 줄들: [number, number][] = [];
  const 줄자국 = new Map<number, number[]>();
  for (const i of 자국) {
    const s = out.lastIndexOf("\n", Math.max(0, i - 1)) + 1;
    const e = out.indexOf("\n", i) < 0 ? out.length : out.indexOf("\n", i);
    if (!줄들.some(([a]) => a === s)) 줄들.push([s, e]);
    줄자국.set(s, [...(줄자국.get(s) ?? []), i - s]);
  }
  줄들.sort((x, y) => x[0] - y[0]);
  let 정리 = "";
  let p = 0;
  for (const [s, e] of 줄들) {
    if (s < p) continue;
    const 손질된 = 자국손질(out.slice(s, e), 줄자국.get(s) ?? []);
    정리 += out.slice(p, s) + 손질된;
    p = e;
    // 글자가 하나도 안 남은 줄은 줄바꿈까지 접는다 — 빈 줄을 새로 만들지 않는다.
    if (!손질된 && s < e && out[e] === "\n") p = e + 1;
  }
  정리 = (정리 + out.slice(p)).trim();

  // ⑥ 통째 교체 — **글자가 하나도 안 남으면** 원답을 되돌리지 않고 정직한 안내로 바꾼다.
  //   ⚠ 옛 판(원답유지)은 세기만 하고 지어낸 출처·숫자를 그대로 내보냈다. 짧고 정직한 답이
  //     길고 거짓인 답보다 낫다 — 보안 제품에서 지어낸 근거는 오답보다 나쁘다.
  //   ⚠ 문장은 **조각이 있느냐로 가른다**(2026-09-05 검토관): 조각이 0건이면 「자료가 없다」가
  //     사실이지만, 조각이 있는데 이 답의 주장이 그 안에 없는 것은 **다른 사실**이다. 확인하지
  //     않은 것(자료 부재)을 코드가 단정하지 않는다 — 「장애≠부재」와 같은 규율이다.
  //   ⚠ **클라우드 출구는 셋째 문장**이다(2026-09-05 검토관). 그 경로의 chunks=[]는 「사내 자료가
  //     없다」가 아니라 「사내 자료를 안 실었다」라, 자료없음안내를 쓰면 같은 규율을 여기서만 어긴다.
  if (!/[\p{L}\p{N}]/u.test(정리)) {
    removed.push({
      kind: "통째교체",
      quote: "",
      reason: 원천없는출구
        ? "클라우드 답이 통째로 확인 안 되는 근거 표시라 안내로 바꿨다"
        : chunks.length === 0
        ? "답이 통째로 지어낸 인용이라 원답 대신 자료없음 안내로 바꿨다"
        : `참고 자료 ${chunks.length}개를 줬는데 답이 통째로 그 안에 없는 인용이라 안내로 바꿨다`,
    });
    const 안내 = 원천없는출구 ? 클라우드근거없음안내 : chunks.length === 0 ? 자료없음안내 : 근거불일치안내;
    return { text: 안내, removed, 보류: [] };
  }
  return { text: 정리, removed, 보류: [] };
}

/**
 * llm:event(kind=cite)의 detail에 실을 한 줄 — 건수와 사유 종류만. 인용 원문은 안 싣는다.
 *
 * ★ 2026-09-05 J4 — **이제 그리는 화면이 있다**(옛 주석 「그리는 화면은 없다」를 여기서 정정한다):
 *   · 이 detail 한 줄 = `agent.html` 「팀 활동 — 실동작 기록」 터미널의 **✂** 줄(실시간).
 *   · 건수 아닌 **뗀 답의 수** = `supervision.html` 「감독 관점」의 ✂ 줄(llm_activity_daily 집계).
 *   두 자리가 서로 다른 것을 센다 — 표는 **답 개수**, 이 줄은 **인용 건수**다. 섞어 적으면 거짓이 된다.
 * ⚠ 「뗐습니다」가 거짓이 될 조건: 감독 표는 `removed.length > 0 || 보류.length > 0`에서 나간
 *   이벤트를 센다. 지금은 `보류`가 모든 반환 경로에서 빈 배열이라 「cite 이벤트 = 실제로 뗀 답」이
 *   성립하지만, 「막지 못한 부류」가 다시 `보류`에 담기는 날 그 문구는 거짓이 된다 —
 *   그때는 표 문구를 「손댄 답 N개」로 바꾸거나 removed만 세는 신호를 따로 내야 한다.
 */
export function 뗀인용요약(removed: 뗀인용[], 보류: 뗀인용[] = []): string {
  const 종류: Record<string, number> = {};
  for (const r of removed) 종류[r.kind] = (종류[r.kind] ?? 0) + 1;
  const 목록 = Object.entries(종류).map(([k, v]) => `${k} ${v}`).join(" · ");
  const 앞 = removed.length ? `근거 없는 인용 ${removed.length}건 제거 — ${목록}` : "";
  const 뒤 = 보류.length ? `원답유지 ${보류.length}건 — 답이 통째로 인용이라 못 뗐다` : "";
  return [앞, 뒤].filter(Boolean).join(" · ");
}

