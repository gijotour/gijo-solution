// ★ J1 — **마크다운 내성**: 굵게·기울임 표식을 걷어낸 「판정용 사본」에서 찾고, **제거는 원문에** 건다.
//
// ★ 왜 필요한가(2026-09-05 배포 dist 실측 — 라이브 다섯 번째 구멍):
//   아래 다섯 꼴이 **전부 뗌 0**이었다. 표식과 따옴표 사이에 `**`가 끼면 사이말_RE가 깨지고,
//   따옴표를 `**`가 감싸면 뒤따른인용이 여는 따옴표를 못 찾는다.
//     · 「**출처:** "제목"」   · 「**출처**: "제목"」   · 「**원문:** "…"」
//     · 「출처: **"제목"**」   · 「출처:⏎"제목"」(줄바꿈 — 위 사이말줄넘김_RE가 맡는다)
//   그런데 이건 **드문 꼴이 아니라 주류**다 — 제품 프롬프트가 모델에게 마크다운으로 쓰게 한다.
//   즉 가드가 막으려던 바로 그 답의 **가장 흔한 모양**을 원리상 못 보고 있었다.
//
// ⚠ 왜 「원문에서 표식을 지우고 판정」이 아니라 **사본 + 자리표**인가: 원문을 고쳐 판정하면
//   돌려주는 답에서 사용자의 정상 굵게까지 사라진다. 찾는 것은 사본에서, 지우는 것은 원문에서.

/** 판정용 사본에서 걷어낼 강조 표식 — 백틱은 **안 건드린다**(코드 구간 보호가 백틱으로 산다). */
const 강조표식_RE = /[*_]{1,3}/g;
const 낱말_RE = /[\p{L}\p{N}]/u;

interface 판정본 {
  /** 강조 표식을 걷어낸 글 — 정규식은 전부 이 위에서 돈다. */
  글: string;
  /** 판정본 i번째 글자가 **원문 어디**였나. 길이는 글.length. */
  자리: number[];
  /** 원문 j번째 글자가 걷어내진 강조 표식인가 — 뗄 구간을 왼쪽으로 넓힐 때 본다. */
  지움: boolean[];
}

/**
 * 강조 표식을 걷어낸 판정용 사본과 자리표를 만든다.
 *
 * ⚠ **낱말 사이에 낀 것은 안 건드린다**(`api_key`·`a*b`) — 걷어내면 판정본의 인용 토막이
 *   `apikey`가 되어 원천 대조가 **거짓으로 실패**하고, 멀쩡한 인용을 뗀다. 오탐이 미탐보다 무섭다.
 * ⚠ 코드블록·인라인 코드 안도 안 건드린다 — 그 안은 이 파일이 「한 글자도 안 본다」고 약속한 자리다.
 */
function 판정사본만들기(text: string, 보호: readonly [number, number][]): 판정본 {
  const 지움 = new Array<boolean>(text.length).fill(false);
  강조표식_RE.lastIndex = 0;
  let m: RegExpExecArray | null;
  while ((m = 강조표식_RE.exec(text)) !== null) {
    const a = m.index;
    const b = a + m[0].length;
    if (보호.some(([x, y]) => a < y && b > x)) continue;                    // 코드 구간 안
    if (낱말_RE.test(text[a - 1] ?? "") && 낱말_RE.test(text[b] ?? "")) continue; // api_key
    for (let i = a; i < b; i++) 지움[i] = true;
  }
  let 글 = "";
  const 자리: number[] = [];
  for (let i = 0; i < text.length; i++) {
    if (지움[i]) continue;
    글 += text[i];
    자리.push(i);
  }
  return { 글, 자리, 지움 };
}

/**
 * 판정본 자리 → 원문 자리. 끝자리(글.length)는 원문 끝으로 본다.
 * ★ 끝을 이렇게 잡아야 「"제목"**」처럼 **뒤에 남은 강조가 함께 사라진다**(자국이 안 남는다).
 */
function 원문끝(p: 판정본, j: number, 원문길이: number): number {
  return j < p.자리.length ? p.자리[j] : 원문길이;
}

/**
 * 판정본 시작 자리 → 원문 시작 자리. **바로 앞에 붙은 강조 표식은 함께 먹는다**(「**출처:**」의 여는 `**`).
 * ⚠ 단, 그 표식 앞이 글자면 **남의 굵게를 닫는 표식**이라 안 먹는다(「**중요**출처: …」의 `**`).
 *   먹었다가는 앞 문장의 굵게가 짝을 잃는다 — 우리가 안 만든 자국까지 손대는 것이다.
 */
function 원문시작(p: 판정본, j: number, text: string): number {
  let i = j < p.자리.length ? p.자리[j] : text.length;
  while (i > 0 && p.지움[i - 1]) i--;
  return 낱말_RE.test(text[i - 1] ?? "") ? (j < p.자리.length ? p.자리[j] : text.length) : i;
}

/**
 * **원천 글에서도 같은 규칙으로** 강조 표식을 걷는다 — 대조는 답·원천 **양쪽**을 걷어야 성립한다.
 *
 * ★ 왜(2026-09-05 검토관 실측 — J1이 반쪽이었다): 첫 판은 **답에서만** 표식을 걷고 원천은
 *   원문 그대로 두었다. 그런데 제품 내장 지식 코퍼스(knowledge/*.md 18개)는 **전부 마크다운**이라
 *   조각 안에 `**`가 널려 있다(파일마다 5~130회). 모델이 프롬프트가 시키는 대로 조각을
 *   **그대로 옮기면** 답 쪽 `**`만 사라져 대조가 어긋나고, 멀쩡한 인용이 「겹침없음」으로 떨어진다.
 *   실측: 문단 3개를 이어 붙여 실제 조각에 근사한 재료 3,373건 중 **오탐 322건(9.5%)**
 *   — 옛 판은 0건이었다. 답이 그 인용 하나뿐이면 **통째 교체까지** 이어진다.
 * ⚠ 걷은 글은 **대조에만** 쓴다 — 사용자에게 돌려주는 답은 언제나 원문이다(이 파일의 규약).
 * ⚠ 코드 구간은 답 쪽과 똑같이 **안 건드린다**. 안 그러면 코드에 든 `*`가 한쪽에서만 사라져
 *   같은 종류의 어긋남이 코드 인용에서 되살아난다.
 */
export function 강조걷은글(source: string): string {
  const s = String(source ?? "");
  return 판정사본만들기(s, 코드구간(s)).글;
}

// ─────────────────────────────────────────────────────────────────────────────
// ★ J2 — **따옴표 없는 맨몸 출처 표지**: 「(출처: CSOOnline, 2021년 11월 25일)」
//
// ★ 왜(2026-09-05 배포 dist 실측): 이 꼴은 **조각 0건에서도 뗌 0**이었다. 주장_RE가 자리는
//   잡지만 따옴표가 없어 `!번호갈래 && !붙었나`로 그냥 지나쳤다 — 그래서 **지어낸 CSOOnline
//   기사**가 보안 담당자에게 그대로 나갔다. 따옴표가 없다고 주장이 아닌 것이 아니다.
// ⚠ **앞 문장은 안 뗀다**(표지만). 문장까지 떼면 답이 사라진다 — 단정 문제는 계수로 관측한다.

/** 표지 안에서 **이름이 아닌 꼬리** — 연월일·쪽수. 「CSOOnline, 2021년 11월 25일」의 뒷칸이다. */
// ⚠ ISO·점·빗금 날짜(`2021-11-25`·`2023.04.11`)를 **여기서** 걸러야 한다(2026-09-05 검토관).
//   안 걸러 두면 아래 문서id꼴_RE의 하이픈 규칙이 그 날짜를 「문서 이름」으로 보고 판정을 통째로 끈다.
const 날짜꼴_RE = /^\(?\s*\d{4}\s*년?\s*(?:\d{1,2}\s*월)?\s*(?:\d{1,2}\s*일)?\s*\)?$|^\d{1,2}\s*[월일]|^p\.?\s*\d+$|^\d{1,4}\s*(?:쪽|페이지)$|^\d{4}\s*[-./]\s*\d{1,2}(?:\s*[-./]\s*\d{1,2})?$/;

/**
 * **문서를 가리키는 꼴**(파일 이름·문서 id) — 이 판정에서 **뺀다**.
 *
 * ★ 왜 빼나(실측이 시켰다): 실전 답 기록 152개에는 맨몸 표지가 8개 있는데 **전부 우리 제품이
 *   만든 문서 참조**였다 — 「(근거: GIJO_지식_가명정보_처리.md)」·「근거: store:…#0f40a…」·
 *   「(출처: internet-research-2026-07)」. 모델이 지어낸 것이 아니라 **코드가 붙인 근거**다.
 *   이걸 떼면 가드가 제 제품의 정직한 근거 표시를 지운다(오탐 중에서도 가장 나쁜 종류).
 * ⚠ 정직한 한계: 모델이 「(출처: 없는문서.md)」·「(출처: 없는-문서-이름-2026)」처럼 **문서 꼴로**
 *   지어내면 이 예외가 놓친다. 그 자리는 따옴표가 붙은 꼴(표지꼴 → 제목그대로있나)이 맡고,
 *   여기서는 **안 건드리는 쪽**을 고른다.
 * ⚠ 하이픈 규칙은 **소문자 세 마디 이상**이다(2026-09-05 검토관). 옛 규칙 `[a-z0-9]-[a-z0-9]`(i)는
 *   하이픈이 **하나만 있어도** 걸려서, J2가 닫으려던 바로 그 지어낸 기사 표지를 놓쳤다:
 *     · 「(출처: CSO Online, 2021-11-25)」 · 「(출처: Krebs-on-Security)」
 *     · 「(출처: Bleeping Computer, 2023-04-11)」 — 셋 다 **뗌 0**이었다(실측).
 *   대문자가 끼면 매체 이름으로 본다(`Krebs-on-Security`). 문서 id는 소문자다(`internet-research-2026-07`).
 */
const 문서확장자_RE = /\.(?:md|pdf|docx?|xlsx?|pptx?|hwpx?|txt|csv|json)\b|^store:|[A-Za-z0-9가-힣]_[A-Za-z0-9가-힣]/i;
/** 하이픈으로 이은 **문서 id 꼴** — 소문자·숫자 마디가 셋 이상(대소문자를 가린다: `i` 없음). */
const 문서id꼴_RE = /[a-z0-9]+(?:-[a-z0-9]+){2,}/;
function 문서를가리키나(이름: string): boolean {
  return 문서확장자_RE.test(이름) || 문서id꼴_RE.test(이름);
}

/** 표지 속 글에서 **이름만** 골라낸다(날짜·쪽수 꼬리는 이름이 아니다). 쉼표로 나눈다. */
export function 출처이름들(표지속: string): string[] {
  return String(표지속 ?? "").split(/[,，]/).map((s) => s.trim())
    .filter((s) => s.length > 0 && !날짜꼴_RE.test(s));
}

/**
 * 맨몸 출처 표지의 **이름들을 판정한다** — 「뗄까/둘까/안 볼까」.
 *   · "제외" = 문서를 가리키는 꼴이 하나라도 있다 → 판정하지 않는다(위 문서를가리키나 주석).
 *   · "확인"  = 이름이 **하나라도** 원천에 있다 → 둔다(보수적 — 안 뗀다).
 *   · "미확인" = 어느 이름도 원천에서 못 찾았다 → 표지를 뗀다.
 */
function 맨몸출처판정(표지속: string, 원천: readonly string[]): "제외" | "확인" | "미확인" {
  const 이름 = 출처이름들(표지속);
  if (!이름.length) return "제외";
  if (이름.some((n) => 문서를가리키나(n))) return "제외";
  if (이름.every((n) => n.replace(/\s+/g, "").length < 제목하한)) return "제외";
  return 이름.some((n) => 원천.some((c) => 제목그대로있나(n, c))) ? "확인" : "미확인";
}

/**
 * 괄호로 열린 표지의 **나머지** — 「(출처: 」 뒤부터 **짝이 되는** 닫는 괄호까지.
 * 따옴표가 있으면 이 갈래가 아니다. 닫는 글자를 짝으로 받는 이유는 「[출처: 기관]」·「【출처】」처럼
 * 대괄호 표지가 실물이기 때문이다(2026-09-05 K3) — 아무 닫는 괄호나 먹으면 남의 괄호를 닫는다.
 */
const 맨몸괄호꼬리들 = new Map<string, RegExp>();
function 맨몸괄호꼬리_RE(닫는: string): RegExp {
  let re = 맨몸괄호꼬리들.get(닫는);
  if (!re) {
    const c = 정규식글자(닫는);
    re = new RegExp(`^[ \\t]*([^${c}\\n${여는따옴표}${닫는따옴표}]{2,80})[ \\t]*${c}`);
    맨몸괄호꼬리들.set(닫는, re);
  }
  return re;
}
/** 줄 끝까지가 이름인 꼴 — 「출처: CSOOnline」. 표식이 **줄머리**에 있을 때만 본다(아래 주석). */
const 맨몸줄끝_RE = new RegExp(`^[ \\t]*([^\\n${여는따옴표}${닫는따옴표}]{2,80}?)[ \\t]*(?=\\r?\\n|$)`);
/**
 * 날짜 한 덩어리 — **연월일과 ISO·점·빗금을 한 곳에서** 짓는다(2026-09-05 K3).
 * ★ 왜 합쳤나: 줄표 귀속은 「2021년 11월 25일」만 날짜로 봤는데, 배포 dist 실물의 절반이
 *   「— Krebs on Security, 2021-04-29」였다 — 같은 꼴을 두 곳에 다르게 적어 한쪽만 샜다.
 */
const 날짜덩이 =
  `(?:\\d{4}\\s*년(?:[ \\t]*\\d{1,2}\\s*월)?(?:[ \\t]*\\d{1,2}\\s*일)?|\\d{4}\\s*[-./]\\s*\\d{1,2}(?:\\s*[-./]\\s*\\d{1,2})?)`;

/**
 * 「— CSOOnline, 2021년 11월 25일」·「— Krebs on Security, 2021-04-29」 — 표식 낱말이 아예 없는
 * **줄표 귀속** 꼴.
 * ⚠ 날짜를 **필수**로 요구한다. 안 그러면 「— 자세한 내용은 …」 같은 평범한 줄표 문장이 전부 걸린다.
 */
const 줄표출처_RE = new RegExp(
  `(?:^|\\n)[ \\t]*[—–][ \\t]*([^,，\\n${여는따옴표}${닫는따옴표}]{2,40})[ \\t]*[,，][ \\t]*(${날짜덩이})`,
  "g",
);

/**
 * ★ K1 — **귀속 꼬리**: 인용·표지를 뗀 **바로 뒤에 붙어 남는** 「누가·언제」.
 *
 * ★ 왜(2026-09-05 라이브 실측): 「출처: "제목" by Brian Krebs, 2021-04-29.」에서 따옴표 표지만 떼니
 *   답에 「 by Brian Krebs, 2021-04-29.」가 그대로 남았다. 이건 그냥 지저분한 게 아니라 **없는 기사의
 *   기자 이름과 날짜**라, 담당자는 출처가 있었다고 읽는다 — 표지를 뗀 값어치를 통째로 깎는다.
 *   배포 dist 재현 3꼴이 전부 이 부류였다(「출처: "제목" by 사람, 날짜」·「(출처: 제목) by 사람, 날짜」·
 *   「**출처:** "제목" by 사람」).
 * ⚠ **원천에 그 이름이 있으면 안 뗀다** — 참인 귀속을 지우는 것은 지어낸 출처를 남기는 것만큼 나쁘다.
 * ⚠ 이름은 **대문자·한글로 시작**해야 한다. 소문자로 시작하면 「by design 원칙」 같은 평범한 말이
 *   귀속으로 읽힌다. 그리고 줄표 갈래는 **날짜를 필수**로 둔다(줄표출처_RE와 같은 이유).
 * ⚠ **날짜만 있는 두 갈래는 절 경계를 요구한다**(2026-09-05 검토관 — 첫 판의 실결함). 경계를 안 걸었더니
 *   뒤 문장의 문법 성분인 날짜를 잘라 내고 **조사만 남은 깨진 절**을 만들었다(실측):
 *     「, 2024년 3월에 개정되었습니다.」 → 「에 개정되었습니다.」
 *     「 (2024-03-01) 이후 적용됩니다.」 → 「 이후 적용됩니다.」
 *   옛 판은 날짜를 남겨 읽히기라도 했는데, 새 판은 **기준점을 지운 채 단정만** 남겼다 —
 *   이 파일이 스스로 경고한 「출처만 사라지고 주장은 제품 단정으로 남아 더 나빠졌다」의 되풀이다.
 * ⚠ by·줄표 갈래에는 **안 건다**. 거기서는 이름이 곧 해악(없는 기자 이름)이라 뒤가 이어지더라도
 *   떼는 쪽이 낫고, 경계를 걸면 「by 사람, 날짜 기사입니다.」에서 아무것도 못 떼게 된다.
 */
const 귀속이름 = `[A-Z가-힣][^,，\\n(（)）\\[\\]【】${여는따옴표}${닫는따옴표}]{0,49}`;
/**
 * **절 경계** — 날짜 뒤가 문장·줄·괄호의 끝인가. 날짜만 있는 두 갈래에만 건다(위 ⚠).
 * 마침표·물음표·닫는 괄호·줄바꿈·글 끝만 경계로 본다 — 한국어 조사(「에」·「부터」)나 이어지는 말이
 * 오면 그 날짜는 **귀속이 아니라 뒤 문장의 문법 성분**이다.
 */
const 절경계 = `(?=[ \\t]*(?:[.。!?)）\\]】》」』]|\\r?\\n|$))`;
const 귀속꼬리_RE = new RegExp(
  `^[ \\t]*(?:` +
    `[Bb]y[ \\t]+(${귀속이름})(?:[ \\t]*[,，][ \\t]*${날짜덩이})?` +
    `|[—–][ \\t]*(${귀속이름})[ \\t]*[,，][ \\t]*${날짜덩이}` +
    `|[(（][ \\t]*(${날짜덩이})[ \\t]*[)）]${절경계}` +
    `|[,，][ \\t]*(${날짜덩이})${절경계}` +
  `)`,
);

/**
 * 뗀 자리 **바로 뒤**의 귀속 꼬리 길이(없으면 0). 문장 마침표·가운뎃점은 남긴다 — 우리가 안 만든 자국이다.
 *
 * ★ L1(2026-09-05 실측) — **마침표가 겹친다.** 위 「남긴다」가 무조건이라, 원문 문장이 이미
 *   마침표로 끝난 자리에서는 남긴 마침표가 **하나 더** 붙었다(실측 2꼴):
 *     「…적용합니다. 출처: "제목" by Brian Krebs, 2021-04-29.」 → 「…적용합니다..」
 *     (뒤에 문장이 더 있으면)                                   → 「…적용합니다.. 다음 문장입니다.」
 *   자국손질의 `[ \t]+([.,;:])` 정리가 사이 공백까지 접어서, 「. .」이 아니라 딱 붙은 「..」로 나간다 —
 *   사용자 눈에는 **오타**로 보이고, 인용을 뗀 자리라는 사실만 지저분하게 드러난다.
 * @param 앞 뗄 구간 **바로 앞**의 글(끝쪽 몇 글자면 된다). 여기가 이미 문장부호(`.`·`。`·`!`·`?`)로
 *   끝났으면 문장은 이미 닫혔으므로 **꼬리 쪽 마침표를 남기지 않는다**(함께 뗀다).
 *   반대로 문장부호가 아니면 종전대로 마침표 하나를 남겨 **문장을 닫는다** —
 *   「…적용합니다 출처: "제목" by …, 2021-04-29.」는 마침표를 뺏기면 문장이 안 끝난다.
 *   ⚠ 가운뎃점은 앞이 문장부호여도 **안 먹는다**(이 함수가 원래 지키던 「우리가 안 만든 자국」).
 */
export function 귀속꼬리길이(tail: string, 원천: readonly string[], 앞 = ""): number {
  const m = 귀속꼬리_RE.exec(String(tail ?? ""));
  if (!m) return 0;
  // ★ 날짜만 있는 갈래도 **원천 대조를 탄다**(2026-09-05 검토관). 첫 판은 그 갈래에 캡처 그룹이 없어
  //   `이름 === ""`이 되고 아래 보호 if가 통째로 건너뛰어져, **원천에 그대로 있는 참인 날짜까지** 지웠다
  //   (실측: 원천에 「2021-04-29」가 있어도 13자 제거). 「참인 귀속을 지우는 것은 지어낸 출처를 남기는
  //   것만큼 나쁘다」는 약속이 코드의 절반에만 있던 자리다 — 날짜를 그 갈래의 「이름」으로 삼는다.
  const 이름 = (m[1] ?? m[2] ?? m[3] ?? m[4] ?? "").replace(/[ \t.·]+$/, "").trim();
  // 원천에 그 이름이 실제로 있으면 **참인 귀속**이다 — 안 뗀다.
  if (이름 && 원천.some((c) => 제목그대로있나(이름, c))) return 0;
  let 길이 = m[0].length;
  while (길이 > 0 && /[ \t.·]/.test(tail[길이 - 1])) 길이 -= 1;
  // ★ L1 — 앞이 이미 문장을 닫았으면 꼬리의 마침표는 **덤**이다. 함께 먹는다(위 @param 앞).
  //   뒤따르는 공백은 안 먹는다 — 먹으면 다음 문장이 앞 문장에 들러붙는다(「…합니다.다음 문장」).
  if (/[.。!?！？]$/.test(String(앞 ?? "").replace(/[ \t]+$/, ""))) {
    const 덤 = /^[ \t]*[.。]+/.exec(String(tail ?? "").slice(길이));
    if (덤) 길이 += 덤[0].length;
  }
  return 길이;
}

/**
 * 「참고」처럼 **약한 낱말**로 연 맨몸 표지에서 요구하는 이름 꼴 — 바깥 기관·매체 이름인가.
 *
 * ★ 왜 필요한가: 「(참고: CSOOnline)」은 지어낸 출처지만 「(참고: 위 표)」·「(참고: 담당자 확인)」은
 *   **정당한 주석**이다. 「출처|원문」에만 맨몸 판정을 걸어 둔 좁힘이 바로 그 오탐을 막던 것이라,
 *   낱말을 넓히는 대신 **이름이 바깥 기관·매체처럼 생겼을 때만** 본다(막는 목록이 아니라 **허용 목록**).
 * ⚠ **라틴 낱말이 하나 끼었다고 기관이 아니다**(2026-09-05 검토관 — 첫 판의 실결함).
 *   `[A-Z]{2,}|[A-Z][a-z]` 하나만 보던 첫 판은 보안 제품에서 **가장 흔한 정상 주석**을 통째로
 *   지웠다(실측 7꼴, 옛 판은 한 글자도 안 건드렸다): 「(참고: Nessus 스캔 결과)」·「(참고: Windows
 *   이벤트 뷰어)」·「(참고: Active Directory 그룹 정책)」·「(참고: AWS S3 버킷 설정)」·
 *   「(참고: CVE-2021-44228 영향)」. 줄머리 꼴은 **그 줄이 통째로** 사라졌고, 그 줄이 답의 전부면
 *   근거불일치안내로 통째교체까지 갔다. 게다가 그 삭제가 llm:event(kind=cite)·감독 화면 ✂에
 *   「근거 없는 인용 제거」로 실려 **숫자까지 거짓**이 된다.
 * ⚠ 커밋이 오탐 반대편으로 든 10꼴이 **전부 한글 전용**이라 이 부류를 원리상 못 봤다 — 반대편 표본이
 *   한 갈래로 쏠려 있으면 「0/10 통과」는 아무것도 증명하지 않는다.
 * 규칙(둘 중 하나):
 *   ⓐ **한글이 한 글자도 없는** 라틴 이름 — 낱말 4개 이하, 3자 이상 낱말이 전부 대문자로 시작,
 *      그리고 낱말이 하나뿐이면 **합성 매체 이름**(CSOOnline·TechCrunch)만 본다.
 *      한글이 섞이면 그 라틴 낱말은 매체가 아니라 **제품·규격 이름**이다(위 오탐 전부).
 *   ⓑ 한국어 기관·매체 **꼬리 글자**로 끝난다(…원·청·센터·…·뉴스·신문·일보·타임스·저널).
 * ⚠ 「회사·조사·부서」처럼 흔한 꼬리 글자(사·부·회)는 일부러 뺐다 — 「내부 조사」가 기관이 되어 버린다.
 * ⚠ 정직한 한계 — 「KISA」·「AWS」처럼 **낱말 하나짜리 대문자 약자**는 안 뗀다(미탐). 제품 이름과
 *   기관 약자를 글자만으로 못 가르는데, 이 자리에서는 오탐이 미탐보다 나쁘다(위 실측이 그 값이다).
 */
/**
 * 여는 글자로 열린 괄호가 **그 안에서 닫히는가** — 깊이를 세어 본다(2026-09-05 검토관).
 * 「【출처】」·「[출처]:」는 참, 「[출처 [1]:」은 거짓이다 — 안쪽 번호 대괄호의 닫는 글자에 안 속는다.
 */
function 자기안에서닫히나(s: string, 여는: string, 닫는: string): boolean {
  let 깊이 = 0;
  for (const ch of s) {
    if (ch === 여는) 깊이 += 1;
    else if (ch === 닫는) { 깊이 -= 1; if (깊이 <= 0) return true; }
  }
  return false;
}

const 한국기관꼬리_RE = /(?:원|청|센터|협회|위원회|연구소|재단|공단|진흥원|보안원|뉴스|신문|일보|타임스|저널)$/;
export function 기관이름인가(이름: string): boolean {
  const s = String(이름 ?? "").trim();
  if (!s) return false;
  if (한국기관꼬리_RE.test(s)) return true;
  // 한글이 한 글자라도 섞이면 매체 이름이 아니다 — 라틴 낱말은 **제품·규격 이름**으로 쓰인 것이다.
  if (/[가-힣ㄱ-ㅎㅏ-ㅣ]/.test(s)) return false;
  const 낱말 = s.split(/[ \t]+/).filter(Boolean);
  if (!낱말.length || 낱말.length > 4) return false;
  const 알맹이 = 낱말.filter((w) => w.replace(/[^A-Za-z]/g, "").length >= 3);
  if (!알맹이.length) return false;                       // 「S3」·「AI」만 있는 토막은 이름이 아니다
  if (!알맹이.every((w) => /^[A-Z]/.test(w))) return false; // 「See the admin guide」를 막는다
  if (낱말.length >= 2) return true;                       // 「CSO Online」·「Krebs on Security」
  // 한 낱말이면 **합성 매체 이름**만 본다 — 「CSOOnline」·「TechCrunch」는 매체고,
  //   「Nessus」·「Fortinet」·「Windows」는 제품이다(맨 낱말 하나로는 못 가른다면 안 뗀다).
  const w = 낱말[0];
  return /[a-z][A-Z]/.test(w) || (w.replace(/[^A-Z]/g, "").length >= 2 && /[a-z]/.test(w));
}

