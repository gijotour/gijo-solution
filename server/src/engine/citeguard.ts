/**
 * 답에서 **수치로 보지 않을 자리** — client/src/renderer/pages/chatparts.js 추정치제외_RE의 사본.
 * ⚠ 한 글자도 다르면 짝 시험(citeguard.test.ts)이 빨개진다. 고칠 때는 **두 곳을 함께** 고친다.
 */
export const 실적수치제외_RE = /`[^`\n]{0,200}`|\[[^\]\n]{0,200}\]\([^)\s\n]{0,500}\)|https?:\/\/[^\s)\]]{1,500}|CVE-\d{4}-\d{3,7}|CWE-\d+|CVSS\s*[\d.]+|\bKEV[-\s]?\d{4}-\d{1,5}\b|\d{4}[-.\/]\d{1,2}[-.\/]\d{1,2}|\d{4}\s*년(?:\s*\d{1,2}\s*월(?:\s*\d{1,2}\s*일)?)?|\d{1,2}\s*월\s*\d{1,2}\s*일|\d{1,2}\s*시\s*\d{1,2}\s*분(?:\s*\d{1,2}\s*초)?|\d{1,2}:\d{2}(?::\d{2})?|\b(?:TLS|SSL|HTTP)\s*v?\d+(?:\.\d+)+|[A-Za-z][A-Za-z0-9_+\-]*\s*v?\d+\.\d+(?:\.\d+)*|\bv?\d+\.\d+\.\d+\b|(?:^|\n)[ \t]*\d{1,3}\.(?=[ \t])|\[\d+\]|\bISO\s?\d+\b/gi;

/** 백분율 — 「82.3%」·「3,200 퍼센트」. 숫자 부분만 1번 자리로 받는다. */
const 백분율_RE = /(\d{1,3}(?:,\d{3})+|\d+(?:\.\d+)?)\s*(?:%|퍼센트)/g;
/**
 * 「…율/률」 **바로 뒤**의 맨수 — 「이수율은 82.3입니다」처럼 기호 없이 쓴 꼴.
 * ⚠ 단위가 붙으면 안 잡는다(「조치율 상위 3개」의 3) — 그건 셈이지 비율이 아니다.
 */
// ⚠ 뒤가 `.`·`%`·숫자면 **안 잡는다**(짝 시험이 잡은 실수): 「이수율은 82.3%」에서 정규식이
//   뒤로 물러나 「82」만 떼어 갔다 — 없는 수치 목록에 82.3과 82가 **둘 다** 실려, 담당자가
//   읽을 사유 문자열이 거짓이 된다. 소수·백분율은 위 백분율_RE가 이미 통째로 잡는다.
const 비율맨수_RE = /(?:율|률)\s*(?:은|는|이|가)?\s*(?:약\s*)?(\d{1,3})(?![\d.%]|\s*(?:개|건|명|위|번|년|월|일|시|분|초|퍼센트|배|회|차|가지|종|조|점|단계|달러|원))/g;

/** 대조용 정규화 — 공백과 자리수 쉼표를 지운다(원천이 「3,200」·「3200」 어느 꼴이든 걸린다). */
const 수치납작 = (s: string): string => String(s ?? "").replace(/\s+/g, "").replace(/,/g, "");

/**
 * 원천에서 **날짜·시각·판번호를 가린다** — 「2026-09-05」의 05, 「5.83.0」의 5가 한 자리 백분율의
 * 근거처럼 보이는 것을 막는다. 값 대조로 바꾸면서 「05 = 5」·「5.0 = 5」가 성립해 생긴 샘이다.
 *
 * 실측(2026-09-06, 저장소 md 조각 2,000여 개·400회 무작위 4조각): 지어낸 한 자리 값이 그냥 통과할
 * 확률 93.5% → **85.0%**, 10~29 32.3% → 27.3%, 코퍼스 오탐은 **0건 그대로**.
 * ⚠ 답 쪽 제외 목록(실적수치제외_RE) **전체로** 가려도 봤다 — 그건 진짜 백분율까지 먹어 코퍼스
 *   오탐이 0 → 4건(2.2%)으로 늘었다. 오탐이 미탐보다 비싸다는 잣대로 **재고 버린 판**이다.
 * ⚠ 「·」로 덮는다(공백 아님) — 납작하게 눌러도 이웃 숫자와 안 붙게.
 */
const 날짜판번호_RE = /\d{4}[-.\/]\d{1,2}[-.\/]\d{1,2}|\d{1,2}:\d{2}(?::\d{2})?|\bv?\d+\.\d+\.\d+\b/g;
const 표식가림 = (s: string): string => s.replace(날짜판번호_RE, (m) => "·".repeat(m.length));

/** 원천에서 집는 **수 토큰** — 최대로 물어 집는다(「150」은 150 하나 · 「1,200」은 1200 · 「82.30」은 82.3). */
const 원천수_RE = /\d+(?:,\d{3})*(?:\.\d+)?/g;

/**
 * 그 수가 이 원천에 **수로서** 있나 — 남의 숫자 속에 묻힌 것은 안 친다.
 *
 * ★ 왜 맨 부분문자열이면 안 되나(2026-09-06 운영 라이브 실측): 「보안 인식 교육을 받은 직원
 *   비중」에 모델이 **50%**를 지어냈는데, 조각 어딘가의 「150」·「2050」에 「50」이 들어 있어
 *   「있음」으로 통과했다. 짧은 수(한두 자리)일수록 남의 숫자 안에 늘 들어 있다 —
 *   그 잣대로는 관문이 원리상 헛돈다.
 * → 원천에서 **수 토큰을 통째로 집어**(원천수_RE) Number로 견준다 — 「150」은 150 하나이지 「50」이 아니다.
 *
 * ★ 왜 글자가 아니라 **값**인가(2026-09-06 검토 실측): 첫 판은 글자(부분문자열 + 앞뒤 경계)로 쟀는데,
 *   그러면 원천의 「50.0%」·「74.20%」가 답의 「50%」·「74.2%」와 **안 걸린다**. 리포트·스캔 산출물은
 *   소수 자리를 맞춰 적고(100.0%·99.90%) 모델은 반올림해 옮긴다 — 참인 숫자에 「모델 추정치」가
 *   붙는 쪽이라 값이 비싸다(아래 숫자가원천에있나 머리말의 ⚠⚠ 참고). Number 동치는 그 짝을 잇고,
 *   「3 vs 3.5」처럼 **값이 다른** 짝은 그대로 가른다.
 */
function 수로서있나(원천: string, 수: string): boolean {
  const 값 = Number(수);
  if (!Number.isFinite(값)) return false;
  원천수_RE.lastIndex = 0;
  let m: RegExpExecArray | null;
  while ((m = 원천수_RE.exec(원천)) !== null) {
    if (Number(m[0].replace(/,/g, "")) === 값) return true;
  }
  return false;
}

/**
 * 답에서 뽑은 실적형 수치 **한 자리** — 대조용 값과 **답에 적힌 그대로의 꼴**을 함께 든다.
 *
 * ★ 왜 표면을 따로 드나(2026-09-06 · 시안 mockups/dim-range): 값만으로는 화면이 **어느 글자를**
 *   옅게 할지 못 고른다. 「12.5」는 답에서 "12.5%"로도 "12.5건"으로도 보일 수 있고, 화면(chatparts)이
 *   집는 후보 조각은 **단위까지 붙은 글자**다. 값 하나만 실어 보내면 옅힘 범위를 좁힐 수가 없어
 *   결국 답 전체를 회색으로 칠하게 된다 — 참인 숫자까지 「모델 추정치」가 되는, 이 관문이 막으려는
 *   바로 그 해악이다(숫자가원천에있나 머리말 ⚠⚠).
 */
export interface 수치자리 {
  /** 대조용 납작본(「3,200」→「3200」) — 원천 대조·중복 제거는 이 값으로 한다. */
  값: string;
  /** 답에 적힌 그대로(「12.5%」·「3,200 퍼센트」·「82」) — 화면이 이 글자로 조각을 고른다. */
  표면: string;
}

/**
 * 답에서 **사내 실적형 수치**(백분율)를 자리째 뽑는다 — 제외 구간과 겹치는 것은 버린다.
 *
 * ⚠ 표면은 m[0]이 아니라 **수가 시작하는 자리부터**다(시안은 m[0]이라 적었다 — 실물이 다르다).
 *   비율맨수_RE의 m[0]에는 앞말이 붙는다: "이수율은 82"가 통째로 m[0]다. 그 글자를 표면으로 실으면
 *   ⓐ 배너 꼬리에 「사내 자료에 없는 수치: 이수율은 82」라고 적히고 ⓑ 화면이 집는 후보 조각("82")과
 *   **영영 안 맞아** 아무것도 안 옅어진다. 백분율_RE는 수로 시작하니 이 자름이 m[0]과 같다.
 *   (m[0]의 앞말은 「율/률+조사+약」뿐이라 숫자가 없다 — indexOf가 엉뚱한 자리를 집을 수 없다.)
 * ⚠ 중복은 **값으로** 없앤다 — 같은 값의 다른 꼴(「12.5%」와 「12.5 퍼센트」)이 한 답에 있으면
 *   먼저 나온 꼴만 실린다. 뒤엣것은 화면에서 진하게 남는다(덜 옅어지는 쪽 = 안전한 실패).
 */
export function 실적수치자리(answer: string): 수치자리[] {
  const s = String(answer ?? "");
  if (!s) return [];
  const 제외: [number, number][] = [];
  실적수치제외_RE.lastIndex = 0;
  let m: RegExpExecArray | null;
  while ((m = 실적수치제외_RE.exec(s)) !== null) {
    제외.push([m.index, m.index + m[0].length]);
    if (m.index === 실적수치제외_RE.lastIndex) 실적수치제외_RE.lastIndex++;
  }
  const out: 수치자리[] = [];
  for (const re of [백분율_RE, 비율맨수_RE]) {
    re.lastIndex = 0;
    while ((m = re.exec(s)) !== null) {
      const a = m.index, b = a + m[0].length;
      if (m.index === re.lastIndex) re.lastIndex++;
      if (제외.some(([x, y]) => a < y && b > x)) continue;
      const 값 = 수치납작(m[1]);
      if (!값 || out.some((o) => o.값 === 값)) continue;
      const 수자리 = m[0].indexOf(m[1]);
      out.push({ 값, 표면: 수자리 > 0 ? m[0].slice(수자리) : m[0] });
    }
  }
  return out;
}

/**
 * 답에서 **사내 실적형 수치**(백분율)를 뽑는다 — 제외 구간과 겹치는 것은 버린다.
 * 돌려주는 것은 **숫자 부분**(「82.3」)이다. 기호·단위는 원천마다 달라 대조에 방해가 된다.
 *
 * ⚠ 실제 일은 실적수치자리()가 한다 — 여기서 값만 벗겨 낸다. 두 벌로 적지 않는다.
 *   (이 이름·꼴을 그대로 두는 이유: dispatcher의 수치있음과 짝 시험 numgrounding.test가
 *    string[]로 읽는다. 표면이 필요한 자리만 실적수치자리를 부른다.)
 */
export function 실적수치뽑기(answer: string): string[] {
  return 실적수치자리(answer).map((x) => x.값);
}

/** 숫자 접지 판정 — 「해당없음」=볼 수치가 없다 · 「있음」=하나라도 원천에 있다 · 「없음」=전부 없다. */
export interface 숫자접지 {
  판정: "해당없음" | "있음" | "없음";
  /** 답에서 뽑은 실적형 수치(숫자 부분만) */
  수치: string[];
  /** 그중 **어느 원천에서도 못 찾은 것** */
  없는것: string[];
  /**
   * 없는것을 **답에 적힌 그대로의 꼴**로(「12.5%」). 없는것과 자리·개수가 1:1로 맞는다.
   * 배너 꼬리와 화면 옅힘 범위가 이 글자를 쓴다 — 값만으로는 어느 글자인지 못 가린다.
   */
  없는것표면: string[];
}

/**
 * 답의 실적형 수치가 **우리가 준 글 안에 실제로 있나** — guardCitations와 같은 잣대(글자로 본다).
 *
 * ⚠ 수로서 있는 자리만 센다(위 수로서있나) — 「150」 속의 「50」은 근거가 아니다.
 *   그래도 같은 수가 딱 한 번만 나오면 「있음」이다 — 그 수가 **그 뜻으로** 쓰였는지까지는 글자로 못 가른다(정직한 한계).
 * ⚠ 조각이 null이면(RAG 미실행) 판정하지 않는다 — guardCitations와 같은 규율.
 * ⚠ 규정 숫자(신고 72시간·보관 3년·과징금 3%)는 **조각에 그대로 있으므로 통과한다.**
 *   조각이 표·그림이라 본문에 숫자가 없는 경우는 원리상 못 가른다 — 그 답은 「없음」이 되어 배너가 붙는다.
 * ⚠⚠ **오탐은 공짜가 아니다** — 「실패 방향이 안전하다」고 적지 말 것(2026-09-06 검토 지적). 표식이
 *   하나 붙으면 화면(chatparts.dimEstimates)은 **답 전체의 숫자를 옅게** 그린다. 참인 숫자가
 *   추정치로 보이는 것은 noevidence.ts가 「없던 거짓말이 새로 생긴다」고 부르는 바로 그 해악이다 —
 *   이 관문이 막으려는 것의 정반대다. 그래서 오탐은 **줄일 수 있으면 줄인다**(값 대조·원문 병행이
 *   그 값이고, 짝 시험이 코퍼스로 그것을 지킨다).
 * ⚠ 이 관문이 도는 **정도가 자릿수에 크게 좌우된다**(실측 2026-09-06, 저장소 md 조각 4개 묶음 400회):
 *   지어낸 값이 그냥 통과할 확률 — 한 자리 83% · 10~29 25% · 30~59 10% · 60~100 7% · 소수 한 자리 2%.
 *   짧은 수는 어느 글에나 있어 원리상 못 가른다. **소수·큰 수에서 잘 돌고 한 자리에서는 거의 안 돈다** —
 *   「수 단위로 본다」를 「고르게 돈다」로 읽지 말 것.
 * ⚠⚠ **그 7%가 실제로 나갔다**(2026-09-06 운영 라이브 실측 — 이 한계의 실물 사례다).
 *   물음 「사내 임직원 보안서약서 제출률」에 「제출률은 92%입니다」가 **배너 없이** 나갔다.
 *   운영 /api/memory/query로 같은 물음의 조각 8건을 받아 확인한 결과:
 *     · 8건 어디에도 「제출률」이라는 낱말이 **0건**이다(제품은 이 지표를 세지도 않는다).
 *     · 그런데 2번 조각(KISA 침해사고 통계 표)에 「(랜섬웨어) … (92) (10.2%)」가 있다.
 *       **92는 랜섬웨어 침해사고 건수**이지 제출률이 아니다 — 백분율도 아니고 사내 값도 아니다.
 *     · 수로서있나는 「92라는 수 토큰이 원천에 있나」만 보므로 **참으로 통과**했다.
 *   즉 관문이 고장 난 것이 아니라, 위 머리말이 이미 적어 둔 한계(「그 수가 **그 뜻으로** 쓰였는지까지는
 *   글자로 못 가른다」)가 그대로 실현된 것이다. 숫자 층·근거 출처 층에서는 원리상 못 닫는다 —
 *   **이 부류는 라우팅에서 막는다**(agentloop FORCED_INTENTS[83] 사내 실적률 → kpi_status →
 *   「아직 집계하지 않습니다」). 여기에 뜻 대조를 얹으려 하지 말 것: 그러려면 표의 열 이름과 답의
 *   주어를 잇는 판이 필요하고, 그건 이 관문이 아니라 온톨로지의 일이다.
 */
export function 숫자가원천에있나(
  answer: string,
  chunks: string[] | null | undefined,
  추가원천?: readonly (string | null | undefined)[],
): 숫자접지 {
  // 근거를 모르는 자리(RAG 미실행)에서는 판정하지 않는다 — guardCitations와 같은 규율.
  if (chunks === null || chunks === undefined) return { 판정: "해당없음", 수치: [], 없는것: [], 없는것표면: [] };
  const 자리 = 실적수치자리(answer);
  const 수치 = 자리.map((x) => x.값);
  if (!수치.length) return { 판정: "해당없음", 수치: [], 없는것: [], 없는것표면: [] };
  const 원천 = [
    ...chunks.map((c) => String(c ?? "")),
    ...(추가원천 ?? []).map((c) => String(c ?? "")),
    // ⚠ 원문과 납작본을 **둘 다** 넣는다(2026-09-06 검토 실측). 납작본만 보면 공백·줄바꿈을 지우면서
    //   없던 숫자 이웃이 생겨 — 「이수율 50 <줄바꿈> 2026년」이 「…502026…」이 된다 — 원천에 멀쩡히
    //   적힌 값이 「없음」이 된다. 반대로 원문만 보면 표 꼴(「8 2 . 5 %」)을 못 잇는다. 둘 다 보면
    //   양쪽이 걸리고, 라이브 사고(「150」 속의 50)는 어느 쪽에서도 안 걸린다 — 실측으로 확인했다.
  ].filter(Boolean).flatMap((c) => { const g = 표식가림(c); return [g, 수치납작(g)]; });
  const 없는자리 = 자리.filter((x) => !원천.some((s) => 수로서있나(s, x.값)));
  const 없는것 = 없는자리.map((x) => x.값);
  // **전부 없을 때만** 「없음」 — 하나라도 원천에 있으면 답 전체를 추정치라 부를 수 없다(머리글 참고).
  // ⚠ 「있음」이어도 없는것이 비어 있지 않을 수 있다(부분 접지) — 그 자리를 llm.ts가 배너 꼬리로
  //   적고 화면이 그 글자만 옅게 한다. 판정 세 값의 뜻은 한 글자도 안 바뀌었다.
  return { 판정: 없는것.length === 수치.length ? "없음" : "있음", 수치, 없는것, 없는것표면: 없는자리.map((x) => x.표면) };
}
