/** 겹침 창 크기 — 이 값이 「20자」 잣대의 단일 출처다(사유 문자열도 이 상수로 짓는다). */
export const OVERLAP_CHARS = 20;

/** 겹침 창을 미는 폭. overlap20(tools/distill-precheck.mjs)과 **같은 4칸**이라야 답이 갈리지 않는다. */
export const 겹침걸음 = 4;

/**
 * 인용 토막을 **대조할 수 있는** 최소 길이 = 23자(= 창 20 + 걸음 4 − 1).
 *
 * ★ 왜 20이 아닌가(2026-09-05 검토관 실측): 창은 20자인데 걸음이 4칸이라 원천의 **4의 배수
 *   자리에서만** 창이 시작한다. 그래서 원문을 글자 하나 안 틀리고 옮긴 짧은 인용이 자리에 따라
 *   「겹침없음」으로 떨어졌다 — 무공백 20자 6/23(26%) · 21자 11/22(50%) · 22자 16/21(76%) ·
 *   **23자 20/20(100%)** · 24자 19/19(100%).
 *   23자부터는 [p, p+L−20] 구간에 4의 배수가 반드시 하나 있어 빠짐없이 잡힌다.
 * ⚠ 걸음을 1로 줄이는 쪽은 **일부러 안 골랐다** — 근거겹침은 overlap20(증류기)·관문 ⑧이 함께
 *   쓰는 잣대라, 여기서 걸음을 바꾸면 사다리 회전 1~4의 옛 판정과 값이 갈린다. 재는 자를
 *   흔드는 대신 **판정 하한을 올려** 대조 못 할 것을 안 건드리는 쪽이 안전하다.
 */
export const 대조하한 = OVERLAP_CHARS + 겹침걸음 - 1;

/**
 * 짧은 인용을 **글자 그대로** 대조하는 최소 길이 = 무공백 8자 (2026-09-05 구멍 ② 수리).
 *
 * ★ 왜 필요한가(라이브 실측): 23자 아래는 아예 판정을 안 해서, 없는 사고사례가
 *   `- **"서버 취약점 잠시 무시하다가 다시 발견"** (출처: "서버 취약점 관리 실패 사례", 2023년 4월)`
 *   처럼 **출처·연월까지 붙어** 그대로 나갔다. 계수기도 0이라 감독 화면에는 「지어낸 인용 없음」으로
 *   읽혔다 — 조용한 고장이다.
 * ★ 왜 겹침(창 20·걸음 4)이 아니라 **무공백 verbatim 부분문자열**인가: 창이 20자라 그보다 짧은
 *   토막은 원리상 못 본다. 짧은 토막에는 「원문 그대로 옮겼나」만 물으면 되므로 창이 필요 없고,
 *   무엇보다 **근거겹침의 걸음을 안 건드린다** — 사다리 회전 1~4의 옛 판정이 그대로 산다.
 * ⚠ 8자 미만은 여전히 판정하지 않는다. 「"MFA 필수"」(무공백 6자)처럼 짧은 말은 원천에 없어도
 *   지어낸 인용이라 부를 수 없다(일반 용어). 대조 못 할 것은 안 건드린다 — 이 파일의 원칙 그대로.
 */
export const 짧은대조하한 = 8;

/**
 * 답이 근거 본문과 20자 이상 그대로 겹치는가 — 겹친 창을 돌려준다(없으면 null). 공백은 무시.
 * ⚠ 사본이 셋이다(여기 · tools/distill-precheck.mjs overlap20 · gates.mjs가 그것을 import).
 *   distillprecheck.test.ts:38이 두 함수가 **같은 답**을 내는지 대조한다 — 규칙을 고치면 함께 고친다.
 * ⚠ 걸음이 4칸이라 「20자를 그대로 옮겼는데 못 찾는」 자리가 있다 — 그래서 이 함수를 **판정**에
 *   쓸 때는 위 `대조하한`(23자)을 함께 걸어야 한다.
 */
export function 근거겹침(answer: string, sourceText: string): string | null {
  const a = String(answer ?? "").replace(/\s+/g, "");
  const s = String(sourceText ?? "").replace(/\s+/g, "");
  if (a.length < OVERLAP_CHARS || s.length < OVERLAP_CHARS) return null;
  for (let i = 0; i + OVERLAP_CHARS <= s.length; i += 겹침걸음) {
    const w = s.slice(i, i + OVERLAP_CHARS);
    if (a.includes(w)) return w;
  }
  return null;
}

/** 생략 표기(…·⋯·「...」) — 원문을 줄여 옮긴 자리다. 대조할 때는 나눠서 본다. */
const 말줄임_RE = /[…⋯]|\.{3,}/;
/** 생략으로 나뉜 토막을 대조할 최소 길이 — 이보다 짧은 토막은 판정하지 않는다. */
const 생략토막하한 = 4;

/**
 * 인용 토막이 **이 원천 안에 실제로 있나** — 길이에 따라 잣대를 가른다(단일 판정 창구).
 *   · 23자(대조하한) 이상 → 근거겹침(창 20·걸음 4). **옛 판정을 글자 그대로 보존**한다.
 *   · 8~22자             → 공백 무시 verbatim 부분문자열. 창보다 짧아 겹침으로는 못 본다.
 *   · 8자 미만           → 늘 false. 부르는 쪽이 `대조가능`으로 먼저 걸러 **판정 자체를 안 한다**.
 */
export function 원천에있나(quote: string, source: string): boolean {
  const q = String(quote ?? "").replace(/\s+/g, "");
  if (q.length >= 대조하한) return 근거겹침(quote, source) !== null;
  if (q.length < 짧은대조하한) return false;
  const s = String(source ?? "").replace(/\s+/g, "");
  if (s.includes(q)) return true;
  // 말줄임표는 **생략 표기**다 — 「"설치 직후 변경해야 한다…"」는 원문 그대로인데도 「…」 한 글자
  //   때문에 통째로 떨어졌다(2026-09-05 검토관 실측 — 옛 판에는 없던 새 오탐이고, 답이 그 인용
  //   하나뿐이면 통째 교체까지 이어져 **참인 답이 「자료 없음」으로** 바뀐다). 나눠서 조각마다 본다.
  if (!말줄임_RE.test(q)) return false;
  const 토막 = q.split(말줄임_RE).filter(Boolean);
  const 볼것 = 토막.filter((t) => t.length >= 생략토막하한);
  // 조각이 전부 너무 짧으면 대조할 수 없다 — 이 파일의 원칙대로 **안 건드린다**(있다고 본다).
  return 볼것.length === 0 || 볼것.every((t) => s.includes(t));
}

/** 출처 **제목**을 대조할 최소 길이 — 제목은 흔한 말이 아니라 **이름**이라 하한이 낮다. */
export const 제목하한 = 2;

/**
 * 출처 **제목**이 이 원천 글에 그대로 있나 — 짧은 인용의 8자 하한을 안 건다.
 *
 * ★ 왜 하한을 가르나(2026-09-05 검토관 실측): 8자 하한은 「"MFA 필수"」 같은 **흔한 짧은 말**을
 *   지키려는 것이다. 제목은 흔한 말이 아니라 가리킬 곳이 있어야 하는 이름이라, 하한을 그대로
 *   걸었더니 제목이 짧기만 하면(「실패 사례집」 5자) 표지도 앞 인용문도 하나도 안 떼고
 *   **사고사례 줄이 통째로** 나갔다. 커밋이 「닫았다」고 적은 라이브 실물 2건은 제목이 길었을 뿐이다.
 * ⚠ 정직한 한계: 조각(chunks)에는 **문서 제목이 안 실린다**(memory.ts가 c.text만 담는다).
 *   그래서 여기서 참이 되는 자리는 대개 온톨로지·용어 정의·📎 첨부처럼 제목이 본문 글자로 나오는
 *   원천이다. 「제목이 확인되지 않았다」는 「제목이 가짜다」와 다르므로 뗀 사유도 `출처미확인`으로
 *   따로 센다 — 계수기가 지어냄과 미확인을 뭉개지 않게.
 */
export function 제목그대로있나(title: string, source: string): boolean {
  const q = String(title ?? "").replace(/\s+/g, "");
  if (q.length < 제목하한) return false;
  return String(source ?? "").replace(/\s+/g, "").includes(q) || 원천에있나(title, source);
}

