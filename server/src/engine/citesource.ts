//
// ■ 왜 생겼나 (2026-09-08 실측)
//   citeguard.test의 「실전 답 기록으로 잰 오탐」은 .tmp-reports/ops-sim.json의 답을
//   `guardCitations(t, [])`로 재생한다. 그런데 기록에 있는 `sources`는 **문서 이름**뿐이고
//   (실측: ["GIJO_AS_사용자_매뉴얼.md", …]), 가드가 실제로 대조한 것은 llm.ts의 조각 **본문**이다.
//   그 sources는 chat이 끝난 **뒤** 따로 재검색해 뽑은 후보라(dispatcher.ts:203 스스로 그렇게
//   적는다) 되먹일 수도 없다. 그래서 「챗 경로 + 조각 있었음」 41건이 모집단에서 통째로 빠져
//   있었다 — 재생이 라이브보다 사나워 **없는 오탐**(거짓 빨강)이 나기 때문이다.
//   기록이 **가드가 본 그 글**을 담으면 그 41건이 잣대로 돌아온다.
//
// ■ 왜 반환값이 아니라 꼬리표인가
//   chat()은 `Promise<string>` 한 모양이다(llm.ts). 반환에 칸을 더하면 부르는 자리 전부와
//   스트림 싱크가 함께 흔들린다 — toolevidence.ts가 같은 이유로 고른 무늬다. 방향만 반대다:
//   저기는 도구(아래)→dispatcher(위), 여기는 chat(안)→/api/dispatch(밖).
//
// ■ 왜 llm.ts가 아니라 **따로 선 파일**인가 (2026-09-08 · 설계관 계획에서 갈린 자리)
//   설계관은 「llm.ts에 두고 export」를 대안으로 냈는데, **코드가 그 길을 막는다.** llm을 통째로
//   흉내 내는 시험이 66파일이고(`vi.mock("../src/engine/llm", () => ({…}))`), 그 목은 표면을
//   손으로 나열한다 — dispatcher가 llm에서 심볼을 **하나만 더** 가져와도 그 66개가 통째로
//   죽는다(dispatcher.ts:23의 경고가 같은 사고를 이미 적어 두었다). 잎 모듈은 아무도 목으로
//   안 덮으므로 그 함정이 없다.
//
// ⚠ **그릇은 qa 요청에만 놓인다**(dispatcher의 /api/dispatch). 그릇이 없으면 보고는 조용히
//   아무 일도 안 한다 — 사람 응답에는 조각 본문이 한 글자도 안 실린다.
//
// ★★★ **잴 수 없는 보고(조각 null)는 담지도 세지도 않는다** (2026-09-08 검토관 [높음] 수리)
//   첫 판은 「첫 보고를 담는다」였는데, 그게 **정확히 반대로** 작동했다 — 한 요청의
//   첫 chat()은 답이 아니라 **의도 분류기**다.
//     dispatcher.ts:1912 routeIntent가 executeRoutedAction(1917)보다 **먼저** 돌고,
//     intent.ts:106이 remember 없이 chat을 부른다 -> llm.ts:865 ragResult = null
//     -> llm.ts의 가드조각이 null.
//   그대로 두면 챗 답의 근거조각이 **언제나 분류기의 null**이 되고 보고횟수가 2가 돼,
//   이 라운드가 되살리려던 41건이 새 규칙(가드횟수>1)에 **그대로 다시 걸린다**
//   (모의 실측: 잰 것 94 · 챗 0 — 문턱 100·20이 함께 깨진다).
//   ★ 잣대는 「몇 번째 호출인가」가 아니라 **「가드가 잴 수 있었나」**다 — null은
//     citeguard.ts:922가 즉시 되돌리는 값이라 가드가 **한 글자도 안 잰다.** 그런 호출을
//     기록해 두면 재생이 재지 못하면서 「잰 것」으로 세어지고(가장 나쁜 초록), 같은 요청에서
//     답을 쓴 진짜 호출까지 함께 내버린다. 그래서 **값으로** 가른다.
//   ↳ 뜻은 결과: 도구 경로(composeFinalAnswer가 remember 없이 부른다 · agentloop.ts:903)는
//     보고가 전부 null이라 **칸이 아예 안 생긴다** — 재생은 그 행을 종전 갈래(근사)로 돌린다.
//     그게 맞다: 라이브에서도 그 가드는 무동작이었다.
//   ⚠ `[]`(0건)은 **잰 것**이다 — RAG가 돌았고 대조할 조각이 없었다는 판정이라 가드가 실제로
//     판정을 낸다. null과 뜻이 다르므로 뭉개지 않는다.
// ⚠ 잴 수 있는 보고가 여러 번이면 **첫 것만 담고 횟수를 센다.** 한 턴에 그런 chat이 여러 번
//   도는 답(오케스트레이션·enrichment)에서는 「어느 호출의 조각인가」를 재생이 알 수 없다 —
//   횟수를 안 적으면 시험이 그 사실을 모른 채 엉뚱한 조각으로 재생한다.
import { AsyncLocalStorage } from "node:async_hooks";

/** 인용 가드가 **한 번의 chat에서 실제로 견준 원천**. 재생 시험이 라이브 조건을 되살리는 재료다. */
export interface 인용원천기록 {
  /**
   * 가드가 본 조각 본문. **언제나 배열이다** — `null`(판정 보류)은 애초에 기록을 안 만든다(위 머리말).
   * `[]`(0건)은 다르다 — 가드가 실제로 돌았고 대조할 조각이 없었다는 **판정**이라 그대로 담는다.
   */
  조각: string[];
  /** 번호 없는 대조 원천 — 문서 제목 · 온톨로지 블록 · 용어 그라운딩 · 📎 첨부. */
  추가원천: string[];
  /**
   * 이 요청에서 가드가 **재며** 돈 횟수(잴 수 없던 호출은 안 센다 — 위 머리말).
   * 1이 아니면 이 기록은 **답 전체의 근거가 아니다.**
   */
  보고횟수: number;
}

/** 한 요청 동안 원천을 담아 두는 그릇. 부르는 쪽이 만들어 넘긴다(만든 사람이 읽는다). */
export interface 인용원천수거 { 값?: 인용원천기록 }

const store = new AsyncLocalStorage<인용원천수거>();

/** 새 그릇 하나. */
export function 새인용원천수거(): 인용원천수거 {
  return {};
}

/** fn이 도는 동안(그 안의 비동기 포함) chat이 원천을 담을 수 있게 한다. */
export function 인용원천을수거하며<T>(그릇: 인용원천수거, fn: () => T): T {
  return store.run(그릇, fn);
}

/**
 * chat이 「가드에게 이것을 줬다」고 알린다. 수거 중이 아니면 조용히 무시한다.
 *
 * ★ 부르는 쪽(llm.ts)은 **조건 없이 한 줄**로 부른다 — 「어떤 보고가 기록감인가」는
 *   **이 한 곳에서만** 가른다(잣대 한 곳). 부르는 자리마다 조건을 적으면 새 호출부가
 *   그 조건을 빼먹고, 이 저장소가 반복해 겪은 「같은 것을 여러 곳에 적으면 어긋난다」가 된다.
 */
export function 인용원천보고(조각: string[] | null, 추가원천: string[]): void {
  const 그릇 = store.getStore();
  if (!그릇) return;
  // ★★ **잴 수 없었으면 없던 일이다** — 담지도 세지도 않는다(위 머리말 ★★★).
  //   이 한 줄이 없으면 분류기(routeIntent)의 null이 답의 조각을 가로채고, 보고횟수가 2가 돼
  //   재생이 그 행을 통째로 다시 내버린다.
  if (조각 === null) return;
  if (그릇.값) { 그릇.값.보고횟수++; return; } // ⚠ 잴 수 있는 보고 중 첫 것만 담고 횟수만 올린다
  그릇.값 = { 조각, 추가원천, 보고횟수: 1 };
}
