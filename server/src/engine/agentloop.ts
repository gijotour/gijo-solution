// 사용자에게는 "제품이 자기 데이터를 못 찾는다"로 보인다 — 실사용 신뢰를 직접 깨는 회귀다.
const DENIAL_RE = /찾을 수 없|찾지 못|정보가 없|확인되지 않|해당하는 (자산|취약점|데이터).{0,10}없|존재하지 않습니다|없습니다\.?$/;
