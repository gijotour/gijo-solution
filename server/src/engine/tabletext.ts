//
// ■ 왜 따로 있나 (2026-09-10, 갈래 U)
//   「무엇이 표인가」를 서버가 네 벌로 적고 있었다 — memory.ts(주석은 「유일한 정의」라 적혀 있었다)
//   · webreport.ts(글자까지 같은 사본) · inspectionreport.ts(이름 없는 인라인 사본이자 **딴 잣대**)
//   · dataset.ts(내는 쪽). 사본이 생긴 이유는 정직하다: 정의가 memory.ts에 있었고 그 모듈이
//   DB·LanceDB를 물어서, 파서가 import하면 통째로 딸려 왔다. **정의를 잎으로 뽑으면 그 이유가 사라진다.**
//
// ■ 이 파일의 계약 두 줄
//   ⚠ **잎이다 — import이 한 줄도 없다**(값·타입·동적 전부). 하나라도 붙는 순간 「부담 없이 부른다」가
//     깨지고, 다음 사람이 다시 사본을 만들 이유가 생긴다. fs·path·process.env도 안 쓴다
//     (그것이 붙으면 .mjs 도구가 dist로 부를 길이 막힌다 — docledger가 겪은 자리).
//   ⚠ **사본을 만들지 말 것.** server/test/tabletext.test.ts가 server/src 전부를 훑어
//     표줄·구분선·열수·칸가르기의 사본이 다시 생기면 빨개진다(감시자 자신도 거기서 반증한다).
//
// ■ 「읽는 쪽」과 「내는 쪽」을 한 파일에 둔 이유
//   내는 쪽(파이프표)의 규격이 곧 읽는 쪽(표본문행자리)의 전제다 — 「한 표의 모든 행을 같은 열
//   수로 낸다」가 깨지면 그 행이 표에서 떨어져 나간다. 둘을 갈라 두면 그 짝이 조용히 어긋난다.

// ── 표(마크다운 테이블) 인지 — **이 술어들이 표에 관한 유일한 정의다** (2026-09-08, ⓐ3) ──
//   ⚠ 사본을 만들지 말 것. 청킹·반복줄 제거·웹취약점 파서·점검보고서 내보내기가 모두 여기를 본다 —
//     여러 곳이 다른 잣대를 쓰면 「지우는 쪽은 표로 보고 붙이는 쪽은 아니라고 보는」 어긋남이
//     조용히 생긴다(실측 2026-09-10: inspectionreport가 정렬 구분선을 표에 찍고, 대시만 든
//     본문 행을 구분선으로 보고 **버리고** 있었다).
/** 표 행 — 마크다운 표는 줄이 파이프로 시작한다. */
export const 표줄 = (l: string) => l.trimStart().startsWith("|");
/** 구분선 — |---|---| · |:---|---:| 꼴. 머리글과 본문을 가르는 줄이라 이게 없으면 표가 아니다. */
export const 구분선 = (l: string) => /^\s*\|(?:\s*:?-{2,}:?\s*\|)+\s*$/.test(l);
/** 표 한 줄의 **열 수** — 파이프 개수 - 1.
 *  ⚠ 이스케이프된 `\|`는 칸 **안의 글자**라 세지 않는다. 추출기(칸글)가 칸 내용의
 *    파이프를 그렇게 내보내므로, 안 걸러 내면 그 행만 열 수가 부풀어 표에서 떨어져 나간다. */
export const 열수 = (l: string) => (l.replace(/\\\|/g, "").match(/\|/g)?.length ?? 0) - 1;
/** 한 줄을 칸으로 가른다 — 양끝 파이프를 벗기고 칸 안 이스케이프(`\|`)를 되돌린다.
 *  ⚠ **이스케이프를 푸는 유일한 구현**이다. 안 풀면 칸이 하나 더 생기고 역슬래시가 남는다
 *    (2026-09-10 실측: inspectionHtml이 `| a\|b | 1 |`을 3칸으로 냈다 — 머리글보다 한 칸 많다). */
export function 칸가르기(l: string): string[] {
  const t = l.trim().replace(/^\|/, "").replace(/\|$/, "");
  return t.split(/(?<!\\)\|/).map((c) => c.replace(/\\\|/g, "|").trim());
}
/** 표 머리글 — **바로 다음 줄이 구분선인** 표 행. 「표꼴 줄」 전부가 아니라 여기까지가 예외다.
 *  ⚠ 넓히면 KISA 가이드의 바닥글 「| 한국인터넷진흥원 |」 429줄이 지식으로 되살아난다(실측). */
export function 표머리글들(lines: string[]): Set<string> {
  const out = new Set<string>();
  for (let i = 0; i + 1 < lines.length; i += 1) if (표줄(lines[i]) && 구분선(lines[i + 1])) out.add(lines[i].trim());
  return out;
}
/** 표 **본문 행의 자리** — 「머리글 + 구분선」으로 시작한 표 덩어리 안에 있는 표줄.
 *  (2026-09-08 검토관 [상] 적발 · 실행 재현) 추출기가 워드·pptx 표를 파이프 표로 내기 시작하자
 *  본문 행이 60자 이하의 짧은 줄이 됐고, 그러자 memory.ts의 「3회 이상 반복되는 짧은 줄」 제거가
 *  **본문 행을 지웠다** — 머리글+구분선만 남은 표가 되어, 그 라운드가 없애려던 증상이 그대로
 *  재현됐다(같은 점검표 3벌짜리 docx에서 본문 행이 하나도 안 남는다).
 *  ⚠ 위 두 예외와 달리 **글자가 아니라 자리로** 센다. 같은 글자가 어떤 데선 표 행이고 어떤 데선
 *    바닥글일 수 있는데, 글자로 예외를 주면 바닥글 쪽까지 함께 살아난다.
 *  ⚠ 예외는 **「머리글+구분선이 앞선」 표까지**다 — KISA 가이드의 바닥글 「| 한국인터넷진흥원 |」
 *    429줄은 앞에 머리글도 구분선도 없는 홑 파이프 줄이라 여전히 지워진다(그 문서에 진짜 표는
 *    0개다 — 2026-09-08 실측).
 *  ★ 그리고 **구분선과 열 수가 같은 줄까지**다 (2026-09-08 검토관 2차 적발 · 실행 재현).
 *    「표줄이면 무조건」으로 두면 반복 바닥글이 **빈 줄 없이 본문 행에 바로 이어 붙었을 때**
 *    표 안으로 보여 되살아난다(재현: 「머리글/구분선/본문행/| 한국인터넷진흥원 |」 3벌 →
 *    바닥글 3줄이 그대로 남는다. 바닥글을 머리글 **위**에 두면 0줄이라, 붙는 방향에 따라
 *    답이 갈리던 자리다). 열 수로 가르면 홑 파이프 바닥글(1열)이 2열짜리 표 안에서도 걸린다.
 *    ⚠ 값어치의 근거: 이 표를 내는 곳(아래 파이프표)은 **한 표의 모든 행을 같은 열 수로**
 *      낸다 — 열 수가 다른 줄은 그 표의 본문 행이 아니다. 손으로 쓴 .md에서 꼬리 파이프를
 *      빠뜨린 행이 3벌 넘게 반복되면 그 행은 종전처럼 지워지지만, 매니페스트 35편 실측에서
 *      그런 줄은 0줄이다(조각 지문 35편 전부 동일). */
export function 표본문행자리(lines: string[]): boolean[] {
  const out = new Array<boolean>(lines.length).fill(false);
  for (let i = 0; i + 1 < lines.length; i += 1) {
    if (!표줄(lines[i]) || !구분선(lines[i + 1])) continue; // 제대로 선 표만 — 홑 파이프 줄은 표가 아니다
    const 폭 = 열수(lines[i + 1]);
    let k = i + 2;
    while (k < lines.length && 표줄(lines[k]) && 열수(lines[k]) === 폭) { out[k] = true; k += 1; }
    // i를 k-1로 두면 for의 +1이 **멈춘 그 줄**을 다시 본다 — 열 수가 어긋나 멈춘 줄이
    // 곧 다음 표의 머리글일 수 있어서다. 건너뛰면 뒤 표의 본문이 통째로 보호를 잃는다.
    i = k - 1;
  }
  return out;
}
// ── 여기까지가 「읽는 쪽」 ─────────────────────────────────────────────────────────────
//   ⚠ 위 구간의 알맹이는 test/tablechunk.test.ts의 **청커 지문**에 들어간다(memory.ts 구간과 함께).
//     자르는 규칙을 고치면 거기서 빨개지며 CHUNKER_VERSION을 올리라고 말한다.

/** 칸 하나의 글 — **엔티티는 여기서 안 푼다.** 조립이 끝난 뒤 태그걷기()가 한 번에 푼다.
 *  미리 풀면 `&lt;script&gt;`가 `<script>`가 되고, 마지막 태그걷기가 그것을 **태그로 보고 통째로
 *  지운다**(칸 내용이 사라진다). 지금 파이프라인은 「조립 → 딱 한 번 푼다」가 계약이다.
 *  ⚠ `|`는 열 구분자라 이스케이프한다 — 안 하면 열 수가 어긋나 구분선과 안 맞고 표 인지가 깨진다
 *    (실측: AI_보안제품_기획_v11.docx 추출본에 파이프가 이미 2개 있다). 되돌리는 곳은 칸가르기() 한 곳.
 *  ⚠ 공백 압축은 `[ \t\r\n]+`만 — `\s`로 넓히면 줄바꿈아님공백(NBSP)까지 바꿔 종전 글과 갈린다. */
export const 칸글 = (raw: string) => raw.replace(/[ \t\r\n]+/g, " ").replace(/\|/g, "\\|").trim();

/** 한 행의 열 수 상한 — 워드가 실제로 허용하는 열은 63개다. 512는 그 8배로 넉넉하고,
 *  **자리 채우기가 폭주하는 것을 막는다**: 병합 칸(gridSpan 최대 64)을 잔뜩 넣은 파일 하나가
 *  「빈 칸 수만 곱해」 원본의 수백 배짜리 글을 만들 수 있다(자체 검토 2026-09-08).
 *  ⚠ **두 번째 상한을 만들지 말 것** — 이 값 하나가 추출기(워드·pptx·차트)와 PDF 표 복원에
 *    동시에 걸린다. */
export const 표_최대열 = 512;

/** 행들을 마크다운 파이프 표로 낸다 — **위 표 술어(표줄·구분선·표머리글들)가 읽는 규격**.
 *  ⚠ 자리 맞춤(패딩)은 안 넣는다 — 꼬리 정규화가 `[ \t]+`를 한 칸으로 접어 어차피 사라진다.
 *  ⚠ 칸마다 공백을 넣는다 — `|a|b|`처럼 붙여 내면 라틴·숫자 표가 공백비율 0.05 관문
 *    (ragsanitize.isBinaryLikeChunk)에 걸려 **바이너리로 몰릴** 수 있다.
 *
 *  ✅ **닫혔다 — 반복줄 제거가 표 본문 행을 지우던 접점**(2026-09-08 검토관 적발①②).
 *    증상이었던 것: memory.ts:cleanExtractedText가 「3회 이상 반복되는 60자 이하 줄」을 페이지
 *    머리글/바닥글로 보고 지우는데 예외가 구분선·표 머리글까지여서, 같은 점검표가 한 문서에
 *    3번 이상 들면 **본문 행만 지워지고 머리글+구분선만 남았다.** 표를 한 줄 덩어리로 내던
 *    종전에는 60자를 넘겨 원리상 안 걸리던 갈래라, 추출기 변경이 새로 연 노출이었다.
 *    고친 자리는 표본문행자리() 한 곳 — 커밋 3d092899(본문 행 예외를 **자리로**) + 그 뒤 열 수로
 *    좁힘. CHUNKER_VERSION도 함께 올라갔다(2026-09-08-table-4).
 *    ★ 여기서 지켜야 할 계약: **한 표의 모든 행을 같은 열 수로 낸다.** 표본문행자리()의 예외가
 *      「구분선과 열 수가 같은 줄」까지라, 행마다 열 수가 흔들리면 그 행은 다시 지워진다
 *      (아래가 이미 열수로 맞춰 낸다 — 이 규칙을 깨는 손질을 하지 말 것). 짝 시험은
 *      test/tablechunk.test.ts 「표 본문 행은 반복돼도 지우지 않는다」.
 *
 *  ⓘ 표가 개행을 얻어 블록이 갈리므로 **같은 문서라도 조각 수가 달라진다 — 늘 수도, 줄 수도
 *    있다**(2026-09-08 실물 3편 실측). 제품 기본값(800/100)에서는 기획 docx 11→14 · 제품소개
 *    pptx 32→32 · GSTS pptx 17→21로 준 문서가 없었지만, 자를 크기를 1200/120으로 바꾸면
 *    제품소개 pptx가 26→**24**로 준다 — 빈 줄로 한 블록에 뭉치면서 경계가 옮겨가기 때문이다.
 *    즉 「늘어난다」는 자를 크기에 딸린 말이라 계약으로 삼지 않는다. **내용 손실은 아니다**:
 *    같은 3편의 낱말 다중집합이 앞뒤로 똑같다(표 기호를 걷어낸 지문 7403·18076·10904 동일). */
export function 파이프표(행들: string[][]): string {
  const 열수 = Math.min(행들.reduce((a, r) => Math.max(a, r.length), 0), 표_최대열);
  if (열수 === 0 || 행들.length === 0) return "";
  // 글자가 하나도 없는 표(빈 격자·자리잡기용)는 지식이 아니다 — 구분선만 남기지 않는다.
  if (!행들.some((r) => r.some((c) => c !== ""))) return "";
  const 줄 = (칸들: string[]) => `| ${Array.from({ length: 열수 }, (_, i) => 칸들[i] ?? "").join(" | ")} |`;
  const 구분 = `| ${Array.from({ length: 열수 }, () => "---").join(" | ")} |`;
  return [줄(행들[0]), 구분, ...행들.slice(1).map(줄)].join("\n");
}
