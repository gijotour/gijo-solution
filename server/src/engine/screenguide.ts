/** 명령창 아래 팁 — 질문 예시(화면별)와 알아두기(공통)를 함께 준다. */
export function screenTips(screen?: string): { title: string; examples: string[]; rules: string[] } {
  const g = getScreenGuide(screen);
  // can 항목은 '"오늘 뭐부터 볼까?" — 오늘의 우선 업무 브리핑' 꼴 — 따옴표 안의 질문만 뽑는다.
  // 따옴표가 없는 설명 문장은 눌러 넣을 질문이 아니므로 버린다.
  const examples = g.can
    .map((c) => c.match(/"([^"]{2,40})"/)?.[1])
    .filter((q): q is string => Boolean(q))
    .slice(0, 4);
  return { title: g.title, examples, rules: PRODUCT_RULES };
}

// ⚠ lite는 **인자로 받는다**(2026-08-18). 여기서 registry의 에디션제한중()을 부르면
//   registry.ts:52가 이 파일을 import하므로 **순환**이 된다. 부르는 쪽(dispatcher·handlers)은
//   이미 에디션제한중을 import하고 있으니 그쪽에서 넘긴다.
export function getScreenGuide(screen?: string, lite = false): ScreenGuide {
  if (!screen) return lite ? LITE_OVERVIEW : OVERVIEW;
  // ⚠ **쿼리를 떼야 한다**(2026-08-30 검토관 [높음]) — 탭 주소는 쿼리를 달고 온다
  //   (console.js가 활성 탭 값을 쿼리째 넘기고, dispatcher가 그대로 흘린다). 안 떼면
  //   settings.html?s=my·aihub.html?panel=knowledge·mydocs.html?tab=vendor 같은 **메뉴의
  //   유일한 진입 주소**에서 ⓘ가 그 화면 안내 대신 일반 개요로 떨어진다(TAB_REDIRECT 도착지
  //   17종도 전부 ?panel=…이다). workflow.ts stageOfScreen이 이미 쓰는 꼴과 같게 맞춘다 —
  //   한 곳만 다른 잣대를 쓰면 그 차이 자체가 결함이 된다.
  const key = (screen.split(/[\\/]/).pop() ?? screen).split("?")[0];
  // 화면 이름이 넘어왔는데 표에 없으면 개요로 떨어진다 — 그 개요도 에디션에 맞춰야 한다.
  return GUIDES[key] ?? (lite ? LITE_OVERVIEW : OVERVIEW);
}

