//
// 그래서 「우리 화면 이름 + 방법 질문」이면 **그 화면 안내**로 결정적으로 답한다.
// 자리 질문(「어디야?」)과 갈라 둔다 — 그건 위치를 묻고, 이건 하는 법을 묻는다.
// ⚠ 2026-08-10 2차: 「레드팀 점검 **어떻게 돌려**?」가 안 걸려 엉뚱한 자산 이름을 답했다.
//   「돌려·돌리·실행」을 더한다. ⚠ **좁게** 더한다 — `어떻게 \S+`처럼 넓히면
