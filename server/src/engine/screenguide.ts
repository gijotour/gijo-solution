export function 이름으로화면찾기(text: string): { screen: string; title: string } | null {
  const t = String(text ?? "");
  if (!자리질문_RE.test(t)) return null;
  const 붙인질문 = t.replace(/\s/g, "");
  type 후보 = { screen: string; title: string; 길이: number };
  let 최선: 후보 | undefined;
  const 담기 = (screen: string, 이름: string) => {
    if (이름.length < 2 || !붙인질문.includes(이름)) return;
    if (최선 && 이름.length <= 최선.길이) return;
    최선 = { screen, title: GUIDES[screen]?.title ?? 이름, 길이: 이름.length };
  };
  for (const [screen, g] of Object.entries(GUIDES)) 담기(screen, g.title.replace(/\s/g, ""));
  for (const [별명, screen] of Object.entries(화면별칭)) 담기(screen, 별명);
  return 최선 ? { screen: 최선.screen, title: 최선.title } : null;
}

/** 「○○은 여기 있습니다」 — 화면 위치 + 그 화면이 절차 몇 단계인지 + 거기서 하는 일. */
export function 화면위치안내(screen: string, title: string): string {
  const g = getScreenGuide(screen);
  const 단계 = stageOfScreen(screen);
  const 단계말 = 단계 ? workflowStages().find((s) => s.no === 단계) : null;
  return [
    `**${title}** — ${단계말 ? `사이드바 ${단계말.no} ${단계말.label} 안에 있습니다.` : "사이드바 메뉴에서 찾을 수 있습니다."}`,
    "",
    g.what,
    ...(g.can?.length ? ["", "여기서 하는 일:", ...g.can.slice(0, 5).map((c) => `- ${c}`)] : []),
  ].join("\n");
}

/**
 * 「이 화면은 절차 몇 단계인가」 한 줄 (2026-08-02 업무 절차 개편).
 *
 * 왜: 화면 안내가 그 화면 안의 일만 설명하면, 담당자는 **이 일이 전체 어디쯤인지** 모른 채
 *   화면마다 새로 배운다. 사용자 지시("취약점 기준 업무절차… 보고 리포트까지 전과정을
 *   볼수있어야해")는 화면 하나가 아니라 **흐름**을 보여 달라는 뜻이다.
 *
 * ⚠ 단계 표는 **서버 한 곳**(workflow.ts STAGE_SCREENS)만 본다. 여기서 따로 들면 사이드바·띠와
 *   어긋나고, 어긋나는 순간 셋 다 못 믿게 된다.
 * ⚠ 절차 화면이 아니면 **안 붙인다** — 설정 화면에 "③ 조치입니다"는 틀린 말이다.
 */
/**
 * 「로 / 으로」를 받침에 따라 고른다.
 * ⚠ 단계 이름을 그냥 이어 붙였더니 "**4 검증**로 갑니다"가 나왔다(실측 2026-08-02).
 *   담당자에게 나가는 우리말이라 조사는 맞아야 한다 — 받침 없거나 ㄹ이면 「로」, 아니면 「으로」.
 */
function 로조사(말: string): string {
  const 끝 = 말.trim().slice(-1);
  const code = 끝.charCodeAt(0);
  if (code < 0xac00 || code > 0xd7a3) return "로";   // 한글이 아니면 건드리지 않는다
  const 받침 = (code - 0xac00) % 28;
  return 받침 === 0 || 받침 === 8 ? "로" : "으로";   // 8 = ㄹ
}

function 절차줄(screen?: string): string | null {
  const no = stageOfScreen(screen);
  if (!no) return null;
  const stages = workflowStages();
  const 여기 = stages.find((s) => s.no === no);
  if (!여기) return null;
  const 앞 = stages.find((s) => s.no === no - 1);
  const 뒤 = stages.find((s) => s.no === no + 1);
  const 길 = [앞 && `앞: ${앞.no} ${앞.label}`, `**지금: ${no} ${여기.label}**`, 뒤 && `다음: ${뒤.no} ${뒤.label}`]
    .filter(Boolean)
    .join("  →  ");
  const 끝말 = 뒤
    ? `이 화면 일이 끝나면 **${뒤.no} ${뒤.label}**${로조사(뒤.label)} 갑니다.`
    : "여기까지가 한 바퀴입니다 — 다음 주기는 다시 **1 발견·수집**부터입니다.";
  return `📍 업무 절차 ${길}\n   ${끝말}`;
}

// 챗봇/지휘 콘솔이 그대로 최종 답으로 쓸 수 있는 안내 텍스트.
// question에 패널 이름이 들어 있으면(예: "SMTP 설정 방법 알려줘" — ⓘ 버튼이 이런 질문을 주입)
// 그 패널 상세만 답한다. 없으면 화면 전체 안내 + 패널 목차를 준다.
export function formatScreenGuide(screen?: string, question?: string): string {
  const g = getScreenGuide(screen);
  const q = (question ?? "").replace(/\s/g, "");
  if (g.panels && q) {
    // 화면에 적힌 이름으로 물어도 찾도록 별명표까지 본다(PANEL_ALIASES).
    const hit = resolvePanel(screen, q);
    // ⚠ 화면 이름과 구역 이름이 같으면 **같은 말이 두 번** 나온다 — 실측(2026-08-01 챗봇 전수):
    //   "🤖 AI-BOM 구성 › AI-BOM 코드 의존성(SBOM)을 넘어…". 담당자에겐 앞머리가 군더더기고,
    //   점검에서는 "내부 규칙 누출"로 잡혔다. 겹치면 한 번만 적는다.
    if (hit) {
      const 같은말 = g.title.replace(/\s/g, "").includes(hit.replace(/\s/g, ""));
      const 머리 = 같은말 ? `${hit}` : `${g.title} › ${hit}`;
      return `${머리}\n${g.panels[hit]}`;
    }
  }
  const L: string[] = [];
  L.push(`${g.title} — 이 화면 사용 안내`);
  L.push(g.what);
  const 절차 = 절차줄(screen);
  if (절차) { L.push(""); L.push(절차); }
  L.push("");
  L.push("이 화면에서 대화창으로 할 수 있는 것:");
  for (const c of g.can) L.push(`  • ${c}`);
  if (g.panels) {
    L.push("");
    L.push(`구역별 상세: ${Object.keys(g.panels).map((p) => `"${p}"`).join(" · ")} — 이름을 넣어 물어보세요(예: "${Object.keys(g.panels)[0]} 사용법 알려줘")`);
  }
  if (g.tip) { L.push(""); L.push(`💡 ${g.tip}`); }
  return L.join("\n");
}

