export function getScreenGuide(screen?: string): ScreenGuide {
  if (!screen) return OVERVIEW;
  const key = screen.split(/[\\/]/).pop() ?? screen;
  return GUIDES[key] ?? OVERVIEW;
}

// 챗봇/지휘 콘솔이 그대로 최종 답으로 쓸 수 있는 안내 텍스트.
export function formatScreenGuide(screen?: string): string {
  const g = getScreenGuide(screen);
  const L: string[] = [];
  L.push(`🤖 ${g.title} — 이 화면 사용 안내`);
  L.push(g.what);
  L.push("");
  L.push("이 화면에서 챗봇으로 할 수 있는 것:");
  for (const c of g.can) L.push(`  • ${c}`);
  if (g.tip) { L.push(""); L.push(`💡 ${g.tip}`); }
  return L.join("\n");
}
