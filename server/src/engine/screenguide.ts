export function 이름으로화면찾기(text: string): { screen: string; title: string; open?: string } | null {
  const t = String(text ?? "");
  if (!자리질문_RE.test(t)) return null;
  const 붙인질문 = t.replace(/\s/g, "");
  type 후보 = { screen: string; title: string; 길이: number; open?: string };
  let 최선: 후보 | undefined;
  const 담기 = (screen: string, 이름: string, open?: string) => {
    if (이름.length < 2 || !붙인질문.includes(이름)) return;
    // ⚠ 「내문서」는 「사내문서」의 꼬리에도 들어 있다 — 사내 문서(사내규정 등) 질문이
    //   개인 문서 화면으로 새면 안 된다(「법령」 낱말 가로채기 실사고와 같은 모양, 검토관 중7).
    if (이름 === "내문서" && 붙인질문.includes("사내문서")) return;
    if (최선 && 이름.length <= 최선.길이) return;
    최선 = { screen, title: GUIDES[screen]?.title ?? 이름, 길이: 이름.length, open };
  };
  for (const [screen, g] of Object.entries(GUIDES)) 담기(screen, g.title.replace(/\s/g, ""));
  for (const [별명, screen] of Object.entries(화면별칭)) 담기(screen, 별명, 별명열기탭[별명]);
  return 최선 ? { screen: 최선.screen, title: 최선.title, open: 최선.open } : null;
}

// ── 「○○ 하려면 어떻게 해?」 — 방법을 묻는 말 ────────────────────────────────
//
// ⚠ 왜 필요한가(2026-08-10 실측): 「자산을 등록하려면 어떻게 해?」가 **등록 승인창**을 띄웠다.
//   담당자는 방법을 물었는데 제품이 등록을 하려 든 것이다. 그 강제 규칙을 좁혔더니
//   이번엔 **9.6초 + 「근거 약함」 + 남의 제품 설명 유추**가 나왔다 — 그 규칙을 처음 만든
