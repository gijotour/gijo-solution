//
// dispatcher가 도움말 의도를 감지하면 이 모듈을 먼저 태워 화면 가이드를 답으로 준다. 화면을
// 모르면 전체 개요를 준다. 화면이 늘면 여기 GUIDES에 한 줄 추가한다.

