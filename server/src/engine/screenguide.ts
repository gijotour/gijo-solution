// engine/screenguide.ts — 화면별 "이 화면 챗봇" 사용 가이드.
//
// 담당자가 어느 메뉴에서든 "이 화면 뭐 할 수 있어?", "도움말", "사용법", "어떻게 써?"라고 물으면
// 그 화면에 맞춘 가이드를 결정적으로(LLM 없이) 돌려준다. 예시 명령은 전부 실제 등록된 도구
// (agenttools.ts)·기능에 근거한다 — 없는 기능을 안내하지 않는다(그라운딩).
//
// dispatcher가 도움말 의도를 감지하면 이 모듈을 먼저 태워 화면 가이드를 답으로 준다. 화면을
// 모르면 전체 개요를 준다. 화면이 늘면 여기 GUIDES에 한 줄 추가한다.

export interface ScreenGuide {
  title: string;
  what: string; // 이 화면이 하는 일 (한 줄)
  can: string[]; // 챗봇으로 할 수 있는 것 — 실제 예시 명령
  tip?: string; // 한 줄 팁
}

// 도움말/사용법 의도 — 동사 없이 물어도 잡는다. 단, 구체 데이터 질문("취약점 몇 건")은
// 여기에 안 걸리게 좁게 둔다(그건 원래 도구가 답해야 하므로).
const HELP_RE = /(이\s*화면|여기|이\s*메뉴|이\s*페이지).{0,6}(뭐|무엇|어떻게|할\s*수|사용|기능)|도움말|사용법|사용\s*방법|어떻게\s*(써|사용|쓰|해)|가이드\s*(줘|알려|보여)|help\b|무엇을\s*할\s*수|뭐\s*할\s*수|기능\s*(안내|설명|알려)/i;

export function isHelpIntent(text: string): boolean {
  return HELP_RE.test(text.trim());
}

