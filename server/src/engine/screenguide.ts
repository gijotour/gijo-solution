/** 명령창 아래 팁 — 질문 예시(화면별)와 알아두기(공통)를 함께 준다. */
export function screenTips(screen?: string): { title: string; examples: string[]; rules: string[] } {
  const g = getScreenGuide(screen);
  // can 항목은 '"오늘 뭐부터 볼까?" — 오늘의 우선 업무 브리핑' 꼴 — 따옴표 안의 질문만 뽑는다.
  // 따옴표가 없는 설명 문장은 눌러 넣을 질문이 아니므로 버린다.
  const examples = g.can
    .map((c) => c.match(/"([^"]{2,40})"/)?.[1])
    .filter((q): q is string => Boolean(q))
    .slice(0, 4);
  return { title: g.title, examples, rules: PRODUCT_RULES };
}

export function getScreenGuide(screen?: string): ScreenGuide {
  if (!screen) return OVERVIEW;
  const key = screen.split(/[\\/]/).pop() ?? screen;
  return GUIDES[key] ?? OVERVIEW;
}

// 챗봇/지휘 콘솔이 그대로 최종 답으로 쓸 수 있는 안내 텍스트.
// question에 패널 이름이 들어 있으면(예: "SMTP 설정 방법 알려줘" — ⓘ 버튼이 이런 질문을 주입)
// 그 패널 상세만 답한다. 없으면 화면 전체 안내 + 패널 목차를 준다.
export function formatScreenGuide(screen?: string, question?: string): string {
  const g = getScreenGuide(screen);
  const q = (question ?? "").replace(/\s/g, "");
  if (g.panels && q) {
    // 화면에 적힌 이름으로 물어도 찾도록 별명표까지 본다(PANEL_ALIASES).
    const hit = resolvePanel(screen, q);
    if (hit) return `🤖 ${g.title} › ${hit}\n${g.panels[hit]}`;
  }
  const L: string[] = [];
  L.push(`🤖 ${g.title} — 이 화면 사용 안내`);
  L.push(g.what);
  L.push("");
  L.push("이 화면에서 챗봇으로 할 수 있는 것:");
  for (const c of g.can) L.push(`  • ${c}`);
  if (g.panels) {
    L.push("");
    L.push(`구역별 상세: ${Object.keys(g.panels).map((p) => `"${p}"`).join(" · ")} — 이름을 넣어 물어보세요(예: "${Object.keys(g.panels)[0]} 사용법 알려줘")`);
  }
  if (g.tip) { L.push(""); L.push(`💡 ${g.tip}`); }
  return L.join("\n");
}

// 명령창 아래 팁 줄이 읽어가는 곳. 규칙(PRODUCT_RULES)이 바뀌면 서버만 배포하면 되고
// 클라이언트를 다시 게시할 필요가 없다 — 규칙은 한 곳에서만 관리한다는 원칙(2026-07-26).
export function registerScreenGuideRoutes(app: Express): void {
  app.get("/api/screen-tips", authMiddleware, (req, res) => {
    const screen = typeof req.query.screen === "string" ? req.query.screen : undefined;
    res.json(screenTips(screen));
  });
  // 화면 안내 본문 — 대시보드 대화가 "이 화면은 무엇을 하는 곳인지"를 바로 띄울 때 쓴다.
  // 예전엔 화면마다 ⓘ 아이콘이 있어 누르면 그 화면 안의 챗봇이 열렸는데, 안내는 대시보드
  // 대화 한 곳에서만 하기로 정하면서(2026-07-27) ⓘ를 없앴다. LLM을 태우지 않고 이 정적
  // 안내를 그대로 내려준다 — 화면을 열 때마다 모델을 깨우면 느리고, 답이 매번 달라진다.
  app.get("/api/screen-guide", authMiddleware, (req, res) => {
    const screen = typeof req.query.screen === "string" ? req.query.screen : undefined;
    const question = typeof req.query.question === "string" ? req.query.question : undefined;
    const g = getScreenGuide(screen);
    // what = "이 화면이 하는 일" 한 줄. 팝업 머리 아래 얇은 줄이 이것만 쓴다(2026-07-27).
    // text = 전문. 담당자가 그 줄을 눌렀을 때만 대화로 보낸다.
    res.json({ title: g.title, what: g.what, text: formatScreenGuide(screen, question) });
  });
}
