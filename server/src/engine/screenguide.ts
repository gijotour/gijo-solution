// 화면에 보이는 구역 이름에는 보기 좋으라고 넣은 구분 기호가 섞여 있다("모델 받기 · 인증").
// 담당자는 그 기호를 타이핑하지 않는다 — 안 지우면 "모델 받기 인증 뭐야?"가 안 걸려 LLM 일반
// 답변으로 새고, 사내 문서에서 엉뚱한 내용을 끌어온다(2026-07-28 실측: 무관한 반입 절차를 답함).
function normalizeName(s: string): string {
  return s.replace(/[\s·・ㆍ]/g, "");
}

/** panel = 안내에서 찾은 구역, matched = 질문 안에서 실제로 걸린 글자(별명일 수 있다). */
function resolvePanelHit(screen: string | undefined, q: string): { panel: string; matched: string } | null {
  const g = screen ? GUIDES[screen] : undefined;
  if (!g?.panels) return null;
  const nq = normalizeName(q);
  // ⚠ 가장 **긴**(구체적인) 이름이 이긴다. 선언 순서로 고르면 "2차 인증"이 "계정별 2차 인증"을
  //   가려, "담당자 2차 인증 해제하는 방법"에 내 계정 안내가 나왔다(2026-07-30 실측).
  //   이름이 포개지는 구역(계정 ⊂ 계정별 …)은 앞으로도 생기니 순서에 기대지 않는다.
  let best: { panel: string; matched: string } | null = null;
  for (const name of Object.keys(g.panels)) {
    const n = normalizeName(name);
    if (nq.includes(n) && (!best || n.length > normalizeName(best.matched).length)) {
      best = { panel: name, matched: name };
    }
  }
  const alias = screen ? PANEL_ALIASES[screen] : undefined;
  if (alias) {
    for (const [shown, real] of Object.entries(alias)) {
      const n = normalizeName(shown);
      if (nq.includes(n) && g.panels[real] && (!best || n.length > normalizeName(best.matched).length)) {
        best = { panel: real, matched: shown };
      }
    }
  }
  return best;
}
function resolvePanel(screen: string | undefined, q: string): string | null {
  return resolvePanelHit(screen, q)?.panel ?? null;
}

function panelNameHit(text: string, screen?: string): boolean {
  const g = screen ? GUIDES[screen] : undefined;
  if (!g?.panels) return false;
  const q = text.replace(/\s/g, "");
  // 설명을 구하는 말투일 때만(단순히 패널명이 스친 지시는 도구가 처리해야 한다).
  // "좋아·좋을까·추천"은 고르는 질문의 말투다("어떤 모델 받으면 좋아?"). 구역 이름이 함께
  // 걸릴 때만 쓰이므로(아래 resolvePanel), 이 낱말만으로 화면 안내가 열리지는 않는다.
  // 곤란을 털어놓는 말투도 안내를 구하는 것이다 — "복구 코드 잃어버렸어"에 일반 LLM이
  // "지원 센터에 문의하세요"라고 답했다(2026-07-30 실측). 폐쇄망 제품에 지원 센터는 없다.
  // 넓혀도 안전한 이유: 아래 resolvePanel이 **구역 이름 전체**가 질문에 들어 있을 때만 참이라,
  // "스캔 실패했어"처럼 이름이 안 걸리는 하소연은 여전히 도구·LLM이 맡는다.
  if (!/(뭐|무엇|어떻게|어디|누가|언제|사용|설명|알려|방법|바꿔|바꾸|변경|저장할|왜|가능|되나|하나요|좋아|좋을까|추천|해\?|돼\?|잃어버|분실|못\s*찾|안\s*보여|막혔|어떡)/.test(text)) return false;
  return resolvePanel(screen, q) !== null;
}

// "기능 설명/안내/알려"는 화면 사용법일 수도, 특정 제품 질문일 수도 있는 약한 신호다.
// 나머지(도움말·사용법·이 화면 …)는 화면을 가리키는 게 분명한 강한 신호.
// "X에서 내가 할 수 있는 게 뭐야?" — 가장 흔한 물음인데 HELP_RE 어느 가지에도 안 걸렸다
// (`뭐 할 수`는 잡는데 `할 수 있는 게 뭐`는 어순이 반대다). 2026-08-01 챗봇 전수에서 발견.
// ⚠ 강한 가지(HELP_RE)가 아니라 **약한 가지**에 둔다 — 약한 가지는 특정 대상(영문 제품명·CVE)이
//   끼면 비켜서므로, "Tenable로 할 수 있는 게 뭐야?"가 화면 안내로 새지 않는다.
const WEAK_HELP_RE = /기능\s*(안내|설명|알려)|할\s*수\s*있는\s*(게|것|일)/i;
// 특정 대상을 콕 집은 질문인지 — 영문 고유명사(제품·도구 이름), 취약점 코드, 파일 확장자.
// 다만 도움말 자체를 뜻하는 영어 낱말은 대상이 아니므로 세어주지 않는다.
const SPECIFIC_SUBJECT_RE = /[A-Za-z][A-Za-z0-9._-]{2,}|(CVE|CWE|KEV|CCE)-?\d|\.(pdf|docx?|xlsx?|csv|log)\b/i;
function hasSpecificSubject(text: string): boolean {
  return SPECIFIC_SUBJECT_RE.test(text.replace(/\b(help|guide|gijo|as)\b/gi, ""));
}

// [2026-07-26 실사용 사고] "Tenable Web App Scanning 주요기능 설명해줘"가 화면 사용 안내로 샜다.
// HELP_RE의 `기능 설명` 가지에 걸린 것 — 벤더 제품을 물었는데 대시보드 사용법이 돌아왔다.
// 약한 신호뿐인데 특정 대상(제품명 등)이 함께 있으면 화면 안내가 아니다.
// 프롬프트로 달랠 문제가 아니라 라우팅 조건으로 막는다.
export function isHelpIntent(text: string, screen?: string): boolean {
  const t = text.trim();
  const strong = HELP_RE.test(t) && !(WEAK_HELP_RE.test(t) && !/(이\s*화면|여기|이\s*메뉴|이\s*페이지|도움말|사용법|사용\s*방법)/.test(t));
  if (strong) return true;
  if (WEAK_HELP_RE.test(t) && !hasSpecificSubject(t)) return true;
  const hit = resolvePanelHit(screen, t.replace(/\s/g, ""));
  if (hit && panelNameHit(t, screen)) {
    // ⚠ 구역 이름 자체에 영문이 들어 있으면(예: "구독 중인 CTI 피드", "이메일(SMTP) 설정")
    //   그 영문을 "특정 제품을 콕 집은 질문"으로 오해해 화면 안내를 막아 버렸다(2026-07-27 실측).
    //   질문에서 걸린 구역 이름을 지운 뒤 남는 말로 판단한다 — 그래야 진짜 제품명만 걸러진다.
    //   띄어쓰기가 다를 수 있어 글자 사이 공백을 허용하는 형태로 지운다.
    const loose = hit.matched.replace(/\s/g, "").split("").map((c) => c.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")).join("\\s*");
    const rest = t.replace(new RegExp(loose, "gi"), " ");
    return !hasSpecificSubject(rest);
  }
  return false;
}

