  title: string;
  what: string; // 이 화면이 하는 일 (한 줄)
  can: string[]; // 챗봇으로 할 수 있는 것 — 실제 예시 명령
  tip?: string; // 한 줄 팁
  // 패널(구역) 단위 상세 사용법 — 화면 가독성 개편(2026-07-23)으로 UI 상시 노출 설명을 이곳으로
  // 이관했다. 키=패널 이름(질문에 이 단어가 들어오면 해당 상세만 답한다), 값=옮겨온 설명.
