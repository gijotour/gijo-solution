/**
 * 답 앞머리의 배너를 읽어 「근거 없음」 사실을 돌려준다 — **잣대를 새로 만들지 않는다.**
 *
 * ⚠ 왜 근거 0을 다시 판정하지 않고 **이미 붙은 문장**을 읽나:
 *   근거 0을 세는 곳이 이미 넷이다(llm.ts 자료없음 / llm.ts 약한근거만 / agentloop 도구 경로 /
 *   dispatcher 배지용 재검색). 다섯 번째를 만들면 어긋난다. 반대로 **답에 실려 나간 배너 문장**은
 *   담당자가 실제로 읽는 그 사실이라, 배너가 맨 앞인 답에서는 화면과 표식이 못 어긋난다.
 * ⚠ 앞머리만 본다(startsWith). 배너는 코드가 `${배너}\n\n${답}` 꼴로 **맨 앞에** 붙인다.
 *   실전 답 152건 실측(2026-09-05)에서 배너 3건이 전부 맨 앞이었고 중간에 있는 건 0건이다.
 *   덕분에 거짓완료 대체답(falseclaim)처럼 본문이 통째로 갈린 답은 배너가 사라져 표식도 자동으로
 *   안 붙는다 — 그래서 dispatcher **출구**(모든 거르개 뒤)에서 부른다.
 *
 * ⚠⚠ **덮지 못하는 자리 하나 — 복합 지시(오케스트레이션) 답**(2026-09-05 검토관 적발, 미수리).
 *   복합 지시는 단계마다 머리표를 달아 잇는다: `【1. 스캔】 …\n\n【2. 우선순위 분석】 ⚠배너…`.
 *   배너가 **본문 중간**이라 startsWith가 안 걸리고 표식이 null이 된다 — 배너 글자는 보이는데
 *   숫자는 진하게 남는다. 커밋이 내걸었던 「원리상 못 어긋난다」는 이 경로에서 참이 아니다.
 *
 *   **왜 그대로 두는가**(고치는 쪽이 더 나쁘다 — 실측으로 확인):
 *     · 단계 머리표를 벗겨 판정하게 만들면 표식이 붙고, 화면은 **답 전체**의 숫자를 옅게 한다.
 *       그런데 배너가 붙는 조건은 「앞 단계 findings가 0건」이라, 같은 답의 1단계 출력은
 *       "3개 자산 스캔 완료 — 발견 0건"처럼 **진짜 세어 온 숫자**다. 그걸 「모델 추정치」라고
 *       회색 처리하면 **없던 거짓말이 새로 생긴다**(이 파일이 막으려는 바로 그 해악).
 *     · 「배너 뒤부터만 옅게」로 좁히려면 화면 두 벌(지휘소=gijomd 문단 / 위젯=<br> 한 덩어리)이
 *       단계 경계를 알아야 하는데, 위젯은 배너가 <b>·텍스트로 쪼개져 경계를 못 잡는다.
 *       흔한 경로(배너=맨 앞)를 건드려야 해서 **위험이 이득보다 크다**.
 *     · 지금의 실패 방향은 **안전**하다 — 표식이 없으면 종전 동작(아무것도 안 옅게)이고,
 *       ⚠ 배너 글자는 그 단계 바로 앞에 그대로 보인다. 실전 답 152건에서 복합 답은 0건이다.
 *   → 제대로 닫으려면 「표식에 **범위**를 실어 보내기」가 필요하다(값 하나가 아니라 구간).
 *     그건 시안·설계관을 다시 태울 크기라, 여기 적어 두고 다음 라운드로 넘긴다.
 *     짝 시험(noevidence-mark.test.ts)이 이 공백을 **글자로 못박아** 둔다 — 누가 무심코
 *     「머리표 벗기고 판정」으로 고치면 그 시험이 빨개져 위 거짓말 문제를 다시 읽게 된다.
 */
export function 근거없음종류판정(output: string | undefined | null): 근거없음종류 | null {
  const s = String(output ?? "").replace(/^\s+/, "");
  if (!s) return null;
  for (const [종류, 배너] of 근거없음배너표) if (s.startsWith(배너)) return 종류;
  return null;
}

