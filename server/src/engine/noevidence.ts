/**
 * 답 앞머리의 배너를 읽어 「근거 없음」 사실을 돌려준다 — **잣대를 새로 만들지 않는다.**
 *
 * ⚠ 왜 근거 0을 다시 판정하지 않고 **이미 붙은 문장**을 읽나:
 *   근거 0을 세는 곳이 이미 넷이다(llm.ts 자료없음 / llm.ts 약한근거만 / agentloop 도구 경로 /
 *   dispatcher 배지용 재검색). 다섯 번째를 만들면 어긋난다. 반대로 **답에 실려 나간 배너 문장**은
 *   담당자가 실제로 읽는 그 사실이라, 배너가 맨 앞인 답에서는 화면과 표식이 못 어긋난다.
 * ⚠ 앞머리만 본다(startsWith). 배너는 코드가 `${배너}\n\n${답}` 꼴로 **맨 앞에** 붙인다.
 *   실전 답 152건 실측(2026-09-05)에서 배너 3건이 전부 맨 앞이었고 중간에 있는 건 0건이다.
 *   덕분에 거짓완료 대체답(falseclaim)처럼 본문이 통째로 갈린 답은 배너가 사라져 표식도 자동으로
 *   안 붙는다 — 그래서 dispatcher **출구**(모든 거르개 뒤)에서 부른다.
 *
 * ★ **복합 지시(오케스트레이션) 답 — 2026-09-06에 닫았다**(시안 mockups/dim-range 승인).
 *   복합 지시는 단계마다 머리표를 달아 잇는다: `【1. 스캔】 …\n\n【2. 우선순위 분석】 ⚠배너…`.
 *   배너가 **본문 중간**이라 startsWith가 안 걸려 표식이 null이었다 — ⚠ 글자는 보이는데 숫자는
 *   진하게 나갔다. 「앞머리만 본다」 규율은 **그대로 두고, 무엇의 앞머리인가만 좁힌다**:
 *   단계로 나뉜 답이면 **각 단계의 앞머리**에 같은 startsWith를 건다.
 *
 *   ⚠ 이 수리는 **범위(근거범위)와 짝이라야 성립한다.** 표식만 붙이면 화면이 답 전체를 옅게 하는데,
 *     같은 답의 1단계 출력은 "3개 자산 스캔 완료 — 발견 0건"처럼 **진짜 세어 온 숫자**다.
 *     그걸 「모델 추정치」로 회색 칠하면 없던 거짓말이 새로 생긴다(이 파일이 막으려는 해악).
 *     그래서 아래 근거범위()가 **배너가 붙은 단계 번호**를 함께 실어 보내고, 화면은 그 단계 안에서만
 *     옅게 한다. 범위를 못 읽으면 undefined → 종전 동작이라 실패 방향은 여전히 안전하다.
 */
export function 근거없음종류판정(output: string | undefined | null): 근거없음종류 | null {
  const s = String(output ?? "").replace(/^\s+/, "");
  if (!s) return null;
  const 앞머리판정 = (t: string): 근거없음종류 | null => {
    for (const [종류, 배너] of 근거없음배너표) if (t.startsWith(배너)) return 종류;
    return null;
  };
  const 곧바로 = 앞머리판정(s);
  if (곧바로) return 곧바로;
  // 단계로 나뉜 답이면 **각 단계의 앞머리**를 같은 잣대로 본다(복합 지시 경로).
  const 단계들 = 단계나누기(s);
  if (!단계들) return null;
  for (const 단 of 단계들) {
    const 종류 = 앞머리판정(단.본문);
    if (종류) return 종류;
  }
  return null;
}

