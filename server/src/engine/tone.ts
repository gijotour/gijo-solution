/**
 * **예고 서두 판정 — 한 벌만 둔다.**
 *
 * 이 판정이 세 곳에서 필요하다: 채팅 답 다듬기(llm.ts) · 리포트 요약 다듬기(report.ts) ·
 * 말투 감시(아래 금지말투). 예전에는 llm과 report가 **각자 목록**을 들고 있었고,
 * 그래서 어긋났다 — 채팅은 잡는 `우선, 1페이지 요약에 대해 알려드리겠습니다.`를
 * 리포트가 놓쳐 담당자 화면에 그대로 나갔다(2026-08-03 실전 147상황).
 *
 * ⚠ 여기에 두는 이유: 이 파일이 말투의 단일 출처이고, **시험이 흉내 내지 않는다**.
 *   llm.ts는 여러 시험이 통째로 흉내 내서(vi.mock) 거기 두면 시험마다 손봐야 한다.
 */
export const 예고서두 =
  /(답변|설명|작성|보고|안내|정리|요약|말씀|브리핑|리포트|검토)\S*\s*(을|를|에 대해|에 대한|해)?\s*(드리겠습니다|드릴게요|하겠습니다|할게요|알려드리겠습니다|말씀드리겠습니다|보고드리겠습니다)[.!?]?\s*$/;
/** 인사말 서두("안녕하세요, …") */
export const 인사서두 = /^(안녕하세요|안녕히 계세요|안녕|반갑습니다|반가워요|반갑네요|좋은 (아침|오후|하루)(입니다|이에요|예요)?)[\s,·!.]*/;
/** 자기소개 서두("저는 …입니다", "보안담당자입니다") */
// ⚠ 세 번째 갈래(사람 이름 사칭)를 더했다 — 실측(2026-08-03 실전 147상황):
//   `보안 담당자 맷 망고입니다. 인사말은 굳이 필요하지 않고…`가 담당자에게 나갔다.
//   **없는 사람 이름을 지어냈고**, 자기 규칙("인사말 없이")까지 소리 내어 읽었다.
//   앞의 두 갈래는 `담당자입니다`가 붙어 있어야 잡혀서 `담당자 맷 망고입니다`를 놓쳤다.
//   역할 낱말과 `입니다` 사이에 **이름 같은 것이 끼어 있으면** 그게 곧 사칭이다.
export const 소개서두 =
  /^((저는|제가|나는)\s.*(입니다|이에요|예요|담당(합니다|입니다)?)|[^\n.!?]{0,30}(담당자|어시스턴트|에이전트|보안 AI|AI)(\s+[^\n.!?]{1,12})?입니다)[.!?]?\s*$/;

/** 이 문장이 본론 앞에 붙은 껍데기인가(예고·인사·자기소개). */
export function 예고서두인가(s: string): boolean {
  const t = (s ?? "").trim();
  return !!t && (예고서두.test(t) || 소개서두.test(t) || 인사서두.test(t));
}

/** 답변이 규범을 어겼는가. 어긴 것만 돌려준다(빈 배열이면 통과). */
export function 말투위반(answer: string): { 이름: string; 왜: string; 대신: string }[] {
  const t = String(answer ?? "");
  if (!t.trim()) return [];
  const out: { 이름: string; 왜: string; 대신: string }[] = [];
  for (const g of 금지말투) if (g.re.test(t)) out.push({ 이름: g.이름, 왜: g.왜, 대신: g.대신 });

  // 사전에 없는 기호를 표식처럼 쓰는가 — 줄 맨 앞에 온 기호만 본다.
  // ⚠ 본문 속 이모지(예: 문서 제목에 든 것)까지 잡으면 오탐이 쏟아진다.
  for (const line of t.split("\n")) {
    const m = /^\s*([\u{1F300}-\u{1FAFF}\u{2600}-\u{27BF}\u{2B00}-\u{2BFF}])/u.exec(line);
    if (m && !허용표식.has(m[1])) {
      out.push({
        이름: `사전에 없는 표식 ${m[1]}`,
        왜: "기호는 뜻이 하나여야 눈에 들어온다 — 자리마다 다른 뜻이면 아무 뜻도 없어진다",
        대신: "tone.ts의 표식 사전에 먼저 추가하고 쓴다",
      });
      break;   // 한 줄만 알려도 충분하다
    }
  }

  // 뜻이 겹치는 기호 — 사전에 있는 기호와 **같은 뜻인데 모양만 다른** 것들.
  // 줄 앞이 아니어도 잡는다. 한 화면에 ✅와 ✓가 같이 나오면 담당자는 둘이 다른 줄 안다.
  for (const [바른, 나쁜들] of Object.entries(겹치는기호)) {
    const 쓴것 = 나쁜들.filter((x) => t.includes(x));
    if (쓴것.length) {
      out.push({
        이름: `뜻이 겹치는 기호 ${쓴것.join(" ")}`,
        왜: `${바른}와 같은 뜻인데 모양이 달라, 담당자는 둘이 다른 뜻인 줄 안다`,
        대신: `${바른} 하나로 통일한다`,
      });
    }
  }
  return out;
}
