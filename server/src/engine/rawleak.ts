// 기계 데이터를 사람에게 그대로 내보내지 않는다 — 원문 누출 관문.
//
// 왜 있나: 2026-08-09 자산 조회 답에 검색 원문 조각이 그대로 섞여 나왔다.
//   "payload_id":"was_asset-…"
// 담당자가 볼 화면에 저장소 내부 표현이 나가면 ① 무슨 말인지 못 알아보고 ② 제품이 덜
// 다듬어진 것으로 보이며 ③ 내부 구조가 드러난다. 무엇보다 **QA가 이걸 못 잡았다** —
// 도구도 맞고 숫자도 맞아서 통과였다. 형식만 보는 판정의 한계다.
//
// 거짓 완료 관문(falseclaim.ts)과 같은 자리에 둔다. 갈래마다 심으면 새 갈래에서 또 샌다.
//
// ⚠ 좁게 잡는다. 고객이 **일부러 요청한** JSON·원문·코드는 건드리면 안 된다
//   (SBOM·VEX·설정 예시는 정상적으로 기계 형식이다). 그래서 두 겹으로 좁힌다:
//     ① 지시가 기계 형식을 요청했으면 통째로 비켜간다
//     ② 코드블록(``` 안)은 건드리지 않는다 — 거긴 원래 기계가 사는 자리다

/** ① 사람이 기계 형식을 **달라고 했나.** 했으면 이 관문은 아무것도 안 한다. */
const 형식요청 =
  /(json|JSON|yaml|YAML|xml|XML|sbom|SBOM|vex|VEX|원문|raw|스키마|schema|설정\s*파일|코드로|쿼리문)/;

/** ② 저장소 내부에서만 쓰는 열쇠말 — 사람 문장에는 나올 이유가 없다. */
const 내부열쇠 =
  /"(payload_id|chunk_id|doc_id|documentId|vector|embedding|_distance|_rowid|rowid|score|metadata)"\s*:/;

/** ③ JSON 낱쌍이 한 줄에 둘 이상 — 문장이 아니라 자료다. */
const 낱쌍둘 = /"[A-Za-z_][A-Za-z0-9_]*"\s*:\s*("[^"]*"|[-\d.]+|true|false|null)[\s,}]+.*"[A-Za-z_][A-Za-z0-9_]*"\s*:/;

/** ④ 끊기지 않는 긴 덩어리 — base64·해시·벡터가 통째로 실려 온 것. */
const 긴덩어리 = /[A-Za-z0-9+/=]{80,}/;

/** 이 줄이 사람에게 보일 것이 아닌가. */
export function 기계데이터줄인가(줄: string): boolean {
  const t = 줄.trim();
  if (!t) return false;
  return 내부열쇠.test(t) || 낱쌍둘.test(t) || 긴덩어리.test(t);
}

/**
 * 답에서 기계 데이터 줄을 걷어낸다.
 *
 * 지운 자리에 아무 말도 안 남기면 답이 갑자기 끊긴 것처럼 보인다 — 무엇이 빠졌는지 한 줄 남긴다.
 * 걷어내고 나서 **남는 말이 없으면** 답을 통째로 바꾼다. 빈 답을 내보내는 게 제일 나쁘다.
 */
export function 원문누출차단(지시: string, 답: string): { 답: string; 막았나: boolean; 걸린수: number } {
  if (!답) return { 답, 막았나: false, 걸린수: 0 };
  if (형식요청.test(지시)) return { 답, 막았나: false, 걸린수: 0 };

  const 줄들 = 답.split("\n");
  const 남길: string[] = [];
  let 코드블록안 = false;
  let 걸린수 = 0;

  for (const 줄 of 줄들) {
    if (/^\s*```/.test(줄)) { 코드블록안 = !코드블록안; 남길.push(줄); continue; }
    // 코드블록 안은 원래 기계가 사는 자리다 — 손대지 않는다.
    if (코드블록안) { 남길.push(줄); continue; }
    if (기계데이터줄인가(줄)) { 걸린수++; continue; }
    남길.push(줄);
  }

  if (!걸린수) return { 답, 막았나: false, 걸린수: 0 };

  const 정리 = 남길.join("\n").replace(/\n{3,}/g, "\n\n").trim();
  // 사람이 읽을 말이 남았는지 — 한글이나 문장부호가 있어야 말이다.
  const 말이남았나 = /[가-힣]{2,}/.test(정리);

  if (!말이남았나) {
    return {
      막았나: true,
      걸린수,
      답: [
        "찾은 자료가 **사람이 읽을 형태로 정리되지 않아** 그대로 보여 드리지 않았습니다.",
        "",
        "저장소 안의 내부 표현이라 그대로 내면 오히려 헷갈립니다.",
        "다시 물어봐 주시면 정리해서 답하겠습니다 — 어떤 자산·어떤 항목인지 하나만 짚어 주세요.",
      ].join("\n"),
    };
  }
  return {
    막았나: true,
    걸린수,
    답: `${정리}\n\n_(내부 자료 ${걸린수}줄은 사람이 읽을 형태가 아니라 뺐습니다.)_`,
  };
}
