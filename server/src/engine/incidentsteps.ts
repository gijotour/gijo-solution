// ── 침해사고 의심 ─────────────────────────────────────────────────────────
//
// 왜 형제로 만드나(2026-08-10 실측): 「침해사고 의심될 때 대응 절차 알려줘」에
// **「일반 취약점 조치 · 30일 내」 표**가 나왔다. 침해는 지금 벌어지는 일이고 취약점은
// 아직 안 벌어진 일인데, 담당자가 급할 때 30일짜리 패치 일정표를 받은 것이다.
//
// ⚠ 위 「장애」와 갈라 둔다 — 장애는 **안 되는 것**이고 침해는 **당한 것**이라 순서가 다르다.
//   장애는 복구가 먼저지만, 침해는 **증거 보전이 복구보다 먼저**다(지우면 못 되돌린다).
// ⚠ logguide(로그 이벤트별 절차)와도 다르다 — 그건 유형이 정해졌을 때고, 여기는
//   「뭔가 이상한데 침해 같다」는 **유형 미상**의 첫걸음이다.

/** 침해사고를 의심하는 말인가. ⚠ 좁게 — 「침해사고 대응 교육」·「법령」까지 삼키면 안 된다. */
// ⚠ `감염됐|감염되었`을 더했다(2026-08-22 실측). 「**감염됐는데** 랜선 뽑아도 되나요?」가
//   침해로 안 잡혀 초동을 잃고 있었다. 바로 아래 `활성침해`는 `감염(됐|되었|당|된)`으로
//   **이미 그 어형을 알고 있었는데** 이 목록만 `감염된` 하나였다 — 같은 파일 안에서 어긋나 있었다.
//   ⚠ 「감염」 홑낱말은 넣지 않는다 — 「악성코드 감염 **교육**」·「감염 **통계**」까지 삼킨다.
const 침해말 = /(침해\s*사고|해킹|랜섬|정보\s*유출|자료\s*유출|유출\s*(사고|의심)|악성코드\s*(감염|발견)|감염(된|됐|되었)|공격\s*받|털렸|뚫렸)/;
const 침해아님 = /(교육|훈련|법령|조항|제\d+조|보고서\s*(양식|서식)|신고\s*(양식|기한|절차는)|보험|사례\s*(연구|공유))/;

export function 침해사고질문인가(text: string): boolean {
  const t = String(text ?? "");
  if (!침해말.test(t)) return false;
  // ⚠ 법적 신고 의무를 묻는 말(법 질문)은 비켜 준다 — 단 활성 침해(걸렸/당했)면 사고 중이라 초동이
  //   먼저다(위 법의무/활성침해 주석 참고). 비켜 준 뒤 FORCED law_lookup 약칭(망법·신용정보법)이 받는다.
  if (법의무.test(t) && !활성침해.test(t)) return false;
  if (침해아님.test(t)) return false;
  // ⚠ 문서를 콕 집어 그 내용/존재를 묻는 말(「이 안내서에 랜섬웨어 대응 절차 **있어?**」)은 문서
  //   RAG(explain) 몫이다 — 침해 낱말이 있어도 초동 절차로 채 가면 안 된다(2026-08-21 실측). 「대응
  //   하려면?」류 절차 의도는 문서지목질문이 스스로 비켜 주므로 여기 걸리지 않는다.
  if (문서지목질문(t)) return false;
  // 「어떻게·절차·대응」처럼 **무엇을 해야 하나**를 묻는 말일 때만. 현황 조회는 다른 몫이다.
  if (/(어떻게|절차|대응|해야\s*(하나|되나|할까)|뭐부터|첫\s*조치|초동)/.test(t)) return true;
  // ★ **사고 중에 「~해도 되나요」는 절차를 묻는 말이다**(2026-08-22 운영 실측으로 신설).
  //
  //   실측: 「랜섬웨어 걸렸을 때 전원을 **꺼도 되나요?**」가 이 목록에 안 걸려 초동을 잃고
  //   **행동 대조**(사내규정 판정)로 갔다. 규정 문서가 없으니 「판단 불가」가 나갔는데,
  //   ⚠ **정답은 바로 아래 침해사고초동절차()에 코드로 들어 있다** — 「전원을 끄지 말고 선을 뽑습니다」.
  //   더 나쁜 것: 그 답변이 참고 자료 칸에 그 문장을 **인용해 놓고** 「판정 근거로 쓰지 않았습니다」
  //   라고 적었다. **정답을 손에 쥐고도 모른다고 답한 것**이다. 불난 집에서 가장 나쁜 모양이다.
  //
  //   ⚠ **활성 사고일 때만** 이 갈래를 연다. 「USB 써도 되나요」 같은 평시 허락 질문까지 여기서
  //   삼키면 행동 대조(계획서 전-2)가 죽는다 — 그건 우리 차별 기능이다.
  //   같은 대칭이 위 법의무/활성침해 게이트에 이미 있다(2026-08-21 검토관 지적으로 만든 것).
  if (활성침해.test(t) && 사고중허락물음.test(t)) return true;
  return false;
}

/** 사고 **중에** 「이렇게 해도 되나」를 묻는 말.
 *
 *  ⚠ 이 저장소에는 같은 「허락 질문인가」 잣대가 이미 **두 벌** 있다
 *    (`actioncheck.ts`의 ACTION_CHECK_RE · `howto.ts`의 PERMISSION_ASK_RE) —
 *    그리고 **이미 어긋나 있다**(한쪽은 `됩`을 받고 한쪽은 안 받는다).
 *  ★ 여기 세 번째를 만드는 것이 마음에 걸리지만, 지금 셋을 합치면 **행동 대조의 그물이 넓어져**
 *    지금은 막다른 길인 「판단 불가」로 더 많은 물음이 떨어진다(그 길은 다음 작업에서 연다).
 *    그래서 **지금은 사고 중 갈래만** 좁게 열고, 합치는 일은 「규정 판정 요청함」과 함께 한다.
 *    ⚠ 이 주석을 지우지 말 것 — 합칠 때 이 자리도 함께 지워야 한다. */
/*  ⚠ 동사 앞을 **선택으로** 둔다. 처음엔 `[가-힣]{1,8}`로 한글을 요구했는데
 *    「**PC** 꺼도 괜찮나요?」가 안 걸렸다 — 앞말이 영문이면 죽는다. 장비 이름은 영문이 흔하다
 *    (PC·NAS·DB·VM·AP). 실측으로 잡은 구멍이다. */
const 사고중허락물음 =
  /(?:[가-힣A-Za-z0-9]{1,12}\s*)?(아도|어도|여도|해도|꺼도|켜도|둬도|놔도|써도|봐도|빼도|뽑아도|지워도|눌러도|끊어도|밀어도|덮어도)\s*(돼|되나|되는지|될까|됩|괜찮|무방|문제\s*없)/;

