// engine/incidentsteps.ts — 장비 장애·중단 초동 절차 (계획서 전-4, 2026-08-09)
//
// 왜 만드나(실측): 「방화벽 장비가 갑자기 죽었어」에 도구가 하나도 안 돌고 모델이 8~13초 동안
// 일반론을 썼다. 답 자체는 그럴듯했지만 **사내 근거가 없어 「근거 약함」 배너**가 붙었다 —
// 지식 저장소를 뒤져 보니 장애 대응 자료가 없고 무관한 문서(Tenable·악성코드 분석)만 걸렸다.
// 제품은 정직했지만, 담당자가 급할 때 받는 것이 「출처 없는 일반론 + 10초 대기」였다.
//
// 그래서 **코드로 낸다**(logguide의 이벤트 대응 절차와 같은 원칙):
//  · 절차는 결정적 규칙 — LLM에 묻지 않는다. 급할 때 읽는 글에 지어냄이 섞이면 안 된다.
//  · 근거는 표준(KISA 침해사고 대응 안내·이중화 운영 관행)에 둔다. 사내 문서 인용이 필요하면
//    "대화창에 물어 근거와 함께 받으라"고 안내하되, 여기서 문서 내용을 지어 넣지 않는다.
//  · **우리 데이터를 붙인다** — 말한 장비가 보안제품 등록부·자산에 있으면 담당자·최근 점검을
//    같이 보여 준다. 그것이 남의 매뉴얼과 다른 점이다.
//
// ⚠ 이건 조회(읽기)다 — 아무것도 바꾸지 않는다. 차단·재부팅 같은 행위는 사람이 한다.
import { listProducts } from "./securityproducts";
import { listAssets } from "./assets";

/** 장애·중단을 말하는 문장인가. 좁게 — 「점검·취약점·설정」 물음까지 삼키면 안 된다. */
const 장애말 =
  /(죽었|다운|먹통|멈췄|멈춤|중단|장애|안\s*(되|돼|열려|잡혀|붙어)|접속\s*(안|불가)|응답\s*(없|안)|끊겼|나갔|셧다운|reboot|재부팅\s*됐)/;
/** 반대로 이 말들이 있으면 장애 질문이 아니다 — 예방·점검·설정 축이다. */
const 장애아님 =
  /(취약점|패치|점검\s*(주기|일정|계획)|설정\s*(방법|어떻게)|스캔|규정|법령|보고서|리포트)/;

export function 장애질문인가(text: string): boolean {
  const t = String(text ?? "");
  if (!장애말.test(t)) return false;
  if (장애아님.test(t)) return false;
  // 대상(장비·시스템)을 가리키는 말이 있어야 한다 — 「일이 안 돼」 같은 넋두리는 아니다.
  if (/(장비|서버|방화벽|ips|ids|waf|edr|utm|스위치|라우터|시스템|호스트|장치|콘솔|웹서버|디비|db)/i.test(t)) return true;
  // ★ 우리 등록부에 있는 이름이면 낱말 종류를 안 따진다(2026-08-09 실측):
  //   「SECUI MF2가 먹통이야」가 장비 낱말이 없어 분기를 비켜 갔다 — 담당자는 장비를
  //   종류가 아니라 **제품 이름**으로 부른다. 이름이 곧 대상이다.
  if (우리것찾기(t) !== null) return true;
  // ★★ 등록부에 **없는** 이름도 받는다(같은 날 재실측): 실서버 등록부에 SECUI MF2가 없어
  //   여전히 12초 LLM 답이었다. 고객마다 장비 이름이 다르므로 등록 여부에 기대면 안 된다.
  //   제품명처럼 보이는 영문 토큰(3자 이상)을 대상으로 인정한다 — 「일이 안 돼」류는
  //   영문이 없어 여전히 걸러지고, 취약점·패치 축은 위 장애아님이 이미 막는다.
  return /[A-Za-z][A-Za-z0-9-]{2,}/.test(t);
}

/** 문장에 든 우리 보안제품·자산 이름(있으면). 없으면 null — 없는 것을 지어내지 않는다. */
function 우리것찾기(text: string): { 종류: "제품" | "자산"; 이름: string; 담당?: string | null } | null {
  const t = text.toLowerCase();
  for (const p of listProducts()) {
    const 이름 = String(p.name ?? "").trim();
    if (이름.length >= 2 && t.includes(이름.toLowerCase())) {
      return { 종류: "제품", 이름, 담당: (p as { owner?: string | null }).owner ?? null };
    }
  }
  for (const a of listAssets()) {
    const 이름 = String((a as { displayName?: string }).displayName || a.name || "").trim();
    if (이름.length >= 3 && t.includes(이름.toLowerCase())) {
      return { 종류: "자산", 이름, 담당: (a as { owner?: string | null }).owner ?? null };
    }
  }
  return null;
}

/**
 * 장비 장애 초동 절차. 급할 때 읽는 글이라 **순서와 이유**만 짧게 준다.
 * 보안장비 특유의 함정(장애 조치로 보안이 뚫리는 것)을 반드시 포함한다 — 이것이 일반
 * IT 장애 절차와 다른 지점이고, 우리가 보안 제품인 이유다.
 */
export function 장애초동절차(instruction: string): string {
  const 것 = 우리것찾기(instruction);
  const 머리 = 것
    ? `**${것.이름}** 장애로 보고 초동 절차를 드립니다(우리 ${것.종류} 등록부에 있는 장비입니다${것.담당 ? ` · 담당 ${것.담당}` : ""}).`
    : "장비 장애 초동 절차입니다(말씀한 장비를 우리 등록부에서 찾지 못했습니다 — 이름을 정확히 적으면 담당자·최근 점검까지 함께 봅니다).";

  return [
    머리,
    "",
    "1. **현상 고정** — 멈춘 시각, 영향 범위(전체 두절인지 일부인지), 직전 변경 작업(패치·정책 수정)을 적습니다. 재부팅부터 하면 원인이 사라집니다.",
    "2. **로그 확보** — 재부팅 **전에** 콘솔 메시지·시스템 로그를 내려받습니다. 살아 있는 증거는 이때만 남습니다.",
    "3. **이중화 확인** — HA 구성이면 대기 장비로 절체됐는지 봅니다. 절체가 안 됐으면 그것이 두 번째 장애입니다.",
    "4. **우회 경로의 보안 상태 확인** ⚠ — 장애를 피하려고 트래픽을 우회시키면 **그 구간은 무방비**가 됩니다. 우회했다면 임시 차단 정책을 함께 겁니다(이 단계가 일반 IT 장애 절차와 다른 자리입니다).",
    "5. **복구 후 검증** — 정책·룰셋이 장애 전 상태로 돌아왔는지, 우회 중 들어온 트래픽에 이상이 없었는지 로그로 확인합니다.",
    "",
    "▸ 이어서 — " +
      (것
        ? `"${것.이름} 최근 점검 내역 보여줘" · "${것.이름} 매뉴얼에서 장애 조치 찾아줘"`
        : '"보안장비 목록 보여줘"로 대상을 먼저 확인하거나, 장비 이름을 적어 다시 물어보세요'),
    "",
    "※ 이 절차는 표준 관행(KISA 침해사고 대응 안내·이중화 운영)에 따른 **일반 순서**입니다. 장비별 세부 조치는 그 제품 매뉴얼이 기준이며, 매뉴얼을 올려 두셨다면 대화창에서 근거와 함께 찾아 드립니다.",
  ].join("\n");
}
