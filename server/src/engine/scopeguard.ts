// engine/scopeguard.ts — 보안 업무 밖 질문을 일관되게 거절하고 할 수 있는 것으로 되돌린다.
//
// 왜(2026-07-26 사용자 지시 + 표준 조사): 도메인 챗봇 모범사례는 "명확히 거절하고, 대신 할 수 있는
// 것을 알려주며, 일관된 문구로 답하라"다(NN/g·가드레일 실무 가이드 공통). 지금은 이 처리가 없어서
// 업무 밖 질문이 오면 사내 문서에서 아무거나 끌어와 그럴듯하게 답했다 — 오답보다 나쁜 건 "그럴듯한 오답"이다.
//
// 왜 인터넷 검색을 붙이지 않았나: 이 제품은 온프렘이 원칙이다. 업무 밖 질문 때문에 외부 연결을 열면
// 담당자가 무심코 사내 정보를 섞어 물었을 때 그게 밖으로 나간다. 외부가 정말 필요하면 이미 있는
// 클라우드 LLM 연동(관리자 승인 + egress 게이트)이 그 자리를 맡는다.
//
// 설계 원칙: **좁게 잡는다.** 업무 질문을 잘못 거절하는 쪽이 훨씬 나쁘므로, 누가 봐도 업무 밖인
// 주제만 목록으로 두고, 보안·IT 낱말이 하나라도 섞이면 거절하지 않는다.

// 누가 봐도 우리 업무가 아닌 주제. 새로 추가할 땐 "보안 담당자가 업무 중 물을 리 없는가"를 기준으로.
const OFF_TOPIC_RE =
  /(날씨|기온|미세먼지|비\s*와|눈\s*와)|(주식|코인|비트코인|환율|부동산|집값|로또)|(맛집|레시피|요리|다이어트|운동\s*추천)|(영화|드라마|예능|아이돌|연예인|축구|야구|프로야구|월드컵)|(운세|사주|타로|궁합)|(여행|숙소|항공권|호텔\s*추천)|(농담|웃긴|심심|놀자|사랑해|결혼|연애)|(번역해|영작|일본어로|중국어로)/;

// 우리 업무 낱말 — 하나라도 있으면 업무 질문으로 본다(잘못 거절하지 않기 위한 안전장치).
const IN_SCOPE_RE =
  /보안|취약|자산|스캔|점검|하드닝|침해|악성|공격|해킹|위협|로그|방화벽|백신|랜섬|피싱|인증|권한|접근|암호|계정|패치|서버|네트워크|시스템|장비|제품|리포트|보고서|규정|컴플라이언스|개인정보|법령|고시|판례|AI|LLM|모델|에이전트|세션|백업|알림|설정|화면|메뉴|기능|사용법|도움말|CVE|KEV|SBOM|ISMS|OWASP|MITRE/i;

/** 보안 업무와 상관없는 질문인가 — 확실할 때만 true(애매하면 false). */
export function isOutOfScope(text: string): boolean {
  const t = String(text ?? "").trim();
  if (t.length < 2) return false;
  if (IN_SCOPE_RE.test(t)) return false; // 업무 낱말이 섞이면 절대 거절하지 않는다
  return OFF_TOPIC_RE.test(t);
}

/** 거절 문구 — 매번 같아야 신뢰가 쌓인다(얼버무리면 오히려 불신). 할 수 있는 것을 함께 알린다. */
export function outOfScopeAnswer(): string {
  return [
    "이 질문은 제가 다루는 범위가 아닙니다 — 저는 사내 보안 업무만 돕습니다.",
    "",
    "대신 이런 것을 물어보세요:",
    '  · "오늘 뭐부터 볼까?" — 급한 조치 순서',
    '  · "미조치 취약점 알려줘" — 남은 취약점과 담당',
    '  · "개인정보보호법 뭐라고 돼 있어?" — 관련 법령·고시 원문',
    "",
    "사내 자료와 등록된 도구로 답할 수 있는 것만 다룹니다(외부로 질문을 보내지 않습니다).",
  ].join("\n");
}

// 뜻을 알 수 없는 입력 — 한두 글자, 기호·자음만, 숫자만. LLM에 보내면 헤매다 10초를 쓰고
// 그게 "오래 걸리는 작업"으로 오해돼 리포트까지 만들어졌다(2026-07-26 실측: "1"·"?"·"ㅁ" 모두 10.4초).
// 보내기 전에 되묻는 게 빠르고 정직하다.
const MEANINGLESS_RE = /^[\s.,!?~\-_'"`\/\|@#$%^&*()\[\]{}<>:;+=]*$|^[ㄱ-ㅎㅏ-ㅣ]+$/;

// ── 「…해 줘」 요청 어미 — 오타·구어를 **한 곳에서** 받는다 ──────────────────────
//
// 왜(2026-09-04 야간 회귀 ⑪마당 「사람은 이렇게 친다 — 모호·오타·짧게」 실위반):
//   「취약점 알려주세여」가 어느 도구에도 안 걸려 LLM 일반론으로 답했다("현재 제공된
//   정보로는 특정 취약점이 명시되어 있지 않습니다…"). 같은 마당의 「취약점」 한 낱말은
//   현황 카드로 잘 가는데 **말을 더 붙이자 답이 나빠졌다** — 공손하게 물을수록 손해다.
//   실제 데이터가 202건 있는데 "명시되어 있지 않습니다"는 「할 일 없다」 거짓 계열이다.
//
// ⚠ 새 어미는 **여기만** 늘린다. 규칙마다 베껴 적으면 한 곳만 고쳐져 어긋난다
//   (이 저장소가 반복해 겪은 「같은 것을 여러 곳에 적으면 어긋난다」).
// ⚠ 긴 것을 앞에 둔다 — 「줘」가 먼저 맞으면 「줘여」의 뒷글자가 남아 문장 끝($)에서 깨진다.
// ⚠ 이 상수는 **문자열**이다(정규식 조각). 쓰는 쪽에서 다른 조각과 이어 붙인다.
export const 요청어미 =
  "(?:주세요|주세여|주세염|주세욤|주세용|주십시오|주시오|주실래요?|주라|줄래요?|줘요|줘여|줘용|줘|주삼)";

/**
 * **한 낱말만 던졌을 때** 되묻되, 그 낱말에 맞는 예시를 준다.
 *
 * 실측(2026-08-01 하루 실전 ⑪마당): 담당자는 "취약점", "급한거", "방화벽"처럼
 * 한 낱말만 치는 일이 흔하다. 그런데 이건 뜻 없는 입력이 아니라서 LLM으로 갔고,
 * **34초를 헤매다 내부 규칙 이야기**를 내놨다. 뜻은 분명한데 무엇을 원하는지만 없다.
 *
 * ⚠ 대신 답해 주지 않는다 — "취약점"이 "목록 보여줘"인지 "설명해줘"인지 알 수 없다.
 *   추측해서 답하면 틀렸을 때 담당자가 더 헤맨다. **고를 수 있게** 해 주는 것이 맞다.
 */
const 한낱말안내: { re: RegExp; 예시: string[] }[] = [
  { re: /^취약점$|^취약점\s*[?？]?$/, 예시: ['"미조치 취약점 알려줘"', '"오늘 뭐부터 볼까?"', '"Log4Shell 있어?"'] },
  { re: /^(급한거|급한\s*거|급한것|긴급)[?？]?$/, 예시: ['"오늘 뭐부터 볼까?"', '"기한 지난 조치 알려줘"', '"KEV 걸린 거 있어?"'] },
  { re: /^방화벽[?？]?$/, 예시: ['"방화벽 뭐 쓰고 있어?"', '"방화벽 월간 정기점검 절차 알려줘"', '"방화벽 반려 사유 뭐였어?"'] },
  // ⚠ 「자산」·「취약점」·「리포트」·「보고서」·「보고」·「조치」·「기록」·「위협」 등은 화면이름 카드
  //   (datacard.ts 화면이름카드, dispatcher에서 이 되묻기보다 앞)가 먼저 잡는다 — 아래 해당
  //   항목은 도달 불가(2026-08-20 카드 확장으로 리포트·보고서도 편입). 지우지 않고 남긴다:
  //   카드 맵에서 빠지면 여기가 다시 받는다.
  { re: /^자산[?？]?$/, 예시: ['"우리 자산 몇 대야?"', '"위험도 높은 자산 알려줘"', '"자산 등록하려면 어떻게 해?"'] },
  { re: /^점검[?？]?$/, 예시: ['"기한 지난 점검 알려줘"', '"이번 달 점검 일정 뭐야?"', '"유지보수 점검 절차 알려줘"'] },
  { re: /^리포트[?？]?$|^보고서[?？]?$/, 예시: ['"이번 달 보안 리포트 만들어줘"', '"경영진 보고용으로 요약해줘"'] },
  { re: /^오늘[?？]?$/, 예시: ['"오늘 뭐부터 볼까?"', '"오늘 브리핑 해줘"', '"내 할 일 몇 개 남았어?"'] },
];

/** 한 낱말 입력이면 그 낱말에 맞는 예시 안내를 돌려준다. 아니면 null. */
export function 한낱말되묻기(text: string): string | null {
  const t = String(text ?? "").trim();
  const hit = 한낱말안내.find((h) => h.re.test(t));
  if (!hit) return null;
  return [
    `"${t}"에 대해 무엇을 알고 싶으신가요? 이렇게 물어보시면 바로 답합니다.`,
    "",
    ...hit.예시.map((e) => `  · ${e}`),
  ].join("\n");
}
export function isTooVague(text: string): boolean {
  const t = String(text ?? "").trim();
  if (!t) return true;
  if (MEANINGLESS_RE.test(t)) return true;   // 기호·자음만
  if (/^\d+$/.test(t)) return true;          // 숫자만("1")
  return t.replace(/\s/g, "").length <= 2;   // 두 글자 이하
}

