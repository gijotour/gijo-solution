// engine/scopeguard.ts — 보안 업무 밖 질문을 일관되게 거절하고 할 수 있는 것으로 되돌린다.
//
// 왜(2026-07-26 사용자 지시 + 표준 조사): 도메인 챗봇 모범사례는 "명확히 거절하고, 대신 할 수 있는
// 것을 알려주며, 일관된 문구로 답하라"다(NN/g·가드레일 실무 가이드 공통). 지금은 이 처리가 없어서
// 업무 밖 질문이 오면 사내 문서에서 아무거나 끌어와 그럴듯하게 답했다 — 오답보다 나쁜 건 "그럴듯한 오답"이다.
//
// 왜 인터넷 검색을 붙이지 않았나: 이 제품은 온프렘이 원칙이다. 업무 밖 질문 때문에 외부 연결을 열면
// 담당자가 무심코 사내 정보를 섞어 물었을 때 그게 밖으로 나간다. 외부가 정말 필요하면 이미 있는
// 클라우드 LLM 연동(관리자 승인 + egress 게이트)이 그 자리를 맡는다.
//
// 설계 원칙: **좁게 잡는다.** 업무 질문을 잘못 거절하는 쪽이 훨씬 나쁘므로, 누가 봐도 업무 밖인
// 주제만 목록으로 두고, 보안·IT 낱말이 하나라도 섞이면 거절하지 않는다.

// 누가 봐도 우리 업무가 아닌 주제. 새로 추가할 땐 "보안 담당자가 업무 중 물을 리 없는가"를 기준으로.
const OFF_TOPIC_RE =
  /(날씨|기온|미세먼지|비\s*와|눈\s*와)|(주식|코인|비트코인|환율|부동산|집값|로또)|(맛집|레시피|요리|다이어트|운동\s*추천)|(영화|드라마|예능|아이돌|연예인|축구|야구|프로야구|월드컵)|(운세|사주|타로|궁합)|(여행|숙소|항공권|호텔\s*추천)|(농담|웃긴|심심|놀자|사랑해|결혼|연애)|(번역해|영작|일본어로|중국어로)/;

// 우리 업무 낱말 — 하나라도 있으면 업무 질문으로 본다(잘못 거절하지 않기 위한 안전장치).
const IN_SCOPE_RE =
  /보안|취약|자산|스캔|점검|하드닝|침해|악성|공격|해킹|위협|로그|방화벽|백신|랜섬|피싱|인증|권한|접근|암호|계정|패치|서버|네트워크|시스템|장비|제품|리포트|보고서|규정|컴플라이언스|개인정보|법령|고시|판례|AI|LLM|모델|에이전트|세션|백업|알림|설정|화면|메뉴|기능|사용법|도움말|CVE|KEV|SBOM|ISMS|OWASP|MITRE/i;

/** 보안 업무와 상관없는 질문인가 — 확실할 때만 true(애매하면 false). */
export function isOutOfScope(text: string): boolean {
  const t = String(text ?? "").trim();
  if (t.length < 2) return false;
  if (IN_SCOPE_RE.test(t)) return false; // 업무 낱말이 섞이면 절대 거절하지 않는다
  return OFF_TOPIC_RE.test(t);
}

/** 거절 문구 — 매번 같아야 신뢰가 쌓인다(얼버무리면 오히려 불신). 할 수 있는 것을 함께 알린다. */
export function outOfScopeAnswer(): string {
  return [
    "이 질문은 제가 다루는 범위가 아닙니다 — 저는 사내 보안 업무만 돕습니다.",
    "",
    "대신 이런 것을 물어보세요:",
    '  · "오늘 뭐부터 볼까?" — 급한 조치 순서',
    '  · "미조치 취약점 알려줘" — 남은 취약점과 담당',
    '  · "개인정보보호법 뭐라고 돼 있어?" — 관련 법령·고시 원문',
    "",
    "사내 자료와 등록된 도구로 답할 수 있는 것만 다룹니다(외부로 질문을 보내지 않습니다).",
  ].join("\n");
}
