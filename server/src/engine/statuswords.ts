// 담당자가 쓰는 **우리말 상태어**를 저장된 영문 값으로 옮긴다.
//
// ⚠ 이것이 없어서 생긴 실사고(2026-08-01, 챗봇 전수 점검에서 발견):
//   담당자: "컴플라이언스 대응 안 된 항목 알려줘"
//   AI:     "미이행 항목이 없습니다."   ← 실제로는 21건 중 16건이 미대응(open 10·partial 6)
//   담당자: "미조치 취약점 알려줘"
//   AI:     "미조치 취약점이 없습니다." ← 실제로는 활성 46건·조치율 0%
//
//   원인은 **모델이 아니라 코드**였다. 모델은 지시에서 "미이행"·"미조치"를 정확히 뽑아
//   filter로 넘겼는데, 도구가 그 글자를 저장값(open·partial·pending…)에 **글자 그대로**
//   대조했다. 우리말은 저장값에 없으니 언제나 0건이고, 모델은 도구가 없다고 하니
//   없다고 답한 것이다 — 모델은 정직했고 도구가 거짓말을 시켰다.
//
//   보안담당자에게 "할 일이 없다"고 잘못 답하는 것은 이 제품에서 가장 나쁜 실패다.
//   찾지 못했으면 "없다"가 아니라 못 찾았다고 해야 한다.
//
// ⚠ 프롬프트로 고치려 들지 말 것 — 7B에 "필터는 영어로 쓰라"고 시키는 방식은 이 저장소에서
//   반복해 실패했다(CLAUDE.md). 말은 사람이 하는 대로 두고 **코드가 알아듣는다.**

/** 상태어 사전 — 우리말(및 흔한 변형) → 저장된 값들. 한 낱말이 여러 값에 걸릴 수 있다. */
const 사전: { 말: RegExp; 값: string[] }[] = [
  // 아직 손이 필요한 쪽
  // ⚠ 도메인마다 저장값이 다르다 — **한 도메인이라도 빠지면 그 화면에서만 영영 0건**이 된다.
  //   2026-08-01 검토에서 잡혔다: 유지보수 점검의 상태는 scheduled·reported·approved·rejected인데
  //   "미조치"를 open·partial·pending으로만 풀어 **교집합이 비었다.** "미조치 점검 알려줘"가
  //   기한 지난 점검이 잔뜩 있는데도 "못 찾았습니다"로 답했다. 새 도메인을 붙일 때 여기부터 본다.
  { 말: /^(미조치|미대응|미이행|미처리|안된|안됀|해결안됨|미해결|남은|열린)$/, 값: ["open", "partial", "pending", "scheduled", "reported"] },
  { 말: /^(진행중|부분|부분대응|일부)$/, 값: ["partial", "in_progress", "reported"] },
  { 말: /^(대기|검토대기|승인대기|미검토|예정)$/, 값: ["pending", "scheduled"] },
  { 말: /^(지연|기한초과|기한지남|늦음)$/, 값: ["overdue"] },
  // 끝난 쪽
  { 말: /^(조치완료|완료|대응됨|이행|처리됨|승인|승인됨|닫힘)$/, 값: ["covered", "approved", "done", "closed"] },
  { 말: /^(반려|오탐|거부)$/, 값: ["rejected"] },
  // 위험수용 — 반려(취약점 아님)와 다르다: 실재하지만 기한까지 안 고치기로 결정한 것(2026-08-20).
  { 말: /^(위험수용|수용|리스크수용)$/, 값: ["accepted"] },
  { 말: /^(해당없음|무관|해당사항없음)$/, 값: ["na", "not_affected"] },
];

/**
 * 우리말 상태어면 대응하는 저장값들을 돌려준다. 상태어가 아니면 빈 배열.
 * (자산 이름·코드 같은 보통 검색어는 여기 걸리지 않아야 하므로 **완전일치**로만 본다.)
 */
export function 상태값들(말: string): string[] {
  const w = String(말 ?? "").trim().toLowerCase().replace(/\s+/g, "");
  if (!w) return [];
  for (const e of 사전) if (e.말.test(w)) return e.값;
  return [];
}

/**
 * 상태 칸이 아니라 **줄의 다른 속성**(담당·기한·심각도)을 가리키는 우리말.
 *
 * ⚠ 이것이 없어서 생긴 실사고(2026-08-07, 147상황 4차):
 *   담당자: "미배정 취약점 몇 건이야?" → AI: "조건('미배정')에 맞는 취약점을 못 찾았습니다"
 *   같은 회차의 현황 답은 **담당자 미배정 4,820건**이라고 말했다 — 한 제품이 같은 것을
 *   두 입으로 다르게 말한 것이다. "기한"·"고위험,미배정"도 같은 길로 죽었다(쉼표도 못 갈랐다).
 *   미배정은 상태 칸에 없다 — 담당 칸이 비었다는 뜻이다. 상태어 사전만으로는 영영 0건이다.
 */
export interface 줄속성 {
  심각도?: string | null;   // critical·high·medium·low
  담당자?: string | null;   // 비어 있으면 미배정
  기한지남?: boolean;       // 기한이 지났는데 아직 안 끝난 건
}

const 속성사전: { 말: RegExp; 판정: (a: 줄속성) => boolean }[] = [
  { 말: /^(미배정|담당자?없(음|는|이)?|배정안됨?|담당미지정|미지정)$/, 판정: (a) => !String(a.담당자 ?? "").trim() },
  { 말: /^(기한|기한초과|기한지남|기한넘은|지연|늦은|늦음|초과)$/, 판정: (a) => a.기한지남 === true },
  { 말: /^(고위험|심각|매우심각|치명|위험높은)$/, 판정: (a) => ["critical", "high"].includes(String(a.심각도 ?? "").trim().toLowerCase()) },
];

/**
 * 도구 필터 공용 대조. 검색어를 낱말로 쪼개, 낱말마다
 *   · 속성어(미배정·기한·고위험)면 → 그 줄의 **해당 속성**을 본다(속성을 준 호출자만)
 *   · 상태어면 → 그 줄의 **상태 칸**과 정확히 맞는지 본다
 *   · 아니면   → 본문에 글자 그대로 들어 있는지 본다
 * 모든 낱말이 통과해야 맞는 것으로 본다(AND). 낱말을 늘릴수록 좁아진다는 상식과 맞는다.
 * 낱말은 공백뿐 아니라 쉼표·가운뎃점으로도 가른다 — 모델이 "고위험,미배정"처럼 넘긴다.
 *
 * ⚠ 상태는 **본문에서 찾으면 안 된다**(2026-08-01 실측). 처음엔 본문에 open이 들어 있는지로
 *   봤더니 `OpenSSH < 9.6 …` 취약점이 "미조치"로 잡혔다 — 상태는 approved인데도. openssl·
 *   OpenVPN처럼 제품 이름에 상태값이 우연히 섞이는 일은 보안 도메인에서 매우 흔하다.
 *   상태를 물으면 상태 칸만 본다. 속성어도 같은 이유로 본문 대조에 떨어뜨리지 않는다 —
 *   속성을 못 받은 호출자(그 도메인에 담당·기한 개념이 없는 곳)에서만 본문 대조로 남는다.
 *
 * @param 상태 그 줄의 실제 상태값(open·pending·approved…). 없으면 상태어 조건은 통과 못 한다.
 * @param 속성 담당·기한·심각도. 이 도메인에 그 개념이 있으면 호출자가 채워 준다.
 */
export function 필터에맞나(건초더미: string, 검색어: string, 상태?: string | null, 속성?: 줄속성): boolean {
  const hay = String(건초더미 ?? "").toLowerCase();
  const st = String(상태 ?? "").trim().toLowerCase();
  const words = String(검색어 ?? "").trim().toLowerCase().split(/[\s,·、]+/).filter(Boolean);
  if (!words.length) return true;
  return words.every((w) => {
    if (속성) {
      const p = 속성사전.find((e) => e.말.test(w));
      if (p) return p.판정(속성);
    }
    const 값 = 상태값들(w);
    if (값.length) return st ? 값.includes(st) : false;
    // 영문 저장값(open·approved…)을 그대로 친 경우도 상태 칸으로 받는다. 본문 대조에 맡기면
    // OpenSSH 같은 이름에 걸린다 — 상태는 언제나 상태 칸에서만 본다.
    if (st && st === w) return true;
    return hay.includes(w);
  });
}
