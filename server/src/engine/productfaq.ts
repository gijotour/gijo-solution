/** 지시가 지식 카드에 맞으면 그 답을, 아니면 null. */
export function faqAnswerFor(instruction: string): { id: string; answer: string } | null {
  const t = String(instruction ?? "").trim();
  if (!t) return null;
  for (const c of FAQ_CARDS) if (c.re.test(t)) return { id: c.id, answer: c.answer };
  return null;
}
