// 하지 않은 일을 했다고 말하지 않는다 — 거짓 완료 관문.
//
// 왜 있나: 2026-08-09 평가 게이트에서 「새 서버 10.0.0.99를 자산으로 등록해줘」가
// 쓰기 도구로 못 가고 잡담(chat)으로 샜다. 그러자 모델이
//   "10.0.0.99 IP 주소의 서버를 자산으로 등록하였습니다."
// 라고 답했다. **등록부에는 아무것도 없었다.** 담당자는 등록된 줄 알고 넘어간다 —
// 못 한 것보다 나쁘다.
//
// 라우팅 규칙(FORCED_INTENTS)을 넓히는 것만으로는 못 막는다. 사람이 쓰는 말투는 무한하고,
// 규칙에 없는 표현은 앞으로도 잡담으로 샌다. 그래서 **출구에 관문을 하나 둔다**:
// 쓰기를 시킨 말에 잡담으로 답했는데 그 답이 "했습니다"라고 말하면, 그 문장을 내보내지 않는다.
//
// ⚠ 좁게 잡는다 — 지시가 쓰기였고(①) 답이 1인칭 완료를 주장할 때(②) 둘 다일 때만 바꾼다.
//    "등록하면 됩니다" 같은 안내나 남이 한 일 서술은 건드리지 않는다.

/** ① 쓰기를 시킨 말인가 — 「…해줘/할게/해라」꼴로 시키는 동사만. */
const 쓰기지시 =
  /(등록|추가|생성|삭제|지워|제거|변경|수정|배정|할당|설정|저장|올려|반영|적용|표시|표기|닫아|종료)\s*(을|를)?\s*(해\s*줘|해줘|해라|하자|할게|하고\s*싶|해\s*주세요|부탁|처리해)/;

/** ② 답이 「내가 했다」고 주장하는가 — 과거 완료형만. */
const 완료주장 =
  /(등록|추가|생성|삭제|제거|변경|수정|배정|할당|설정|저장|반영|적용|표시|표기|처리)\s*(을|를)?\s*(하였|했|완료하였|완료했|마쳤|끝냈)(습니다|어요|다\b)|(등록|추가|생성|삭제|제거|변경|수정|배정|할당|설정|저장|반영|적용|표시|표기)\s*(이|가)?\s*(되었|됐|완료되었|완료됐)(습니다|어요)/;

export function 쓰기지시인가(말: string): boolean {
  return 쓰기지시.test(말);
}

export function 완료를주장하는가(답: string): boolean {
  return 완료주장.test(답);
}

/** 거짓 완료일 때 대신 내보낼 정직한 답. 무엇이 실제로 일어났는지부터 말한다. */
export function 정직한대체답(지시: string): string {
  return [
    "**아직 아무것도 바꾸지 않았습니다.**",
    "",
    `“${지시.trim()}” — 이건 자료를 **바꾸는 일**이라 확인(결재판)을 거쳐야 실행됩니다.`,
    "제가 무엇을 바꿀지 아직 정확히 짚지 못해서, 임의로 실행하지 않고 멈췄습니다.",
    "",
    "이렇게 다시 적어 주시면 바로 결재판을 띄워 드립니다 —",
    "· 자산 등록: `자산 등록해줘 — 이름 웹서버01, 주소 10.0.0.99`",
    "· 담당자 배정: `CVE-2021-44228 담당자를 홍길동으로 배정해줘`",
    "· 상태 변경: `이 취약점을 오탐으로 표시해줘`",
  ].join("\n");
}

/**
 * 잡담 경로로 나온 답을 검사한다. 거짓 완료면 정직한 답으로 바꾸고,
 * 아니면 원문 그대로 돌려준다.
 *
 * @param 도구가돌았나 쓰기 도구가 실제로 실행됐으면 true — 그때는 "했습니다"가 사실이므로 통과.
 */
export function 거짓완료차단(지시: string, 답: string, 도구가돌았나 = false): { 답: string; 막았나: boolean } {
  if (도구가돌았나) return { 답, 막았나: false };
  if (!지시 || !답) return { 답, 막았나: false };
  if (!쓰기지시인가(지시)) return { 답, 막았나: false };
  if (!완료를주장하는가(답)) return { 답, 막았나: false };
  return { 답: 정직한대체답(지시), 막았나: true };
}
