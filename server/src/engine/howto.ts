// ★ "이거 해도 돼?"는 **순서를 묻는 말이 아니다.**
//
//   평가 게이트가 잡았다(2026-07-31): "점검 결과를 개인 메일로 보내도 돼?" 에
//   이 표의 SMTP 항목이 걸려("메일"+"보내") **설정 순서**를 안내했다.
//   그 질문은 사내규정·법령 근거로 ○/△/× 를 판정하는 **행동 대조**(계획서 전-2)의 몫이고,
//   그건 우리 제품의 차별점이다 — 순서 안내가 가로채면 차별 기능이 죽는다.
//
//   개별 규칙을 하나씩 좁히는 대신 여기서 한 번에 막는다. 규칙을 더할 때마다 같은 실수를
//   반복하지 않으려면 판단이 한 곳에 있어야 한다.
const PERMISSION_ASK_RE =
  // ⚠ "됩니까"는 '되'로 시작하지 않는다(됩) — 시험이 이 빠짐을 잡았다. 어미를 넉넉히 적는다.
  /(해도|하여도|봐도|보내도|써도|쓰도|사용해도|저장해도|올려도|내려받아도|가져가도|공유해도|접속해도|열어도|반출해도|복사해도)\s*(되|돼|됩|괜찮|무방|문제\s*없)|허용\s*(되|됩|인가)|규정\s*(상|에)\s*(맞|되)/;

/** 담당자 말에 걸리는 안내를 찾는다. 없으면 null(평소대로 답한다). */
export function findHowTo(text: string): HowTo | null {
  const t = String(text || "");
  if (PERMISSION_ASK_RE.test(t)) return null; // 허용 여부 질문 → 행동 대조가 답한다
  return HOWTOS.find((h) => h.match.test(t)) ?? null;
}

/** 대화창에 그대로 그려질 마크다운(굵은 글씨·번호 목록이 렌더된다). */
export function howToMarkdown(h: HowTo): string {
  const head = h.page ? `**${h.where}** 에서 이렇게 하세요 — ${h.title}` : `**${h.title}** — ${h.where}`;
  return [h.why, "", head, "", ...h.steps.map((s, i) => `${i + 1}. ${s}`)].join("\n");
}
