//   제거한 개조본)다. `Qwen3-14B-GGUF`로 쳐도 공식본이 안 나오고, **조직명을 포함한**
//   `Qwen/Qwen3-14B-GGUF`로만 나온다.
//   → 안내를 그대로 따른 고객이 **안전장치가 제거된 모델을 먼저 본다.**
//     보안 관제 제품에서 그런 모델이 실리면 그 자체가 감사 지적 사항이 된다.
//
// ■ 그래서 검색이 아니라 **목록**이다
//   우리는 이미 기준 모델을 정했고(평가 게이트 통과 근거까지 있다), 고객에게 고르게 할
//   이유가 없다. 조직명·파일명·크기를 **여기 한 곳에** 못 박고 화면은 누르기만 한다.
//
// ■ 과거 전례 대응 — 죽은 안내를 만들지 않는다
//   2026-08-08에 추천 카탈로그를 지운 이유가 「추천 모델이 서버에 없는 죽은 안내를 냈다」였다.
//   그래서 이번엔 목록을 **그대로 믿지 않는다**: 화면에 뿌리기 전에 저장소가 실제로 있는지
//   확인하고, 없으면 「확인 필요」로 표시한다(가짜 버튼을 만들지 않는다).
//
// ⚠ 여기 없는 모델을 받는 길(BYOM)은 막지 않는다 — 화면의 「고급 · 직접 검색」에 남는다.
//   BYOM은 이 제품의 차별점이다. 다만 **기본값이 안전한 쪽**이어야 한다.

/** 안전정렬이 제거된 개조본을 가리키는 이름들. 받기 전에 한 번 더 확인을 받는다. */
const 개조본표식 = /(uncensored|abliterat|heretic|jailbr|unaligned|unfiltered|no[-_]?guard)/i;

/**
 * 이름만으로 「개조본일 수 있다」고 본다.
 * ⚠ 이건 **거름망이지 판정이 아니다.** 이름 규칙은 계속 새로 생기므로 여기에 기대면 안 된다 —
 *   진짜 방어는 「고르지 않게 하는 것」(권장 목록)이고, 이건 마지막 그물이다.
 */
export function 개조본일수있나(modelId: string): boolean {
  return 개조본표식.test(modelId);
}

