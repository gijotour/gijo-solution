/**
 * 이 저장소가 **로컬에 놓일 수 있는 폴더 이름들**. 하나가 아니라 여러 개다.
 *
 * ⚠ 왜 여러 개인가(2026-08-10 실측): 받기 경로(hfmodels.runHfDownload)는
 *   `Qwen/Qwen3-14B-GGUF` → `models/Qwen__Qwen3-14B-GGUF/` 로 놓는데,
 *   **운영에 실제로 있는 것은 `models/qwen3-14b/`·`models/bge-m3/`** 다(사람이 짧은 이름으로
 *   놓았다). 그래서 `org__repo` 하나만 보면 **이미 가진 모델에 「받기」가 뜬다** —
 *   눌러도 되지만 8.4GB를 다시 받는다. 죽은 버튼의 반대 방향 사고다.
 *   목록에 있는 것이 실제로 있는지 보려면 **두 가지 이름을 다** 봐야 한다.
 * ⚠ 추측하지 말 것: 이 규칙은 운영 models/ 폴더를 직접 보고 맞췄다.
 */
export function 로컬폴더후보(repo: string): string[] {
  const 전체 = repo.trim();
  const 짧은이름 = (전체.split("/").pop() ?? 전체).replace(/[-_.]?gguf$/i, "");
  return [
    전체.replace(/\//g, "__"), // 받기가 만드는 이름
    짧은이름, // 사람이 짧게 놓은 이름 (예: Qwen3-14B)
    짧은이름.toLowerCase(), // 운영 실제 (예: qwen3-14b · bge-m3)
  ];
}
