//   확인해 보니 **없었다.** 지원이 끝난 소프트웨어는 취약점이 나와도 고칠 패치가 없으니
//   보안담당자에게는 취약점 목록만큼 중요한 정보다.
//
// ■ 왜 표를 실어 나르나
//   온라인 EOL API(endoflife.date 등)를 쓸 수 없다 — 우리 제품은 폐쇄망 전제다.
//   그래서 기본 지식 번들(전-4)에 실어 배포하고, 갱신은 번들 갱신으로 한다(후-3 구독화의 근거).
//
// ⚠⚠ **이 표의 날짜는 아직 확인 전이다.**
//   보안 제품에서 틀린 지원종료일은 "고칠 패치가 있는 줄 알았는데 없다" 또는 그 반대를 만든다.
//   그래서 **모든 항목에 `확인필요: true`가 붙어 있고**, 답변·화면은 그 사실을 함께 말한다.
//   벤더 공지로 대조한 뒤 `확인필요`를 내리고 `확인일`을 적는 것이 다음 걸음이다.
//   ⚠ 확인 전 항목을 **확인된 것처럼 보이게 만들지 않는다** — 그러면 이 표는 없느니만 못하다.

export interface EolRow {
  /** 제품 이름 — SBOM 부품 이름과 느슨하게 맞춘다(소문자·부분 일치). */
  제품: string;
  /** 버전 대역(있으면). 비우면 제품 전체. */
  버전?: string;
  /** 지원 종료일 YYYY-MM-DD. 모르면 비운다 — **추측해 채우지 않는다.** */
  종료일?: string;
  /** 어디서 온 값인가. **출처 없는 줄은 넣지 않는다.** */
  출처: string;
  /** 벤더 공지로 대조했는가. 안 했으면 true(=아직 못 믿는다). */
  확인필요: boolean;
  /** 대조한 날. 확인필요가 false일 때만 뜻이 있다. */
  확인일?: string;
}

