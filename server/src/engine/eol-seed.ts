/** 부품 이름·버전으로 표를 찾는다. **못 찾으면 null**(모른다 — 지원 중이라는 뜻이 아니다). */
export function eol찾기(이름: string, 버전?: string): EolRow | null {
  const n = String(이름 ?? "").toLowerCase();
  if (!n) return null;
  const v = String(버전 ?? "");
  // 제품 이름이 들어 있고, 버전 대역이 있으면 그 대역으로 시작하는 것만.
  const 후보 = EOL_SEED.filter((r) => n.includes(r.제품));
  if (후보.length === 0) return null;
  if (!v || v === "-") return 후보.find((r) => !r.버전) ?? null;
  return 후보.find((r) => r.버전 && v.startsWith(r.버전)) ?? 후보.find((r) => !r.버전) ?? null;
}

/** 담당자에게 그대로 나가는 한 줄. **확인 전이라는 사실을 반드시 함께 말한다.** */
export function eol한줄(row: EolRow, 오늘 = new Date()): string {
  if (!row.종료일) return `지원 종료일을 모릅니다(${row.출처} — 값 없음).`;
  const 끝 = new Date(row.종료일 + "T00:00:00");
  const 지났나 = 끝.getTime() < 오늘.getTime();
  // ⚠⚠ **「패치가 없다」를 조건 없이 단정하지 않는다**(2026-09-02 벤더 대조에서 드러남).
  //   9줄 중 5줄이 오늘도 유상 패치를 받는 중이다 — 그 고객에게 이 문장은 **거짓**이고,
  //   담당자는 멀쩡히 패치받는 서버를 교체 대상에 올린다.
  //   ⚠ 그렇다고 「연장이 있으니 괜찮다」로 뒤집지도 않는다 — **우리는 그 고객이 그걸 샀는지
  //     모른다**(자산 목록에 구독 칸이 없다). 판정(⚠)은 그대로 두고 **확인을 요청**한다.
  const 연장 = row.유상연장;
  const 연장살아있나 = 연장 ? !연장.종료일 || new Date(연장.종료일.length === 7 ? `${연장.종료일}-28` : 연장.종료일).getTime() >= 오늘.getTime() : false;
  const 머리 = 지났나
    ? 연장 && 연장살아있나
      ? `⚠ **무상 지원이 끝난 버전입니다**(${row.종료일}). 다만 **${연장.이름}**${연장.종료일 ? `(${연장.종료일}까지)` : "(종료일 미정)"}을 계약했다면 아직 보안 패치를 받습니다 — **귀사가 그것을 쓰고 있는지 확인해 주세요.** 안 쓰고 있다면 취약점이 나와도 고칠 패치가 없습니다.`
      : 연장
        ? `⚠ **지원이 끝난 버전입니다**(${row.종료일}) — 취약점이 나와도 고칠 패치가 없습니다. (${연장.이름}도 ${연장.종료일}에 끝났습니다.)`
        : `⚠ **지원이 끝난 버전입니다**(${row.종료일}) — 취약점이 나와도 고칠 패치가 없습니다.`
    : `지원 종료 예정일 ${row.종료일}.` +
      (연장 ? ` 그 뒤 **${연장.이름}**${연장.종료일 ? `(${연장.종료일}까지)` : ""}으로 연장할 수 있습니다.` : "");
  // ⚠ 확인 전이면 **그렇다고 말한다.** 이 문장을 빼면 담당자가 확정 사실로 읽는다.
  const 꼬리 = row.확인필요
    ? ` (출처 ${row.출처} · **아직 벤더 공지로 대조하지 않은 값입니다 — 조치 전에 확인해 주세요**)`
    : ` (출처 ${row.출처} · ${row.확인일 ?? "확인일 미상"} 대조함)`;
  // 연장 조건은 담당자가 「우리가 그 조건을 만족하나」를 판단할 때 필요하다(구독 등급·판올림 등).
  const 조건 = 지났나 && 연장?.조건 && 연장살아있나 ? ` ※${연장.이름} 조건: ${연장.조건}` : "";
  return 머리 + 꼬리 + 조건;
}

/** 표 전체의 상태 — **얼마나 믿을 수 있는지 밝힌다.** */
export function eol표상태(): string {
  const 전체 = EOL_SEED.length;
  const 확인전 = EOL_SEED.filter((r) => r.확인필요).length;
  const 날짜없음 = EOL_SEED.filter((r) => !r.종료일).length;
  const 연장있음 = EOL_SEED.filter((r) => r.유상연장).length;
  return (
    `지원 종료(EOL) 표 ${전체}줄` +
    (확인전 ? ` · **${확인전}줄이 아직 확인 전**입니다(벤더 공지 대조 필요)` : " · 전부 대조 완료") +
    (날짜없음 ? ` · ${날짜없음}줄은 날짜를 모릅니다` : "") +
    // ⚠ **이 한 줄이 중요하다.** 「무상 종료」와 「아예 못 씀」은 다르다 — 유상 연장을 계약한
    //   고객은 오늘도 패치를 받는다. 표 상태에서 그 사실을 안 밝히면, 담당자가 목록만 보고
    //   멀쩡한 서버를 교체 대상에 올린다.
    (연장있음 ? ` · ${연장있음}줄은 **유상 연장 지원**(Ubuntu Pro·ELS·ESU 등)이 있습니다 — 계약 여부는 저희가 알 수 없으니 담당자가 확인해야 합니다` : "") +
    ". 폐쇄망이라 온라인 조회를 쓰지 않고 번들로 실어 나릅니다 — 갱신은 번들 갱신으로 합니다." +
    // 연장 종료일이 곧 지나는 줄은 **번들 갱신 없이 두면 거짓이 된다**. 미리 알린다.
    (() => {
      const 임박 = EOL_SEED.filter((r) => {
        const d = r.유상연장?.종료일;
        if (!d || d.length < 10) return false;
        const t = new Date(d).getTime() - Date.now();
        return t > 0 && t < 120 * 24 * 3600 * 1000;
      });
      return 임박.length
        ? ` ⚠ ${임박.map((r) => `${r.제품} ${r.버전}(${r.유상연장!.종료일})`).join(" · ")}의 연장 지원이 곧 끝납니다 — 그때 이 표를 갱신하지 않으면 안내가 틀리게 됩니다.`
        : "";
    })()
  );
}

