/**
 * 승인 문답 문서가 본문 꼬리에 달던 **메타 라벨 줄** — 「근거 조각: …」·「교사 모델: …」.
 *
 * ⚠ **경로 유무를 안 본다** — 라벨로 시작하는 줄이면 줄째 걷는다. 그 대가를 정직하게 적어 둔다
 *   (2026-09-06 검토관 [중간]):
 *   · **우리 코드**의 생산자는 learnmemory.approvedQaContent 하나뿐이었다(전수 grep). 하지만
 *     ⓒ가 재는 것은 **모델이 방금 쓴 글**이라 그 근거가 거기까지 가지 않는다. 「- 교사 모델:
 *     27B 계열」처럼 경로 없는 줄을 모델이 쓰면 그 줄도 사라진다.
 *   · 그래도 **줄째 걷는 쪽을 고른다**: 교사 모델이 늘 파일 경로인 것은 아니고(모델 id만 적힐
 *     수 있다) 「어느 두뇌를 쓰나」 자체가 고객에게 약속한 적 없는 내부 사정이다. 경로가 있을
 *     때만 걷으면 그 갈래가 통째로 샌다.
 *   · 대신 **감독 화면 문구를 갈랐다** — 진짜 경로를 잡았을 때만 「내부 경로 N줄」이라 적고,
 *     라벨만 뗐으면 「내부 메타 N줄」이다(llm.ts). 없는 경로를 있다고 세지 않는다.
 *   ⚠ 지식 문서가 이 라벨 꼴을 본문에 쓰기 시작하면(예: 증류학습 계획서) 여기부터 다시 볼 것.
 */
const 메타라벨줄_RE = /^[ \t>*·\-]*(?:근거\s*조각|교사\s*모델)\s*[:：][^\n]*$/gm;

/**
 * 내부 경로 토막 — 지식 저장소 조각 참조(`store:<문서>#<sha12>`)와 모델 파일(`models/…/….gguf`).
 *
 * ⚠ **놓아 준 자리(일부러)**: `models/<id>/<id>.gguf` 같은 **자리표시 문구**는 안 잡는다.
 *   우리 제품 안내 문서·용어사전이 경로 꼴을 설명하며 그렇게 적는다(CLAUDE.md도 그렇다).
 *   그래서 조각 이름에 `<`·`>`·공백이 없는 **진짜 파일 이름**일 때만 잡는다 — 설명하는 글을
 *   지우면 「내부 경로를 막는다」가 「제품 설명을 갉아먹는다」가 된다.
 * ⚠ sha12는 소문자 16진수 12자리다(learnloop.cites가 만드는 `경로#sha12` 꼴 그대로).
 */
const 내부경로_RE = /store:[^\s,、)\]]*#[0-9a-f]{12}|models\/[A-Za-z0-9_.\-]+\/[A-Za-z0-9_.\-]+\.gguf/g;

/** 이 줄이 **내부 사정**인가 — 메타 라벨이거나, 진짜 내부 경로를 품은 줄. */
function 메타줄인가(line: string): boolean {
  메타라벨줄_RE.lastIndex = 0;
  내부경로_RE.lastIndex = 0;
  return 메타라벨줄_RE.test(line) || 내부경로_RE.test(line);
}

/** 줄을 걷어낸 뒤 남는 빈 줄·꼬리 공백 정리(빈 줄이 세 개로 벌어지지 않게). */
function 줄정리(s: string): string {
  return s.replace(/[ \t]+$/gm, "").replace(/\n{3,}/g, "\n\n").trim();
}

export interface 메타걷기결과 {
  text: string;
  /** 걷어낸 **줄 수**. 감독 화면에는 이 수만 나간다(경로 문자열을 다시 흘리지 않는다). */
  뗀줄수: number;
  /** 걷어낸 줄에서 찾은 내부 경로 토막 — **시험이 무엇을 잡았는지 보려는 용도**다. */
  경로: string[];
  /**
   * **통째로 메타뿐이라 원문을 그대로 돌려줬다** — 걷을 것이 있었는데 걷지 못한 자리.
   *
   * ⚠ 2026-09-06 검토관 [낮음]: 이 절충(빈 [n]을 안 만든다)은 그대로 두되 **조용하지는 않게**
   *   한다. 뗀줄수는 0이라야 정직하고(안 뗐으니까), 그러면 감독 화면에 아무 신호도 안 뜬다 —
   *   그래서 칸을 따로 판다. llm.ts ⓒ가 이 값을 「내부 메타 전부(원문 유지)」로 싣는다.
   */
  통째메타: boolean;
}

/**
 * 내부 메타 줄을 **줄 단위로** 걷는다 — 조각(ⓑ)과 답 출구(ⓒ)가 같은 이 함수를 쓴다.
 *
 * ★ 왜 줄 단위인가: 「근거 조각: store:…#sha12」는 라벨과 경로가 **한 줄**이다. 경로만 지우면
 *   「근거 조각:」이라는 **빈 약속**이 남아 담당자가 「근거가 있었는데 잘렸다」고 읽는다
 *   (citeguard 자국손질이 껍데기를 지우는 것과 같은 이유). 줄로 세면 계수도 겹치지 않는다.
 *
 * ⚠ 걷고 나서 **글자가 하나도 안 남으면 원문을 그대로 돌려준다**(뗀줄수 0). 조각이 통째로
 *   메타뿐이거나(꼬리만 잘린 조각) 답이 경로뿐인 병리적 자리인데, 빈 문자열을 돌려주면
 *   「참고 자료 [3] 」 같은 빈 번호가 생기고 그 번호를 가리킨 인용이 대조할 것이 없어
 *   통째교체까지 간다. 빈 답을 내보내는 것은 정직한 제거가 아니라 **다른 고장**이다.
 */
export function 메타줄걷기(text: string): 메타걷기결과 {
  const s = String(text ?? "");
  if (!s) return { text: s, 뗀줄수: 0, 경로: [], 통째메타: false };
  const 줄들 = s.split("\n");
  const 남길것: string[] = [];
  const 경로: string[] = [];
  let 뗀줄수 = 0;
  for (const line of 줄들) {
    if (!메타줄인가(line)) { 남길것.push(line); continue; }
    뗀줄수 += 1;
    내부경로_RE.lastIndex = 0;
    for (const m of line.matchAll(내부경로_RE)) 경로.push(m[0]);
  }
  if (뗀줄수 === 0) return { text: s, 뗀줄수: 0, 경로: [], 통째메타: false };
  const 걷힘 = 줄정리(남길것.join("\n"));
  // 통째로 메타뿐 — 원문을 그대로 돌려주되(빈 [n] 방지) **표는 남긴다**(통째메타).
  if (!/[\p{L}\p{N}]/u.test(걷힘)) return { text: s, 뗀줄수: 0, 경로: [], 통째메타: true };
  return { text: 걷힘, 뗀줄수, 경로, 통째메타: false };
}

/** 조각을 실을 때 쓰는 짧은 꼴 — 글만 돌려준다(memory.hybridSearch·조각 판독기 3종). */
export function 메타걷은조각(text: string): string {
  return 메타줄걷기(text).text;
}

/** 걷을 것이 있는가 — 시험·진단용(문자열을 새로 만들지 않고 묻는다). */
export function 메타줄있나(text: string): boolean {
  return String(text ?? "").split("\n").some(메타줄인가);
}
