// util/devmode.ts — **개발 모드**: 개발 기간에만 접근 제약을 푼다 (2026-08-23 사장님 지시).
//
// ■ 지시 원문
//   「개발 동안 제약사항은 다 풀고 하자 / 등급도 개발 끝나면 지정」
//
// ■ 왜 코드를 뜯지 않고 스위치로 두나
//   제약을 지우면 **출하 때 되돌릴 것**이 생기고, 되돌리는 걸 잊으면 통제 없는 제품이 나간다.
//   이 저장소는 그 부류의 사고를 이미 겪었다(고쳤다고 믿었는데 한 곳만 고친 것들).
//   스위치로 두면 **끄는 것이 기본**이고, 켜져 있으면 제품이 스스로 크게 말한다.
//
// ■ 실제로 있었던 일 — 이 스위치가 왜 필요한지
//   `GIJO_지식_취약점_식별체계.md`(제품이 담아 온 취약점 근거 지식)에 QA 시험 중 **기밀(C)**이
//   걸린 채 남아, 사장님을 포함한 **전 계정이 그 문서를 못 읽었다.** 취약점 파일을 올려도
//   CVE·CWE 설명의 근거가 안 닿았다. 게다가 등급을 되돌리려면 **그 문서를 볼 수 있어야** 해서
//   (우회 열람 방지) 아무도 풀 수 없는 **잠금 자물쇠**였다.
//
// ⚠⚠ 반드시 지킬 것
//   · **환경변수로만** 켠다. 화면·API로 켤 수 있게 만들면 그 순간 통제가 아니다.
//   · **기본은 꺼짐.** 값이 정확히 "1"일 때만 켜진다.
//   · 켜져 있으면 **부팅 로그·자가 진단**이 크게 말한다 — 조용히 켜져 있으면 안 된다.
//   · 고객 설치본·파일럿에는 **절대** 켜서 내보내지 않는다.
//
// ■ 무엇이 풀리나 (지금)
//   · 업무정보 **등급 게이트**(기밀/민감 열람 차단) — 등급은 「개발 끝나면 지정」이므로
//     그때까지 아무도 막지 않는다.
//   ⚠ **개인 문서 격리는 안 푼다** — 그건 「등급」이 아니라 제품의 뼈대이고, 풀면
//     개발 중 검증이 **제품이 아닌 것**을 재게 된다(이 저장소의 「테스트가 env를 덮어써서
//     제품 아닌 것을 검증하는 함정」). 필요해지면 그때 따로 판단한다.

/** 개발 모드인가 — **환경변수 GIJO_DEV_MODE=1 일 때만** 참. */
export function 개발모드(): boolean {
  return process.env.GIJO_DEV_MODE === "1";
}

/** 부팅 때 한 번 크게 말한다. 조용히 켜져 있는 것이 가장 나쁘다. */
export function 개발모드경고(): void {
  if (!개발모드()) return;
  console.warn("");
  console.warn("  ⚠⚠  개발 모드(GIJO_DEV_MODE=1) — 업무정보 **등급 게이트가 꺼져 있습니다**.");
  console.warn("       기밀(C)·민감(S) 문서도 누구나 열람합니다. 개발 기간 한정 조치입니다.");
  console.warn("       고객 설치본·파일럿에는 이 값을 절대 넣지 마세요.");
  console.warn("");
}
