// util/josa.ts — **한국어 조사를 앞말에 맞춰 고르는 단 한 곳.**
//
// ■ 왜 생겼나 — 사장님이 승인할 때마다 보는 문구가 「지식화을(를) 진행합니다」였다
//   결재판(승인창)은 이 제품에서 사람이 **가장 자주 보는 화면**이다 — 쓰기 도구를 부를 때마다 뜬다.
//   그 자리에 조사를 안 고른 「을(를)」이 그대로 나가고 있었다(2026-08-22 링크 지식화 라이브 확인 중 발견).
//   도구 이름이 값으로 들어오니 한 문장으로 고정할 수 없어 「을(를)」로 두었던 것인데,
//   받침은 **계산할 수 있는 값**이라 사람이 포기할 자리가 아니었다. 서버 전체에 16곳 있었다.
//
// ⚠ 새로 문구를 쓸 때 「을(를)」·「이(가)」라고 적지 말 것 — 이 파일의 함수를 쓴다.
//   `server/test/josa.test.ts`가 소스를 훑어 그 표기가 다시 생기면 실패한다.

/** 받침이 있는가 — 한글·숫자·영문 각각의 **읽는 소리** 기준. 모르면 null(=없는 쪽으로 처리). */
function 받침있나(글자: string): boolean | null {
  const c = 글자.codePointAt(0);
  if (c === undefined) return null;
  // 한글 음절(가~힣) — 받침 번호가 0이면 없다.
  if (c >= 0xac00 && c <= 0xd7a3) return (c - 0xac00) % 28 !== 0;
  // 숫자는 **읽는 소리**로 가른다: 영·일·삼·육·칠·팔에 받침이 있다.
  if (c >= 0x30 && c <= 0x39) return [true, true, false, true, false, false, true, true, true, false][c - 0x30];
  // 영문도 읽는 소리로: l(엘)·m(엠)·n(엔)·r(알)은 받침이 있고 나머지는 없다.
  //   ⚠ f(에프)는 「프」로 끝나 받침이 없다 — 흔히 헷갈리는 자리라 못 박아 둔다.
  const a = 글자.toLowerCase();
  if (a >= "a" && a <= "z") return ["l", "m", "n", "r"].includes(a);
  return null;
}

/** 조사를 붙일 **실제 끝소리**를 찾는다 — 뒤에 붙은 따옴표·괄호·마침표는 건너뛴다. */
function 끝소리(말: string): boolean | null {
  // 「자산 "web-01"」처럼 닫는 부호로 끝나는 문구가 흔하다. 부호에 조사를 맞추면 늘 틀린다.
  const 다듬은 = String(말).replace(/[\s"'”’)\]}』」〉>.,·…!?]+$/u, "");
  if (!다듬은) return null;
  return 받침있나(다듬은.slice(-1));
}

/**
 * 앞말에 맞는 조사를 돌려준다(조사만 — 앞말은 안 붙인다).
 *
 * @example 조사("지식화", "을") → "를"   ·   조사("보고서", "을") → "을"
 * @example 조사("web-01", "이") → "이"   ·   조사("qwen2", "이") → "가"
 */
export function 조사(말: string, 종류: "을" | "이" | "은" | "와" | "으로"): string {
  const 받침 = 끝소리(말);
  // 모르는 글자(이모지·한자·빈 값)는 **받침 없는 쪽**으로 읽는다 — 「를·가·는」이 덜 어색하다.
  const 있음 = 받침 === true;
  switch (종류) {
    case "을": return 있음 ? "을" : "를";
    case "이": return 있음 ? "이" : "가";
    case "은": return 있음 ? "은" : "는";
    case "와": return 있음 ? "과" : "와";
    case "으로": {
      // 「으로」만 규칙이 하나 더 있다 — **ㄹ 받침은 「로」**다(서울로, 파일로).
      if (!있음) return "로";
      const 끝 = String(말).replace(/[\s"'”’)\]}』」〉>.,·…!?]+$/u, "").slice(-1);
      const c = 끝.codePointAt(0) ?? 0;
      const ㄹ받침 = c >= 0xac00 && c <= 0xd7a3 && (c - 0xac00) % 28 === 8;
      const ㄹ영문 = /^[lLrR]$/.test(끝);
      const ㄹ숫자 = /^[178]$/.test(끝); // 일·칠·팔
      return ㄹ받침 || ㄹ영문 || ㄹ숫자 ? "로" : "으로";
    }
  }
}

/** 앞말 + 조사를 한 번에. `말조사("지식화", "을")` → `"지식화를"` */
export function 말조사(말: string, 종류: "을" | "이" | "은" | "와" | "으로"): string {
  return `${말}${조사(말, 종류)}`;
}
