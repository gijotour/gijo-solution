// gijomd.js — 마크다운을 화면에 그리는 **공용** 렌더러.
//
// ■ 왜 공용인가 (2026-07-31)
//   문서함이 쓰던 것을 대화창(지휘소)도 쓰게 되면서 두 벌이 될 뻔했다. 두 벌로 두면
//   한쪽만 고쳐져 "문서함에선 표가 나오는데 대화창에선 안 나온다"가 된다 —
//   오늘만 "같은 것이 여러 군데" 문제를 세 번 겪었다. **자료도 코드도 한 곳이다.**
//
// ■ 왜 대화창에 필요했나 (사용자 지적)
//   대화창은 답을 **글자 그대로만** 그렸다. 그래서 모델이 보낸 `**자원 상태**`가
//   별표째로 보였다("지금 너하고 하는 대화처럼" 보이게 해 달라는 요청의 실체가 이것이다).
//   표·굵은 글씨·목록이 그려져야 숫자와 이름이 눈에 들어온다 — 그래픽이 아니라 **데이터**다.
//
// ⚠ 반드시 esc()를 먼저 걸고 그 위에 서식을 얹는다. 순서가 바뀌면 남이 보낸 글이
//   그대로 화면에서 실행된다(문서·대화 둘 다 밖에서 온 글을 그린다).
(function () {
  "use strict";
  if (window.gijoMd) return;

  function esc(s) {
    return String(s == null ? "" : s)
      .replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
  }

  // ── 표 규격 — server/src/engine/tabletext.ts의 **사본**이다 (2026-09-10, 갈래 C) ──────
  //
  // ■ 왜 사본을 두는가
  //   서버는 「무엇이 표인가」를 engine/tabletext.ts 한 곳으로 모았는데(갈래 U), 사람이 실제로
  //   보는 이 화면만 제 나름대로 읽고 있었다 — 구분선을 헐겁게 보고, 셀을 `split("|")`로 갈라
  //   **칸 안 이스케이프 `\|`를 몰랐고**(칸이 하나 더 생기고 역슬래시가 남는다), 행마다 칸 수가
  //   달라도 안 맞췄다. 내보내기(inspectionHtml/Docx)가 고친 바로 그 증상이 화면에만 남아 있었다.
  //   이 파일은 preload 없이 도는 **순수 브라우저 스크립트**라 서버 TS를 import할 길이 원리상
  //   없다(화면은 소스를 그대로 싣는다 — 번들러가 없다). 그래서 사본이 불가피하다.
  //
  // ■ 사본을 두는 대신 지키는 계약
  //   ⚠ **원본은 저쪽이다.** 고칠 일이 생기면 언제나 tabletext.ts를 먼저 고치고 여기로 옮겨 적는다.
  //   ⚠ 어긋나면 빨개진다 — server/test/gijomdtable.test.ts가 이 파일을 가짜 window로 **실제로
  //     실행해서** 같은 입력을 양쪽에 먹이고 같은 답인지 잰다(소스 훑기가 아니라 돌려 보고 잰다).
  //     그래서 아래 함수들을 window.gijoMd.표규격으로 내놓는다 — **시험이 꺼내 보는 창구**이고
  //     화면 코드는 여기 안에서만 쓴다.
  //
  // ■ 사본과 「화면 나름」을 가른 자리 (2026-09-10 검토관 2차 · 셋 다 실행 재현)
  //   ① **칸의 내용**(칸가르기·표행맞추기·표_최대열)은 서버와 **똑같아야 한다** — 같은 표를
  //      화면과 내보내기(Word/PDF)가 다르게 그리면 고객이 「미리보기와 파일이 다르다」고 한다.
  //   ② **무엇을 표로 볼 것인가**(표구분선·표 범위)는 화면이 조금 넓다. 서버 쪽 술어는 「이 줄을
  //      지워도 되나」를 줄의 자리와 무관하게 묻는 자리에서 쓰이고, 화면은 「이 덩어리를 어떻게
  //      그리나」를 묻는다. 조여서 얻는 것 없이 GFM 표 3꼴만 잃는 것이 실측으로 드러나 되돌렸다.
  //      ⚠ 넓히는 방향만 허용한다 — 서버가 구분선이라 부르는 것은 화면도 전부 구분선이다(짝 시험).

  /** tabletext.ts의 `표줄`의 사본 — 마크다운 표 행은 파이프로 **시작한다**. */
  function 표줄(l) { return String(l).trimStart().startsWith("|"); }

  /** tabletext.ts의 `구분선`의 사본 — |---|---| · |:---|---:| · |-|-| 꼴.
   *  ⚠ 대시 2개 이상은 공백을 둘러도 구분선이지만, **대시 하나는 꽉 붙은 것만** 구분선이다.
   *    `| - | - |`은 「해당 없음」을 적은 **본문 행**이라 구분선이 아니다 — 두 갈래는 함께 고친다.
   *  ⚠ 화면은 이 술어로 **표를 시작하지 않는다** — 아래 표구분선()이 그 일을 한다. 여기 남긴
   *    이유는 「서버가 구분선이라 부르는 것」의 기준점이라서다(짝 시험이 동치를 잰다). */
  function 구분선(l) { return /^\s*\|(?:(?:\s*:?-{2,}:?\s*|:?-:?)\|)+\s*$/.test(l); }

  /** GFM 규격의 구분선 — 칸 안이 `-`(하나 이상)에 앞뒤 `:`만 든 줄. 양끝 파이프는 있어도 없어도 된다.
   *  ⚠ 파이프가 **한 개도 없는 줄은 제외**한다 — `---`는 가로줄(hr)이지 구분선이 아니다. */
  function GFM구분선(l) {
    var t = String(l).trim();
    if (t.indexOf("|") < 0) return false;
    return /^\|?\s*:?-+:?\s*(?:\|\s*:?-+:?\s*)*\|?$/.test(t);
  }

  /** 화면이 「여기서 표가 시작한다」고 볼 구분선 — 서버 구분선 ∪ GFM 구분선.
   *
   *  ■ 왜 서버보다 넓은가 (2026-09-10 검토관 적발 ① · 실행 재현)
   *    서버 구분선을 그대로 쓰게 했더니 GFM 정규 구분선 3꼴이 화면에서 표로 안 그려졌다 —
   *    `| - | - |` · `| :- | -: |` · 앞 파이프 없는 `--- | ---`. 셋 다 그 전에는 표였다.
   *    **그런데 조여서 얻은 것이 0이다**: 서버가 좁게 보는 이유는 「지우면 안 되는 본문 행
   *    `| - | - |`을 구분선으로 오인해 버리는 것」을 막으려는 것인데(내보내기·반복줄 제거는
   *    줄의 **자리를 안 보고** 모든 줄에 그 질문을 던진다), 화면은 그 질문을 **머리글 바로
   *    다음 줄 한 자리에서만** 던진다 — 본문 행을 먹을 길이 원리상 없다(아래 renderMd).
   *    잣대가 갈리는 게 아니라 **묻는 자리가 다르다.**
   *  ⚠ 합집합으로 적은 이유: 서버가 구분선이라 부르는 것을 화면이 **하나도 빠짐없이** 받는다는
   *    보장을 코드 모양으로 남긴다(짝 시험이 20꼴로 초집합을 잰다). GFM 쪽을 나중에 손대도
   *    서버가 낸 표는 계속 그려진다. */
  function 표구분선(l) { return 구분선(l) || GFM구분선(l); }

  /** tabletext.ts의 `칸가르기`의 사본 — 양끝 파이프를 벗기고 칸 안 이스케이프(`\|`)를 되돌린다.
   *  ⚠ 안 풀면 칸이 하나 더 생기고 역슬래시가 화면에 남는다. 추출기 칸글()이 실제로 내는 꼴이다. */
  function 칸가르기(l) {
    var t = String(l).trim().replace(/^\|/, "").replace(/\|$/, "");
    return t.split(/(?<!\\)\|/).map(function (c) { return c.replace(/\\\|/g, "|").trim(); });
  }

  /** tabletext.ts의 `표_최대열`의 사본 — 자리 채우기가 폭주하는 것을 막는 **하나뿐인** 상한. */
  var 표_최대열 = 512;

  /** tabletext.ts의 `표행맞추기`의 사본 — 한 표의 모든 행을 같은 열 수로. 폭은 가장 넓은 행.
   *  ⚠ **넘치는 칸을 자르지 않는다** — GFM은 버리지만 우리 제품에서 그 글은 고객이 쓴 점검
   *    결과다. 표가 한 칸 넓어지는 것보다 글이 사라지는 것이 나쁘다. */
  function 표행맞추기(행들) {
    var 폭 = Math.min(행들.reduce(function (a, r) { return Math.max(a, r.length); }, 0), 표_최대열);
    return 행들.map(function (r) {
      var out = [];
      // ⚠ `== null`이다 — 원본은 `r[i] ?? ""`라 **null도** 빈 칸으로 본다(2026-09-10 검토관 적발 ③).
      //   `=== undefined`로 적었더니 null이 그대로 남아 사본이 원본과 다른 답을 냈다. 지금
      //   제품 경로는 칸가르기가 문자열만 내서 안 닿지만, 주석이 「같은 답」을 계약으로 적고
      //   표규격 창구가 열려 있는 한 도달 가능한 것으로 친다.
      for (var i = 0; i < 폭; i++) out.push(r[i] == null ? "" : r[i]);
      return out;
    });
  }

  function inline(t) {
    return esc(t)
      .replace(/`([^`]+)`/g, "<code>$1</code>")
      .replace(/\*\*([^*]+)\*\*/g, "<strong>$1</strong>")
      .replace(/(^|[^*])\*([^*\n]+)\*/g, "$1<em>$2</em>")
      // 이미지 — 링크보다 **먼저** 처리해야 한다(![]()가 []()에 먼저 잡히면 그림이 사라진다).
      // 실측(2026-07-31): 미리보기에 붙여넣은 캡처가 안 보였다 — 파일에는 들어 있는데 화면에만
      // 없어서, "저장될 모습 그대로"라는 미리보기의 약속이 깨졌다.
      // ⚠ data: 와 http(s): 만 허용한다. javascript: 같은 것이 src로 들어가면 안 된다.
      .replace(/!\[([^\]]*)\]\(([^)]+)\)/g, function (_m, alt, src) {
        return /^(data:image\/|https?:)/i.test(src) ? '<img src="' + src + '" alt="' + alt + '">' : "";
      })
      .replace(/\[([^\]]+)\]\(([^)]+)\)/g, function (_m, txt, href) {
        return /^https?:/i.test(href) ? '<a href="' + href + '" target="_blank" rel="noreferrer">' + txt + "</a>" : txt;
      });
  }

  function renderMd(src) {
    var lines = String(src || "").split(/\r?\n/);
    var out = [];
    var i = 0;
    while (i < lines.length) {
      var L = lines[i];

      // 코드 블록
      if (/^```/.test(L)) {
        var buf = [];
        i++;
        while (i < lines.length && !/^```/.test(lines[i])) { buf.push(lines[i]); i++; }
        i++;
        out.push("<pre><code>" + esc(buf.join("\n")) + "</code></pre>");
        continue;
      }
      // 표 — 다음 줄이 구분선이면 표로 본다. 잣대는 위 「표 규격」(tabletext.ts 사본) 한 곳.
      //   ★ 구분선 질문을 던지는 자리는 **여기 한 곳뿐**이다(머리글 바로 다음 줄). 그래서
      //     화면은 GFM만큼 넓게 봐도 본문 행을 구분선으로 오인해 먹을 길이 없다.
      //   ⚠ 이미 **다른 블록으로 정해진 줄**(제목·목록·인용)은 표 머리글로 보지 않는다 — GFM도
      //     블록이 먼저다. 이 가드가 없으면 `- 가 | 나` 아래 `- | -`가 온 **목록**이, `## 표 | 아님`
      //     아래 `--- | ---`가 온 **제목**이 표로 둔갑한다(실행 재현). 구분선을 넓힌 만큼 이
      //     구멍도 넓어지므로 함께 닫는다(넓히기 전에도 있던 구멍이다 — 새로 만든 것이 아니다).
      if (/\|/.test(L) && !/^\s*(#{1,4}\s|>|([-*·]|\d+\.)\s)/.test(L) && i + 1 < lines.length && 표구분선(lines[i + 1])) {
        // 표의 **범위** — 표를 연 꼴을 그대로 따른다 (2026-09-10 검토관 적발 ② · 실행 재현).
        //   파이프로 시작한 표면 이어지는 줄도 파이프로 시작해야 한다(tabletext:표줄과 같은 잣대).
        //   안 그러면 표 바로 뒤(빈 줄 없이) 붙은 **문장** 하나가 표 안으로 들어와, 아래 폭
        //   맞추기가 그 문장의 파이프 수만큼 표 **전체에 빈 열을 번식**시킨다
        //   (재현: `| a | b |`+구분선+`| 1 | 2 |`+`참고: a | b | c | d 입니다` → 2열 표가 4열).
        //   ⚠ 서버 표본문행자리()는 여기에 **열 수까지** 같아야 한다는 조건을 더 건다. 화면은
        //     그 반쪽을 안 가져온다 — 거기서 끊으면 남은 행들이 `| B | y | 양호 |` 꼴 **날 파이프
        //     문단**으로 화면에 찍힌다. 서버 쪽 질문은 「이 줄을 지워도 되나」(끊어도 손해가 한 줄)
        //     이고 화면 쪽 질문은 「어떻게 그리나」(끊으면 표가 두 동강)라 답이 갈리는 자리다.
        var 파이프로연표 = 표줄(L);
        var 행들 = [칸가르기(L)];
        i += 2;
        while (i < lines.length && lines[i].trim() && (파이프로연표 ? 표줄(lines[i]) : /\|/.test(lines[i]))) { 행들.push(칸가르기(lines[i])); i++; }
        // 폭은 **다 모은 뒤** 한 번에 맞춘다 — 행마다 그리면 뒤에 나온 넓은 행이 앞 행을 못 늘려
        // 칸 수가 갈린 표가 나간다(내보내기가 같은 자리에서 겪은 증상이다).
        var 맞춘 = 표행맞추기(행들);
        var 머리 = 맞춘[0] || [];
        out.push(
          "<table><thead><tr>" + 머리.map(function (h) { return "<th>" + inline(h) + "</th>"; }).join("") +
          "</tr></thead><tbody>" +
          맞춘.slice(1).map(function (r) { return "<tr>" + r.map(function (c) { return "<td>" + inline(c) + "</td>"; }).join("") + "</tr>"; }).join("") +
          "</tbody></table>"
        );
        continue;
      }
      // 제목
      var h = L.match(/^(#{1,4})\s+(.*)$/);
      if (h) { var lv = Math.min(h[1].length, 3); out.push("<h" + lv + ">" + inline(h[2]) + "</h" + lv + ">"); i++; continue; }
      // 구분선
      if (/^\s*(-{3,}|\*{3,}|_{3,})\s*$/.test(L)) { out.push("<hr>"); i++; continue; }
      // 인용
      if (/^\s*>/.test(L)) {
        var q = [];
        while (i < lines.length && /^\s*>/.test(lines[i])) { q.push(lines[i].replace(/^\s*>\s?/, "")); i++; }
        out.push("<blockquote>" + q.map(inline).join("<br>") + "</blockquote>");
        continue;
      }
      // 목록
      if (/^\s*([-*·]|\d+\.)\s+/.test(L)) {
        var ordered = /^\s*\d+\./.test(L);
        var items = [];
        while (i < lines.length && /^\s*([-*·]|\d+\.)\s+/.test(lines[i])) {
          items.push(lines[i].replace(/^\s*([-*·]|\d+\.)\s+/, ""));
          i++;
        }
        var tag = ordered ? "ol" : "ul";
        out.push("<" + tag + ">" + items.map(function (t) { return "<li>" + inline(t) + "</li>"; }).join("") + "</" + tag + ">");
        continue;
      }
      // 빈 줄
      if (!L.trim()) { i++; continue; }
      // 문단 — 이어지는 줄을 묶는다
      var para = [L];
      i++;
      while (i < lines.length && lines[i].trim() && !/^(#{1,4}\s|```|\s*>|\s*([-*·]|\d+\.)\s|\s*(-{3,}|\*{3,}))/.test(lines[i]) && !/\|/.test(lines[i])) {
        para.push(lines[i]); i++;
      }
      out.push("<p>" + para.map(inline).join(" ") + "</p>");
    }
    return out.join("\n");
  }

  // 표규격 — server/test/gijomdtable.test.ts가 tabletext.ts 원본과 **동치인지** 재려고 꺼내 보는
  //   창구다. 화면 코드는 이 창구로 부르지 않는다(위 renderMd가 클로저 안에서 직접 쓴다).
  window.gijoMd = {
    render: renderMd, inline: inline, esc: esc,
    표규격: {
      표줄: 표줄, 구분선: 구분선, GFM구분선: GFM구분선, 표구분선: 표구분선,
      칸가르기: 칸가르기, 표행맞추기: 표행맞추기, 표_최대열: 표_최대열,
    },
  };
})();
